import re, sys
REF = (sys.argv[1] if len(sys.argv) > 1 else '/workspace/ref/typescript-go') + '/internal'

def extract(path, names, methods=()):
    src = open(path).read().split('\n')
    out = []
    for name in names:
        pat = re.compile(r'^func ' + re.escape(name) + r'[\[(]')
        found = False
        for i, line in enumerate(src):
            if pat.match(line):
                j = i
                while src[j] != '}':
                    j += 1
                out.append('\n'.join(src[i:j + 1]))
                found = True
                break
        if not found:
            raise SystemExit('missing func %s in %s' % (name, path))
    for m in methods:
        found = False
        for i, line in enumerate(src):
            if line.startswith(m):
                j = i
                while src[j] != '}':
                    j += 1
                out.append('\n'.join(src[i:j + 1]))
                found = True
                break
        if not found:
            raise SystemExit('missing %s in %s' % (m, path))
    return '\n\n'.join(out)

