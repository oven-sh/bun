#!/usr/bin/env python3
# Builds the ground-truth writer: the reference's own functions, cut out of its files, with the standard library only.
# usage: python3 build.py <typescript-go checkout> <output directory>
import os, re, shutil, subprocess, sys

ref, out = sys.argv[1], sys.argv[2]
here = os.path.dirname(os.path.abspath(__file__))
shutil.rmtree(out, ignore_errors=True)
os.makedirs(out)
open(os.path.join(out, "go.mod"), "w").write("module gt\n\ngo 1.24\n")

# Whole packages that import the standard library only.
for pkg in ["stringutil", "tspath"]:
    os.makedirs(os.path.join(out, pkg))
    src = os.path.join(ref, "internal", pkg)
    for name in sorted(os.listdir(src)):
        if not name.endswith(".go") or name.endswith("_test.go") or name == "generate.go":
            continue
        text = open(os.path.join(src, name)).read()
        text = text.replace('"github.com/microsoft/typescript-go/internal/stringutil"', '"gt/stringutil"')
        open(os.path.join(out, pkg, name), "w").write(text)

def declarations(path):
    # Top-level declarations of a gofmt'ed file: name -> text, with the comment lines above it.
    lines = open(path).read().split("\n")
    decls = {}
    i = 0
    while i < len(lines):
        line = lines[i]
        m = re.match(r"^(func|type|var|const)\b(.*)$", line)
        if not m:
            i += 1
            continue
        start = i
        while start > 0 and lines[start - 1].startswith("//"):
            start -= 1
        kind, rest = m.group(1), m.group(2)
        end = i
        opens_block = line.rstrip().endswith("{") or line.rstrip().endswith("(")
        if opens_block:
            closer = "}" if line.rstrip().endswith("{") else ")"
            end = i + 1
            while not lines[end].startswith(closer):
                end += 1
        text = "\n".join(lines[start:end + 1])
        if kind == "func":
            fm = re.match(r"^\s*(?:\(([^)]*)\)\s*)?([A-Za-z_0-9]+)", rest)
            recv, name = fm.group(1), fm.group(2)
            if recv:
                name = recv.split()[-1].lstrip("*").split("[")[0] + "." + name
        elif rest.strip() == "(":
            name = kind + "@" + str(i + 1)
        else:
            name = re.match(r"^\s*([A-Za-z_0-9]+)", rest).group(1)
        decls.setdefault(name, []).append(text)
        i = end + 1
    return decls

def take(path, names):
    decls = declarations(os.path.join(ref, path))
    parts = ["// ---- " + path + " ----"]
    for name in names:
        if name not in decls:
            raise SystemExit("no declaration " + name + " in " + path + "; has " + ", ".join(sorted(decls)))
        parts.extend(decls[name])
    return "\n\n".join(parts)

chunks = [
    take("internal/core/text.go", ["TextPos"]),
    take("internal/core/core.go", ["Filter", "SameMap", "Same", "CountWhere", "ECMALineStarts", "ComputeECMALineStarts", "ComputeECMALineStartsSeq", "UTF16Offset", "UTF16Len"]),
    take("internal/scanner/scanner.go", ["ComputeLineOfPosition", "GetECMALineStarts", "GetECMALineOfPosition", "GetECMALineAndUTF16CharacterOfPosition", "GetECMAPositionOfLineAndByteOffset", "ComputePositionOfLineAndByteOffset"]),
    take("internal/diagnostics/diagnostics.go", ["Category", "const@22", "Category.Name", "placeholderRegexp", "Format", "StringifyArgs"]),
    take("internal/diagnosticwriter/diagnosticwriter.go", [
        "FileLike", "Diagnostic", "ToDiagnostics", "FormattingOptions", "const@186", "const@194",
        "FormatDiagnosticsWithColorAndContext", "FormatDiagnosticWithColorAndContext", "writeCodeSnippet",
        "FlattenDiagnosticMessage", "WriteFlattenedDiagnosticMessage", "flattenDiagnosticMessageChain", "diagnosticPrefix",
        "getCategoryFormat", "FormattedWriter", "writeWithStyleAndReset", "WriteLocation", "ErrorSummary",
        "WriteErrorSummaryText", "getErrorSummary", "writeTabularErrorsDisplay", "prettyPathForFileError",
        "WriteFormatDiagnostics", "WriteFormatDiagnostic",
    ]),
    take("internal/testutil/tsbaseline/util.go", ["var@10", "var@18", "var@23", "removeTestPathPrefixes", "isDefaultLibraryFile", "isBuiltFile", "isTsConfigFile", "sanitizeTestFilePath"]),
    take("internal/testutil/tsbaseline/error_baseline.go", ["harnessNewLine", "formatOpts", "var@30", "minimalDiagnosticsToString", "GetErrorBaseline", "iterateErrorBaseline", "formatLocation"]),
]
text = "\n\n".join(chunks)

# One package holds what the reference keeps in several: the qualifiers of those go away.
for q in ["core", "scanner", "diagnosticwriter", "diagnostics", "locale", "harnessutil", "ast"]:
    text = re.sub(r"\b" + q + r"\.([A-Z])", r"\1", text)
text = text.replace("testing.T", "testingT")
text = text.replace("SourceFileLike", "FileLike")

header = '''// Code generated by build.py from the reference; the declarations are verbatim but for package qualifiers.
package main

import (
	"fmt"
	"io"
	"iter"
	"maps"
	"regexp"
	"slices"
	"strconv"
	"strings"
	"unicode"
	"unicode/utf16"
	"unicode/utf8"

	"gt/stringutil"
	"gt/tspath"
)

var _ = maps.Keys[map[int]int]
var _ = unicode.IsSpace
var _ = utf16.RuneLen
var _ iter.Seq[int]

'''
open(os.path.join(out, "extracted.go"), "w").write(header + text + "\n")
shutil.copy(os.path.join(here, "main.go"), os.path.join(out, "main.go"))
r = subprocess.run(["go", "build", "-o", "gt", "."], cwd=out, env={**os.environ, "GOFLAGS": "-mod=mod", "GOTOOLCHAIN": "local", "GOPROXY": "off"})
sys.exit(r.returncode)
