#!/usr/bin/env python3
# Builds the ground-truth program of the bottom layer: the reference's own packages and functions, standard library only.
# usage: python3 build.py <typescript-go checkout> <work directory> [path of the go command]
# Offline: GOTOOLCHAIN=local GOPROXY=off. The go command defaults to /tmp/rr/go126/bin/go (Go 1.26.0, what go.mod asks for), else go.
import os, re, shutil, subprocess, sys

ref, out = sys.argv[1], sys.argv[2]
go = sys.argv[3] if len(sys.argv) > 3 else ("/tmp/rr/go126/bin/go" if os.path.exists("/tmp/rr/go126/bin/go") else "go")
here = os.path.dirname(os.path.abspath(__file__))
shutil.rmtree(os.path.join(out, "src"), ignore_errors=True)
src = os.path.join(out, "src")
os.makedirs(src)
open(os.path.join(src, "go.mod"), "w").write("module gt\n\ngo 1.24\n")

# Whole packages that import the standard library only, copied unchanged but for the import path.
for pkg in ["stringutil", "tspath"]:
    os.makedirs(os.path.join(src, pkg))
    d = os.path.join(ref, "internal", pkg)
    for name in sorted(os.listdir(d)):
        if not name.endswith(".go") or name.endswith("_test.go") or name == "generate.go":
            continue
        text = open(os.path.join(d, name)).read()
        text = text.replace('"github.com/microsoft/typescript-go/internal/stringutil"', '"gt/stringutil"')
        open(os.path.join(src, pkg, name), "w").write(text)

# One file added to the copied package: the name that the program needs and the package does not export.
open(os.path.join(src, "tspath", "export_gt.go"), "w").write(
    "package tspath\n\nfunc ReducePathComponents(components []string) []string { return reducePathComponents(components) }\n"
)

def declarations(path):
    # Top-level declarations of a gofmt'ed file: name -> text, with the comment lines above it.
    lines = open(path).read().split("\n")
    decls = {}
    i = 0
    while i < len(lines):
        line = lines[i]
        m = re.match(r"^(func|type|var|const)\b(.*)$", line)
        if not m:
            i += 1
            continue
        start = i
        while start > 0 and lines[start - 1].startswith("//"):
            start -= 1
        kind, rest = m.group(1), m.group(2)
        end = i
        if line.rstrip().endswith("{") or line.rstrip().endswith("("):
            closer = "}" if line.rstrip().endswith("{") else ")"
            end = i + 1
            while not lines[end].startswith(closer):
                end += 1
        text = "\n".join(lines[start:end + 1])
        if kind == "func":
            fm = re.match(r"^\s*(?:\(([^)]*)\)\s*)?([A-Za-z_0-9]+)", rest)
            recv, name = fm.group(1), fm.group(2)
            if recv:
                name = recv.split()[-1].lstrip("*").split("[")[0] + "." + name
        elif rest.strip() == "(":
            # A block is named after the first name it declares.
            name = kind + ":" + re.match(r"^\s*([A-Za-z_0-9]+)", lines[i + 1]).group(1)
        else:
            name = re.match(r"^\s*([A-Za-z_0-9]+)", rest).group(1)
        decls.setdefault(name, []).append(text)
        i = end + 1
    return decls

def take(path, names):
    decls = declarations(os.path.join(ref, path))
    parts = ["// ---- " + path + " ----"]
    for name in names:
        if name not in decls:
            raise SystemExit("no declaration " + name + " in " + path + "; has " + ", ".join(sorted(decls)))
        parts.extend(decls[name])
    return "\n\n".join(parts)

chunks = [
    take("internal/core/text.go", ["TextPos"]),
    take("internal/core/core.go", ["ECMALineStarts", "ComputeECMALineStarts", "ComputeECMALineStartsSeq", "PositionToLineAndByteOffset", "UTF16Offset", "UTF16Len"]),
    take("internal/scanner/scanner.go", [
        "SkipTriviaOptions", "SkipTrivia", "SkipTriviaEx", "var:mergeConflictMarkerLength", "isConflictMarkerTrivia",
        "scanConflictMarkerTrivia", "isShebangTrivia", "scanShebangTrivia", "ComputeLineOfPosition",
        "ComputePositionOfLineAndByteOffset", "ComputePositionOfLineAndUTF16Character",
    ]),
    take("internal/vfs/internal/internal.go", ["decodeBytes", "decodeUtf16"]),
    take("internal/testutil/tsbaseline/util.go", ["var:lineDelimiter"]),
    take("internal/testutil/tsbaseline/error_baseline.go", ["var:diagnosticsLocationPrefix"]),
    take("internal/testrunner/test_case_parser.go", ["optionRegex", "linkRegex"]),
    take("internal/testrunner/compiler_runner.go", ["var:compilerBaselineRegex"]),
]
text = "\n\n".join(chunks)
# One package holds what the reference keeps in several: the qualifiers of those go away.
for q in ["core", "ast", "debug", "diagnostics"]:
    text = re.sub(r"\b" + q + r"\.([A-Za-z])", r"\1", text)

header = '''// Code generated by build.py from the reference; the declarations are verbatim but for package qualifiers.
package main

import (
	"encoding/binary"
	"fmt"
	"iter"
	"regexp"
	"slices"
	"sort"
	"strings"
	"unicode/utf16"
	"unicode/utf8"

	"gt/stringutil"
)

// Stand-ins for the three names of packages that are not copied.
type Message struct{}

var Merge_conflict_marker_encountered *Message

func PositionIsSynthesized(pos int) bool { return pos < 0 }

func Assert(value bool, message ...any) {
	if !value {
		panic("Debug Failure. False expression.")
	}
}

'''
open(os.path.join(src, "extracted.go"), "w").write(header + text + "\n")
shutil.copy(os.path.join(here, "main.go"), os.path.join(src, "main.go"))
env = {**os.environ, "GOFLAGS": "-mod=mod", "GOTOOLCHAIN": "local", "GOPROXY": "off", "GOSUMDB": "off", "GOCACHE": os.path.join(out, "gocache")}
if os.path.dirname(go):
    # A toolchain that sits in its own tree needs its root; the go command of the system finds its own.
    root = os.path.dirname(os.path.dirname(os.path.abspath(go)))
    if os.path.isdir(os.path.join(root, "src", "unicode")):
        env["GOROOT"] = root
    env["PATH"] = os.path.dirname(os.path.abspath(go)) + ":" + env["PATH"]
r = subprocess.run([go, "build", "-o", os.path.join(out, "gt"), "."], cwd=src, env=env)
sys.exit(r.returncode)
