// Writes runner/unicode_tables.ts from the table dump of the ground-truth program (gt tables <file>).
// usage: bun gen_tables.ts <gotab.txt> <out.ts>
import { readFileSync, writeFileSync } from "node:fs";

const lines = readFileSync(process.argv[2], "utf8").split("\n");
const version = lines[0].replace("version ", "");
const lower = new Map<number, number>();
const next = new Map<number, number>();
for (const l of lines) {
  const f = l.split(" ");
  if (f[0] === "L") lower.set(parseInt(f[1], 16), parseInt(f[2], 16));
  if (f[0] === "F") next.set(parseInt(f[1], 16), parseInt(f[2], 16));
}
// The key of a fold orbit is its smallest member.
const key = new Map<number, number>();
for (const cp of next.keys()) {
  let min = cp;
  for (let r = next.get(cp)!; r !== cp; r = next.get(r)!) min = Math.min(min, r);
  if (min !== cp) key.set(cp, min);
}

// Runs of code points at a fixed distance that map by the same difference: lo, hi, stride, delta.
function ranges(m: Map<number, number>): number[] {
  const cps = [...m.keys()].sort((a, b) => a - b);
  const out: number[] = [];
  let i = 0;
  while (i < cps.length) {
    const lo = cps[i];
    const delta = m.get(lo)! - lo;
    let j = i;
    let stride = 1;
    if (i + 1 < cps.length && m.get(cps[i + 1])! - cps[i + 1] === delta && cps[i + 1] - lo <= 2) {
      stride = cps[i + 1] - lo;
      j = i + 1;
      while (j + 1 < cps.length && cps[j + 1] - cps[j] === stride && m.get(cps[j + 1])! - cps[j + 1] === delta) j++;
    }
    out.push(lo, cps[j], stride, delta);
    i = j + 1;
  }
  return out;
}

// One run per line of a template literal: a formatter leaves it as it is.
function rows(name: string, data: number[]): string {
  let s = `export const ${name}: readonly number[] = runs(\`\n`;
  for (let k = 0; k < data.length; k += 4) {
    s += `${data[k].toString(16)} ${data[k + 1].toString(16)} ${data[k + 2]} ${data[k + 3]}\n`;
  }
  return s + "`);\n";
}

const lowerRanges = ranges(lower);
const foldRanges = ranges(key);
let text = `// Generated by gen_tables.ts from Go's unicode package. Do not edit.\n`;
text += `export const unicodeVersion = ${JSON.stringify(version)};\n\n`;
text += `function runs(text: string): number[] {
  const out: number[] = [];
  for (const line of text.trim().split("\\n")) {
    const f = line.split(" ");
    out.push(parseInt(f[0], 16), parseInt(f[1], 16), Number(f[2]), Number(f[3]));
  }
  return out;
}\n\n`;
text += `// unicode.ToLower where it is no identity: first and last in hexadecimal, stride, difference.\n`;
text += rows("lowerRanges", lowerRanges);
text += `\n// The smallest member of the unicode.SimpleFold orbit where that is another code point, in the same form.\n`;
text += rows("foldRanges", foldRanges);
writeFileSync(process.argv[3], text);
console.log(`unicode ${version}: ${lower.size} lower mappings in ${lowerRanges.length / 4} ranges, ${key.size} fold keys in ${foldRanges.length / 4} ranges`);
