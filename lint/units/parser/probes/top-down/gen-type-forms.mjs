const seenText = new Map();
const seenId = new Set();
function add(kind, id, text) {
  const key = `${kind}\n${text}`;
  if (seenText.has(key)) return;
  if (seenId.has(id)) throw new Error(`id used twice: ${id}`);
  seenText.set(key, id);
  seenId.add(id);
  records.push(`=== ${kind} ${id}\n${text}`);
}
