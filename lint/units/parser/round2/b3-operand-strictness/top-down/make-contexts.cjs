// Writes in-contexts.json: each violation kind inside each slot of the grammar that holds an expression.
const fs = require("node:fs");
const V = {
  assign: "a + b = c",
  post2: "a++ ++",
  member: "a--.b",
};
// [name, loader, prefix, suffix]: the violation text goes between prefix and suffix.
const C = [
  ["statement", "ts", "", ";"],
  ["return", "ts", "function f() { return ", "; }"],
  ["throw", "ts", "throw ", ";"],
  ["var-init", "ts", "let x = ", ";"],
  ["var-init-2nd", "ts", "let w = 1, x = ", ", y;"],
  ["paren", "ts", "(", ");"],
  ["call-arg", "ts", "f(", ");"],
  ["call-arg-2nd", "ts", "f(x, ", ", y);"],
  ["new-arg", "ts", "new F(", ");"],
  ["array-elem", "ts", "[", "];"],
  ["object-value", "ts", "({ k: ", " });"],
  ["object-computed-key", "ts", "({ [", "]: 1 });"],
  ["object-shorthand-init", "ts", "({ k = ", " } = o);"],
  ["index", "ts", "o[", "];"],
  ["optional-index", "ts", "o?.[", "];"],
  ["template-span", "ts", "`x${", "}y`;"],
  ["tagged-template-span", "ts", "t`x${", "}y`;"],
  ["cond-yes", "ts", "x ? ", " : y;"],
  ["cond-no", "ts", "x ? y : ", ";"],
  ["cond-no-in-call", "ts", "f(x ? y : ", ");"],
  ["arrow-body", "ts", "x => ", ";"],
  ["arrow-body-in-call", "ts", "f(x => ", ");"],
  ["assign-right", "ts", "x = ", ";"],
  ["comma-right", "ts", "x, ", ";"],
  ["binary-right", "ts", "x || ", ";"],
  ["unary-operand", "ts", "!", ";"],
  ["for-init", "ts", "for (", ";;) {}"],
  ["for-test", "ts", "for (;", ";) {}"],
  ["for-update", "ts", "for (;;", ") {}"],
  ["for-of-rhs", "ts", "for (x of ", ") {}"],
  ["for-in-rhs", "ts", "for (x in ", ") {}"],
  ["if", "ts", "if (", ") {}"],
  ["while", "ts", "while (", ") {}"],
  ["do-while", "ts", "do {} while (", ");"],
  ["switch", "ts", "switch (", ") {}"],
  ["with", "js", "with (", ") {}"],
  ["case", "ts", "switch (x) { case ", ": break; }"],
  ["case-body", "ts", "switch (x) { case 1: ", "; }"],
  ["export-default", "ts", "export default ", ";"],
  ["export-equals", "ts", "export = ", ";"],
  ["enum-init", "ts", "enum E { A = ", " }"],
  ["class-field", "ts", "class C { x = ", "; }"],
  ["class-static-field", "ts", "class C { static x = ", "; }"],
  ["class-computed-key", "ts", "class C { [", "]() {} }"],
  ["class-extends", "ts", "class C extends ", " {}"],
  ["param-default", "ts", "function f(x = ", ") {}"],
  ["arrow-param-default", "ts", "((x = ", ") => x);"],
  ["array-binding-default", "ts", "let [p = ", "] = y;"],
  ["object-binding-default", "ts", "let { p = ", " } = y;"],
  ["spread-arg", "ts", "f(...", ");"],
  ["spread-elem", "ts", "[...", "];"],
  ["yield-operand", "ts", "function* g() { yield ", "; }"],
  ["await-operand", "ts", "async function g() { await ", "; }"],
  ["import-call", "ts", "import(", ");"],
  ["decorator-arg", "ts", "@d(", ") class C {}"],
  ["jsx-attr", "tsx", "<div x={", "} />;"],
  ["jsx-child", "tsx", "<div>{", "}</div>;"],
  ["jsx-spread-attr", "tsx", "<div {...", "} />;"],
  ["as-operand", "ts", "(", " as T);"],
  ["nonnull-in-call", "ts", "f((", ")!);"],
  ["block", "ts", "{ ", "; }"],
  ["fn-body-in-call", "ts", "f(function () { ", "; });"],
  ["label", "ts", "l: ", ";"],
  ["if-body", "ts", "if (x) ", ";"],
  ["namespace", "ts", "namespace N { ", "; }"],
];
const out = [];
for (const [vn, v] of Object.entries(V)) {
  out.push({ g: vn + ": " + v });
  for (const [cn, l, pre, suf] of C) out.push({ l, s: pre + v + suf, c: cn });
}
fs.writeFileSync("in-contexts.json", JSON.stringify(out));
