# Ports the integer flag sets of internal/checker (Go const blocks) into define_flags! blocks, as ../../node-table-id-contract/bottom-up/gen/gen-flags.ts does for internal/ast.
# usage: genflags.py <out file>      `--check` as second argument compares instead of writing
import re, sys
REF = '/workspace/ref/typescript-go/internal/checker/'
SETS = [
    ('types.go', 'TypeFlags', 'u32'), ('types.go', 'ObjectFlags', 'u32'), ('types.go', 'ElementFlags', 'u32'), ('types.go', 'SignatureFlags', 'u32'),
    ('types.go', 'VarianceFlags', 'u32'), ('types.go', 'AccessFlags', 'u32'), ('types.go', 'IndexFlags', 'u32'), ('types.go', 'NodeCheckFlags', 'u32'),
    ('types.go', 'TypePredicateKind', 'i32'), ('types.go', 'SignatureKind', 'i32'),
    ('checker.go', 'CheckMode', 'u32'), ('checker.go', 'InferenceFlags', 'u32'), ('checker.go', 'InferencePriority', 'i32'),
    ('checker.go', 'UnionReduction', 'i32'), ('checker.go', 'IntersectionFlags', 'u32'),
    ('relater.go', 'SignatureCheckMode', 'u32'), ('relater.go', 'IntersectionState', 'u32'), ('relater.go', 'RecursionFlags', 'u32'),
    ('relater.go', 'ExpandingFlags', 'u8'), ('relater.go', 'RelationComparisonResult', 'u32'),
    ('mapper.go', 'TypeMapperKind', 'i32'),
]
def words(name):
    name = name.replace('JSDoc', 'Jsdoc')
    name = re.sub(r'([a-z0-9])([A-Z])', r'\1_\2', name)
    return re.sub(r'([A-Z]+)([A-Z][a-z])', r'\1_\2', name)
def upper_snake(name): return words(name).upper()
def rust_expr(expr, go_type):
    expr = expr.strip()
    if not re.fullmatch(r'\d+\s*<<\s*\d+', expr):
        # Go gives a shift a higher precedence than `-`, Rust a lower one.
        expr = re.sub(r'(\d+)\s*<<\s*(\d+)', r'(\1 << \2)', expr)
    expr = re.sub(r'\b' + go_type + r'(\w+)', lambda m: '0' if m.group(1) == 'None' else 'Self::' + upper_snake(m.group(1)) + '.0', expr)
    expr = re.sub(r'&\s*\^', '& !', expr)
    return re.sub(r'^\^', '!', expr)
def generate():
    out = ['// Generated by py/genflags.py from internal/checker/{types,checker,relater,mapper}.go of typescript-go 89d5d5b. Do not edit.',
           'use crate::tscore::flags::define_flags;', '']
    counts = {}
    for file, go_type, repr_ in SETS:
        rows = []
        iota, iota_expr, in_block = 0, None, False
        for line in open(REF + file, encoding='utf-8').read().split('\n'):
            if line.startswith('const ('): in_block, iota, iota_expr = True, 0, None; continue
            if line.startswith(')'): in_block = False; continue
            if not in_block: continue
            if not line.strip() or line.strip().startswith('//'): continue
            m = re.match(r'^\t(' + go_type + r'\w+)\s+(?:' + go_type + r'\s+)?=\s*([^/]+?)\s*(?://.*)?$', line)
            bare = re.match(r'^\t(' + go_type + r'\w+)\s*(?://.*)?$', line)
            if m:
                name, expr = m.group(1)[len(go_type):], m.group(2)
                if 'iota' in expr:
                    iota_expr = expr
                    expr = expr.replace('iota', str(iota))
                else:
                    iota_expr = None
                if name != 'None': rows.append('    %s = %s,' % (upper_snake(name), rust_expr(expr, go_type)))
            elif bare and iota_expr is not None:
                name = bare.group(1)[len(go_type):]
                rows.append('    %s = %s,' % (upper_snake(name), rust_expr(iota_expr.replace('iota', str(iota)), go_type)))
            iota += 1
        counts[go_type] = len(rows)
        out += ['define_flags!(%s: %s {' % (go_type, repr_)] + rows + ['});', '']
    return '\n'.join(out), counts
if __name__ == '__main__':
    text, counts = generate()
    if len(sys.argv) > 2 and sys.argv[2] == '--check':
        if open(sys.argv[1]).read() != text: sys.exit('flags_generated.rs differs from the generator')
    else:
        open(sys.argv[1], 'w').write(text)
    print('checker flags', counts)
