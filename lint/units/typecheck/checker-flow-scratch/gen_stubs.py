# Writes src/checker/stubs_generated.rs: for every callee of flow.rs that a file of the worktree defines, its signature with an empty body; for the others the hand-written signature of src/checker/stubs_manual.rs. The callees that src/checker/model.rs implements for the tests are left to it.
import re,glob,os,sys
HERE=os.path.dirname(os.path.abspath(__file__))
flow=sys.argv[1]
src=open(flow).read()
code=re.sub(r'^[ \t]*//.*$','',src,flags=re.M)
own=set(re.findall(r'\bfn ([a-z_0-9]+)',code))
calls=set(re.findall(r'\b(?:self|c)\s*\.\s*([a-z_][a-z_0-9]*)\s*(?:::<[^>]*>)?\(',code))
ext=sorted(calls-own)
R='/workspace/wt/typecheck/src/typecheck/checker'
files=sorted(f for f in glob.glob(R+'/*.rs') if not f.endswith('/flow.rs'))
texts={f:open(f).read() for f in files}
manual_lines=open(HERE+'/src/checker/stubs_manual.rs').read().split('\n')
manual={}
for l in manual_lines:
    m=re.search(r'pub fn ([a-z_0-9]+)',l)
    if m: manual[m.group(1)]=l.strip()
model=set(re.findall(r'pub fn ([a-z_0-9]+)',open(HERE+'/src/checker/model.rs').read()))
def real(name,indent):
    sigs=[]
    for f,t in texts.items():
        for m in re.finditer(r'\n'+indent+r'pub fn '+name+r'(<[^>]*>)?\(',t):
            start=m.start()+1
            end=t.index('{',start)
            sigs.append((os.path.basename(f),' '.join(t[start:end].split())))
    return sigs
out=['// Scratch, generated by gen_stubs.py: the signatures of the callees of flow.rs, from the files of the worktree where one defines the callee, else from stubs_manual.rs.',
     'use crate::ast::{Arg, Ast, DiagnosticId, NodeId, SymbolFlags, SymbolId};',
     'use crate::checker::data::*;',
     'use crate::core::{List, Text};',
     'use crate::diagnostics::MessageId;',
     "impl<'a> Checker<'a> {"]
missing=[]; from_real=[]; from_manual=[]
for name in ext:
    sigs=real(name,'    ')
    if name in model:
        if sigs: print('model, and the worktree has:',sigs[0][1],file=sys.stderr)
        continue
    # The sinks and casts of the data model stay hand-written: the real ones need the whole data model.
    if sigs and name not in ('map_set','fail','fail_detail','stack_limit','list_of','type_types') and not name.startswith('as_'):
        if len(set(s for _,s in sigs))>1: print('AMBIGUOUS',name,sigs,file=sys.stderr)
        out.append(f'    // {sigs[0][0]}')
        out.append(f'    {sigs[0][1]} {{ unimplemented!() }}')
        from_real.append(name)
    elif name in manual:
        out.append('    '+manual[name]); from_manual.append(name)
    else:
        missing.append(name)
out.append('}')
imports=re.search(r'use crate::checker::\{(.*?)\};',src,flags=re.S).group(1)
free=[n.strip() for n in imports.split(',') if n.strip() and n.strip()[0].islower()]
for name in free:
    if name=='get_property_name_from_type': continue
    sigs=real(name,'')
    if sigs:
        out.append(f'// {sigs[0][0]}')
        out.append(f'{sigs[0][1]} {{ unimplemented!() }}')
        from_real.append(name)
    elif name in manual:
        out.append(manual[name]); from_manual.append(name)
    else:
        missing.append('free:'+name)
open(HERE+'/src/checker/stubs_generated.rs','w').write('\n'.join(out)+'\n')
print(f'callees: {len(from_real)} with the signature of the worktree, {len(from_manual)} hand-written: {" ".join(from_manual)}',file=sys.stderr)
if missing: print('NO SIGNATURE FOR:',missing,file=sys.stderr)
