def rank(layer):
    # global order: PRE < my first 21 < MID < my last 7 < POST
    if layer.startswith("PRE"): return 0
    if layer in ORDER:
        i = ORDER.index(layer)
        if i <= 20: return 1+i
        return 100+i
    if layer.startswith("MID"): return 50
    if layer.startswith("POST"): return 200
    return 999
