// Name rules of the port: Go identifiers to Rust identifiers.

const RUST_KEYWORDS = new Set([
  "type", "default", "case", "in", "as", "fn", "mod", "ref", "self", "super", "use", "where", "while", "loop", "match",
  "move", "mut", "pub", "impl", "trait", "struct", "enum", "extern", "crate", "const", "static", "unsafe", "async",
  "await", "dyn", "abstract", "become", "box", "do", "final", "macro", "override", "priv", "typeof", "unsized",
  "virtual", "yield", "try", "gen", "let", "if", "else", "for", "return", "break", "continue", "true", "false",
]);

// JSDoc is one word, as in upstream's own uncapitalize (_scripts/schema.ts). A run of capitals is one word.
function words(name: string): string {
  return name
    .replace(/JSDoc/g, "Jsdoc")
    .replace(/([a-z0-9])([A-Z])/g, "$1_$2")
    .replace(/([A-Z]+)([A-Z][a-z])/g, "$1_$2");
}

export function snake(name: string): string {
  return words(name).toLowerCase();
}

export function upperSnake(name: string): string {
  return words(name).toUpperCase();
}

// A member or parameter name. `Type` is `type_node` (upstream's goParamName says typeNode); other keywords get `_node` too.
export function field(name: string): string {
  const s = snake(name);
  return RUST_KEYWORDS.has(s) ? s + "_node" : s;
}

export function lowerFirst(name: string): string {
  return name.charAt(0).toLowerCase() + name.slice(1);
}

