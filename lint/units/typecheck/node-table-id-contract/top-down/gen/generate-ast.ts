const listAliasNames = new Set(api.listAliases().map(a => a.name));
function slotType(goType: string, def: string, field: string): SlotType | null {
  switch (goType) {
    case "*ast.ModifierList": return "ModifierList";
    case "[]*ast.Node": return "RawNodeList";
    case "*ast.Symbol": return "Symbol";
    case "ast.SymbolTable": return "SymbolTable";
    case "*ast.FlowNode": case "*ast.FlowLabel": return "FlowNode";
    case "*ast.FlowList": return "FlowList";
    case "string": case "[]string": return "Text";
    case "bool": return "Bool";
    case "ast.Kind": case "ast.ImportPhaseModifierSyntaxKind": return "Kind";
    case "ast.TokenFlags": return "TokenFlags";
    case "int32": return "I32";
    case "any": return "Any";
    case "atomic.Uint32": return null;
  }
  const m = /^\*ast\.(\w+)$/.exec(goType);
  if (!m) throw new Error(`no slot type for ${def}.${field}: ${goType}`);
  return m[1] === "NodeList" || listAliasNames.has(m[1]) ? "NodeList" : "Node";
}
