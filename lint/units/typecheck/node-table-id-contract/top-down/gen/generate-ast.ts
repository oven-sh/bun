function addDef(name: string, node?: NodeType) {
  const s = structFacts.get(name);
  if (!s) throw new Error("no struct facts for " + name);
  const slots: Slot[] = [];
  for (const f of s.fields) {
    if (f.owner === "Node") continue;
    if (name === "SourceFile" && !SOURCE_FILE_SLOTS.has(f.name)) continue;
    const ty = slotType(f.type, name, f.name);
    if (!ty) continue;
    const bound = BOUND.has(ty) || f.name === "NextContainer";
    slots.push({ go: f.name, rust: rustName(f.name), ty, owner: f.owner, bound, index: slots.length });
  }
  const rustNames = new Set<string>();
  for (const slot of slots) {
    if (rustNames.has(slot.rust)) throw new Error(`field name collision in ${name}: ${slot.rust}`);
    rustNames.add(slot.rust);
  }
  const kinds = node ? node.allKinds().map(k => k.name) : [];
  defs.push({ name, slots, node, kinds, hasText: slots.some(x => x.ty === "Text") });
}
