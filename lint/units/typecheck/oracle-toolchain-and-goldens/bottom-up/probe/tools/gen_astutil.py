# Writes the function tables of the `astutil` sub-command from internal/ast/utilities.go of the reference: every
# exported function that takes one *Node and returns a bool, a node, node or modifier flags, a small enum or a string.
# usage: python3 gen_astutil.py <utilities.go> <out.go>
import re, sys

src = open(sys.argv[1], encoding="utf-8").read()
NODE = {"*Node", "*Expression", "*TypeNode", "*ClassLikeDeclaration"}
INT = {"NodeFlags", "ModifierFlags", "JSDeclarationKind", "SemanticMeaning", "ModuleInstanceState"}
bools, nodes, ints, strings = [], [], [], []
for m in re.finditer(r"^func ([A-Z]\w*)\(\w+ \*Node\) ([^\s{(]+) \{$", src, re.M):
    name, ret = m.group(1), m.group(2)
    if ret == "bool":
        bools.append(name)
    elif ret in NODE:
        nodes.append(name)
    elif ret in INT:
        ints.append(name)
    elif ret == "string":
        strings.append(name)
out = ["// generated by bootstrap.sh (tools/gen_astutil.py) from internal/ast/utilities.go", "package astutil", "",
       'import "github.com/microsoft/typescript-go/internal/ast"', "", "var boolFns = []boolFn{"]
out += ['\t{"%s", ast.%s},' % (n, n) for n in bools]
out += ["}", "", "var nodeFns = []nodeFn{"]
out += ['\t{"%s", func(n *ast.Node) *ast.Node { return ast.%s(n) }},' % (n, n) for n in nodes]
out += ["}", "", "var intFns = []intFn{"]
out += ['\t{"%s", func(n *ast.Node) int64 { return int64(ast.%s(n)) }},' % (n, n) for n in ints]
out += ["}", "", "var stringFns = []stringFn{"]
out += ['\t{"%s", ast.%s},' % (n, n) for n in strings]
out += ["}", ""]
open(sys.argv[2], "w").write("\n".join(out))
print("astutil tables: %d bool, %d node, %d int, %d string" % (len(bools), len(nodes), len(ints), len(strings)))
