#!/usr/bin/env bun
/**
 * Generates completions/bun.ps1 (PowerShell completion for bun & bunx) from
 * completions/bun-cli.json plus the static completer logic in
 * misctools/powershell-completions-logic.ps1. Run from the repo root:
 *
 *   bun misctools/generate-powershell-completions.ts
 *
 * Descriptions the help-text parser fails to capture are patched in
 * DESCRIPTION_FIXUPS.
 */

import { readFileSync, writeFileSync } from "fs";
import { join } from "path";

interface FlagInfo {
  name: string;
  shortName?: string;
  description: string;
  hasValue: boolean;
  choices?: string[];
}

interface CommandInfo {
  name: string;
  description: string;
  flags: FlagInfo[];
  subcommands?: Record<string, { name: string; description: string }>;
}

const data = JSON.parse(readFileSync("completions/bun-cli.json", "utf8")) as {
  commands: Record<string, CommandInfo>;
  globalFlags: FlagInfo[];
};

// Flags whose value is a path or free-form string: the completer returns
// nothing for their values so PowerShell's built-in completion takes over.
const PATH_VALUE_FLAGS = new Set([
  "cwd", "config", "cache-dir", "cafile", "env-file", "preload", "require",
  "import", "outdir", "outfile", "root", "patches-dir", "coverage-dir",
  "coverage-reporter", "reporter-outfile",
]);

// Descriptions the help-text parser could not capture.
const DESCRIPTION_FIXUPS: Record<string, string> = {
  run: "Run a JavaScript/TypeScript file, a package.json script, or a package bin",
  create: "Create a new project from a template (bun create <template>)",
  repl: "Start an interactive JavaScript/TypeScript REPL",
  upgrade: "Upgrade Bun to the latest version",
  discord: "Open Bun's Discord server",
  completions: "Install shell completions for bun",
  help: "Show help for a command",
  bun: "Run a JavaScript/TypeScript file with Bun",
  publish: "Publish a package to the npm registry",
  outdated: "Display outdated dependencies",
};

// Commands whose help output is a minor variation of the same flag set; one
// shared table keeps the generated script small.
const SHARED_GROUP = [
  "install", "add", "remove", "update", "dedupe", "outdated",
  "link", "unlink", "publish", "patch", "info",
];
// Commands whose positional arguments are npm package names, completed through
// 'bun getcompletes a'.
const PACKAGE_COMPLETION_COMMANDS = ["install", "add", "i", "a"];

function psQuote(s: string): string {
  return "'" + s.replace(/'/g, "''") + "'";
}

function flagEntries(flags: FlagInfo[]): [string, string][] {
  const entries: [string, string][] = [];
  const seen = new Set<string>();
  for (const f of flags) {
    let desc = f.description.replace(/\s+/g, " ").trim();
    if (PATH_VALUE_FLAGS.has(f.name)) desc += " <path>";
    if (f.choices?.length) desc += " (one of: " + f.choices.join(", ") + ")";
    const keys = ["--" + f.name];
    if (f.shortName) keys.push("-" + f.shortName);
    for (const k of keys) {
      // PowerShell hash literals reject case-insensitive duplicates (-f vs -F);
      // first occurrence wins, and lookups are case-insensitive anyway.
      const dedupeKey = k.toLowerCase();
      if (!seen.has(dedupeKey)) { seen.add(dedupeKey); entries.push([k, desc]); }
    }
  }
  return entries;
}

function hashtable(entries: [string, string][], inline = false): string {
  if (entries.length === 0) return "@{}";
  const lines = entries.map(([k, v]) => "    " + psQuote(k) + " = " + psQuote(v) + ";");
  return "@{\n" + lines.join("\n") + "\n}";
}

const commands = Object.entries(data.commands).filter(([name]) => name !== "lint");

const groupFlags = flagEntries(
  SHARED_GROUP.flatMap(name => data.commands[name]?.flags ?? []),
);

const choiceEntries: [string, string][] = [];
const seenChoices = new Set<string>();
for (const f of data.globalFlags.concat(commands.flatMap(([, c]) => c.flags ?? []))) {
  if (f.choices?.length && !seenChoices.has(f.name)) {
    seenChoices.add(f.name);
    choiceEntries.push(["--" + f.name, f.choices.join(" ")]);
  }
}
// Known choices the help-text heuristic missed.
choiceEntries.push(
  ["--backend", "clonefile clonefile_each_dir copyfile hardlink symlink"],
  ["--omit", "dev optional peer"],
  ["--linker", "isolated hoisted"],
  ["--jsx-runtime", "automatic classic"],
  ["--target", "browser bun node"],
  ["--format", "esm cjs iife"],
  ["--sourcemap", "linked inline external none"],
  ["--shell", "bun system"],
  ["--packages", "bundle external"],
  ["--audit-level", "low moderate high critical"],
  ["--access", "public restricted"],
);

const parts: string[] = [];

parts.push(`#
# PowerShell completion for bun and bunx. Generated by
# misctools/generate-powershell-completions.ts from completions/bun-cli.json -
# edit the generator, not this file.
#
# Use: dot-source this file from your PowerShell profile, e.g.
#   . "$HOME\\Documents\\PowerShell\\bun.ps1"
# or run 'bun completions' on Windows to install it.
#`);

parts.push(`function script:__bunCompletePackages([string]$prefix) {
    # 'bun getcompletes a <prefix>' prints matching package names, space-separated.
    if ($prefix -eq "") { return }
    try { $out = & bun --silent getcompletes a $prefix 2>$null } catch { return }
    if ($LASTEXITCODE -ne 0 -or -not $out) { return }
    return (($out -join " ") -split "\\s+" | Where-Object { $_ })
}

function script:__bunCompleteScripts {
    # 'bun getcompletes z' prints "name<TAB>description" lines for package.json scripts.
    try { $out = & bun --silent getcompletes z 2>$null } catch { return }
    if ($LASTEXITCODE -ne 0 -or -not $out) { return }
    return (($out -join "\`n") -split "\`r?\`n" | Where-Object { $_ -ne "" })
}

function script:__bunCompleteBins {
    try { $out = & bun --silent getcompletes b 2>$null } catch { return }
    if ($LASTEXITCODE -ne 0 -or -not $out) { return }
    return (($out -join " ") -split "\\s+" | Where-Object { $_ })
}

function script:__bunResult([string]$value, [string]$listText, [string]$tooltip) {
    # Windows PowerShell 5.1 rejects null AND empty tooltips; a space works.
    if (-not $tooltip) { $tooltip = ' ' }
    [System.Management.Automation.CompletionResult]::new($value, $listText, 'ParameterValue', $tooltip)
}`);

parts.push("# Flags that take a value with a fixed set of choices, flag name -> choices.");
parts.push("$script:BunFlagChoices = " + hashtable(choiceEntries));

parts.push("# Subcommand descriptions.");
const commandLines = commands
  .map(([name, cmd]) => "    " + psQuote(name) + " = " + psQuote(DESCRIPTION_FIXUPS[name] ?? cmd.description ?? "") + ";")
  .join("\n");
parts.push("$script:BunCommands = @{\n" + commandLines + "\n}");

parts.push("$script:BunGlobalFlags = " + hashtable(flagEntries(data.globalFlags)));

parts.push("# Per-command flags. '*' holds the shared package-manager flag set used by");
parts.push("# install/add/remove/update/dedupe/outdated/link/unlink/publish/patch/info.");
const flagTableLines = commands
  .filter(([name]) => !SHARED_GROUP.includes(name))
  .map(([name, cmd]) => "    " + psQuote(name) + " = " + hashtable(flagEntries(cmd.flags ?? [])))
  .join("\n");
parts.push("$script:BunFlags = @{\n    '*' = " + hashtable(groupFlags) + "\n" + flagTableLines + "\n}");

parts.push("# Flags that consume the next token as their value. '*' holds the shared");
parts.push("# package-manager value flags plus the global ones.");
const globalValueFlags = hashtable(
  flagEntries(
    data.globalFlags
      .filter(f => f.hasValue)
      .concat(SHARED_GROUP.flatMap(name => (data.commands[name]?.flags ?? []).filter(f => f.hasValue))),
  ),
);
const valueTableLines = commands
  .filter(([name]) => !SHARED_GROUP.includes(name))
  .map(([name, cmd]) => {
    const vf = flagEntries((cmd.flags ?? []).filter(f => f.hasValue));
    return vf.length ? "    " + psQuote(name) + " = " + hashtable(vf) : null;
  })
  .filter(Boolean)
  .join("\n");
parts.push("$script:BunValueFlags = @{\n    '*' = " + globalValueFlags + "\n" + valueTableLines + "\n}");

const pmLines = Object.values(data.commands.pm?.subcommands ?? {})
  .map(sc => "    " + psQuote(sc.name) + " = " + psQuote(sc.description ?? "") + ";")
  .join("\n");
parts.push("$script:BunPmSubcommands = @{\n" + pmLines + "\n}");

parts.push("$script:BunPackageCommands = @(" + PACKAGE_COMPLETION_COMMANDS.map(psQuote).join(", ") + ")");
parts.push("$script:BunCreateTemplates = @('next', 'react')");

parts.push(readFileSync("misctools/powershell-completions-logic.ps1", "utf8"));

const script = parts.join("\n\n");
writeFileSync(join(process.cwd(), "completions", "bun.ps1"), script);
console.log("wrote completions/bun.ps1 (" + script.length + " bytes)");
