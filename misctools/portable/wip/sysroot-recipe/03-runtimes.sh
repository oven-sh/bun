#!/bin/bash
# Step 1c: libunwind + libc++abi + libc++ (static only) for x86_64-linux-musl, portable ABI flags.
set -euo pipefail
. /tmp/portable/jsc/scripts/env.sh
RES=$SYSROOT/clang-resource-dir
B=$JSCDIR/build/runtimes
rm -rf "$B"; mkdir -p "$B"
FLAGS="$PORTABLE_ABI_FLAGS -resource-dir=$RES"
cmake -G Ninja -S $JSCDIR/src/llvm-project/runtimes -B "$B" \
  -DCMAKE_BUILD_TYPE=Release \
  -DLLVM_ENABLE_RUNTIMES="libunwind;libcxxabi;libcxx" \
  -DCMAKE_C_COMPILER=$LLVM_BIN/clang -DCMAKE_CXX_COMPILER=$LLVM_BIN/clang++ -DCMAKE_ASM_COMPILER=$LLVM_BIN/clang \
  -DCMAKE_AR=$LLVM_BIN/llvm-ar -DCMAKE_RANLIB=$LLVM_BIN/llvm-ranlib -DCMAKE_NM=$LLVM_BIN/llvm-nm \
  -DCMAKE_C_COMPILER_TARGET=$PTARGET -DCMAKE_CXX_COMPILER_TARGET=$PTARGET -DCMAKE_ASM_COMPILER_TARGET=$PTARGET \
  -DCMAKE_SYSTEM_NAME=Linux -DCMAKE_SYSTEM_PROCESSOR=x86_64 \
  -DCMAKE_SYSROOT=$SYSROOT \
  -DCMAKE_C_FLAGS="$FLAGS" -DCMAKE_CXX_FLAGS="$FLAGS" -DCMAKE_ASM_FLAGS="$FLAGS" \
  -DCMAKE_EXE_LINKER_FLAGS="-fuse-ld=lld -rtlib=compiler-rt -unwindlib=none -nostdlib++ -static-pie" \
  -DCMAKE_INSTALL_PREFIX=$SYSROOT/usr \
  -DLLVM_ENABLE_PER_TARGET_RUNTIME_DIR=OFF \
  -DLLVM_INCLUDE_TESTS=OFF -DLLVM_INCLUDE_DOCS=OFF \
  -DLIBUNWIND_ENABLE_SHARED=OFF -DLIBUNWIND_ENABLE_STATIC=ON -DLIBUNWIND_USE_COMPILER_RT=ON \
  -DLIBUNWIND_INCLUDE_TESTS=OFF -DLIBUNWIND_INCLUDE_DOCS=OFF \
  -DLIBCXXABI_ENABLE_SHARED=OFF -DLIBCXXABI_ENABLE_STATIC=ON -DLIBCXXABI_USE_COMPILER_RT=ON \
  -DLIBCXXABI_USE_LLVM_UNWINDER=ON -DLIBCXXABI_ENABLE_STATIC_UNWINDER=ON \
  -DLIBCXXABI_INCLUDE_TESTS=OFF \
  -DLIBCXX_ENABLE_SHARED=OFF -DLIBCXX_ENABLE_STATIC=ON -DLIBCXX_USE_COMPILER_RT=ON \
  -DLIBCXX_HAS_MUSL_LIBC=ON \
  -DLIBCXX_CXX_ABI=libcxxabi -DLIBCXX_ENABLE_STATIC_ABI_LIBRARY=ON \
  -DLIBCXX_INCLUDE_TESTS=OFF -DLIBCXX_INCLUDE_BENCHMARKS=OFF -DLIBCXX_INCLUDE_DOCS=OFF
ninja -C "$B" -j$JOBS
ninja -C "$B" install
ls -la $SYSROOT/usr/lib
