// Scratch probe, outside the repo: a yarn.lock that bun reads and then does not use
// (root package.json has no dependencies), followed by `bun add new-dependency`.
import { mkdtempSync, writeFileSync, existsSync, readFileSync, rmSync } from "fs";
import { tmpdir } from "os";
import { join } from "path";

type Pkg = { name: string; version: string; dependencies?: Record<string, string> };
async function registry(packages: Pkg[]) {
  const served = new Map<string, { manifest: Pkg; tarball: Uint8Array; tarballPath: string; integrity: string }>();
  for (const manifest of packages) {
    const { name, version } = manifest;
    const tarball = await new Bun.Archive(
      { "package/package.json": JSON.stringify(manifest), "package/index.js": `module.exports = ${JSON.stringify(name)};` },
      { compress: "gzip" },
    ).bytes();
    served.set(name, { manifest, tarball, tarballPath: `/${name}/-/${name}-${version}.tgz`, integrity: "sha512-" + new Bun.CryptoHasher("sha512").update(tarball).digest("base64") });
  }
  const requests: string[] = [];
  const server = Bun.serve({
    port: 0,
    fetch(request) {
      const { origin, pathname } = new URL(request.url);
      requests.push(pathname);
      for (const { manifest, tarball, tarballPath, integrity } of served.values()) {
        if (pathname === tarballPath) return new Response(tarball);
        if (pathname !== `/${manifest.name}`) continue;
        return Response.json({ name: manifest.name, "dist-tags": { latest: manifest.version }, versions: { [manifest.version]: { ...manifest, dist: { tarball: origin + tarballPath, integrity } } } });
      }
      return new Response("not found", { status: 404 });
    },
  });
  return { url: server.url.href, origin: server.url.origin, requests, integrity: (n: string) => served.get(n)!.integrity, tarballUrl: (n: string) => server.url.origin + served.get(n)!.tarballPath, stop: () => server.stop(true) };
}
const env: Record<string, string> = { ...(process.env as Record<string, string>), NO_COLOR: "1", BUN_DEBUG_QUIET_LOGS: "1" };
delete env.FORCE_COLOR;
const bins: Record<string, string> = { canary: "/workspace/bun/build/release/bun", base: "/workspace/bun/build/release-base/bun", pr: "/workspace/bun/build/release-pr/bun" };
const aliases = { "dependency-of-short": "npm:short@1.0.0", "dependency-of-some-other-package": "npm:some-other-package@1.0.0" };
const plain = { "dependency-of-short": "^1.0.0", "dependency-of-some-other-package": "^1.0.0" };

for (const [label, bin] of Object.entries(bins)) {
  const reg = await registry([
    { name: "short", version: "1.0.0" }, { name: "some-other-package", version: "1.0.0" },
    { name: "dependency-of-short", version: "1.0.0" }, { name: "dependency-of-some-other-package", version: "1.0.0" },
    { name: "has-aliases", version: "1.0.0", dependencies: aliases },
    { name: "new-dependency", version: "1.0.0", dependencies: plain },
  ]);
  const row = (name: string) => `  version "1.0.0"\n  resolved "${reg.tarballUrl(name)}#0123456789abcdef0123456789abcdef01234567"\n  integrity ${reg.integrity(name)}`;
  const cwd = mkdtempSync(join(tmpdir(), "disp-yarn-"));
  writeFileSync(join(cwd, "bunfig.toml"), `[install]\nregistry = "${reg.url}"\n`);
  writeFileSync(join(cwd, "package.json"), JSON.stringify({ name: "app" }));
  writeFileSync(join(cwd, "yarn.lock"), `# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.
# yarn lockfile v1


"dependency-of-short@npm:short@1.0.0":
${row("short")}

"dependency-of-some-other-package@npm:some-other-package@1.0.0":
${row("some-other-package")}

has-aliases@1.0.0:
${row("has-aliases")}
  dependencies:
    dependency-of-short "npm:short@1.0.0"
    dependency-of-some-other-package "npm:some-other-package@1.0.0"
`);
  const proc = Bun.spawn({ cmd: [bin, "add", "new-dependency", "--lockfile-only"], cwd, env: { ...env, BUN_INSTALL_CACHE_DIR: join(cwd, ".cache") }, stdout: "pipe", stderr: "pipe" });
  const [out, err, exitCode] = await Promise.all([proc.stdout.text(), proc.stderr.text(), proc.exited]);
  let packages: any = null;
  const p = join(cwd, "bun.lock");
  if (existsSync(p)) {
    const { packages: pk = {} } = Bun.JSONC.parse(readFileSync(p, "utf8")) as any;
    packages = Object.fromEntries(Object.entries(pk).map(([k, v]: any) => [k, v[0]]));
  }
  console.log(JSON.stringify({
    bin: label, exit: exitCode,
    stderr: err.replaceAll(reg.url, "<registry>/").replaceAll(reg.origin, "<registry>").split("\n").map(l => l.trim()).filter(l => /error|warn|fail|404|migrated/i.test(l)),
    packages, requests: [...new Set(reg.requests)].toSorted(),
  }, null, 1));
  reg.stop();
  rmSync(cwd, { recursive: true, force: true });
}
