pub fn keysym_to_char(symbol: u32) -> Option<char> {
    char::from_u32(match symbol {
        0x20..=0x7e | 0xa0..=0xff => symbol,
        0x0100_0000..=0x0110_ffff => symbol - 0x0100_0000,
        0xff08..=0xff0b | 0xff0d | 0xff1b | 0xff89 | 0xff8d | 0xffaa..=0xffb9 | 0xffbd | 0xffff => {
            symbol & 0x7f
        }
        0xff80 => 0x20,
        _ => {
            let before = RUNS.partition_point(|run| u32::from(run.0) <= symbol);
            let (first, count, character) = RUNS[before.checked_sub(1)?];
            let offset = symbol - u32::from(first);
            (offset < count.into()).then(|| u32::from(character) + offset)?
        }
    })
}
