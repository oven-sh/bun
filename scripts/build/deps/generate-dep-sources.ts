/**
 * Regenerate the explicit file lists the WebKit and ICU builds are described
 * with — `webkit-sources.ts` and `icu-sources.ts` — from a WebKit / ICU tree.
 * The build never reads those trees at configure time; these lists are its
 * inputs, reviewed as a diff on every bump.
 *
 *   bun scripts/build/deps/generate-dep-sources.ts webkit <path to WebKit>
 *   bun scripts/build/deps/generate-dep-sources.ts icu <path to icu (the dir holding source/)>
 *
 * WebKit: runs WebKit's own unified-source bundler (python3) over JSC's
 * Sources.txt lists and records the bundles it forms, plus the header,
 * script and data files the build names. ICU: the per-library sources.txt.
 */

import { spawnSync } from "node:child_process";
import { existsSync, mkdtempSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, isAbsolute, join, relative, resolve } from "node:path";

const here = dirname(import.meta.filename);
const [kind, treeArg] = process.argv.slice(2);
if ((kind !== "webkit" && kind !== "icu") || treeArg === undefined) {
  console.error("usage: generate-dep-sources.ts webkit <WebKit dir> | icu <icu dir>");
  process.exit(1);
}
const tree = resolve(treeArg);

const filesIn = (dir: string, ...exts: string[]): string[] =>
  readdirSync(dir)
    .filter(f => exts.length === 0 || exts.some(e => f.endsWith(e)))
    .sort();

const list = (name: string, doc: string, items: readonly string[]): string =>
  `/** ${doc} */\nexport const ${name}: readonly string[] = [\n${items.map(i => `  ${JSON.stringify(i)},`).join("\n")}\n];\n`;

const banner = (source: string): string =>
  `// Generated by scripts/build/deps/generate-dep-sources.ts from ${source}.\n// Regenerate on a version bump; do not edit by hand.\n\n`;

if (kind === "webkit") {
  const JSC = join(tree, "Source", "JavaScriptCore");
  const WTF = join(tree, "Source", "WTF");
  const BM = join(tree, "Source", "bmalloc");
  if (!existsSync(join(JSC, "Sources.txt")))
    throw new Error(`${tree} is not a WebKit tree (no Source/JavaScriptCore/Sources.txt)`);

  // ─── Unified bundles: run WebKit's bundler into a scratch dir, read back
  // which sources each bundle includes. Same invocation JSC's CMakeLists
  // uses (jsc_unified_source_lists, --ignore-header-groups).
  const unifiedSourceLists = ["Sources.txt", "inspector/remote/SourcesSocket.txt"];
  const scratch = mkdtempSync(join(tmpdir(), "jsc-bundles-"));
  const bundled = spawnSync(
    "python3",
    [
      join(WTF, "Scripts", "generate-unified-source-bundles.py"),
      "--derived-sources-path",
      scratch,
      "--source-tree-path",
      JSC,
      "--ignore-header-groups",
      ...unifiedSourceLists.map(f => join(JSC, f)),
    ],
    { encoding: "utf8", maxBuffer: 1 << 26 },
  );
  if (bundled.status !== 0)
    throw new Error(`generate-unified-source-bundles.py failed:\n${bundled.stderr || bundled.error}`);
  const bundleDir = join(scratch, "unified-sources");
  const bundles: Array<[string, string[]]> = [];
  const nonUnified: string[] = [];
  for (const entry of bundled.stdout.split(/[;\r\n]+/).map(s => s.trim())) {
    if (!/\.(cpp|c|cc)$/.test(entry)) continue;
    if (isAbsolute(entry) && entry.startsWith(bundleDir)) {
      const members = readFileSync(entry, "utf8")
        .split("\n")
        .filter(l => l.startsWith("#include "))
        .map(l => l.slice('#include "'.length, -1));
      for (const m of members) {
        if (isAbsolute(m))
          throw new Error(`bundle ${entry} includes a derived source (${m}); the build would need to know about it`);
      }
      bundles.push([relative(bundleDir, entry), members]);
    } else if (isAbsolute(entry)) {
      throw new Error(`unexpected absolute non-bundle source ${entry}`);
    } else {
      // @no-unify members: relative to the source tree, or a bare name of a
      // generated source in DerivedSources (WEBKIT_COMPUTE_SOURCES' rule).
      nonUnified.push(!/[\\/]/.test(entry) && !existsSync(join(JSC, entry)) ? `DerivedSources/${entry}` : entry);
    }
  }
  rmSync(scratch, { recursive: true, force: true });

  // ─── Header dirs flattened into <JavaScriptCore/X.h> (JavaScriptCore_PRIVATE_FRAMEWORK_HEADERS' directories).
  // config.ts and webkit.ts import each other; loading config.ts first
  // matches the build's entry order so WEBKIT_VERSION initializes before use.
  await import("../config.ts");
  const { jscHeaderDirs } = await import("./webkit.ts");
  const privateHeaders = jscHeaderDirs.flatMap(d => filesIn(join(JSC, d), ".h", ".def").map(f => `${d}/${f}`));
  const bmallocHeaders = [
    ...filesIn(join(BM, "bmalloc"), ".h", ".def").map(f => `bmalloc/${f}`),
    ...filesIn(join(BM, "libpas", "src", "libpas"), ".h", ".def").map(f => `libpas/src/libpas/${f}`),
  ];

  // A clone: its HEAD. The build's own fetch (no .git): the pinned version.
  const { WEBKIT_VERSION } = await import("./webkit.ts");
  const treeVersion = existsSync(join(tree, ".git"))
    ? spawnSync("git", ["--git-dir", join(tree, ".git"), "rev-parse", "HEAD"], { encoding: "utf8" }).stdout.trim()
    : WEBKIT_VERSION;
  const out =
    banner(`oven-sh/WebKit ${treeVersion.slice(0, 12)}`) +
    `/** JSC's unified-source bundles: bundle file → the Sources.txt entries it #includes, in order (WebKit's generate-unified-source-bundles.py over ${unifiedSourceLists.join(" + ")}, --ignore-header-groups). Paths relative to Source/JavaScriptCore. */\n` +
    `export const jscUnifiedBundles: ReadonlyArray<readonly [string, readonly string[]]> = [\n${bundles
      .map(([b, m]) => `  [${JSON.stringify(b)}, [${m.map(x => JSON.stringify(x)).join(", ")}]],`)
      .join("\n")}\n];\n\n` +
    list(
      "jscNonUnifiedSources",
      "Sources.txt entries marked @no-unify, compiled on their own. Relative to Source/JavaScriptCore; `DerivedSources/…` entries are generated files.",
      nonUnified,
    ) +
    "\n" +
    list(
      "jscPrivateHeaders",
      "Every .h/.def under jscHeaderDirs — the names <JavaScriptCore/X.h> resolves. Relative to Source/JavaScriptCore.",
      privateHeaders,
    ) +
    "\n" +
    list(
      "bmallocFrameworkHeaders",
      "Every .h/.def <bmalloc/X.h> resolves. Relative to Source/bmalloc.",
      bmallocHeaders,
    ) +
    "\n" +
    list(
      "jscOfflineasmRuby",
      "offlineasm/*.rb — inputs of the LLInt generator steps.",
      filesIn(join(JSC, "offlineasm"), ".rb").map(f => `offlineasm/${f}`),
    ) +
    "\n" +
    list(
      "jscGeneratorRuby",
      "generator/*.rb — inputs of the bytecode generator step.",
      filesIn(join(JSC, "generator"), ".rb").map(f => `generator/${f}`),
    ) +
    "\n" +
    list(
      "jscUcdFiles",
      "ucd/* — Unicode data the yarr/lexer table generators read.",
      filesIn(join(JSC, "ucd")).map(f => `ucd/${f}`),
    ) +
    "\n" +
    list(
      "jscBuiltinsScripts",
      "Scripts/*.py and Scripts/wkbuiltins/*.py — inputs of the JS builtins / inspector JSON steps.",
      [
        ...filesIn(join(JSC, "Scripts"), ".py").map(f => `Scripts/${f}`),
        ...filesIn(join(JSC, "Scripts", "wkbuiltins"), ".py").map(f => `Scripts/wkbuiltins/${f}`),
      ],
    ) +
    "\n" +
    list(
      "jscInspectorScripts",
      "inspector/scripts/*.py and codegen/*.py — inputs of the inspector protocol bindings step.",
      [
        ...filesIn(join(JSC, "inspector", "scripts"), ".py").map(f => `inspector/scripts/${f}`),
        ...filesIn(join(JSC, "inspector", "scripts", "codegen"), ".py").map(f => `inspector/scripts/codegen/${f}`),
      ],
    );
  writeFileSync(join(here, "webkit-sources.ts"), out);
  console.log(
    `wrote webkit-sources.ts: ${bundles.length} bundles, ${nonUnified.length} standalone sources, ${privateHeaders.length} + ${bmallocHeaders.length} headers`,
  );
} else {
  const S = join(tree, "source");
  if (!existsSync(join(S, "common", "sources.txt")))
    throw new Error(`${tree} is not an ICU tree (no source/common/sources.txt)`);
  const sourcesTxt = (dir: string): string[] =>
    readFileSync(join(S, dir, "sources.txt"), "utf8")
      .split(/\r?\n/)
      .map(s => s.trim())
      .filter(s => s.length > 0)
      .map(s => `${dir}/${s}`);
  const version =
    readFileSync(join(S, "common", "unicode", "uvernum.h"), "utf8").match(/#define U_ICU_VERSION "([^"]+)"/)?.[1] ??
    tree;
  const out =
    banner(`ICU ${version}`) +
    list("icuCommonSources", "source/common/sources.txt. Relative to source/.", sourcesTxt("common")) +
    "\n" +
    list("icuI18nSources", "source/i18n/sources.txt.", sourcesTxt("i18n")) +
    "\n" +
    list("icuStubdataSources", "source/stubdata/sources.txt.", sourcesTxt("stubdata")) +
    "\n" +
    list("icuToolutilSources", "source/tools/toolutil/sources.txt.", sourcesTxt("tools/toolutil")) +
    "\n" +
    list("icuIcupkgSources", "source/tools/icupkg/sources.txt.", sourcesTxt("tools/icupkg"));
  writeFileSync(join(here, "icu-sources.ts"), out);
  console.log(`wrote icu-sources.ts`);
}
