export interface SchemaFile {
  origin: Origin;
  moduleDefinition: ModuleDefinition | null;
  /** In dependency order. */
  types: NamedType[];
  functions: FunctionDefinition[];
}

export interface Tables {
  /** Made into `Identifier`s per VM on first use. */
  memberNames: string[];
  /** Made into `JSString`s per VM on first use. */
  enumerationValues: string[];
  /** Returned dictionaries: a run of `memberNames`, made into a `Structure` per global object on first use. */
  objectStructures: { firstMemberNameIndex: number; memberCount: number }[];
  classes: ClassType[];
}

const banner = (origin: Origin | null) =>
  `// Generated by src/codegen/bindgen.ts${origin ? ` from ${origin.stem}.bind.ts` : ""}. Do not edit.\n`;

function indent(text: string, by: number): string {
  const pad = " ".repeat(by);
  return text
    .split("\n")
    .map(line => (line.length > 0 ? pad + line : line))
    .join("\n");
}

// ───────────────────────────── analysis ─────────────────────────────

function walk(type: Type, visit: (type: Type) => void, seen = new Set<Type>()): void {
  if (seen.has(type)) return;
  seen.add(type);
  visit(type);
  for (const dependency of type.dependencies) walk(dependency, visit, seen);
}

/** Marks which direction each dictionary travels and gives every table entry its index. */
export function analyze(files: readonly SchemaFile[]): Tables {
  const tables: Tables = { memberNames: [], enumerationValues: [], objectStructures: [], classes: [] };
  const markAccepted = (type: Type) => walk(type, t => void (t instanceof DictionaryType && (t.accepted = true)));
  const markReturned = (type: Type) =>
    walk(type, t => void ((t instanceof DictionaryType || t instanceof EnumType) && (t.returned = true)));
  for (const file of files) {
    for (const type of file.types) {
      if (type instanceof DictionaryType && type.fromJS) markAccepted(type);
      if (!(type instanceof ClassType)) continue;
      type.classIndex = tables.classes.push(type) - 1;
      for (const arg of type.construct?.args ?? []) markAccepted(arg.type);
      for (const method of [...type.methods, ...type.staticMethods]) {
        for (const arg of method.args) markAccepted(arg.type);
        markReturned(method.returns);
      }
      for (const getter of type.getters) {
        markReturned(getter.type);
        if (getter.hasSetter) markAccepted(getter.type);
      }
    }
    for (const fn of file.functions) {
      for (const signature of fn.signatures) {
        for (const arg of signature.args) markAccepted(arg.type);
        markReturned(signature.returns);
      }
    }
    assert(
      file.functions.length === 0 ||
        !files.some(other => other.types.some(type => type.name === file.origin.namespace)),
      `${file.origin.stem}.bind.ts: a type is named like the namespace of this file's functions`,
    );
  }
  for (const file of files) {
    for (const type of file.types) {
      if (type instanceof EnumType) {
        if (!type.returned) continue;
        type.firstEnumerationValueIndex = tables.enumerationValues.length;
        tables.enumerationValues.push(...type.spellings.map(([canonical]) => canonical));
      } else if (type instanceof DictionaryType) {
        if (type.accepted) {
          type.firstMemberNameIndex = tables.memberNames.length;
          tables.memberNames.push(...type.names);
        }
        if (type.returned) {
          type.structureIndex = tables.objectStructures.length;
          tables.objectStructures.push({
            firstMemberNameIndex: tables.memberNames.length,
            memberCount: type.members.length,
          });
          tables.memberNames.push(...type.members.map(member => member.name));
          const scope = type.origin!;
          for (const member of type.members) {
            assert(
              !type.accepted || member.type.rustType(scope) === member.type.rustResultFieldType(scope),
              `${type.name}.${member.name}: ${member.type.tsType} has different Rust types as an argument and as a result; split the dictionary`,
            );
          }
        }
      }
    }
  }
  const symbols = files.flatMap(file => [
    ...file.functions.flatMap(fn => fn.signatures.map(signature => thunkSymbol(fn, signature))),
    ...file.types.flatMap(type => (type instanceof ClassType ? classSymbols(type) : [])),
  ]);
  assert(new Set(symbols).size === symbols.length, "two bindings make the same symbol");
  return tables;
}

// ───────────────────────────── C++ ─────────────────────────────

const implementationType = (type: Type) => `${type.idlType}::ImplementationType`;
const externType = (type: Type): string =>
  type instanceof WithValueType
    ? `::Bun::Bindgen::ExternWithValue<${externType(type.inner)}>`
    : `::Bun::Bindgen::ExternTraits<${implementationType(type)}>::ExternType`;

/** True of a value that is not a cell. */
const valueTests: Partial<Record<string, (value: string) => string>> = {
  undefined: value => `${value}.isUndefined()`,
  null: value => `${value}.isNull()`,
  boolean: value => `${value}.isBoolean()`,
  number: value => `${value}.isNumber()`,
  bigint: value => `::Bun::Bindgen::isBigInt32(${value})`,
};
/** True of `cell`, whose type byte is `type`. */
const cellTests: Partial<Record<string, string>> = {
  bigint: "type == JSC::HeapBigIntType",
  string: "type == JSC::StringType",
  stringObject: "type == JSC::StringObjectType || type == JSC::DerivedStringObjectType",
  array: "type == JSC::ArrayType || type == JSC::DerivedArrayType",
  arrayBuffer: "type == JSC::ArrayBufferType",
  arrayBufferView: "JSC::isTypedArrayTypeIncludingDataView(type)",
};

/**
 * C++ that declares `choice`, an index into the `choices` it returns: the distinct values of `byKind`. One test of whether
 * `value` is a cell, then the cheaper tests first, none twice, none that can run JavaScript, and none for a kind that is
 * treated as "other" is.
 */
function cppChooseByKind<T>(value: string, byKind: ReadonlyMap<Kind | "other", T>, key: (choice: T) => string) {
  const choices: T[] = [];
  const indexOf = (choice: T) => {
    const index = choices.findIndex(other => key(other) === key(choice));
    return index >= 0 ? index : choices.push(choice) - 1;
  };
  const other = indexOf(byKind.get("other")!);
  const ofValue = new Map<number, string[]>();
  const ofType = new Map<number, string[]>();
  const ofClass = new Map<number, string[]>();
  const add = (tests: Map<number, string[]>, index: number, test: string | undefined) => {
    if (test !== undefined && index !== other) tests.set(index, [...(tests.get(index) ?? []), test]);
  };
  for (const [kind, choice] of byKind) {
    if (kind === "other") continue;
    const index = indexOf(choice);
    if (typeof kind === "object") {
      add(ofClass, index, `JSC::JSCastingHelpers::inherits<${kind.cpp}>(cell)`);
    } else {
      add(ofValue, index, valueTests[kind]?.(value));
      add(ofType, index, cellTests[kind]);
    }
  }
  const chain = (...tests: Map<number, string[]>[]) =>
    tests
      .flatMap(map => [...map])
      .map(([index, conditions]) => {
        const nullish = [`${value}.isUndefined()`, `${value}.isNull()`];
        const merged = nullish.every(test => conditions.includes(test))
          ? [`${value}.isUndefinedOrNull()`, ...conditions.filter(test => !nullish.includes(test))]
          : conditions;
        return `if (${merged.join(" || ")})\n    choice = ${index};`;
      })
      .join("\nelse ");
  const cell = `${ofClass.size > 0 ? "auto* cell" : "JSC::JSType type"} = ${value}.asCell()${ofClass.size > 0 ? "" : "->type()"};
${ofClass.size > 0 && ofType.size > 0 ? "JSC::JSType type = cell->type();\n" : ""}${chain(ofType, ofClass)}`;
  const hasCellTests = ofType.size + ofClass.size > 0;
  let tree = "";
  if (hasCellTests && ofValue.size > 0) tree = `if (${value}.isCell()) {\n${indent(cell, 4)}\n} else ${chain(ofValue)}`;
  else if (hasCellTests) tree = `if (${value}.isCell()) {\n${indent(cell, 4)}\n}`;
  else if (ofValue.size > 0) tree = chain(ofValue);
  return { choices, code: `unsigned choice = ${other};${tree && "\n"}${tree}` };
}

function layoutAssert(cppType: string, type: Type): string {
  const { size, align } = type.layout();
  return `static_assert(sizeof(${cppType}) == ${size} && alignof(${cppType}) == ${align});`;
}

function humanReadableEnum(type: EnumType): string {
  const quoted = type.spellings.map(([canonical]) => `\\"${canonical}\\"`);
  if (quoted.length <= 2) return quoted.join(" or ");
  return `${quoted.slice(0, -1).join(", ")}, or ${quoted.at(-1)}`;
}

/** Value-initialization zeroes a struct whose constructor is implicit, and these hold the buffers of string views. */
const cppDefaultConstructor = (name: string) => `    ${name}() {}`;

function cppHeaderForUnion(type: UnionType): string {
  const { name, alternatives } = type;
  const idlTypes = alternatives.map(a => a.type.idlType).join(", ");
  const { choices, code } = cppChooseByKind("value", type.alternativesByKind, choice => choice.join());
  const cases = choices.map((choice, index) => {
    if (choice.length === 0) return "";
    const attempts = choice.map(i => {
      const alternative = alternatives[i];
      const member = `result.${alternative.name}`;
      if (alternative.type.kinds !== "any" && alternative.type.refusesSomeOfItsKinds)
        return `if (auto converted = ::Bun::tryConvertIDL<${alternative.type.idlType}>(lexicalGlobalObject, value, ctx)) {
    ${member} = ::std::move(*converted);
    result.tag = ${i};
    return;
}`;
      if (alternative.type instanceof UnitType) return `result.tag = ${i};\nreturn;`;
      const convert = alternative.type.convertsInPlace
        ? alternative.type.cppConvertInto(`${member}.emplace()`, "value", "ctx", "")
        : `${member} = ::Bun::convertIDL<${alternative.type.idlType}>(lexicalGlobalObject, value, ctx);`;
      return `result.tag = ${i};\nscope.release();\n${convert}\nreturn;`;
    });
    const refused = attempts.at(-1)!.endsWith("return;") ? "" : "\n    break;";
    return `case ${index}: {\n${indent(attempts.join("\n"), 4)}${refused}\n}`;
  });
  const canMatchNothing = cases.some(text => text.length === 0 || text.endsWith("break;\n}"));
  const held = alternatives.filter(a => !(a.type instanceof UnitType));
  return `
namespace Bun {
namespace Bindgen {
namespace Generated {
// A member for each alternative, so that the one \`tag\` names is converted where it stays. A large one is made when chosen.
struct ${name} {
${cppDefaultConstructor(name)}
${held.map(a => `    ${a.type.convertsInPlace ? `::std::optional<${implementationType(a.type)}>` : implementationType(a.type)} ${a.name};`).join("\n")}
    ::std::uint8_t tag;
};
struct Extern${name} {
    union {
${alternatives.map(a => `        ${externType(a.type)} ${a.name};`).join("\n")}
    } data;
    ::std::uint8_t tag;
};
${layoutAssert(`Extern${name}`, type)}
struct IDL${name} : ::WebCore::IDLType<${name}> {};
}
template<> struct ExternTraits<Generated::${name}> {
    using ExternType = Generated::Extern${name};
    static ExternType convertToExtern(Generated::${name}&& value)
    {
        ExternType result;
        result.tag = value.tag;
        switch (value.tag) {
${held
  .map(
    a => `        case ${alternatives.indexOf(a)}:
            result.data.${a.name} = ExternTraits<${implementationType(a.type)}>::convertToExtern(::std::move(${a.type.convertsInPlace ? "*" : ""}value.${a.name}));
            break;`,
  )
  .join("\n")}
        }
        return result;
    }
};
}
template<> struct IDLHumanReadableName<Bindgen::Generated::IDL${name}> : IDLHumanReadableName<::Bun::IDLOrderedUnion<${idlTypes}>> {};
}
template<> struct WebCore::Converter<${type.idlType}> : ::Bun::DefaultContextConverter<${type.idlType}> {
    template<::Bun::IDLConversionContext Ctx>
    static ReturnType convert(JSC::JSGlobalObject& globalObject, JSC::JSValue value, Ctx& ctx)
    {
        ReturnType result;
        convertInto(globalObject, value, ctx, result);
        return result;
    }

    template<::Bun::IDLConversionContext Ctx>
    static void convertInto(JSC::JSGlobalObject& lexicalGlobalObject, JSC::JSValue value, Ctx& ctx, ReturnType& result)
    {
        [[maybe_unused]] auto* globalObject = &lexicalGlobalObject;
        auto& vm = JSC::getVM(globalObject);
        auto scope = DECLARE_THROW_SCOPE(vm);
${indent(code, 8)}
        switch (choice) {
${indent(cases.filter(text => text.length > 0).join("\n"), 8)}
        }${canMatchNothing ? `\n        ctx.template throwNoMatchInUnion<${idlTypes}>(lexicalGlobalObject, scope);` : ""}
    }
};
`;
}

function cppHeaderForType(type: NamedType): string {
  const { name } = type;
  if (type instanceof ClassType) return cppHeaderForClass(type);
  if (type instanceof EnumType) {
    return `
namespace Bun {
namespace Bindgen {
namespace Generated {
enum class ${name} : ::std::uint32_t {
${type.variants.map(variant => `    ${variant},`).join("\n")}
};
}
template<> struct ExternTraits<Generated::${name}> : TrivialExtern<Generated::${name}> {};
}
template<> struct IDLHumanReadableName<${type.idlType}> : BaseIDLHumanReadableName {
    static constexpr auto humanReadableName = ::std::to_array("${humanReadableEnum(type)}");
};
}
template<> std::optional<${type.cpp}> WebCore::parseEnumerationFromString<${type.cpp}>(const WTF::String&);
template<> std::optional<${type.cpp}> WebCore::parseEnumeration<${type.cpp}>(JSC::JSGlobalObject&, JSC::JSValue);
`;
  }
  if (type instanceof UnionType) return cppHeaderForUnion(type);
  assert(type instanceof DictionaryType);
  if (!type.accepted) return "";
  return `
namespace Bun {
namespace Bindgen {
namespace Generated {
struct ${name} {
${cppDefaultConstructor(name)}
${type.members.map(member => `    ${implementationType(member.type)} ${member.internalName};`).join("\n")}
};
struct Extern${name} {
${type.members.map(member => `    ${externType(member.type)} ${member.internalName};`).join("\n")}
};
${layoutAssert(`Extern${name}`, type)}
void convert${name}(JSC::JSGlobalObject&, JSC::JSValue, ${name}& result);
}
template<> struct ExternTraits<Generated::${name}> {
    using ExternType = Generated::Extern${name};
    static ExternType convertToExtern(Generated::${name}&& value)
    {
        return ExternType {
${type.members
  .map(
    member =>
      `            .${member.internalName} = ExternTraits<${implementationType(member.type)}>::convertToExtern(::std::move(value.${member.internalName})),`,
  )
  .join("\n")}
        };
    }
};
}
template<> struct IDLHumanReadableName<::WebCore::IDLDictionary<Bindgen::Generated::${name}>> : BaseIDLHumanReadableName {
    static constexpr auto humanReadableName = ::std::to_array("${type.userFacingName}");
};
}
${
  type.holdsJSValue || type.borrowsFrame
    ? `template<> struct WebCore::IDLDictionary<${type.cpp}> : ::Bun::Bindgen::IDLStackOnlyDictionary<${type.cpp}> {};\n`
    : ""
}template<> ${type.cpp} WebCore::convertDictionary<${type.cpp}>(JSC::JSGlobalObject&, JSC::JSValue);
`;
}

export function cppHeader(file: SchemaFile): string {
  const headers = new Set<string>();
  for (const type of file.types) for (const dependency of type.dependencies) dependency.getHeaders(headers);
  if (file.types.some(type => type instanceof ClassType)) headers.add("Bindgen/JSBindgenObject.h");
  headers.delete(`Generated${file.origin.namespace}.h`);
  return `${banner(file.origin)}#pragma once
#include "root.h"
#include "Bindgen.h"
#include "Bindgen/IDLConvert.h"
#include "JSDOMConvertDictionary.h"
#include "JSDOMConvertEnumeration.h"
${[...headers].map(header => `#include "${header}"\n`).join("")}${file.types.map(cppHeaderForType).join("")}${
    file.functions.length > 0
      ? `
namespace Bun::Bindgen::Generated::${file.origin.namespace} {
${file.functions.map(fn => `JSC_DECLARE_HOST_FUNCTION(${hostFunctionName(fn)});`).join("\n")}
}
`
      : ""
  }`;
}

const hostFunctionName = (fn: FunctionDefinition) =>
  `js${fn.name[0] === "_" ? fn.name : fn.name[0].toUpperCase() + fn.name.slice(1)}`;

function cppSourceForEnum(type: EnumType): string {
  const pairs = type.spellings
    .flatMap((spellings, index) => spellings.map(spelling => [spelling, type.variants[index]] as const))
    .sort(([a], [b]) => (a < b ? -1 : 1));
  const pair = `::std::pair<::WTF::ComparableASCIILiteral, ${type.cpp}>`;
  return `
template<> std::optional<${type.cpp}> WebCore::parseEnumerationFromString<${type.cpp}>(const WTF::String& string)
{
    static constexpr ::WTF::SortedArrayMap mapping { ::std::to_array<${pair}>({
${pairs.map(([spelling, variant]) => `        ${pair} { ${asciiLiteral(spelling)}, ${type.cpp}::${variant} },`).join("\n")}
    }) };
    if (auto* value = mapping.tryGet(string)) [[likely]]
        return *value;
    return std::nullopt;
}

template<> std::optional<${type.cpp}> WebCore::parseEnumeration<${type.cpp}>(JSC::JSGlobalObject& globalObject, JSC::JSValue value)
{
    return parseEnumerationFromString<${type.cpp}>(value.toWTFString(&globalObject));
}
`;
}

function cppSourceForDictionary(type: DictionaryType): string {
  if (!type.accepted) return "";
  let nameIndex = 0;
  const members = type.members.map((member, i) => {
    const reads = member.names.map((_, alt) => {
      const read = `value${i} = members.get(${nameIndex++});\n        RETURN_IF_EXCEPTION(scope, void());`;
      return alt === 0
        ? read
        : `if (value${i}.isUndefined()) {\n            ${read.replace("\n", "\n    ")}\n        }`;
    });
    const qualified = `${type.userFacingName}.${member.name}`;
    const convert = `${indent(member.type.cppConvertInto(`result.${member.internalName}`, `value${i}`, `ctx${i}`, qualified), 8).trimStart()}\n        RETURN_IF_EXCEPTION(scope, void());`;
    let body: string;
    if (member.type instanceof DefaultType) {
      const absent = member.type.onNull ? "isUndefinedOrNull" : "isUndefined";
      body = `if (value${i}.${absent}()) {
            ${member.type.cppAssign(`result.${member.internalName}`, member.type.value).replaceAll("\n", "\n            ")}
        } else {
            ${convert.replaceAll("\n", "\n    ")}
        }`;
    } else if (member.type.permitsUndefined) {
      body = convert;
    } else {
      body = `if (value${i}.isUndefined()) [[unlikely]] {
            ctx${i}.throwRequired(lexicalGlobalObject, scope);
            return;
        }
        ${convert}`;
    }
    return `    {
        ::JSC::JSValue value${i};
        [[maybe_unused]] auto ctx${i} = ::Bun::Bindgen::LiteralConversionContext { ${asciiLiteral(qualified)} };
        ${reads.join("\n        ")}
        ${body}
    }`;
  });
  const count = type.names.length;
  return `
void Bun::Bindgen::Generated::convert${type.name}(JSC::JSGlobalObject& lexicalGlobalObject, JSC::JSValue value, ${type.cpp}& result)
{
    auto* globalObject = &lexicalGlobalObject;
    auto& vm = JSC::getVM(globalObject);
    auto scope = DECLARE_THROW_SCOPE(vm);
    [[maybe_unused]] auto ctx = ::Bun::Bindgen::LiteralConversionContext { ${asciiLiteral(type.userFacingName)} };
    auto* object = value.getObject();
${
  type.allowNonObject
    ? `    if (!object || object->isCallable()) {
        ${type.cppAssign("result", {}).replaceAll("\n", "\n        ")}
        return;
    }`
    : `    if (!object) [[unlikely]] {
        ctx.throwNotObject(lexicalGlobalObject, scope);
        return;
    }`
}
${
  type.allowArray
    ? ""
    : `    bool isArray = JSC::isArray(globalObject, value);
    RETURN_IF_EXCEPTION(scope, void());
    if (isArray) [[unlikely]] {
        ctx.throwNotObject(lexicalGlobalObject, scope);
        return;
    }
`
}    ::Bun::Bindgen::DictionaryMemberReader members(vm, globalObject, object, ${type.firstMemberNameIndex}, ${count});
${members.join("\n")}
}

template<> ${type.cpp} WebCore::convertDictionary<${type.cpp}>(JSC::JSGlobalObject& globalObject, JSC::JSValue value)
{
    ${type.cpp} result;
    ::Bun::Bindgen::Generated::convert${type.name}(globalObject, value, result);
    return result;
}
${
  type.fromJS
    ? `
extern "C" bool Bun__Bindgen__${type.name}__fromJS(JSC::JSGlobalObject* globalObject, JSC::EncodedJSValue value, ::Bun::Bindgen::Generated::Extern${type.name}* result)
{
    auto& vm = JSC::getVM(globalObject);
    auto scope = DECLARE_THROW_SCOPE(vm);
    ${type.cpp} converted;
    ::Bun::Bindgen::Generated::convert${type.name}(*globalObject, JSC::JSValue::decode(value), converted);
    RETURN_IF_EXCEPTION(scope, false);
    *result = ::Bun::Bindgen::ExternTraits<${type.cpp}>::convertToExtern(::std::move(converted));
    return true;
}
`
    : ""
}`;
}

const overloadSuffix = (fn: FunctionDefinition, signature: Signature) =>
  fn.signatures.length > 1 ? `${fn.signatures.indexOf(signature) + 1}` : "";

const thunkSymbol = (fn: FunctionDefinition, signature: Signature) =>
  `Bun__Bindgen__${fn.origin!.namespace}__${fn.name.replace(/^_+/, "")}${overloadSuffix(fn, signature)}`;

/** Lines that declare `variable` as what `value` converts to. */
function cppDeclareConverted(type: Type, variable: string, value: string, ctx: string, name: string): string[] {
  const declaration = `${implementationType(type)} ${variable}`;
  const absent = type instanceof DefaultType && `${value}.${type.onNull ? "isUndefinedOrNull" : "isUndefined"}()`;
  if (!type.convertsInPlace) {
    const convert = type.cppConvert(value, ctx, name);
    return [`${declaration} = ${absent ? `${absent} ? ${type.toCpp(type.value)} : ${convert}` : convert};`];
  }
  const into = type.cppConvertInto(variable, value, ctx, name).split("\n");
  if (!absent) return [`${declaration};`, ...into];
  return [
    `${declaration};`,
    `if (${absent}) {`,
    ...type
      .cppAssign(variable, type.value)
      .split("\n")
      .map(line => `    ${line}`),
    "} else {",
    ...into.map(line => `    ${line}`),
    "}",
  ];
}

/** Converts the arguments, then returns what `symbol(globalObject, ...leading, ...converted)` returns. */
function cppCallBody(signature: Signature, symbol: string, leading: readonly string[] = []): string {
  const lines: string[] = [];
  if (signature.requiredCount > 0) {
    lines.push(`if (callFrame->argumentCount() < ${signature.requiredCount}) [[unlikely]]
        return JSC::throwVMError(globalObject, scope, WebCore::createNotEnoughArgumentsErrorBun(globalObject));`);
  }
  const rereads: string[] = [];
  signature.args.forEach(({ name, type }, i) => {
    const argument = i < signature.requiredCount ? "uncheckedArgument" : "argument";
    lines.push(`::JSC::EnsureStillAliveScope argument${i} = callFrame->${argument}(${i});`);
    lines.push(`[[maybe_unused]] auto ctx${i} = ::Bun::Bindgen::LiteralConversionContext { ${asciiLiteral(name)} };`);
    const convert = type.cppConvert(`argument${i}.value()`, `ctx${i}`, name);
    // Converting a later argument can run JavaScript that detaches or resizes the buffer.
    if (type.borrowsHeap && i < signature.args.length - 1)
      rereads.push(`value${i} = ${convert};`, `scope.assertNoException();`);
    lines.push(...cppDeclareConverted(type, `value${i}`, `argument${i}.value()`, `ctx${i}`, name));
    lines.push(`RETURN_IF_EXCEPTION(scope, {});`);
  });
  lines.push(...rereads);
  const args = signature.args.map(({ type }, i) => {
    const converted = `::Bun::Bindgen::ExternTraits<${implementationType(type)}>::convertToExtern(::std::move(value${i}))`;
    return type instanceof WithValueType
      ? `${externType(type)} { ${converted}, JSC::JSValue::encode(argument${i}.value()) }`
      : converted;
  });
  lines.push(`RELEASE_AND_RETURN(scope, ${symbol}(${["globalObject", ...leading, ...args].join(", ")}));`);
  return lines.map(line => `    ${line}`).join("\n");
}

const cppPrologue = `    auto& vm = JSC::getVM(globalObject);
    auto scope = DECLARE_THROW_SCOPE(vm);`;

const cppExtern = (symbol: string, signature: Signature, leading: readonly string[] = []) =>
  `extern "C" JSC::EncodedJSValue ${symbol}(${["JSC::JSGlobalObject*", ...leading, ...signature.args.map(arg => externType(arg.type))].join(", ")});`;

