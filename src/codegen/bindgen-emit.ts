export interface Tables {
  /** Made into `Identifier`s per VM on first use. */
  memberNames: string[];
  /** Made into `JSString`s per VM on first use. */
  enumerationValues: string[];
  classes: ClassType[];
}

const banner = (origin: Origin | null) =>
  `// Generated by src/codegen/bindgen.ts${origin ? ` from ${origin.stem}.bind.ts` : ""}. Do not edit.\n`;

// ───────────────────────────── analysis ─────────────────────────────

function walk(type: Type, visit: (type: Type) => void, seen = new Set<Type>()): void {
  if (seen.has(type)) return;
  seen.add(type);
  assert(
    !(type instanceof NamedType) || type.origin,
    `${type.constructor.name}: used but not exported from a .bind.ts file`,
  );
  visit(type);
  for (const dependency of type.dependencies) walk(dependency, visit, seen);
}

/** Marks which direction each named type travels and gives every table entry its index. */
export function analyze(files: readonly SchemaFile[]): Tables {
  const tables: Tables = { memberNames: [], enumerationValues: [], classes: [] };
  const markAccepted = (type: Type) => walk(type, t => void (t instanceof NamedType && (t.accepted = true)));
  const markReturned = (type: Type) => walk(type, t => void (t instanceof NamedType && (t.returned = true)));
  for (const file of files) {
    for (const type of file.types) {
      if (type instanceof DictionaryType && type.fromJS) markAccepted(type);
      if (!(type instanceof ClassType)) continue;
      type.classIndex = tables.classes.push(type) - 1;
      for (const arg of type.construct?.args ?? []) markAccepted(arg.type);
      for (const method of type.methods) {
        for (const arg of method.args) markAccepted(arg.type);
        markReturned(method.returns);
      }
      for (const getter of [...type.getters, ...type.staticGetters]) {
        markReturned(getter.type);
        if (getter.hasSetter) markAccepted(getter.type);
      }
    }
    for (const fn of file.functions) {
      for (const signature of fn.signatures) {
        for (const arg of signature.args) markAccepted(arg.type);
        markReturned(signature.returns);
      }
    }
    assert(
      !files.some(other =>
        other.types.some(type => type.cpp === `Bun::Bindgen::Generated::${file.origin.namespace}`),
      ) ||
        (file.functions.length === 0 && !file.types.some(type => type instanceof ClassType && type.construct)),
      `${file.origin.stem}.bind.ts: a type is named like the namespace of this file's functions`,
    );
  }
  for (const file of files) {
    for (const type of file.types) {
      if (type instanceof EnumerationType) {
        if (!type.returned) continue;
        type.firstEnumerationValueIndex = tables.enumerationValues.length;
        tables.enumerationValues.push(...type.spellings.map(([canonical]) => canonical));
      } else if (type instanceof DictionaryType) {
        if (type.accepted) {
          type.firstMemberNameIndex = tables.memberNames.length;
          tables.memberNames.push(...type.names);
        }
        if (type.returned) {
          type.firstReturnedMemberNameIndex = tables.memberNames.length;
          tables.memberNames.push(...type.members.map(member => member.name));
          const scope = type.origin!;
          for (const member of type.members) {
            assert(
              !type.accepted || member.type.rustType(scope) === member.type.rustResultFieldType(scope),
              `${type.name}.${member.name}: ${member.type.tsType} has different Rust types as an argument and as a result; split the dictionary`,
            );
          }
        }
      }
    }
  }
  const symbols = files.flatMap(file => [
    ...file.functions.flatMap(fn => fn.signatures.map(signature => thunkSymbol(fn, signature))),
    ...file.types.flatMap(type => (type instanceof ClassType ? classSymbols(type) : [])),
  ]);
  const repeated = symbols.filter((symbol, i) => symbols.indexOf(symbol) !== i);
  assert(repeated.length === 0, `two bindings make the same symbol: ${repeated.join(", ")}`);
  return tables;
}

// ───────────────────────────── C++ ─────────────────────────────

const implementationType = (type: Type) => `${type.idlType}::ImplementationType`;
const externType = (type: Type): string =>
  type.passesValue
    ? `Bun::Bindgen::ExternWithValue<Bun::Bindgen::ExternOf<${type.idlType}>>`
    : `Bun::Bindgen::ExternOf<${type.idlType}>`;
const toExtern = (variable: string) => `Bun::Bindgen::toExtern(${variable})`;

/** How C++ tells that a value is of a kind: `ofValue` if it is not a cell, `ofCell` of `cell`, by its type byte. */
const kindTests: Record<Exclude<ValueKind, JSClass>, { ofValue?: (value: string) => string; ofCell?: string }> = {
  undefined: { ofValue: value => `${value}.isUndefined()` },
  null: { ofValue: value => `${value}.isNull()` },
  boolean: { ofValue: value => `${value}.isBoolean()` },
  number: { ofValue: value => `${value}.isNumber()` },
  bigint: { ofValue: value => `${value}.isBigInt32()`, ofCell: "cell->isHeapBigInt()" },
  string: { ofCell: "cell->isString()" },
  stringObject: { ofCell: "cell->inherits<JSC::StringObject>()" },
  array: { ofCell: "JSC::isJSArray(cell)" },
  arrayBuffer: { ofCell: "cell->inherits<JSC::JSArrayBuffer>()" },
  arrayBufferView: { ofCell: "cell->inherits<JSC::JSArrayBufferView>()" },
};

/**
 * C++ that declares `choice`, an index into the `outcomes` it returns: the distinct values of `byKind`, "other"'s first.
 * `condition`, if the choice is that simple, is true of `outcomes[1]` and false of `outcomes[0]`.
 */
function cppChooseByKind<T>(value: string, byKind: ReadonlyMap<ValueKind | "other", T>, choice = "choice") {
  const other = byKind.get("other")!;
  const outcomes = [...new Set([other, ...byKind.values()])];
  const ofValue = new Map<T, string[]>();
  const ofType = new Map<T, string[]>();
  const ofClass = new Map<T, string[]>();
  for (const [kind, outcome] of byKind) {
    if (kind === "other" || outcome === other) continue;
    const add = (tests: Map<T, string[]>, test: string | undefined) => {
      if (test !== undefined) tests.set(outcome, [...(tests.get(outcome) ?? []), test]);
    };
    if (typeof kind === "object") {
      add(ofClass, `cell->inherits<${kind.cpp}>()`);
    } else {
      add(ofValue, kindTests[kind].ofValue?.(value));
      add(ofType, kindTests[kind].ofCell);
    }
  }
  const nullish = [`${value}.isUndefined()`, `${value}.isNull()`];
  const chain = (...tests: Map<T, string[]>[]) =>
    tests
      .flatMap(map => [...map])
      .map(([outcome, conditions]) => {
        const merged = nullish.every(test => conditions.includes(test))
          ? [`${value}.isUndefinedOrNull()`, ...conditions.filter(test => !nullish.includes(test))]
          : conditions;
        return { condition: merged.join(" || "), index: outcomes.indexOf(outcome) };
      });
  const cppChain = (...tests: Map<T, string[]>[]) =>
    chain(...tests)
      .map(({ condition, index }) => `if (${condition})\n    ${choice} = ${index};`)
      .join("\nelse ");
  const lines = [`unsigned ${choice} = 0;`];
  if (ofType.size + ofClass.size > 0) {
    lines.push(`if (${value}.isCell()) {`, `    auto* cell = ${value}.asCell();`);
    lines.push(indent(cppChain(ofType, ofClass), 4), ofValue.size > 0 ? `} else ${cppChain(ofValue)}` : "}");
  } else if (ofValue.size > 0) {
    lines.push(cppChain(ofValue));
  }
  const isSimple = outcomes.length === 2 && ofType.size + ofClass.size === 0;
  return { outcomes, code: lines.join("\n"), condition: isSimple ? chain(ofValue)[0].condition : undefined };
}

function layoutAssert(cppType: string, type: Type): string {
  const { size, align } = type.layout();
  return `static_assert(sizeof(${cppType}) == ${size} && alignof(${cppType}) == ${align});`;
}

function humanReadableEnumeration(type: EnumerationType): string {
  const quoted = type.spellings.map(([canonical]) => asciiLiteral(`"${canonical}"`).slice(1, -3));
  if (quoted.length <= 2) return quoted.join(" or ");
  return `${quoted.slice(0, -1).join(", ")}, or ${quoted.at(-1)}`;
}

/** Value-initialization zeroes a struct whose constructor is implicit, and these hold the buffers of string views. */
const cppDefaultConstructor = (type: NamedType) =>
  `${type.needsLifetime ? "    WTF_FORBID_HEAP_ALLOCATION;\n\npublic:\n" : ""}    ${type.name}() {}`;

/** C++ that offers `value` to `candidates`, indices of alternatives, in order. All but the last may refuse it. */
function cppConvertToAlternative(type: UnionType, candidates: readonly number[]): string {
  return candidates
    .map(i => {
      const { name, type: alternative } = type.alternatives[i];
      const member = `result.${name}`;
      if (alternative.refuses)
        return `if (auto converted = Bun::tryConvertIDL<${alternative.idlType}>(*globalObject, value, ctx)) {
    ${member} = WTF::move(*converted);
    result.tag = ${i};
    return;
}
RETURN_IF_EXCEPTION(scope, void());`;
      if (alternative instanceof UnitType) return `result.tag = ${i};\nreturn;`;
      const convert = (target: string) => alternative.cppConvertInto(target, "value", "ctx", "", "");
      return `result.tag = ${i};
scope.release();
${alternative.convertsInPlace ? cppEmplace(member, convert) : convert(member)}
return;`;
    })
    .join("\n");
}

function cppHeaderForUnion(type: UnionType): string {
  const { name, alternatives } = type;
  /** As error messages list them: null last. */
  const idlTypes = alternatives
    .toSorted((a, b) => Number(a.type instanceof UnitType) - Number(b.type instanceof UnitType))
    .map(a => a.type.idlType)
    .join(", ");
  const { outcomes, code } = cppChooseByKind("value", type.alternativesByKind);
  const mayMatchNone = (candidates: readonly number[]) =>
    candidates.length === 0 || !!alternatives[candidates.at(-1)!].type.refuses;
  const cases = outcomes.flatMap((candidates, index) =>
    candidates.length === 0
      ? []
      : `case ${index}: {\n${indent(cppConvertToAlternative(type, candidates), 4)}${mayMatchNone(candidates) ? "\n    break;" : ""}\n}`,
  );
  const held = alternatives.filter(a => !(a.type instanceof UnitType));
  return `
namespace Bun::Bindgen::Generated {
struct ${name} {
${cppDefaultConstructor(type)}
${held.map(a => `    ${a.type.convertsInPlace ? `std::optional<${implementationType(a.type)}> ${a.name}` : `${implementationType(a.type)} ${a.name} {}`};`).join("\n")}
    uint8_t tag;
};
struct Extern${name} {
    union {
${alternatives.map(a => `        ${externType(a.type)} ${a.name};`).join("\n")}
    } data;
    uint8_t tag;
};
${layoutAssert(`Extern${name}`, type)}
}
template<> struct Bun::Bindgen::ExternTraits<${type.cpp}> {
    using ExternType = Bun::Bindgen::Generated::Extern${name};
    static ExternType convertToExtern(${type.cpp}&& value)
    {
        ExternType result;
        result.tag = value.tag;
        switch (value.tag) {
${held
  .map(
    a => `        case ${alternatives.indexOf(a)}:
            result.data.${a.name} = ${toExtern(`${a.type.convertsInPlace ? "*" : ""}value.${a.name}`)};
            break;`,
  )
  .join("\n")}
        }
        return result;
    }
};
template<> struct Bun::IDLHumanReadableName<${type.idlType}> : Bun::IDLHumanReadableName<Bun::IDLAlternatives<${idlTypes}>> {};
template<> struct WebCore::Converter<${type.idlType}> : Bun::DefaultContextConverter<${type.idlType}> {${
    type.needsLifetime
      ? ""
      : `
    template<Bun::IDLConversionContext Ctx>
    static ReturnType convert(JSC::JSGlobalObject& globalObject, JSC::JSValue value, Ctx& ctx)
    {
        ReturnType result;
        convertInto(globalObject, value, ctx, result);
        return result;
    }
`
  }
    template<Bun::IDLConversionContext Ctx>
    static void convertInto(JSC::JSGlobalObject& lexicalGlobalObject, JSC::JSValue value, Ctx& ctx, ReturnType& result)
    {
        auto* globalObject = &lexicalGlobalObject;
        auto& vm = JSC::getVM(globalObject);
        auto scope = DECLARE_THROW_SCOPE(vm);
${indent(code, 8)}
        switch (choice) {
${indent(cases.join("\n"), 8)}
        }${outcomes.some(mayMatchNone) ? `\n        ctx.template throwNoMatchInUnion<${idlTypes}>(*globalObject, scope);` : ""}
    }
};
`;
}

function cppHeaderForType(type: NamedType): string {
  const { name } = type;
  if (type instanceof ClassType) return cppHeaderForClass(type);
  if (type instanceof EnumerationType) {
    return `
namespace Bun::Bindgen::Generated {
enum class ${name} : uint32_t {
${type.variants.map(variant => `    ${variant},`).join("\n")}
};
}
template<> struct Bun::Bindgen::ExternTraits<${type.cpp}> : Bun::Bindgen::TrivialExtern<${type.cpp}> {};
template<> struct Bun::IDLHumanReadableName<${type.idlType}> : Bun::BaseIDLHumanReadableName {
    static constexpr auto humanReadableName = std::to_array("${humanReadableEnumeration(type)}");
};
template<> std::optional<${type.cpp}> WebCore::parseEnumerationFromString<${type.cpp}>(const WTF::String&);
template<> std::optional<${type.cpp}> WebCore::parseEnumeration<${type.cpp}>(JSC::JSGlobalObject&, JSC::JSValue);
`;
  }
  if (type instanceof UnionType) return type.accepted ? cppHeaderForUnion(type) : "";
  assert(type instanceof DictionaryType);
  if (!type.accepted) return "";
  return `
namespace Bun::Bindgen::Generated {
struct ${name} {
${cppDefaultConstructor(type)}
${type.members.map(member => `    ${implementationType(member.type)} ${member.fieldName};`).join("\n")}
};
struct Extern${name} {
${type.members.map(member => `    ${externType(member.type)} ${member.fieldName};`).join("\n")}
};
${layoutAssert(`Extern${name}`, type)}
}
template<> struct Bun::Bindgen::ExternTraits<${type.cpp}> {
    using ExternType = Bun::Bindgen::Generated::Extern${name};
    static ExternType convertToExtern(${type.cpp}&& value)
    {
        return ExternType {
${type.members.map(member => `            .${member.fieldName} = ${toExtern(`value.${member.fieldName}`)},`).join("\n")}
        };
    }
};
template<> struct Bun::IDLHumanReadableName<${type.idlType}> : Bun::BaseIDLHumanReadableName {
    static constexpr auto humanReadableName = std::to_array("${type.name}");
};
template<> void Bun::Bindgen::convertDictionaryInto<${type.cpp}>(JSC::JSGlobalObject&, JSC::JSValue, ${type.cpp}&);
${
  type.needsLifetime
    ? `template<> struct WebCore::IDLDictionary<${type.cpp}> : Bun::Bindgen::IDLStackOnlyDictionary<${type.cpp}> {};`
    : type.convertedByValue
      ? `template<> ${type.cpp} WebCore::convertDictionary<${type.cpp}>(JSC::JSGlobalObject&, JSC::JSValue);`
      : ""
}
`;
}

export function cppHeader(file: SchemaFile): string {
  const headers = new Set<string>();
  for (const type of file.types) for (const dependency of type.dependencies) dependency.getHeaders(headers);
  if (file.types.some(type => type instanceof ClassType)) headers.add("Bindgen/JSWrapper.h");
  headers.delete(`Generated${file.origin.namespace}.h`);
  const propertyCallbacks = [
    ...file.namespaces.map(cppNamespaceSignature),
    ...file.types.filter(type => type instanceof ClassType && type.construct).map(cppConstructorSignature),
  ];
  const declarations = [
    ...file.functions.map(fn => `JSC_DECLARE_HOST_FUNCTION(${hostFunctionName(fn)});`),
    ...propertyCallbacks.map(signature => `// A PropertyCallback of a static property table.\n${signature};`),
  ];
  return `${banner(file.origin)}#pragma once
#include "root.h"
#include "Bindgen/ExternTraits.h"
#include "Bindgen/IDLConvert.h"
#include "JSDOMConvertDictionary.h"
#include "JSDOMConvertEnumeration.h"
${[...headers].map(header => `#include "${header}"\n`).join("")}${file.types.map(cppHeaderForType).join("")}${
    declarations.length > 0
      ? `
namespace Bun::Bindgen::Generated::${file.origin.namespace} {
${declarations.join("\n")}
}
`
      : ""
  }`;
}

const hostFunctionName = (fn: FunctionDefinition) => `js${cap(fn.name.replace(/^_+/, ""))}`;

const cppNamespaceSignature = (namespace: NamespaceDefinition) =>
  `JSC::JSValue create${cap(namespace.name)}(JSC::VM& vm, JSC::JSObject* owner)`;
const cppConstructorSignature = (type: NamedType) =>
  `JSC::JSValue get${type.name}Constructor(JSC::VM& vm, JSC::JSObject* owner)`;

function cppSourceForNamespace(namespace: NamespaceDefinition, origin: Origin): string {
  return `
namespace Bun::Bindgen::Generated::${origin.namespace} {
${cppNamespaceSignature(namespace)}
{
    JSC::JSGlobalObject* globalObject = owner->globalObject();
    JSC::JSObject* object = ${
      namespace.call
        ? `JSC::JSFunction::create(vm, globalObject, ${namespace.call.length}, ${asciiLiteral(namespace.name)}, ${hostFunctionName(namespace.call)}, JSC::ImplementationVisibility::Public)`
        : `JSC::constructEmptyObject(globalObject, globalObject->objectPrototype(), std::min<unsigned>(${namespace.functions.length}, JSC::JSFinalObject::maxInlineCapacity))`
    };
${namespace.functions
  .map(
    fn =>
      `    object->putDirectNativeFunction(vm, globalObject, JSC::Identifier::fromString(vm, ${asciiLiteral(fn.name)}), ${fn.length}, ${hostFunctionName(fn)}, JSC::ImplementationVisibility::Public, JSC::NoIntrinsic, 0);`,
  )
  .join("\n")}
    return object;
}
}
`;
}

function cppSourceForEnum(type: EnumerationType): string {
  const pairs = type.spellings
    .flatMap((spellings, index) => spellings.map(spelling => [spelling, type.variants[index]] as const))
    .sort(([a], [b]) => (a < b ? -1 : 1));
  const pair = `std::pair<WTF::ComparableASCIILiteral, ${type.cpp}>`;
  return `
template<> std::optional<${type.cpp}> WebCore::parseEnumerationFromString<${type.cpp}>(const WTF::String& string)
{
    static constexpr WTF::SortedArrayMap mapping { std::to_array<${pair}>({
${pairs.map(([spelling, variant]) => `        { ${asciiLiteral(spelling)}, ${type.cpp}::${variant} },`).join("\n")}
    }) };
    if (auto* value = mapping.tryGet(string)) [[likely]]
        return *value;
    return std::nullopt;
}

template<> std::optional<${type.cpp}> WebCore::parseEnumeration<${type.cpp}>(JSC::JSGlobalObject& globalObject, JSC::JSValue value)
{
    return parseEnumerationFromString<${type.cpp}>(value.toWTFString(&globalObject));
}
`;
}

/** Made of literals, so it is static and a call stores nothing for it. */
const cppStaticContext = (variable: string, context: string) =>
  `[[maybe_unused]] static constinit auto ${variable} = Bun::Bindgen::${context};`;

function cppSourceForDictionary(type: DictionaryType): string {
  if (!type.accepted) return "";
  let nameIndex = 0;
  const members = type.members.map((member, i) => {
    const [first, ...others] = member.names.map(
      () => `members.get(${nameIndex++});\nRETURN_IF_EXCEPTION(scope, void());`,
    );
    const qualified = `${type.name}.${member.name}`;
    const lines = [
      cppStaticContext(`ctx${i}`, `LiteralConversionContext { ${asciiLiteral(qualified)} }`),
      `JSC::JSValue value${i} = ${first}`,
      ...others.map(read => `if (value${i}.isUndefined()) {\n${indent(`value${i} = ${read}`, 4)}\n}`),
    ];
    if (!member.type.takesUndefined)
      lines.push(`if (value${i}.isUndefined()) [[unlikely]] {
    ctx${i}.throwRequired(*globalObject, scope);
    return;
}`);
    lines.push(
      member.type.cppConvertInto(
        `result.${member.fieldName}`,
        `value${i}`,
        `ctx${i}`,
        qualified,
        "RETURN_IF_EXCEPTION(scope, void());",
      ),
    );
    return `    {\n${indent(lines.join("\n"), 8)}\n    }`;
  });
  const count = type.names.length;
  return `
template<> void Bun::Bindgen::convertDictionaryInto<${type.cpp}>(JSC::JSGlobalObject& lexicalGlobalObject, JSC::JSValue value, ${type.cpp}& result)
{
    auto* globalObject = &lexicalGlobalObject;
    auto& vm = JSC::getVM(globalObject);
    auto scope = DECLARE_THROW_SCOPE(vm);
    ${cppStaticContext("ctx", `LiteralConversionContext { ${asciiLiteral(type.name)} }`)}
    auto* object = value.getObject();
${
  type.nonObjectAsEmpty
    ? `    if (!object${type.nonObjectAsEmpty === "typeof" ? " || object->isCallable()" : ""}) {
${indent(type.cppAssign("result", {}), 8)}
        return;
    }`
    : `    if (!object) [[unlikely]] {
        ctx.throwNotObject(*globalObject, scope);
        return;
    }`
}
${
  type.allowArray
    ? ""
    : `    bool isArray = JSC::isArray(globalObject, value);
    RETURN_IF_EXCEPTION(scope, void());
    if (isArray) [[unlikely]] {
        ctx.throwNotObject(*globalObject, scope);
        return;
    }
`
}    Bun::Bindgen::DictionaryMemberReader members(vm, globalObject, object, ${type.firstMemberNameIndex}, ${count});
${members.join("\n")}
}
${
  type.needsLifetime || !type.convertedByValue
    ? ""
    : `
template<> ${type.cpp} WebCore::convertDictionary<${type.cpp}>(JSC::JSGlobalObject& globalObject, JSC::JSValue value)
{
    ${type.cpp} result;
    Bun::Bindgen::convertDictionaryInto(globalObject, value, result);
    return result;
}
`
}${
    type.fromJS
      ? `
extern "C" bool Bun__Bindgen__${type.name}__fromJS(JSC::JSGlobalObject* globalObject, JSC::EncodedJSValue value, Bun::Bindgen::Generated::Extern${type.name}* result)
{
    auto& vm = JSC::getVM(globalObject);
    auto scope = DECLARE_THROW_SCOPE(vm);
    ${type.cpp} converted;
    Bun::Bindgen::convertDictionaryInto(*globalObject, JSC::JSValue::decode(value), converted);
    RETURN_IF_EXCEPTION(scope, false);
    *result = ${toExtern("converted")};
    return true;
}
`
      : ""
  }`;
}

const overloadSuffix = (fn: FunctionDefinition, signature: Signature) =>
  fn.signatures.length > 1 ? `${fn.signatures.indexOf(signature) + 1}` : "";

const thunkSymbol = (fn: FunctionDefinition, signature: Signature) =>
  `Bun__Bindgen__${fn.origin!.namespace}__${fn.name.replace(/^_+/, "")}${overloadSuffix(fn, signature)}`;

/** Lines that declare `variable` as what `value` converts to. `check` is that of `cppConvertInto`. */
function cppDeclareConverted(
  type: Type,
  variable: string,
  value: string,
  ctx: string,
  name: string,
  check: string,
): string[] {
  if (!type.convertsInPlace)
    return [`auto ${variable} = ${type.cppConvert(value, ctx, name)};`, ...(type.conversionThrows ? [check] : [])];
  return [
    `${implementationType(type)} ${variable};`,
    ...type.cppConvertInto(variable, value, ctx, name, check).split("\n"),
  ];
}

/** Converts the arguments, then returns what `symbol(globalObject, ...leading, ...converted)` returns. */
function cppCallBody(signature: Signature, symbol: string, leading: readonly string[] = []): string {
  const lines: string[] = [];
  // Converting a later argument can run JavaScript that detaches or resizes a buffer.
  const readLast: string[] = [];
  signature.args.forEach(({ name, type, expected }, i) => {
    lines.push(`JSC::EnsureStillAliveScope argument${i} = callFrame->argument(${i});`);
    let ctx = `ctx${i}`;
    if (typeof expected === "string") {
      lines.push(cppStaticContext(ctx, `ArgumentMessageContext { ${asciiLiteral(name)}, ${asciiLiteral(expected)} }`));
    } else if (expected) {
      lines.push(
        `[[maybe_unused]] static constexpr WTF::ASCIILiteral expected${i}[] = { ${expected.map(asciiLiteral).join(", ")} };`,
      );
      // It holds the argument, so it is made where a conversion takes it.
      ctx = `Bun::Bindgen::asLvalue(Bun::Bindgen::NodeArgumentContext { ${asciiLiteral(name)}, expected${i}, argument${i}.value() })`;
    } else {
      lines.push(cppStaticContext(ctx, `LiteralConversionContext { ${asciiLiteral(name)} }`));
    }
    readLast.push(...type.cppReadLast(`converted${i}`, `argument${i}.value()`));
    lines.push(
      ...cppDeclareConverted(
        type,
        `converted${i}`,
        `argument${i}.value()`,
        ctx,
        name,
        "RETURN_IF_EXCEPTION(scope, {});",
      ),
    );
  });
  lines.push(...readLast);
  const args = signature.args.map(({ type }, i) => {
    return type.passesValue
      ? `${externType(type)} { ${toExtern(`converted${i}`)}, JSC::JSValue::encode(argument${i}.value()) }`
      : toExtern(`converted${i}`);
  });
  lines.push(`RELEASE_AND_RETURN(scope, ${symbol}(${["globalObject", ...leading, ...args].join(", ")}));`);
  return lines.map(line => `    ${line}`).join("\n");
}

const cppPrologue = `    auto& vm = JSC::getVM(globalObject);
    auto scope = DECLARE_THROW_SCOPE(vm);`;

const cppExtern = (symbol: string, signature: Signature, leading: readonly string[] = []) =>
  `extern "C" JSC::EncodedJSValue ${symbol}(${["JSC::JSGlobalObject*", ...leading, ...signature.args.map(arg => externType(arg.type))].join(", ")});`;

