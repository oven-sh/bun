const implementationType = (type: Type) => `${type.idlType}::ImplementationType`;
const externType = (type: Type): string =>
  type.passesValue
    ? `Bun::Bindgen::ExternWithValue<Bun::Bindgen::ExternOf<${type.idlType}>>`
    : `Bun::Bindgen::ExternOf<${type.idlType}>`;
const toExtern = (variable: string) => `Bun::Bindgen::toExtern(${variable})`;

/**
 * C++ that declares `choice`, an index into the `outcomes` it returns: the distinct values of `byKind`, "other"'s first.
 * `condition`, if the choice is that simple, is true of `outcomes[1]` and false of `outcomes[0]`.
 */
function cppChooseByKind<T>(value: string, byKind: ReadonlyMap<ValueKind | "other", T>, choice = "choice") {
  const other = byKind.get("other")!;
  const outcomes = [...new Set([other, ...byKind.values()])];
  const ofValue = new Map<T, string[]>();
  const ofType = new Map<T, string[]>();
  const ofClass = new Map<T, string[]>();
  for (const [kind, outcome] of byKind) {
    if (kind === "other" || outcome === other) continue;
    const add = (tests: Map<T, string[]>, test: string | undefined) => {
      if (test !== undefined) tests.set(outcome, [...(tests.get(outcome) ?? []), test]);
    };
    if (typeof kind === "object") {
      add(ofClass, `cell->inherits<${kind.cpp}>()`);
    } else {
      add(ofValue, kindTests[kind].ofValue?.(value));
      add(ofType, kindTests[kind].ofCell);
    }
  }
  const nullish = [`${value}.isUndefined()`, `${value}.isNull()`];
  const chain = (...tests: Map<T, string[]>[]) =>
    tests
      .flatMap(map => [...map])
      .map(([outcome, conditions]) => {
        const merged = nullish.every(test => conditions.includes(test))
          ? [`${value}.isUndefinedOrNull()`, ...conditions.filter(test => !nullish.includes(test))]
          : mergeViewTests(conditions);
        return { condition: merged.join(" || "), index: outcomes.indexOf(outcome) };
      });
  const cppChain = (...tests: Map<T, string[]>[]) =>
    chain(...tests)
      .map(({ condition, index }) => `if (${condition})\n    ${choice} = ${index};`)
      .join("\nelse ");
  const lines = [`unsigned ${choice} = 0;`];
  if (ofType.size + ofClass.size > 0) {
    lines.push(`if (${value}.isCell()) {`, `    auto* cell = ${value}.asCell();`);
    lines.push(indent(cppChain(ofType, ofClass), 4), ofValue.size > 0 ? `} else ${cppChain(ofValue)}` : "}");
  } else if (ofValue.size > 0) {
    lines.push(cppChain(ofValue));
  }
  const isSimple = outcomes.length === 2 && ofType.size + ofClass.size === 0;
  return { outcomes, code: lines.join("\n"), condition: isSimple ? chain(ofValue)[0].condition : undefined };
}

function layoutAssert(cppType: string, type: Type): string {
  const { size, align } = type.layout();
  return `static_assert(sizeof(${cppType}) == ${size} && alignof(${cppType}) == ${align});`;
}

function humanReadableEnumeration(type: EnumerationType): string {
  const quoted = type.spellings.map(([canonical]) => asciiLiteral(`"${canonical}"`).slice(1, -3));
  return new Intl.ListFormat("en", { type: "disjunction" }).format(quoted);
}

/** Value-initialization zeroes a struct whose constructor is implicit, and these hold the buffers of string views. */
const cppDefaultConstructor = (type: NamedType) =>
  `${type.needsLifetime ? "    WTF_FORBID_HEAP_ALLOCATION;\n\npublic:\n" : ""}    ${type.name}() {}`;

/** C++ that offers `value` to `candidates`, indices of alternatives, in order. All but the last may refuse it. */
function cppConvertToAlternative(type: UnionType, candidates: readonly number[]): string {
  return candidates
    .map(i => {
      const { name, type: alternative } = type.alternatives[i];
      const member = `result.${name}`;
      const returnSuccess = type.conversionThrows ? "return true;" : "return result;";
      if (alternative instanceof UnitType) return `result.tag = ${i};\n${returnSuccess}`;
      // As the last, its own conversion reports what is not an object.
      const reportsNonObjects = refusesNonObjects(alternative) && i === candidates.at(-1);
      // Choosing by kind has already run the only test `tryConvert` makes.
      const isKnownToConvert =
        alternative.conversionThrows &&
        !alternative.tryConvertThrows &&
        (refusesNonObjects(alternative)
          ? !reportsNonObjects
          : alternative.valueKinds !== "any" && !alternative.refuses);
      const convert = (target: string) =>
        !isKnownToConvert
          ? alternative.cppConvertInto(target, "value", "ctx", "", "false")
          : alternative.returnsValueUnchanged
            ? `${target} = ${alternative.cppOfUnchangedValue("value")};`
            : `${target} = Bun::uncheckedConvertIDL<${alternative.idlType}>(*globalObject, value, ctx);`;
      const take = `result.tag = ${i};
${
  type.cppStoresAsBits(alternative)
    ? `${implementationType(alternative)} converted;
${convert("converted")}
result.bits = Bun::Bindgen::toBits(converted);`
    : `std::construct_at(&${member});
${alternative.convertsInPlace ? cppEmplace(member, convert) : convert(member)}`
}
${returnSuccess}`;
      if (refusesNonObjects(alternative))
        return reportsNonObjects ? take : `if (value.isObject()) {\n${indent(take, 4)}\n}`;
      if (alternative.refuses)
        return `if (auto converted = Bun::tryConvertIDL<${alternative.idlType}>(*globalObject, value, ctx)) {
    std::construct_at(&${member}, WTF::move(*converted));
    result.tag = ${i};
    ${returnSuccess}
}${alternative.tryConvertThrows ? "\nRETURN_IF_EXCEPTION(scope, false);" : ""}`;
      return take;
    })
    .join("\n");
}

function cppHeaderForUnion(type: UnionType): string {
  const { name, alternatives } = type;
  /** As error messages list them: null last. */
  const idlTypes = alternatives
    .toSorted((a, b) => Number(a.type instanceof UnitType) - Number(b.type instanceof UnitType))
    .map(a => a.type.idlType)
    .join(", ");
  const { outcomes, code } = cppChooseByKind("value", type.alternativesByKind);
  const cases = outcomes.flatMap((candidates, index) =>
    candidates.length === 0
      ? []
      : `case ${index}: {\n${indent(cppConvertToAlternative(type, candidates), 4)}${type.mayMatchNone(candidates) ? "\n    break;" : ""}\n}`,
  );
  const held = type.heldAlternatives;
  const switchOnHeld = (statement: (name: string) => string) =>
    held.length === 0
      ? ""
      : `switch (tag) {
${held.map(a => `        case ${alternatives.indexOf(a)}:\n            ${statement(a.name)};\n            break;`).join("\n")}
        }`;
  const chooseAlternative = `${indent(code, 8)}
        switch (choice) {
${indent(cases.join("\n"), 8)}
        }`;
  const converter = type.conversionThrows
    ? `template<> struct WebCore::Converter<${type.idlType}> : Bun::DefaultContextConverter<${type.idlType}> {${
        type.needsLifetime
          ? ""
          : `
    template<Bun::IDLConversionContext Ctx>
    static ReturnType convert(JSC::JSGlobalObject& globalObject, JSC::JSValue value, Ctx& ctx)
    {
        ReturnType result;
        convertInto(globalObject, value, ctx, result);
        return result;
    }
`
      }
    template<Bun::IDLConversionContext Ctx>
    static bool convertInto(JSC::JSGlobalObject& lexicalGlobalObject, JSC::JSValue value, Ctx& ctx, ReturnType& result)
    {
        auto* globalObject = &lexicalGlobalObject;
        auto& vm = JSC::getVM(globalObject);
        auto scope = DECLARE_THROW_SCOPE(vm);
${chooseAlternative}
        ${outcomes.some(candidates => type.mayMatchNone(candidates)) ? `ctx.template throwNoMatchInUnion<${idlTypes}>(*globalObject, scope);\n        return false;` : "RELEASE_ASSERT_NOT_REACHED();"}
    }
};`
    : `template<> struct WebCore::Converter<${type.idlType}> : WebCore::DefaultConverter<${type.idlType}> {
    static ReturnType convert(JSC::JSGlobalObject& lexicalGlobalObject, JSC::JSValue value)
    {
        [[maybe_unused]] auto* globalObject = &lexicalGlobalObject;
        [[maybe_unused]] Bun::DefaultConversionContext ctx;
        ReturnType result;
${chooseAlternative}
        RELEASE_ASSERT_NOT_REACHED();
    }
};`;
  return `
namespace Bun::Bindgen::Generated {
// Only the alternative that \`tag\` names is constructed.
struct ${name} {
${cppDefaultConstructor(type)}${
    type.needsLifetime || type.cppCanBitCastToExtern
      ? ""
      : `
    ${name}(${name}&& other)
        : tag(other.tag)
    {
        ${switchOnHeld(member => `std::construct_at(&this->${member}, WTF::move(other.${member}))`)}
    }
    ${name}& operator=(${name}&& other)
    {
        std::destroy_at(this);
        std::construct_at(this, WTF::move(other));
        return *this;
    }`
  }${
    type.cppCanBitCastToExtern
      ? ""
      : `
    ~${name}()
    {
        ${switchOnHeld(member => `std::destroy_at(&${member})`)}
    }`
  }
    uint8_t tag${type.cppCanBitCastToExtern ? "" : ` { ${alternatives.length} }`};
${
  held.length === 0
    ? ""
    : `    union {
${held.some(a => type.cppStoresAsBits(a.type)) ? "        uint64_t bits;\n" : ""}${held.map(a => `        ${a.type.convertsInPlace ? `std::optional<${implementationType(a.type)}>` : implementationType(a.type)} ${a.name};`).join("\n")}
    };
`
}};
struct Extern${name} {
    uint8_t tag;
    union {
${type.externParameterFields ? "        uint64_t bits;\n" : ""}${alternatives.map(a => `        ${externType(a.type)} ${a.name};`).join("\n")}
    } data;
};
${layoutAssert(`Extern${name}`, type)}
}
${type.cppCanBitCastToExtern ? `template<> inline constexpr bool Bun::Bindgen::canBitCastToExtern<${type.cpp}> = true;\n` : ""}template<> struct Bun::Bindgen::ExternTraits<${type.cpp}> {
    using ExternType = Bun::Bindgen::Generated::Extern${name};
    static ExternType convertToExtern(${type.cpp}&& value)
    {
${
  type.cppCanBitCastToExtern
    ? `${held.map(a => `        static_assert(Bun::Bindgen::canBitCastToExtern<decltype(value.${a.name})>);`).join("\n")}
        return std::bit_cast<ExternType>(value);`
    : `        ExternType result;
        result.tag = value.tag;
        switch (value.tag) {
${held
  .map(
    a => `        case ${alternatives.indexOf(a)}:
            result.data.${a.name} = ${toExtern(`${a.type.convertsInPlace ? "*" : ""}value.${a.name}`)};
            break;`,
  )
  .join("\n")}
        }
        return result;`
}
    }
};
template<> struct Bun::IDLHumanReadableName<${type.idlType}> : Bun::IDLHumanReadableName<Bun::IDLAlternatives<${idlTypes}>> {};
${converter}
`;
}

function cppHeaderForType(type: NamedType): string {
  const { name } = type;
  if (type instanceof ClassType) return cppHeaderForClass(type);
  if (type instanceof EnumerationType) {
    return `
namespace Bun::Bindgen::Generated {
enum class ${name} : uint32_t {
${type.variants.map(variant => `    ${variant},`).join("\n")}
};
}
template<> struct Bun::Bindgen::ExternTraits<${type.cpp}> : Bun::Bindgen::TrivialExtern<${type.cpp}> {};
template<> struct Bun::IDLHumanReadableName<${type.idlType}> : Bun::BaseIDLHumanReadableName {
    static constexpr auto humanReadableName = std::to_array("${humanReadableEnumeration(type)}");
};
template<> std::optional<${type.cpp}> WebCore::parseEnumerationFromString<${type.cpp}>(const WTF::String&);
template<> std::optional<${type.cpp}> WebCore::parseEnumeration<${type.cpp}>(JSC::JSGlobalObject&, JSC::JSValue);
`;
  }
  if (type instanceof UnionType) return type.accepted ? cppHeaderForUnion(type) : "";
  if (type instanceof DeferredDictionaryType) return "";
  assert(type instanceof DictionaryType);
  if (!type.accepted) return "";
  return `
namespace Bun::Bindgen::Generated {
struct ${name} {
${cppDefaultConstructor(type)}
${type.members.map(member => `    ${implementationType(member.type)} ${member.fieldName};`).join("\n")}
};
struct Extern${name} {
${type.members.map(member => `    ${externType(member.type)} ${member.fieldName};`).join("\n")}
};
${layoutAssert(`Extern${name}`, type)}
}
template<> struct Bun::Bindgen::ExternTraits<${type.cpp}> {
    using ExternType = Bun::Bindgen::Generated::Extern${name};
    static ExternType convertToExtern(${type.cpp}&& value)
    {
        return ExternType {
${type.members.map(member => `            .${member.fieldName} = ${toExtern(`value.${member.fieldName}`)},`).join("\n")}
        };
    }
};
template<> struct Bun::IDLHumanReadableName<${type.idlType}> : Bun::BaseIDLHumanReadableName {
    static constexpr auto humanReadableName = std::to_array("${type.name}");
};
template<> bool Bun::Bindgen::convertDictionaryInto<${type.cpp}>(JSC::JSGlobalObject&, JSC::JSValue, ${type.cpp}&);
${
  type.needsLifetime
    ? `template<> struct WebCore::IDLDictionary<${type.cpp}> : Bun::Bindgen::IDLStackOnlyDictionary<${type.cpp}> {};`
    : type.convertedByValue
      ? `template<> ${type.cpp} WebCore::convertDictionary<${type.cpp}>(JSC::JSGlobalObject&, JSC::JSValue);`
      : ""
}
`;
}

export function cppHeader(file: SchemaFile): string {
  const headers = new Set<string>();
  for (const type of file.types) for (const dependency of type.dependencies) dependency.getHeaders(headers);
  if (file.types.some(type => type instanceof ClassType)) headers.add("Bindgen/JSWrapper.h");
  headers.delete(`Generated${file.origin.namespace}.h`);
  const propertyCallbacks = [
    ...file.namespaces.map(cppNamespaceSignature),
    ...file.types.filter(type => type instanceof ClassType && type.construct).map(cppConstructorSignature),
  ];
  const exported = file.functions.filter(fn => fn.exportName);
  const declarations = [
    ...file.functions
      .filter(fn => !fn.exportName && !fn.isValue)
      .map(fn => `JSC_DECLARE_HOST_FUNCTION(${hostFunctionName(fn)});`),
    ...propertyCallbacks.map(signature => `// A PropertyCallback of a static property table.\n${signature};`),
  ];
  return `${banner(file.origin)}#pragma once
#include "root.h"
#include "Bindgen/ExternTraits.h"
#include "Bindgen/IDLConvert.h"
#include "JSDOMConvertDictionary.h"
#include "JSDOMConvertEnumeration.h"
${[...headers].map(header => `#include "${header}"\n`).join("")}${file.types.map(cppHeaderForType).join("")}${
    exported.length > 0 ? `\n${exported.map(fn => `BUN_DECLARE_HOST_FUNCTION(${fn.exportName});`).join("\n")}\n` : ""
  }${
    declarations.length > 0
      ? `
namespace Bun::Bindgen::Generated::${file.origin.namespace} {
${declarations.join("\n")}
}
`
      : ""
  }`;
}

const hostFunctionName = (fn: FunctionDefinition) => fn.exportName ?? `js${cap(fn.name.replace(/^_+/, ""))}`;
const namespaceCreatorName = (namespace: NamespaceDefinition) => `create${cap(namespace.name)}`;
const constructorGetterName = (type: NamedType) => `get${type.name}Constructor`;

const cppNamespaceSignature = (namespace: NamespaceDefinition) =>
  `JSC::JSValue ${namespaceCreatorName(namespace)}(JSC::VM& vm, JSC::JSObject* owner)`;
const cppConstructorSignature = (type: NamedType) =>
  `JSC::JSValue ${constructorGetterName(type)}(JSC::VM& vm, JSC::JSObject* owner)`;

const cppQualified = (origin: Origin, name: string) => `Bun::Bindgen::Generated::${origin.namespace}::${name}`;
/** What a static property table writes to hold a function, a namespace or the constructor of a class. */
export const cppFunctionSymbol = (fn: FunctionDefinition) =>
  fn.exportName ?? cppQualified(fn.origin!, hostFunctionName(fn));
export const cppNamespaceSymbol = (namespace: NamespaceDefinition) =>
  cppQualified(namespace.functions[0].origin!, namespaceCreatorName(namespace));
export const cppConstructorSymbol = (type: NamedType) => cppQualified(type.origin!, constructorGetterName(type));
/** In the table of built-ins, the object that `$bindgen` of a namespace makes for the module that asks. It has the functions of the namespace and no other members. */
export const pathOfBoundNamespace = (namespace: NamespaceDefinition) =>
  `%${namespace.functions[0].origin!.namespace}${cap(namespace.name)}%`;

function cppSourceForNamespace(namespace: NamespaceDefinition, origin: Origin): string {
  return `
namespace Bun::Bindgen::Generated::${origin.namespace} {
${cppNamespaceSignature(namespace)}
{
    JSC::JSGlobalObject* globalObject = owner->globalObject();
    JSC::JSObject* object = ${
      namespace.call
        ? `JSC::JSFunction::create(vm, globalObject, ${namespace.call.length}, ${asciiLiteral(namespace.name)}, ${hostFunctionName(namespace.call)}, JSC::ImplementationVisibility::Public)`
        : `JSC::constructEmptyObject(globalObject, globalObject->objectPrototype(), std::min<unsigned>(${namespace.functions.length}, JSC::JSFinalObject::maxInlineCapacity))`
    };
${namespace.functions
  .map(
    fn =>
      `    object->putDirectNativeFunction(vm, globalObject, JSC::Identifier::fromString(vm, ${asciiLiteral(fn.name)}), ${fn.length}, ${hostFunctionName(fn)}, JSC::ImplementationVisibility::Public, JSC::NoIntrinsic, 0);`,
  )
  .join("\n")}
    return object;
}
}
extern "C" SYSV_ABI JSC::EncodedJSValue js2native_bindgen_${origin.stem}_${namespace.name}(Zig::GlobalObject* globalObject)
{
    return JSC::JSValue::encode(Bun::Bindgen::Generated::${origin.namespace}::create${cap(namespace.name)}(JSC::getVM(globalObject), globalObject));
}
`;
}

/** The body of a `case`: returns the variant of the candidate that `string` equals. All have its length, so it switches on characters where they differ and compares the one left. */
function cppMatchSpelling(candidates: readonly (readonly [spelling: string, variant: string])[]): string {
  if (candidates.length === 1) {
    const [[spelling, variant]] = candidates;
    return `if (string == ${asciiLiteral(spelling)})\n    return ${variant};\nbreak;`;
  }
  const [at, groups] = Array.from(
    candidates[0][0],
    (character, at) => [at, Map.groupBy(candidates, ([spelling]) => spelling[at])] as const,
  ).reduce((best, next) => (next[1].size > best[1].size ? next : best));
  return `switch (string[${at}]) {
${[...groups].map(([character, group]) => `case '${character.replace(/['\\]/, "\\$&")}':\n${indent(cppMatchSpelling(group), 4)}`).join("\n")}
}
break;`;
}

function cppSourceForEnum(type: EnumerationType): string {
  const byLength = Map.groupBy(
    type.spellings.flatMap((spellings, index) =>
      spellings.map(spelling => [spelling, `${type.cpp}::${type.variants[index]}`] as const),
    ),
    ([spelling]) => spelling.length,
  );
  return `
template<> std::optional<${type.cpp}> WebCore::parseEnumerationFromString<${type.cpp}>(const WTF::String& string)
{
    switch (string.length()) {
${[...byLength]
  .sort(([a], [b]) => a - b)
  .map(([length, candidates]) => `    case ${length}:\n${indent(cppMatchSpelling(candidates), 8)}`)
  .join("\n")}
    }
    return std::nullopt;
}

template<> std::optional<${type.cpp}> WebCore::parseEnumeration<${type.cpp}>(JSC::JSGlobalObject& globalObject, JSC::JSValue value)
{
    return parseEnumerationFromString<${type.cpp}>(value.toWTFString(&globalObject));
}
`;
}

/** Made of literals, so it is static and a call stores nothing for it. */
const cppStaticContext = (variable: string, context: string) =>
  `[[maybe_unused]] static constexpr auto ${variable} = Bun::Bindgen::${context};`;

/** Declares in `lines` what reports the `i`th argument or member, `value`, and returns the C++ expression for it. */
function cppContext(
  lines: string[],
  i: number,
  name: string,
  expected: readonly string[] | string | undefined,
  value: string,
): string {
  if (typeof expected === "string") {
    lines.push(
      cppStaticContext(`ctx${i}`, `ArgumentMessageContext { ${asciiLiteral(name)}, ${asciiLiteral(expected)} }`),
    );
  } else if (expected) {
    lines.push(
      `static constexpr WTF::ASCIILiteral expected${i}[] = { ${expected.map(asciiLiteral).join(", ")} };`,
      cppStaticContext(`nodeArgument${i}`, `NodeArgument { ${asciiLiteral(name)}, expected${i} }`),
    );
    // It holds the value, so it is made where a conversion takes it.
    return `Bun::Bindgen::asLvalue(Bun::Bindgen::NodeArgumentContext { nodeArgument${i}, ${value} })`;
  } else {
    lines.push(cppStaticContext(`ctx${i}`, `LiteralConversionContext { ${asciiLiteral(name)} }`));
  }
  return `ctx${i}`;
}

const qualifiedName = (type: DictionaryType | DeferredDictionaryType, member: Member) =>
  member.reportedAs ?? (type.reportedAs ? `${type.reportedAs}.${member.name}` : member.name);

/** Declares `value`, read through `members` from the names of `member`, the first of which is at `nameIndex`. */
function cppReadMember(member: Member, value: string, nameIndex: number, ctx: string): string[] {
  const reads = member.privateSymbol
    ? [`members.get(WebCore::builtinNames(vm).${member.privateSymbol}PrivateName())`]
    : member.names.map((_, i) => `members.${member.own ? "getOwn" : "get"}(${nameIndex + i})`);
  if (isIfPassed(member.type))
    return [
      `JSC::JSValue ${value} = members.getOwnIfPropertyExists(${nameIndex});`,
      "RETURN_IF_EXCEPTION(scope, false);",
    ];
  const [first, ...others] = reads.map(read => `${read};\n${cppReturnIfFailed(`!!${value}`, "false")}`);
  return [
    `JSC::JSValue ${value} = ${first}`,
    ...others.map(read => `if (${value}.isUndefined()) {\n${indent(`${value} = ${read}`, 4)}\n}`),
    ...(member.type.takesUndefined
      ? []
      : [
          `if (${value}.isUndefined()) [[unlikely]] {
    ${ctx}.throwRequired(*globalObject, scope);
    return false;
}`,
        ]),
  ];
}

function cppSourceForDictionary(type: DictionaryType): string {
  if (!type.accepted) return "";
  let nameIndex = 0;
  const members = type.members.map((member, i) => {
    const qualified = qualifiedName(type, member);
    const lines: string[] = [];
    const ctx = cppContext(lines, i, qualified, member.expected, `value${i}`);
    lines.push(...cppReadMember(member, `value${i}`, nameIndex, ctx));
    nameIndex += member.names.length;
    lines.push(member.type.cppConvertInto(`result.${member.fieldName}`, `value${i}`, ctx, qualified, "false"));
    return `    {\n${indent(lines.join("\n"), 8)}\n    }`;
  });
  const count = type.names.length;
  return `
template<> bool Bun::Bindgen::convertDictionaryInto<${type.cpp}>(JSC::JSGlobalObject& lexicalGlobalObject, JSC::JSValue value, ${type.cpp}& result)
{
    auto* globalObject = &lexicalGlobalObject;
    auto& vm = JSC::getVM(globalObject);
    auto scope = DECLARE_THROW_SCOPE(vm);
    ${cppStaticContext("ctx", `LiteralConversionContext { ${asciiLiteral(type.reportedAs || type.name)} }`)}
    auto* object = value.getObject();
${
  type.nonObjectAsEmpty
    ? `    if (!object${type.nonObjectAsEmpty === "typeof" ? " || object->isCallable()" : ""}) {
${indent(type.cppAssign("result", {}), 8)}
        return true;
    }`
    : `    if (!object) [[unlikely]] {
        ctx.throwNotObject(*globalObject, scope);
        return false;
    }`
}
${
  type.allowArray
    ? ""
    : `    bool isArray = JSC::isArray(globalObject, value);
    RETURN_IF_EXCEPTION(scope, false);
    if (isArray) [[unlikely]] {
        ctx.throwNotObject(*globalObject, scope);
        return false;
    }
`
}    Bun::Bindgen::DictionaryMemberReader members(vm, globalObject, object, ${type.firstMemberNameIndex}, ${count});
${members.join("\n")}
    return true;
}
${
  type.needsLifetime || !type.convertedByValue
    ? ""
    : `
template<> ${type.cpp} WebCore::convertDictionary<${type.cpp}>(JSC::JSGlobalObject& globalObject, JSC::JSValue value)
{
    ${type.cpp} result;
    Bun::Bindgen::convertDictionaryInto(globalObject, value, result);
    return result;
}
`
}${
    type.fromJS
      ? `
extern "C" bool ${fromJSSymbol(type)}(JSC::JSGlobalObject* globalObject, JSC::EncodedJSValue value, Bun::Bindgen::Generated::Extern${type.name}* result)
{
    auto& vm = JSC::getVM(globalObject);
    auto scope = DECLARE_THROW_SCOPE(vm);
    ${type.cpp} converted;
${indent(cppReturnIfFailed("Bun::Bindgen::convertDictionaryInto(*globalObject, JSC::JSValue::decode(value), converted)", "false"), 4)}
    *result = ${toExtern("converted")};
    return true;
}
`
      : ""
  }`;
}

const overloadSuffix = (fn: FunctionDefinition, signature: Signature) =>
  fn.signatures.length > 1 ? `${fn.signatures.indexOf(signature) + 1}` : "";

export const thunkSymbol = (fn: FunctionDefinition, signature: Signature) =>
  signature.cppSymbol ??
  `Bun__Bindgen__${fn.origin!.namespace}__${fn.name.replace(/^_+/, "")}${overloadSuffix(fn, signature)}`;

/** Lines that declare `variable` as what `value` converts to, and return `failure` if converting throws. */
function cppDeclareConverted(
  type: Type,
  variable: string,
  value: string,
  ctx: string,
  name: string,
  failure: string,
): string[] {
  if (!type.conversionThrows) return [`auto ${variable} = ${type.cppConvert(value, ctx)};`];
  return [
    `${implementationType(type)} ${variable};`,
    ...type.cppConvertInto(variable, value, ctx, name, failure).split("\n"),
  ];
}

const cppHeldValue = (type: Type, variable: string) =>
  type.pointsIntoValue
    ? { holder: "JSC::EnsureStillAliveScope", value: `${variable}.value()` }
    : { holder: "JSC::JSValue", value: variable };

/**
 * Whether each argument goes by pointer: one that the C ABI would copy to the stack, because it does not fit two
 * registers or because the six of x86-64 have run out.
 * `leading`: how many parameters sit between the global object and the arguments.
 */
export function passedByPointer(args: readonly { type: Type }[], leading: number): boolean[] {
  let registers = 6 - 1 - leading;
  return args.map(({ type }) => {
    const needed = Math.ceil(type.layout().size / 8);
    const byPointer = needed > 2 || (needed === 2 && registers < 2);
    registers -= byPointer ? 1 : needed;
    return byPointer;
  });
}

/** The types of the parameters that take an extern value of `type`. */
const cppExternParameters = (type: Type, byPointer: boolean): string[] =>
  byPointer
    ? [`${externType(type)}*`]
    : (type.externParameterFields?.map(field => `decltype(${externType(type)}::${field.name})`) ?? [externType(type)]);

/**
 * The arguments for `cppExternParameters`. `converted`: the C++ value. `extern`: the expression that makes its extern value.
 * `lines` gets a declaration of `variable` if the arguments read it.
 */
function cppExternArguments(
  type: Type,
  byPointer: boolean,
  converted: string,
  extern: string,
  variable: string,
  lines: string[],
): string[] {
  if (byPointer && type.cppCanBitCastToExtern) return [`Bun::Bindgen::asExtern(${converted})`];
  if (!byPointer && !type.externParameterFields) return [extern];
  lines.push(`auto ${variable} = ${extern};`);
  return byPointer ? [`&${variable}`] : type.externParameterFields!.map(field => `${variable}.${field.name}`);
}

type Argument = Signature["args"][number];

/** A converted `String` object is in no frame but this one. */
const cppHeldArgument = (type: Type, i: number) =>
  type.cppPrepare("") === null
    ? cppHeldValue(type, `argument${i}`)
    : { holder: "JSC::EnsureStillAliveScope", value: `argument${i}.value()` };

/** The host function looks at each argument of the rest. */
const cppGoesThroughRest = (type: RestType) => type.element instanceof LocalStringType || type.cppPrepare("") !== null;

/** Lines that declare `argument${i}`, which holds what is converted. `fromParameters`: as for `cppCallBody`. */
function cppDeclareArgument({ type }: Argument, i: number, fromParameters?: { failure: string }): string[] {
  if (type instanceof RestType) {
    if (!cppGoesThroughRest(type)) return [];
    return [
      `Bun::Bindgen::RestArguments argument${i} { *callFrame, ${i} };`,
      ...(type.cppPrepare("") === null
        ? []
        : [`argument${i}.convertStringObjects(*globalObject);`, "RETURN_IF_EXCEPTION(scope, {});"]),
    ];
  }
  const passed = fromParameters ? `parameter${i}` : `callFrame->argument(${i})`;
  const prepared = type.cppPrepare(passed);
  const { holder } = cppHeldArgument(type, i);
  if (prepared !== null) {
    return [`${holder} argument${i} = ${prepared};`, `RETURN_IF_EXCEPTION(scope, ${fromParameters?.failure ?? "{}"});`];
  }
  return [
    !fromParameters && isIfPassed(type)
      ? `${holder} argument${i} = callFrame->argumentCount() > ${i} ? callFrame->uncheckedArgument(${i}) : JSC::JSValue();`
      : `${holder} argument${i} = ${passed};`,
  ];
}

/** As `cppContext`, for an argument: `value` is the argument or, with `index`, one of a `b.rest`. */
function cppArgumentContext(
  lines: string[],
  { name, expected, validatorExpects }: Argument,
  i: number,
  value: string,
  index?: string,
): string {
  if (expected !== undefined || !validatorExpects) return cppContext(lines, i, name, expected, value);
  const fields = [asciiLiteral(name), asciiLiteral(validatorExpects), value, ...(index ? [index] : [])];
  return `Bun::Bindgen::asLvalue(Bun::Bindgen::ValidatorArgumentContext { ${fields.join(", ")} })`;
}

/** What a result is only declared to be: the words of `.returning`, and a class, a cell or a JS string, for which Rust may hand back any JS value. */
export function checkedWordsOf(type: Type): readonly string[] | null {
  if (type instanceof ClassType) return [type.name];
  if (type instanceof CellType) return [type.cpp];
  if (type instanceof OpaqueType || type instanceof LocalType || type instanceof BufferSourceType) {
    return type.checkedResult;
  }
  if (type instanceof LocalStringType) return ["string"];
  if (!(type instanceof OptionalType)) return null;
  const words = type.inner instanceof OpaqueType ? null : checkedWordsOf(type.inner);
  return words && [...words, type.modifier === "optional" ? "undefined" : "null"];
}

/**
 * Converts the arguments, then returns what `symbol(globalObject, ...leading, ...converted)` returns, or ends with the lines `finish` makes from that call.
 * `fromParameters`: the arguments are the function's `JSValue` parameters `parameter0`.., not the call frame's, and a failed conversion returns `failure`.
 */
function cppCallBody(
  signature: Signature,
  symbol: string,
  leading: readonly string[] = [],
  finish = (call: string) => [`RELEASE_AND_RETURN(scope, ${call});`],
  fromParameters?: { failure: string },
): string {
  const indented = (lines: readonly string[]) => lines.map(line => `    ${line}`).join("\n");
  if (signature.cppInlineBody) {
    return indented(
      finish(`${signature.cppInlineBody.name}(globalObject, Bun::Bindgen::ArgumentsInFrame { *callFrame })`),
    );
  }
  // Converting a later argument can run JavaScript that detaches or resizes a buffer.
  const readLast: string[] = [];
  const convert = (argument: Argument, i: number): string[] => {
    const { name, type } = argument;
    const lines: string[] = [];
    if (type instanceof RestType) {
      if (!cppGoesThroughRest(type)) return [`auto converted${i} = Bun::Bindgen::variadicArguments(callFrame, ${i});`];
      if (!(type.element instanceof LocalStringType)) return [];
      const ctx = cppArgumentContext(lines, argument, i, `argument${i}.at(index)`, "index");
      return [
        ...lines,
        `for (size_t index = 0; index < argument${i}.size(); ++index) {`,
        `    if (!argument${i}.at(index).isString()) [[unlikely]] {`,
        `        ${ctx}.throwNotString(*globalObject, scope);`,
        "        return {};",
        "    }",
        "}",
      ];
    }
    const { value } = cppHeldArgument(type, i);
    const ctx = cppArgumentContext(lines, argument, i, value);
    readLast.push(...type.cppReadLast(`converted${i}`, value));
    return [...lines, ...cppDeclareConverted(type, `converted${i}`, value, ctx, name, fromParameters?.failure ?? "{}")];
  };
  const lines = [
    ...signature.args.flatMap((argument, i) => cppDeclareArgument(argument, i, fromParameters)),
    ...signature.conversionOrder.flatMap(i => convert(signature.args[i], i)),
    ...readLast,
  ];
  const byPointer = passedByPointer(signature.args, leading.length);
  const args = signature.args.flatMap(({ type }, i) => {
    const extern =
      type instanceof RestType && cppGoesThroughRest(type)
        ? `${externType(type)} { argument${i}.data(), argument${i}.size() }`
        : type.passesValue
          ? `${externType(type)} { ${toExtern(`converted${i}`)}, JSC::JSValue::encode(${cppHeldArgument(type, i).value}) }`
          : toExtern(`converted${i}`);
    return cppExternArguments(type, byPointer[i], `converted${i}`, extern, `extern${i}`, lines);
  });
  lines.push(...finish(`${symbol}(${["globalObject", ...leading, ...args].join(", ")})`));
  return indented(lines);
}

const cppPrologue = `    auto& vm = JSC::getVM(globalObject);
    auto scope = DECLARE_THROW_SCOPE(vm);`;

const fromJSSymbol = (type: NamedType) => `Bun__Bindgen__${type.name}__fromJS`;

/** `Name::from_js` of a union. */
function cppSourceForFromJS(type: UnionType): string {
  if (!type.fromJS) return "";
  const conversion = new Conversion(type, type.name, undefined);
  conversion.symbol = fromJSSymbol(type);
  return cppSourceForConversion(conversion);
}

function cppSourceForConversion({ symbol, type, name, expected, member }: Conversion): string {
  const { holder, value } = cppHeldValue(type, "argument");
  const lines: string[] = [];
  let ctx: string;
  if (member) {
    const { firstMemberNameIndex, members } = member.of;
    const read = members[member.index];
    const nameIndex = firstMemberNameIndex + members.slice(0, member.index).flatMap(({ names }) => names).length;
    ctx = cppContext(lines, 0, qualifiedName(member.of, read), expected, "read");
    lines.push(
      `Bun::Bindgen::DictionaryMemberReader members(vm, globalObject, JSC::asObject(JSC::JSValue::decode(encodedValue)), ${nameIndex}, ${read.names.length});`,
      ...cppReadMember(read, "read", 0, ctx),
      `${holder} argument = read;`,
    );
  } else {
    lines.push(`${holder} argument = JSC::JSValue::decode(encodedValue);`);
    ctx = cppContext(lines, 0, name, expected, value);
  }
  lines.push(
    ...cppDeclareConverted(type, "converted", value, ctx, "", "false"),
    `*result = ${toExtern("converted")};`,
    "return true;",
  );
  return `
extern "C" bool ${symbol}(JSC::JSGlobalObject* globalObject, JSC::EncodedJSValue encodedValue, ${externType(type)}* result)
{
${cppPrologue}
${indent(lines.join("\n"), 4)}
}
`;
}

export const cppExtern = (
  symbol: string,
  signature: { args: readonly { type: Type }[] },
  leading: readonly string[] = [],
  returns = "JSC::EncodedJSValue",
) => {
  const byPointer = passedByPointer(signature.args, leading.length);
  return `extern "C" SYSV_ABI ${returns} ${symbol}(${["JSC::JSGlobalObject*", ...leading, ...signature.args.flatMap((arg, i) => cppExternParameters(arg.type, byPointer[i]))].join(", ")});`;
};

