const overloadSuffix = (fn: FunctionDefinition, signature: Signature) =>
  fn.signatures.length > 1 ? `${fn.signatures.indexOf(signature) + 1}` : "";

export const thunkSymbol = (fn: FunctionDefinition, signature: Signature) =>
  signature.cppSymbol ??
  `Bun__Bindgen__${fn.origin!.namespace}__${fn.name.replace(/^_+/, "")}${overloadSuffix(fn, signature)}`;

/** Lines that declare `variable` as what `value` converts to, and return `failure` if converting throws. */
function cppDeclareConverted(
  type: Type,
  variable: string,
  value: string,
  ctx: string,
  name: string,
  failure: string,
): string[] {
  if (!type.conversionThrows) return [`auto ${variable} = ${type.cppConvert(value, ctx)};`];
  return [
    `${implementationType(type)} ${variable};`,
    ...type.cppConvertInto(variable, value, ctx, name, failure).split("\n"),
  ];
}

/** EnsureStillAliveScope is for a pointer a conversion takes out of the value. A Rust type with no lifetime has none. */
const cppHeldValue = (type: Type, variable: string) =>
  type.returnsValueUnchanged || !(type.needsLifetime || type.borrowsCell || type.passesValue)
    ? { holder: "JSC::JSValue", value: variable }
    : { holder: "JSC::EnsureStillAliveScope", value: `${variable}.value()` };

/** The C ABI copies an argument that does not fit two registers. */
const isPassedByPointer = (type: Type) => type.layout().size > 16;

type Argument = Signature["args"][number];

/** A converted `String` object is in no frame but this one. */
const cppHeldArgument = (type: Type, i: number) =>
  type.cppPrepare("") === null
    ? cppHeldValue(type, `argument${i}`)
    : { holder: "JSC::EnsureStillAliveScope", value: `argument${i}.value()` };

/** Lines that declare `argument${i}`, which holds what is converted. `fromParameters`: as for `cppCallBody`. */
function cppDeclareArgument(
  { type }: Argument,
  i: number,
  fromParameters?: { failure: string },
  isThere = false,
): string[] {
  if (type instanceof VariadicType) return [];
  if (type instanceof RestType) {
    return [
      `Bun::Bindgen::RestArguments argument${i} { *callFrame, ${i} };`,
      ...(type.element.cppPrepare("") === null
        ? []
        : [`argument${i}.convertStringObjects(*globalObject);`, "RETURN_IF_EXCEPTION(scope, {});"]),
    ];
  }
  const passed = fromParameters ? `parameter${i}` : `callFrame->${isThere ? "uncheckedArgument" : "argument"}(${i})`;
  const prepared = type.cppPrepare(passed);
  const { holder } = cppHeldArgument(type, i);
  if (prepared !== null) {
    return [`${holder} argument${i} = ${prepared};`, `RETURN_IF_EXCEPTION(scope, ${fromParameters?.failure ?? "{}"});`];
  }
  return [
    !fromParameters && isIfPassed(type)
      ? `${holder} argument${i} = callFrame->argumentCount() > ${i} ? callFrame->uncheckedArgument(${i}) : JSC::JSValue();`
      : `${holder} argument${i} = ${passed};`,
  ];
}

/** As `cppContext`, for an argument: `value` is the argument or, with `index`, one of a `b.rest`. */
function cppArgumentContext(
  lines: string[],
  { name, expected, validatorExpects }: Argument,
  i: number,
  value: string,
  index?: string,
  isWeb = false,
): string {
  if (expected !== undefined || !validatorExpects) return cppContext(lines, i, name, expected, value, isWeb);
  const fields = [asciiLiteral(name), asciiLiteral(validatorExpects), value, ...(index ? [index] : [])];
  return `Bun::Bindgen::asLvalue(Bun::Bindgen::ValidatorArgumentContext { ${fields.join(", ")} })`;
}

/** What a thunk holds its result to: the words of `.returning`, and a class or a JS string, for which Rust may hand back any JS value. */
export function checkedWordsOf(type: Type): readonly string[] | null {
  if (type instanceof AnyType) return type.checkedResult;
  // Rust hands back an instance of an interface as its own type.
  if (type instanceof ClassType) return type.web ? null : [type.name];
  if (type instanceof LocalStringType) return ["string"];
  if (!(type instanceof OptionalType)) return null;
  const words = type.inner instanceof AnyType ? null : checkedWordsOf(type.inner);
  return words && [...words, type.modifier === "optional" ? "undefined" : "null"];
}

/** A body in C++ has no thunk. */
export const hasThunk = (signature: Signature): boolean => !signature.cppSymbol && !signature.cppInlineBody;

/** Whose result it is, as the message names it, and Rust for its receiver, a `JSValue`. */
interface ResultSite {
  member: string;
  receiver?: string;
}

const rustTestsOfDeclaredWords = {
  string: "value.is_string_literal()",
  number: "value.is_number()",
  int32: "value.is_int32()",
  bigint: "value.is_big_int()",
  boolean: "value.is_boolean()",
  undefined: "value.is_undefined()",
  null: "value.is_null()",
  object: "value.is_object()",
};
const cellTypesOfDeclaredInstances: Readonly<Record<string, readonly string[]>> = {
  Array: ["Array"],
  Error: ["ErrorInstance"],
  Promise: ["JSPromise"],
  String: ["StringObject", "DerivedStringObject"],
  Uint8Array: ["Uint8Array"],
};
/** Classes that no `.bind.ts` file defines and no cell type tells. Their tests are in src/jsc/bindings/Bindgen/ToJS.cpp. */
const nativeInstances: readonly string[] = ["AbortSignal", "ArrayBuffer", "Buffer", "Headers", "ReadableStream", "URL"];

/** A Rust closure that is true of a `JSValue` that is one of the words. */
function rustTestOfDeclaredWords(words: readonly string[], { member, receiver }: ResultSite): string {
  const symbols: string[] = [];
  const tests = words.map(word => {
    const alternative = parseDeclaredAlternative(word);
    if (alternative === "this") {
      assert(receiver !== undefined, `${member}: it has no receiver to return`);
      return `value == ${receiver}`;
    }
    if (typeof alternative === "string" && alternative !== "Promise") return rustTestsOfDeclaredWords[alternative];
    const name = typeof alternative === "string" ? alternative : alternative.instance;
    if (name in cellTypesOfDeclaredInstances)
      return `matches!(value.js_type(), ${cellTypesOfDeclaredInstances[name].map(cellType => `bun_jsc::JSType::${cellType}`).join(" | ")})`;
    const generated = classesByName.get(name);
    assert(generated || nativeInstances.includes(name), `${member}: no test is known for an instance of ${name}`);
    symbols.push(generated ? symbolName(generated, "isInstance") : `Bun__Bindgen__is${name}`);
    return `${symbols.at(-1)}(value)`;
  });
  if (symbols.length === 0) return `|value| ${tests.join(" || ")}`;
  return `|value| {
    unsafe extern "C" {
${symbols.map(symbol => `        safe fn ${symbol}(value: JSValue) -> bool;`).join("\n")}
    }
    ${tests.join(" || ")}
}`;
}

/** What `hold_to_declared_type` and `hold_cached_to_declared_type` take after the value. */
const rustDeclaredWords = (words: readonly string[], site: ResultSite, depth: number) =>
  `${indent(rustTestOfDeclaredWords(words, site), depth).trimStart()}, ${JSON.stringify(site.member)}, ${JSON.stringify(words.join(" | "))}`;

/** `returned`, the `JSValue` that a thunk ends with, held to the words. Compiled code takes them for proven. */
function rustHoldResult(type: Type, site: ResultSite, returned: string): string {
  const words = checkedWordsOf(type);
  if (words === null) return returned;
  return `{
    let returned = ${returned};
    bindgen::hold_to_declared_type(cx, returned, ${rustDeclaredWords(words, site, 4)})
}`;
}

/**
 * Converts the arguments, then ends with the lines `finish` makes from `symbol(globalObject, ...leading, ...converted)`.
 * `fromParameters`: the arguments are the function's `JSValue` parameters `parameter0`.., not the call frame's, and a failed conversion returns `failure`.
 */
function cppCallBody(
  signature: Signature,
  symbol: string,
  leading: readonly string[] = [],
  finish = (call: string) => [`RELEASE_AND_RETURN(scope, ${call});`],
  fromParameters?: { failure: string },
  shared?: { particulars: Particulars; leadingTypes: readonly string[]; counted?: number },
): string {
  const indented = (lines: readonly string[]) => lines.map(line => `    ${line}`).join("\n");
  if (signature.cppInlineBody) {
    return indented(
      finish(`${signature.cppInlineBody.name}(globalObject, Bun::Bindgen::ArgumentsInFrame { *callFrame })`),
    );
  }
  // Converting a later argument can run JavaScript that detaches or resizes a buffer.
  const readLast: string[] = [];
  const generalize = signature.args.map(() => (text: string) => text);
  const convert = (argument: Argument, i: number): string[] => {
    const { name, type } = argument;
    if (type instanceof VariadicType) return [`auto converted${i} = Bun::Bindgen::variadicArguments(callFrame, ${i});`];
    const lines: string[] = [];
    if (type instanceof RestType) {
      if (type.convertsElements) {
        const ctx = cppContext(lines, i, name, undefined, "", signature.isWeb);
        const converted = `argument${i}.convertEach<${type.element.idlType}>(*globalObject, ${ctx})`;
        return [...lines, ...cppReturnIfFailed(converted, "{}").split("\n")];
      }
      if (!(type.element instanceof LocalStringType)) return [];
      const ctx = cppArgumentContext(lines, argument, i, `argument${i}.at(index)`, "index");
      return [
        ...lines,
        `for (size_t index = 0; index < argument${i}.size(); ++index) {`,
        `    if (!argument${i}.at(index).isString()) [[unlikely]] {`,
        `        ${ctx}.throwNotString(*globalObject, scope);`,
        "        return {};",
        "    }",
        "}",
      ];
    }
    const { value } = cppHeldArgument(type, i);
    readLast.push(...type.cppReadLast(`converted${i}`, value));
    if (shared && argument.expected === undefined && !argument.validatorExpects) {
      const converted = cppDeclareConvertedForSize(
        type,
        `converted${i}`,
        value,
        name,
        signature.isWeb,
        "{}",
        shared.particulars,
      );
      generalize[i] = converted.generalize;
      return converted.lines;
    }
    const ctx = cppArgumentContext(lines, argument, i, value, undefined, signature.isWeb);
    return [...lines, ...cppDeclareConverted(type, `converted${i}`, value, ctx, name, fromParameters?.failure ?? "{}")];
  };
  const lines = [
    ...signature.args.flatMap((argument, i) =>
      cppDeclareArgument(argument, i, fromParameters, i < (shared?.counted ?? 0)),
    ),
    ...signature.conversionOrder.flatMap(i => convert(signature.args[i], i)),
    ...readLast,
  ];
  const args = signature.args.map(({ type }, i) => {
    if (type instanceof RestType) return `argument${i}.data(), argument${i}.size()`;
    const extern = type.passesValue
      ? `${generalize[i](externType(type))} { ${toExtern(`converted${i}`)}, JSC::JSValue::encode(argument${i}.value()) }`
      : toExtern(`converted${i}`);
    if (!isPassedByPointer(type)) return extern;
    if (shared && !type.passesValue && isPlain(type))
      return `reinterpret_cast<${generalize[i](externType(type))}*>(&converted${i})`;
    lines.push(`auto extern${i} = ${extern};`);
    return `&extern${i}`;
  });
  if (shared) {
    const types = signature.args.map(
      ({ type }, i) => generalize[i](externType(type)) + (isPassedByPointer(type) ? "*" : ""),
    );
    symbol = `reinterpret_cast<JSC::EncodedJSValue(SYSV_ABI*)(${["JSC::JSGlobalObject*", ...shared.leadingTypes, ...types].join(", ")})>(function)`;
  }
  lines.push(...finish(`${symbol}(${["globalObject", ...leading, ...args].join(", ")})`));
  return indented(lines);
}

