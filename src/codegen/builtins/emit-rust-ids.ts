import type { Schema } from "../aot-schema/load.ts";
import { GeneratorError, Problems } from "./declarations.ts";
import type { ModelBuiltin, ModelClass, ModelFunction, ModelModule, ModelName, TableModel } from "./model.ts";
import { compareBytes } from "./paths.ts";

export type EnumRepr = "u8" | "u16" | "u32";

export interface RustEnum {
  name: string;
  repr: EnumRepr;
  countName: string;
  variants: readonly string[];
}

interface TokenTables {
  tokensName: string;
  byTokenName: string;
}

interface IdEnum extends RustEnum {
  tokenTables: TokenTables | null;
}

interface NameConstant {
  word: string;
  number: number;
}

export const fileHeader = "// Generated by src/codegen/builtins/index.ts in Bun's tree. Do not edit.\n";
const enumDerives = "#[derive(Copy, Clone, PartialEq, Eq, Hash, PartialOrd, Ord, Debug)]";
const rustIdentifierPattern = /^[A-Za-z_][A-Za-z0-9_]*$/;
const reservedMemberNames: ReadonlySet<string> = new Set(["Self", "_", "ALL", "COUNT"]);
const maxVariantCounts: Record<EnumRepr, number> = { u8: 2 ** 8, u16: 2 ** 16, u32: 2 ** 32 };
const nameExternal = "BuiltinName";

export function emitRustIds(model: TableModel, schema: Schema): string {
  const problems = new Problems();
  const enums = collectEnums(model);
  checkModel(model, enums, problems);
  const nameConstants = resolveNameConstants(model, schema, problems);
  problems.throwIfAny();
  return [
    fileHeader,
    ...enums.map(emitEnum),
    ...enums.map(({ countName, variants }) => emitCount(countName, variants.length)),
    emitCount("NAME_COUNT", model.names.length),
    `const RUNTIME_FUNCTION_LIMIT: u32 = ${computeRuntimeFunctionLimit(model.functions)};\n`,
    ...enums.map(emitTokenTables),
    emitNameConstants(nameConstants),
  ].join("");
}

function collectEnums(model: TableModel): IdEnum[] {
  const { checkedJSTypes, linkTimeConstants } = model.syntax;
  return [
    {
      name: "BuiltinId",
      repr: "u16",
      countName: "BUILTIN_COUNT",
      variants: model.builtins.map(getToken),
      tokenTables: { tokensName: "BUILTIN_TOKENS", byTokenName: "BUILTINS_BY_TOKEN" },
    },
    {
      name: "BuiltinClass",
      repr: "u16",
      countName: "CLASS_COUNT",
      variants: model.classes.map(getToken),
      tokenTables: { tokensName: "CLASS_TOKENS", byTokenName: "CLASSES_BY_TOKEN" },
    },
    {
      name: "RuntimeModule",
      repr: "u16",
      countName: "MODULE_COUNT",
      variants: model.modules.map(getToken),
      tokenTables: { tokensName: "MODULE_TOKENS", byTokenName: "MODULES_BY_TOKEN" },
    },
    {
      name: "CheckedJSType",
      repr: "u32",
      countName: "CHECKED_JS_TYPE_COUNT",
      variants: checkedJSTypes,
      tokenTables: null,
    },
    {
      name: "LinkTimeConstant",
      repr: "u32",
      countName: "LINK_TIME_CONSTANT_COUNT",
      variants: linkTimeConstants.map(capitalize),
      tokenTables: null,
    },
  ];
}

function checkModel(model: TableModel, enums: readonly RustEnum[], problems: Problems): void {
  checkDenseNumbers("builtins", model.builtins.map(getId), problems);
  checkDenseNumbers("classes", model.classes.map(getId), problems);
  checkDenseNumbers("modules", model.modules.map(getId), problems);
  checkDenseNumbers(
    "names",
    model.names.map(name => name.number),
    problems,
  );
  const firstToken = model.builtins[0]?.token;
  if (firstToken !== "GlobalThis") problems.add(null, `builtins[0] is ${firstToken}, not GlobalThis`);
  for (const rustEnum of enums) checkEnum(rustEnum, problems);
}

function checkDenseNumbers(listName: string, numbers: readonly number[], problems: Problems): void {
  const index = numbers.findIndex((number, position) => number !== position);
  if (index !== -1) problems.add(null, `${listName}[${index}] is numbered ${numbers[index]}`);
}

function checkEnum({ name, repr, variants }: RustEnum, problems: Problems): void {
  if (variants.length > maxVariantCounts[repr]) {
    problems.add(null, `${name} has ${variants.length} variants, more than a ${repr} can number`);
  }
  checkMemberNames(name, variants, problems);
}

function checkMemberNames(typeName: string, members: readonly string[], problems: Problems): void {
  const seen = new Set<string>();
  for (const member of members) {
    if (!rustIdentifierPattern.test(member) || reservedMemberNames.has(member)) {
      problems.add(null, `${typeName}::${member} is not a valid name for a member of a Rust type`);
    }
    if (seen.has(member)) problems.add(null, `${typeName}::${member} is declared twice`);
    seen.add(member);
  }
}

function computeRuntimeFunctionLimit(functions: readonly ModelFunction[]): number {
  return functions.reduce((limit, { id }) => Math.max(limit, id + 1), 0);
}

function emitTokenTables({ name, countName, variants, tokenTables }: IdEnum): string {
  if (tokenTables === null) return "";
  return [
    emitArray(`static ${tokenTables.tokensName}: [&str; ${countName}]`, variants.map(formatString)),
    emitArray(
      `static ${tokenTables.byTokenName}: [${name}; ${countName}]`,
      sortByBytes(variants).map(token => `${name}::${token}`),
    ),
  ].join("");
}

function resolveNameConstants(model: TableModel, schema: Schema, problems: Problems): NameConstant[] {
  const words = schema.externals.get(nameExternal) ?? [];
  checkMemberNames(nameExternal, words, problems);
  const constants: NameConstant[] = [];
  for (const word of words) {
    const name = model.names.find(candidate => candidate.cppConstant === word);
    if (name === undefined) {
      problems.add(null, `the schema lists ${nameExternal}::${word}, and the table has no such name`);
      continue;
    }
    constants.push({ word, number: name.number });
  }
  return constants.sort((a, b) => a.number - b.number);
}

function emitNameConstants(constants: readonly NameConstant[]): string {
  if (constants.length === 0) return "";
  const body = constants.map(({ word, number }) => `    pub const ${word}: Self = Self(${number});\n`).join("");
  return `#[allow(non_upper_case_globals)]\nimpl ${nameExternal} {\n${body}}\n`;
}

function getToken(item: { token: string }): string {
  return item.token;
}

function getId(item: { id: number }): number {
  return item.id;
}

export function formatBuiltinName(number: number): string {
  return `BuiltinName(${number})`;
}

export function formatBuiltinId(builtin: ModelBuiltin): string {
  return `BuiltinId::${builtin.token}`;
}

export function formatClass(builtinClass: ModelClass): string {
  return `BuiltinClass::${builtinClass.token}`;
}

export function formatModule(module: ModelModule): string {
  return `RuntimeModule::${module.token}`;
}

export function formatRuntimeFunction(id: number): string {
  return `RuntimeFunction(${id})`;
}

export function formatLinkTimeConstant(constant: string): string {
  return `LinkTimeConstant::${capitalize(constant)}`;
}

export function formatWellKnownSymbol(symbol: ModelName): string {
  if (symbol.kind !== "WellKnownSymbol") throw new GeneratorError(`${symbol.text} is not a well-known symbol`);
  return `WellKnownSymbol::${capitalize(symbol.text)}`;
}

export function formatOption<T>(value: T | null, format: (value: T) => string): string {
  return value === null ? "None" : `Some(${format(value)})`;
}

export function formatStruct(name: string, fields: readonly string[]): string {
  return `${name} { ${fields.join(", ")} }`;
}

export function capitalize(text: string): string {
  return text.charAt(0).toUpperCase() + text.slice(1);
}

export function emitEnum({ name, repr, countName, variants }: RustEnum): string {
  const body = variants.map(variant => `    ${variant},\n`).join("");
  const all = variants.map(variant => `        Self::${variant},\n`).join("");
  return [
    `${enumDerives}\n#[allow(non_camel_case_types)]\n#[repr(${repr})]\npub enum ${name} {\n${body}}\n`,
    `impl ${name} {\n    pub const ALL: [Self; ${countName}] = [\n${all}    ];\n}\n`,
  ].join("");
}

export function emitCount(name: string, count: number): string {
  return `const ${name}: usize = ${count};\n`;
}

function emitElements(elements: readonly string[]): string {
  return elements.map(element => `    ${element},\n`).join("");
}

export function emitArray(declaration: string, elements: readonly string[]): string {
  return `${declaration} = [\n${emitElements(elements)}];\n`;
}

export function emitSlice(declaration: string, elements: readonly string[]): string {
  return `${declaration} = &[\n${emitElements(elements)}];\n`;
}

function isPrintableAscii(byte: number): boolean {
  return byte >= 0x20 && byte <= 0x7e;
}

function escapeByte(byte: number): string {
  if (byte === 0x22) return '\\"';
  if (byte === 0x5c) return "\\\\";
  if (isPrintableAscii(byte)) return String.fromCharCode(byte);
  return `\\x${byte.toString(16).padStart(2, "0")}`;
}

export function formatByteString(text: string): string {
  return `b"${Array.from(Buffer.from(text, "utf8"), escapeByte).join("")}"`;
}

export function formatString(text: string): string {
  const bytes = Buffer.from(text, "utf8");
  if (!bytes.every(isPrintableAscii)) throw new GeneratorError(`${JSON.stringify(text)} is not printable ASCII`);
  return `"${Array.from(bytes, escapeByte).join("")}"`;
}

export function sortByBytes(texts: readonly string[]): string[] {
  return [...texts].sort(compareBytes);
}

export function sortUniqueNumbers(numbers: readonly number[]): number[] {
  return [...new Set(numbers)].sort((a, b) => a - b);
}

export function sortModules(modules: readonly ModelModule[]): ModelModule[] {
  return [...new Set(modules)].sort((a, b) => a.id - b.id);
}

export function sortStrictly<T>(
  items: readonly T[],
  compare: (a: T, b: T) => number,
  describeRepeat: (item: T) => string,
): T[] {
  const sorted = [...items].sort(compare);
  for (let index = 1; index < sorted.length; index++) {
    if (compare(sorted[index - 1], sorted[index]) === 0) throw new GeneratorError(describeRepeat(sorted[index]));
  }
  return sorted;
}
