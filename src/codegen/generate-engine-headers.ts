// Writes what C++ needs to know of the engine's Rust sources:
//   EngineConstants.h  the enums, flags, static names and realm slots that src/engine/embed/types.txt lists, and the options
//   EngineExports.h    a declaration and a typed wrapper for each `#[export]` function of src/engine/embed/api, and a
//                      declaration for each function that Rust expects of C++
import { readdirSync, readFileSync } from "node:fs";
import { join } from "node:path";
import { writeIfNotChanged } from "./helpers.ts";

const engine = join(import.meta.dirname, "..", "engine");
const outDir = process.argv[2];
const read = (path: string) => readFileSync(join(engine, path), "utf8");
const withoutComments = (source: string) => source.replace(/\/\/.*$/gm, "");
const header = (what: string) =>
  `// Generated by src/codegen/generate-engine-headers.ts from ${what}. Do not edit.\n#pragma once\n`;

/** The text between the bracket at `open` and the one that closes it. */
function enclosed(source: string, open: number): string {
  let depth = 0;
  for (let i = open; i < source.length; i++) {
    if ("([{".includes(source[i])) depth++;
    else if (")]}".includes(source[i]) && --depth === 0) return source.slice(open + 1, i);
  }
  throw new Error("unbalanced brackets");
}

function splitAtCommas(list: string): string[] {
  const parts: string[] = [];
  let [depth, start] = [0, 0];
  for (let i = 0; i < list.length; i++) {
    if ("([{<".includes(list[i])) depth++;
    else if (")]}".includes(list[i]) || (list[i] === ">" && list[i - 1] !== "-")) depth--;
    else if (list[i] === "," && depth === 0) (parts.push(list.slice(start, i)), (start = i + 1));
  }
  return [...parts, list.slice(start)].map(part => part.trim()).filter(Boolean);
}

type Kind = "cell" | "opaque" | "value" | "counted" | "wrapped";
const types = new Map<string, { kind: Kind; cpp: string }>();
const forwardDeclarations = new Set<string>();
const mirrors: [name: string, file: string][] = [];
for (const line of read("embed/types.txt").split("\n")) {
  const [kind, name, ...rest] = line.replace(/#.*/, "").trim().split(/\s+/);
  if (!kind) continue;
  if (kind === "mirror") {
    mirrors.push([name, rest[0]]);
    continue;
  }
  const keyword = rest[0] === "class" || rest[0] === "struct" ? rest.shift() : undefined;
  const cpp = rest.join(" ");
  types.set(name, { kind: kind as Kind, cpp });
  const scope = cpp.lastIndexOf("::");
  if (keyword) forwardDeclarations.add(`namespace ${cpp.slice(0, scope)} { ${keyword} ${cpp.slice(scope + 2)}; }`);
}

// ─── Constants ───

const integers: Record<string, string> = {
  u8: "uint8_t",
  u16: "uint16_t",
  u32: "uint32_t",
  u64: "uint64_t",
  usize: "size_t",
  i8: "int8_t",
  i16: "int16_t",
  i32: "int32_t",
  i64: "int64_t",
  isize: "ptrdiff_t",
};

const constants = (name: string, type: string, entries: string[]) =>
  `namespace ${name} {\nenum : ${type} {\n${entries.map(entry => `    ${entry},\n`).join("")}};\n}\n`;
const withoutAttributes = (item: string) => item.replace(/#\[[^\]]*\]\s*/g, "");
const cppExpression = (rust: string) =>
  rust.replace(/Self::|\.bits\(\)/g, "").replace(/(?<=\w)_(?=[0-9a-f]{4}\b)/g, "");

function mirror(name: string, file: string): string {
  const source = withoutComments(read(file));
  const body = (match: RegExpExecArray) => enclosed(source, match.index + match[0].length - 1);
  let match;
  if (
    (match = new RegExp(
      `#\\[repr\\((\\w+)\\)\\](?:\\s*#\\[[^\\]]*\\])*\\s*(?:pub(?:\\(\\w+\\))? )?enum ${name} \\{`,
    ).exec(source)) &&
    !body(match).includes("$")
  )
    return constants(name, integers[match[1]], splitAtCommas(body(match)).map(withoutAttributes).map(cppExpression));
  if ((match = new RegExp(`struct ${name}: (\\w+) \\{`).exec(source))) {
    const flags = [...body(match).matchAll(/const (\w+) =([^;]*);/g)];
    return constants(
      name,
      integers[match[1]],
      flags.map(flag => `${flag[1]} = ${cppExpression(flag[2].trim().replace(/\s+/g, " "))}`),
    );
  }
  // A list in an invocation of the macro that declares the type: `cell_types! { .. }` for `CellType`.
  const macro = name.replace(/(?<!^)[A-Z]/g, "_$&").toLowerCase() + "s";
  if ((match = new RegExp(`^${macro}! \\{`, "m").exec(source))) {
    const list = body(match).replace(/\w+ \{|\}/g, "");
    const entries = splitAtCommas(list).map(entry => cppExpression(withoutAttributes(entry).replace(/:.*/s, "")));
    return constants(name, "uint16_t", [...entries, ...(list.includes(" = 0,") ? [] : ["COUNT"])]);
  }
  throw new Error(`${file} does not declare ${name} in a form that is understood here`);
}

/** The integer that Rust passes for a type that is mirrored. */
function representation(name: string, file: string): string {
  const declaration = new RegExp(
    `#\\[repr\\((\\w+)\\)\\](?:\\s*#\\[[^\\]]*\\])*\\s*(?:pub(?:\\(\\w+\\))? )?enum ${name} \\{|struct ${name}(?:: |\\(pub )(\\w+)`,
  ).exec(withoutComments(read(file)))!;
  return integers[declaration[1] ?? declaration[2]];
}

/** In the order in which src/engine/text/build.rs lays them out. */
function staticNames(): string {
  const [atoms, symbols, privateNames] = [new Map<string, string>(), new Set<string>(), new Set<string>()];
  for (const line of read("text/names.txt").split("\n").filter(Boolean)) {
    if (line.startsWith("@@")) symbols.add(line.slice(2));
    else if (line.startsWith("@")) privateNames.add(line.slice(1));
    else atoms.set(line.split(" = ")[0], line.includes(" = ") ? line.slice(line.indexOf(" = ") + 3) : line);
  }
  let count = 256;
  const indexed = [...atoms.keys()].sort().map(name => {
    const text = Buffer.from(atoms.get(name)!);
    return `${name}_ = ${text.length === 1 ? text[0] : count++}`;
  });
  const list = (names: Set<string>) => [...[...names].sort().map(name => `${name}_`), "COUNT"];
  return [
    constants("StaticAtom", "uint16_t", [...indexed, `COUNT = ${count}`]),
    constants("WellKnownSymbol", "uint16_t", list(symbols)),
    constants("PrivateName", "uint16_t", list(privateNames)),
  ].join("\n");
}

/** The fields have the names by which the options are set. */
function options(): string {
  const list = [...read("vm/options.rs").matchAll(/^ +\w+ \/ (\w+): (\w+) =/gm)];
  const fields = list.map(
    ([, name, type]) => `    ${integers[type] ?? { bool: "bool", f64: "double" }[type]} ${name};\n`,
  );
  return `struct Options {\n${fields.join("")}    bool wereSet[${list.length}];\n};\n`;
}

writeIfNotChanged(
  join(outDir, "EngineConstants.h"),
  `${header("src/engine")}\n#include <cstddef>\n#include <cstdint>\n\nnamespace Engine {\n\n${[...mirrors.map(it => mirror(...it)), staticNames(), options()].join("\n")}\n}\n`,
);

// ─── Functions ───

const strings: Record<string, { raw: string; cpp: string; adopt: (p: string) => string }> = {
  StringRef: { raw: "WTF::StringImpl", cpp: "WTF::String", adopt: p => `WTF::String(WTF::adoptRef(${p}))` },
  Atom: { raw: "WTF::AtomStringImpl", cpp: "WTF::AtomString", adopt: p => `WTF::AtomString(WTF::adoptRef(${p}))` },
  Identifier: { raw: "WTF::UniquedStringImpl", cpp: "JSC::Identifier", adopt: p => `JSC::Identifier::adopt(${p})` },
};

const simplified = (type: string) =>
  type
    .replace(/<'\w+>/g, "")
    .replace(/'\w+,?\s*/g, "")
    .replace(/\b(?:\w+::)+(?=\w)/g, "")
    .trim();
const argumentOf = (type: string, wrapper: string) =>
  type.startsWith(`${wrapper}<`) ? type.slice(wrapper.length + 1, -1).trim() : undefined;
const pointee = (type: string) => /^(?:&mut |&|\*mut |\*const )(.*)$/s.exec(type)?.[1].trim() ?? argumentOf(type, "Gc");

function named(name: string): string {
  const known = {
    c_void: "void",
    bool: "bool",
    f64: "double",
    f32: "float",
    c_char: "char",
    StringImpl: "WTF::StringImpl",
  };
  const cpp = integers[name] ?? known[name] ?? types.get(name)?.cpp;
  if (!cpp) throw new Error(`src/engine/embed/types.txt does not have ${name}`);
  return cpp;
}

/** The type in a C declaration. What a caller in C++ passes by address is `const` unless Rust changes it. */
function raw(type: string, isPassedToRust: boolean): string {
  const inner = argumentOf(type, "Option") ?? argumentOf(type, "JsResult");
  if (inner !== undefined) return raw(inner, isPassedToRust);
  if (type === "()") return "void";
  if (type === "Value") return "JSC::EncodedJSValue";
  if (type === "PropertyName") return "WTF::UniquedStringImpl*";
  if (strings[type]) return `${strings[type].raw}*`;
  const callback = /^(?:unsafe )?extern "C" fn\(/.exec(type);
  if (callback) {
    const list = enclosed(type, callback[0].length - 1);
    const result =
      type
        .slice(callback[0].length + list.length + 1)
        .replace(/^\s*->/, "")
        .trim() || "()";
    const parameters = splitAtCommas(list).map(it => raw(it.replace(/^\w+: /, ""), false));
    return `std::add_pointer_t<${raw(result, false)}(${parameters.join(", ")})>`;
  }
  const target = pointee(type);
  if (target !== undefined) {
    const isNamed = /^\w+$/.test(target) && target !== "Value" && !strings[target] && target !== "PropertyName";
    const isConst =
      type.startsWith("*const ") ||
      (isPassedToRust && !type.startsWith("*") && (!type.startsWith("&mut ") || types.get(target)?.kind === "cell"));
    const cpp = isNamed && types.get(target)?.kind !== "counted" ? named(target) : raw(target, false);
    return `${cpp}${isConst ? " const" : ""}*`;
  }
  const known = types.get(type);
  if (known?.kind === "counted") return `${known.cpp}*`;
  if (known?.kind === "wrapped") return `${known.cpp}::Ptr`;
  if (known && known.kind !== "value") throw new Error(`${type} cannot be passed by value`);
  return named(type);
}

interface Parameter {
  raw: string[];
  cpp: string;
  pass: string;
  /** What Rust takes for granted and the type in C++ does not say. */
  requires?: string;
}

function parameter(type: string, name: string): Parameter {
  const one = (cpp: string, pass: string, requires?: string) => ({ raw: [raw(type, true)], cpp, pass, requires });
  const slice = /^&(mut )?\[(.*)\]$/.exec(type);
  if (slice && strings[slice[2]]) {
    const element = `${strings[slice[2]].raw}* const*`;
    return {
      raw: [element, "size_t"],
      cpp: `std::span<const ${strings[slice[2]].cpp}>`,
      pass: `reinterpret_cast<${element}>(${name}.data()), ${name}.size()`,
      requires: `std::ranges::none_of(${name}, &${strings[slice[2]].cpp}::isNull)`,
    };
  }
  if (slice) {
    const isOpaque = types.get(slice[2])?.kind === "opaque";
    const element = `${isOpaque ? named(slice[2]) : raw(slice[2], false)}${slice[1] ? "" : " const"}`;
    return {
      raw: [`${element}*`, "size_t"],
      cpp: `std::span<${element}>`,
      pass: `${name}.data(), ${name}.size()`,
      requires: slice[2] === "Value" ? `hasNoEmptyValue(${name})` : undefined,
    };
  }
  if (type === "Text")
    return {
      raw: ["const void*", "size_t", "bool"],
      cpp: "WTF::StringView",
      pass: `${name}.rawCharacters(), ${name}.length(), ${name}.is8Bit()`,
    };
  if (type === "AsciiLiteral")
    return { raw: ["const char*", "size_t"], cpp: "WTF::ASCIILiteral", pass: `${name}.characters(), ${name}.length()` };
  const optional = argumentOf(type, "Option");
  const bare = optional ?? type;
  const isOptional = optional !== undefined;
  if (bare === "Value") return one("JSC::JSValue", `JSC::JSValue::encode(${name})`);
  if (bare === "PropertyName")
    return one("JSC::PropertyName", `${name}.uid()`, isOptional ? undefined : `${name}.uid()`);
  if (bare === "&StringImpl") return one("const WTF::String&", isOptional ? `${name}.impl()` : `implOrEmpty(${name})`);
  if (bare === "StringRef") return one("WTF::String&&", `${isOptional ? "leak" : "leakOrEmpty"}(WTF::move(${name}))`);
  if (bare === "&Identifier")
    return one("const JSC::Identifier&", `${isOptional ? "addressOrNull" : "addressOrEmpty"}(${name})`);
  const known = types.get(bare);
  if (known?.kind === "counted")
    return isOptional
      ? one(`WTF::RefPtr<${known.cpp}>&&`, `${name}.leakRef()`)
      : one(`WTF::Ref<${known.cpp}>&&`, `&${name}.leakRef()`);
  if (known?.kind === "wrapped") return one(known.cpp, `${name}.get()`, isOptional ? undefined : `${name}.get()`);
  if (type.startsWith("&") && types.get(pointee(type)!)?.kind !== "cell") {
    if (type === "&mut Option<Value>") return one("JSC::JSValue&", `reinterpret_cast<JSC::EncodedJSValue*>(&${name})`);
    const owned = strings[argumentOf(pointee(type)!, "Option") ?? ""];
    if (owned) return one(`${owned.cpp}&`, `reinterpret_cast<${owned.raw}**>(&${name})`);
    const provider = type === "&SourceCode" ? `*reinterpret_cast<void* const*>(&${name})` : undefined;
    return one(raw(type, true).replace(/\*$/, "&"), `&${name}`, provider);
  }
  return one(raw(type, true), name, /^(&|Gc<)/.test(type) ? name : undefined);
}

function result(type: string): { cpp: string; convert: (call: string) => string } {
  let [bare, isOptional] = [type, false];
  for (let inner; (inner = argumentOf(bare, "JsResult") ?? argumentOf(bare, "Option")) !== undefined; bare = inner)
    isOptional = true;
  if (bare === "Value") return { cpp: "JSC::JSValue", convert: call => `JSC::JSValue::decode(${call})` };
  if (strings[bare]) return { cpp: strings[bare].cpp, convert: strings[bare].adopt };
  const known = types.get(bare);
  if (known?.kind === "counted")
    return isOptional
      ? { cpp: `WTF::RefPtr<${known.cpp}>`, convert: call => `WTF::adoptRef(${call})` }
      : { cpp: `WTF::Ref<${known.cpp}>`, convert: call => `WTF::adoptRef(*${call})` };
  if (known?.kind === "wrapped") return { cpp: known.cpp, convert: call => call };
  return { cpp: raw(type, false), convert: call => call };
}

function* functions(source: string, start: RegExp) {
  for (const match of source.matchAll(start)) {
    const open = match.index + match[0].length - 1;
    const list = enclosed(source, open);
    const returned = /^\s*(?:->([^{;]*))?[{;]/.exec(source.slice(open + list.length + 2))!;
    const parameters = splitAtCommas(list).map(it => simplified(it.slice(it.indexOf(":") + 1)));
    yield { name: match[1], parameters, returns: simplified(returned[1] ?? "()") };
  }
}

const [declarations, wrappers]: string[][] = [[], []];
for (const file of readdirSync(join(engine, "embed", "api")).sort()) {
  const source = withoutComments(read(`embed/api/${file}`));
  try {
    const exported = /#\[export\](?:\s*#\[[^\]]*\])*\s*(?:pub(?:\(\w+\))? )?(?:unsafe )?fn (\w+)(?:<[^>]*>)?\(/g;
    for (const { name, parameters, returns } of functions(source, exported)) {
      const list = parameters.map((type, index) => parameter(type, `a${index}`));
      const { cpp, convert } = result(returns);
      declarations.push(`${raw(returns, false)} engine_${name}(${list.flatMap(it => it.raw).join(", ")});`);
      const realm = parameters.findIndex(type => pointee(type) === "Cx");
      const mayThrow = returns.startsWith("JsResult<") && realm >= 0;
      const signature = [
        ...list.map((it, index) => `${it.cpp} a${index}`),
        ...(mayThrow ? ["bool canThrow = true"] : []),
      ];
      const body = [
        ...list.filter(it => it.requires).map(it => `ASSERT(${it.requires});`),
        ...(mayThrow ? [`MayThrow mayThrow(a${realm}, canThrow);`] : []),
        `return ${convert(`engine_${name}(${list.map(it => it.pass).join(", ")})`)};`,
      ];
      wrappers.push(`ALWAYS_INLINE ${cpp} ${name}(${signature.join(", ")}) { ${body.join(" ")} }`);
    }
    for (const block of source.matchAll(/unsafe extern "C" \{/g)) {
      const body = enclosed(source, block.index + block[0].length - 1);
      for (const { name, parameters, returns } of functions(body, /fn (\w+)(?:<[^>]*>)?\(/g))
        declarations.push(`${raw(returns, false)} ${name}(${parameters.map(it => raw(it, false)).join(", ")});`);
    }
  } catch (error) {
    throw new Error(`src/engine/embed/api/${file}: ${(error as Error).message}`);
  }
}

writeIfNotChanged(
  join(outDir, "EngineExports.h"),
  [
    header("src/engine/embed"),
    ...forwardDeclarations,
    ...mirrors
      .filter(([name]) => types.get(name)?.kind === "value")
      .map(it => `static_assert(sizeof(${types.get(it[0])!.cpp}) == sizeof(${representation(...it)}));`),
    '\nextern "C" {',
    ...declarations,
    "}\n\nnamespace Engine {",
    ...wrappers,
    "}\n",
  ].join("\n"),
);
