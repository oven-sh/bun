import { join } from "node:path";
import { BuildError } from "../../scripts/build/error.ts";
import {
  featureIndexLimit,
  featureNamed,
  firstEmbedderFeatureIndex,
  loadFeatures,
  narrowestTrimFeature,
  serializeFeatureModel,
  type Feature,
  type FeatureModel,
  type FeatureName,
  type TrimFeature,
} from "../../scripts/build/trim/features.ts";
import { rustTableFormat } from "../../scripts/build/trim/table-format.ts";
import { writeIfNotChanged } from "./helpers.ts";

const generatorPath = "src/codegen/generate-removable-features.ts";

const rustEnteredFrom: Record<Feature["enteredFrom"], string> = {
  program: "EnteredFrom::Program",
  startup: "EnteredFrom::Startup",
  "command-line": "EnteredFrom::CommandLine",
};

function checkNotEmpty(model: FeatureModel): void {
  if (model.features.length === 0) throw new BuildError("no feature is declared in src/trim/features/*.def");
  if (model.trimFeatures.length === 0) {
    throw new BuildError("no trim feature is declared in src/trim/features/trim-features.def");
  }
}

function hashDigits(model: FeatureModel): string {
  return model.hash.toString(16).padStart(16, "0");
}

function rustEnum(representation: "u8" | "u16", name: string, variants: string[]): string[] {
  return [
    `#[repr(${representation})]`,
    "#[derive(Copy, Clone, PartialEq, Eq, Hash, PartialOrd, Ord, Debug)]",
    `pub enum ${name} {`,
    ...variants.map(variant => `    ${variant},`),
    "}",
  ];
}

function rustSlice(name: string, elementType: string, elements: string[]): string[] {
  return [`pub(crate) const ${name}: &[${elementType}] = &[`, ...elements.map(element => `    ${element},`), "];"];
}

function rustFeatureNameFunction(features: Feature[]): string[] {
  return [
    "#[unsafe(no_mangle)]",
    'extern "C" fn Bun__removableFeatureName(index: u16) -> *const core::ffi::c_char {',
    "    match index {",
    ...features.map(({ name, index }) => `        ${index} => c${JSON.stringify(name)}.as_ptr(),`),
    "        _ => core::ptr::null(),",
    "    }",
    "}",
  ];
}

export function rustSource(model: FeatureModel): string {
  checkNotEmpty(model);
  const { features, trimFeatures } = model;
  const featurePath = (feature: Feature) => `Feature::${feature.rustName}`;
  const trimFeaturePath = (trimFeature: TrimFeature) => `TrimFeature::${trimFeature.rustName}`;
  const featureList = (names: FeatureName[]) =>
    `&[${names.map(name => featurePath(featureNamed(model, name))).join(", ")}]`;

  const featureRecord = (feature: Feature) => {
    const narrowest = narrowestTrimFeature(model, feature.name);
    const members = [
      `name: ${JSON.stringify(feature.name)}`,
      `text: ${JSON.stringify(feature.text)}`,
      `entered_from: ${rustEnteredFrom[feature.enteredFrom]}`,
      `narrowest_trim_feature: ${narrowest ? `Some(${trimFeaturePath(narrowest)})` : "None"}`,
    ];
    return `FeatureRecord { ${members.join(", ")} }`;
  };

  const trimFeatureRecord = (trimFeature: TrimFeature) => {
    const members = [`name: ${JSON.stringify(trimFeature.name)}`, `features: ${featureList(trimFeature.features)}`];
    return `TrimFeatureRecord { ${members.join(", ")} }`;
  };

  const featureVariants = features.map(({ rustName, index }) => `${rustName} = ${index}`);
  const trimFeatureVariants = trimFeatures.map(({ rustName }, position) => `${rustName} = ${position}`);
  return [
    `// Generated by ${generatorPath}. Do not edit.`,
    `pub const FEATURES_HASH: u64 = 0x${hashDigits(model).replace(/.{4}(?=.)/g, "$&_")};`,
    ...rustEnum("u16", "Feature", featureVariants),
    ...rustEnum("u8", "TrimFeature", trimFeatureVariants),
    ...rustSlice("ALL_FEATURES", "Feature", features.map(featurePath)),
    ...rustSlice("ALL_TRIM_FEATURES", "TrimFeature", trimFeatures.map(trimFeaturePath)),
    ...rustSlice("FEATURE_RECORDS", "FeatureRecord", features.map(featureRecord)),
    ...rustSlice("TRIM_FEATURE_RECORDS", "TrimFeatureRecord", trimFeatures.map(trimFeatureRecord)),
    ...rustFeatureNameFunction(features),
    "pub(crate) const RUST_SOURCE_VERSION: u32 = 3;",
    "",
  ].join("\n");
}

export function cppHeader(model: FeatureModel): string {
  checkNotEmpty(model);
  const { features } = model;
  const engineFeatures = features.filter(feature => feature.isEngine);
  const literal = (text: string) => `${JSON.stringify(text)}_s`;

  const constant = ({ name, index, isEngine }: Feature) =>
    `inline constexpr JSC::RemovableFeature ${name} ${isEngine ? `= JSC::RemovableFeature::${name}` : `{ ${index} }`};`;
  const indexAssertion = ({ name, index }: Feature) =>
    `static_assert(static_cast<uint16_t>(JSC::RemovableFeature::${name}) == ${index});`;
  const featureText = ({ name, index, text }: Feature) =>
    `    { ${index}, ${literal(text)}, ${literal(narrowestTrimFeature(model, name)?.name ?? "")} },`;

  return [
    `// Generated by ${generatorPath} from src/trim/features/*.def. Do not edit.`,
    "#pragma once",
    "#include <JavaScriptCore/AOTRemovableFeature.h>",
    "#include <wtf/text/ASCIILiteral.h>",
    "namespace Bun::Feature {",
    ...features.map(constant),
    "}",
    `static_assert(JSC::firstEmbedderRemovableFeature == ${firstEmbedderFeatureIndex} && JSC::removableFeatureIndexLimit == ${featureIndexLimit});`,
    ...engineFeatures.map(indexAssertion),
    "namespace Bun {",
    `inline constexpr unsigned numberOfEngineRemovableFeatures = ${engineFeatures.length};`,
    `inline constexpr uint64_t removableFeaturesHash = 0x${hashDigits(model)}ULL;`,
    "struct RemovableFeatureText { uint16_t index; ASCIILiteral text; ASCIILiteral trimFeatureName; };",
    "inline constexpr RemovableFeatureText removableFeatureTexts[] = {",
    ...features.map(featureText),
    "};",
    "}",
    `static_assert(JSC::numberOfEngineRemovableFeatures == Bun::numberOfEngineRemovableFeatures, "src/trim/features/engine.def and JavaScriptCore's generated feature list differ");`,
    "",
  ].join("\n");
}

function generate(repositoryRoot: string, codegenDir: string): void {
  const model = loadFeatures(repositoryRoot);
  const outputs = {
    "removable_features.rs": rustSource(model) + rustTableFormat().join("\n") + "\n",
    "BunRemovableFeatures.h": cppHeader(model),
    "removable-features.json": serializeFeatureModel(model),
  };
  for (const [name, text] of Object.entries(outputs)) writeIfNotChanged(join(codegenDir, name), text);
}

if (import.meta.main) {
  const [repositoryRoot, codegenDir, ...rest] = process.argv.slice(2);
  if (repositoryRoot === undefined || codegenDir === undefined || rest.length > 0) {
    console.error(`usage: bun ${generatorPath} <repository root> <codegen dir>`);
    process.exit(1);
  }
  try {
    generate(repositoryRoot, codegenDir);
  } catch (error) {
    if (!(error instanceof BuildError)) throw error;
    process.stderr.write(error.format());
    process.exit(1);
  }
}
