import type { Reference, Table } from "./table.ts";

function rustString(text: string): string {
  let out = '"';
  for (const character of text) {
    const code = character.codePointAt(0)!;
    if (character === "\\") out += "\\\\";
    else if (character === '"') out += '\\"';
    else if (character === "\n") out += "\\n";
    else if (character === "\r") out += "\\r";
    else if (character === "\t") out += "\\t";
    else if (code < 0x20 || code > 0x7e) out += `\\u{${code.toString(16)}}`;
    else out += character;
  }
  return out + '"';
}

function withoutIndentation(text: string): string {
  if (text.includes("`") || text.includes("\\\n")) return text;
  return text.replace(/\n[ \t]+/g, "\n");
}

function rustReference(reference: Reference): string {
  if (reference.kind === "itself") return "Reference::Itself";
  if (reference.kind === "helper") return `Reference::Helper(Helper::${reference.helper})`;
  if (reference.kind === "operand") return "Reference::Operand";
  return `Reference::Global(&[${reference.path.map(rustString).join(", ")}])`;
}

function unique(names: readonly string[]): string[] {
  return [...new Set(names)];
}

export function writeRust(table: Table): string {
  const helpers = unique(table.entries.map(entry => entry.line.helper));
  const shapes = unique(table.entries.map(entry => entry.line.shape));
  const helperOf = new Map<string, string>(table.entries.map(entry => [entry.line.shape, entry.line.helper]));
  const lines = [
    "// Generated by src/codegen/known-helpers/index.ts from the published sources of the helpers. Do not edit.",
    "",
    "use super::{PublishedFunction, Reference};",
    "",
    "#[derive(Copy, Clone, PartialEq, Eq, Hash, Debug)]",
    "pub enum Helper {",
    ...helpers.map(helper => `    ${helper},`),
    "}",
    "",
    "#[derive(Copy, Clone, PartialEq, Eq, Hash, Debug)]",
    "pub enum Shape {",
    ...shapes.map(shape => `    ${shape},`),
    "}",
    "",
    "impl Shape {",
    "    pub const fn helper(self) -> Helper {",
    "        match self {",
    ...shapes.map(shape => `            Shape::${shape} => Helper::${helperOf.get(shape)},`),
    "        }",
    "    }",
    "}",
    "",
    "pub(super) static PUBLISHED_FUNCTIONS: &[PublishedFunction] = &[",
  ];
  for (const entry of table.entries) {
    const references = entry.references.map(([name, reference]) => `(${rustString(name)}, ${rustReference(reference)})`);
    lines.push(
      "    PublishedFunction {",
      `        shape: Shape::${entry.line.shape},`,
      `        text: ${rustString(withoutIndentation(entry.tree.text))},`,
      `        references: &[${references.join(", ")}],`,
      `        origin: ${rustString(entry.origin)},`,
      "    },",
    );
  }
  lines.push("];", "");
  return lines.join("\n");
}
