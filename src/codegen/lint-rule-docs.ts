// Generates part of the lint rule docs in `docs/lint/rules/<plugin>/<rule>.mdx`.
//
// You write `title`, `description` and the body by hand. This script fills in the rest of the frontmatter, adds the
// "## Configure" section and writes `index.mdx`, using the output of `bun lint --rules -f json`:
//
//   bun src/codegen/lint-rule-docs.ts --write [--bun=<path to bun> | --rules=<file with that JSON>]
//
// It also lints every example and writes what gets reported to `reports.json`. The website underlines that in the
// examples. With `--rules` there's no `bun` to lint with, so that file is left alone.
//
// `test/cli/lint/rule-docs.test.ts` fails if the generated parts are stale. It also runs every example on every page.
import {
  existsSync,
  mkdirSync,
  mkdtempSync,
  readdirSync,
  readFileSync,
  rmSync,
  statSync,
  writeFileSync,
} from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, relative, sep } from "node:path";
import {
  documentedIn,
  inferredSchema,
  isObject,
  optionsSnippet,
  WIDTH,
  type Json,
  type Schema,
  type Snippet,
} from "./lint-rule-options.ts";

export const pagesRoot = join(import.meta.dirname, "..", "..", "docs", "lint", "rules");

/** One entry in the output of `bun lint --rules -f json`. */
export type Rule = {
  scope: string;
  value: string;
  id: string;
  aliases: string[];
  description: string;
  kind: string | null;
  category: string | null;
  fix: string;
  type_aware: boolean;
  deprecated: boolean;
  on_by_default: "error" | "warn" | false;
  docs_url: string;
  /** JSON schema of the options. `null` if the rule takes none, or if it was ported from oxlint, which has no schemas. */
  schema: Schema | Schema[] | null;
  default_options: Json[] | null;
  /**
   * Without an ESLint config, a core rule and its typescript-eslint version act as one rule. Setting either name sets
   * both, and each runs in its own kind of file. Filled in by `readRules`.
   */
  twin?: Rule;
};

/** Parses the output of `bun lint --rules -f json`. */
export function readRules(json: string) {
  const rules: Rule[] = JSON.parse(json);
  for (const rule of rules)
    rule.twin = rules.find(
      it => it.value === rule.value && [it.scope, rule.scope].sort().join() === "eslint,typescript" && it !== rule,
    );
  return rules;
}

/** Page name for a rule, e.g. `typescript/no-explicit-any`. Taken from its docs URL. */
export const pageOf = (rule: Rule) =>
  rule.docs_url.slice(rule.docs_url.indexOf("/lint/rules/") + "/lint/rules/".length);

const walk = (dir: string): string[] =>
  readdirSync(dir).flatMap(name =>
    statSync(join(dir, name)).isDirectory() ? walk(join(dir, name)) : [join(dir, name)],
  );

/** Names of all existing pages, e.g. `typescript/no-explicit-any`. */
export const pageNames = (root = pagesRoot) =>
  walk(root)
    .filter(path => path.endsWith(".mdx"))
    .map(path => relative(root, path).slice(0, -".mdx".length).split(sep).join("/"))
    .filter(name => name.includes("/"))
    .sort();

const MARK = "# Generated by src/codegen/lint-rule-docs.ts. Do not edit below this line.";

export type Page = { title: unknown; description: unknown; written: string; generated: string; body: string };

export function readPage(text: string): Page | null {
  const found = /^---\n([\s\S]*?)\n---\n/.exec(text);
  if (!found) return null;
  const [written, generated = ""] = found[1].split(`\n${MARK}\n`);
  const field = (key: string) => {
    const value = new RegExp(`^${key}: (.*)$`, "m").exec(written)?.[1];
    try {
      return value === undefined ? undefined : JSON.parse(value);
    } catch {
      return undefined;
    }
  };
  return {
    title: field("title"),
    description: field("description"),
    written,
    generated,
    body: text.slice(found[0].length),
  };
}

const fixable = (fix: string) =>
  fix === "none" ? "no" : fix.includes("suggestion") && !fix.includes("fix_or") ? "suggestion" : "yes";

export const generatedFor = (rule: Rule) =>
  [
    `plugin: ${JSON.stringify(pageOf(rule).split("/")[0])}`,
    `aliases: ${JSON.stringify(rule.aliases)}`,
    `kind: ${JSON.stringify(rule.kind)}`,
    `category: ${JSON.stringify(rule.category)}`,
    `default: ${JSON.stringify(rule.on_by_default || "off")}`,
    `fixable: ${JSON.stringify(fixable(rule.fix))}`,
    `typeAware: ${rule.type_aware}`,
    `deprecated: ${rule.deprecated}`,
  ].join("\n");

const CONFIG_START = "{/* Generated by src/codegen/lint-rule-docs.ts. Do not edit this section. */}";
const CONFIG_END = "{/* End of the generated section. */}";

/** The `[lint.rules]` lines in a rule's "## Configure" section. */
export type Config = {
  /** Turns the rule on, or off if it's on by default. */
  toggle: string[];
  /** The rule is a config error without options, so `toggle` has some. */
  needsOptions: boolean;
  /** Sets every option to its default. */
  defaults?: Snippet;
};

/** `written` is the page's body without the generated section. `null` for a rule that nobody should turn on. */
export function configFor(rule: Rule, written: string): Config | null {
  if (rule.deprecated || written.includes("\n{/* never reports */}\n")) return null;
  const documented = documentedIn(written);
  const schema = rule.schema ?? inferredSchema(documented, examplesOf(pageOf(rule), written, 1).examples);
  const severity = rule.on_by_default || "error";
  // Where the twin's default differs, no value is the default in every file.
  const unset = (rule.default_options ?? []).flatMap((options, i) => {
    const other = rule.twin?.default_options?.[i];
    if (!isObject(options) || !isObject(other)) return [];
    return Object.keys(options).filter(key => key in other && !Bun.deepEquals(options[key], other[key]));
  });
  const snippet = schema && optionsSnippet(rule.id, severity, schema, rule.default_options ?? [], documented, unset);
  if (snippet?.isRequired) return { toggle: snippet.lines, needsOptions: true };
  const toggle = `${JSON.stringify(rule.id)} = "${rule.on_by_default ? "off" : "error"}"`;
  const hint = ` # or "${severity === "error" ? "warn" : "error"}"`;
  return {
    toggle: [toggle.length + hint.length <= WIDTH ? toggle + hint : toggle],
    needsOptions: false,
    defaults: snippet ?? undefined,
  };
}

function configSection(rule: Rule, { toggle, needsOptions, defaults }: Config) {
  const block = (lines: string[]) => `\`\`\`toml bunfig.toml\n[lint.rules]\n${lines.join("\n")}\n\`\`\``;
  const parts = ["## Configure"];
  if (rule.on_by_default === "error") parts.push("On by default as an error. To turn it off:");
  else if (rule.on_by_default) parts.push("On by default as a warning. To turn it off:");
  else if (rule.type_aware)
    parts.push("Off by default. This rule needs types, so turning it on makes `bun lint` type check your code first.");
  else if (needsOptions) parts.push("Off by default. It needs an option:");
  else parts.push("Off by default. To turn it on:");
  parts.push(block(toggle));
  if (defaults?.hasUnset)
    parts.push("Every option, set to its default. The ones that are commented out are unset by default.");
  else if (defaults) parts.push("Every option, set to its default:");
  if (defaults) parts.push(block(defaults.lines));
  return parts.join("\n\n");
}

/** A page's body without the generated section. */
export function writtenPart(body: string) {
  const [start, end] = [body.indexOf(`${CONFIG_START}\n`), body.indexOf(`${CONFIG_END}\n\n`)];
  return start < 0 || end < start ? body : body.slice(0, start) + body.slice(end + CONFIG_END.length + 2);
}

/** A page's body with an up-to-date "## Configure" section, which goes before "## Examples". */
export function bodyFor(rule: Rule, body: string) {
  const written = writtenPart(body);
  const config = configFor(rule, written);
  const at = written.search(/^## Examples$/m);
  if (!config || at < 0) return written;
  const section = `${CONFIG_START}\n\n${configSection(rule, config)}\n\n${CONFIG_END}\n\n`;
  return written.slice(0, at) + section + written.slice(at);
}

export const withGenerated = (page: Page, rule: Rule) =>
  `---\n${page.written}\n${MARK}\n${generatedFor(rule)}\n---\n${bodyFor(rule, page.body)}`;

const PLUGINS: Record<string, string> = {
  "eslint": "ESLint",
  "typescript": "typescript-eslint",
  "react": "React",
  "react-perf": "React performance",
  "jsx-a11y": "Accessibility (jsx-a11y)",
  "nextjs": "Next.js",
  "import": "import",
  "unicorn": "unicorn",
  "promise": "promise",
  "node": "Node.js (n)",
  "oxc": "oxc",
  "bun": "Bun",
  "bun-test": "bun:test",
  "jest": "Jest",
  "vitest": "Vitest",
  "prettier": "Prettier",
};

/** Contents of `index.mdx`: a table of every rule, grouped by plugin. */
export function indexFor(rules: Rule[]) {
  const cell = (text: string) => text.replaceAll("|", "\\|");
  const sections = Object.entries(PLUGINS).map(([plugin, name]) => {
    const rows = rules
      .filter(rule => pageOf(rule).split("/")[0] === plugin)
      .sort((a, b) => (a.id < b.id ? -1 : 1))
      .map(
        rule =>
          `| [\`${rule.id}\`](/lint/rules/${pageOf(rule)}) | ${cell(rule.description)} | ${rule.on_by_default || ""} | ${fixable(rule.fix) === "no" ? "" : fixable(rule.fix)} | ${rule.type_aware ? "yes" : ""} |`,
      );
    return `## ${name}\n\n${rows.length} rules.\n\n| Rule | Description | Default | Fixable | Needs types |\n| --- | --- | --- | --- | --- |\n${rows.join("\n")}\n`;
  });
  return `---
title: "Lint rules"
description: "Every rule built into bun lint"
---

{/* Generated by src/codegen/lint-rule-docs.ts. Do not edit. */}

\`bun lint\` has ${rules.length.toLocaleString("en-US")} rules built in. Turn one on in [\`bunfig.toml\`](/lint#configure-rules), or read about it in the terminal with \`bun lint --explain <rule>\`.

${sections.join("\n")}`;
}

export type Example = {
  page: string;
  /** Line number in the page where the code block starts. */
  line: number;
  want: "bad" | "good";
  language: string;
  code: string;
  options: unknown[];
  count?: number;
  filename: string;
  compilerOptions?: Record<string, unknown>;
  /** Lint this example in its own project directory. Needed when options are paths relative to the project root. */
  root: boolean;
  /** Lint this example with an `.oxlintrc.json` that enables the rule. For rules that only report with an oxlint config. */
  config?: "oxlint";
  settings?: Record<string, unknown>;
  /** Fake packages to install next to the example (name to version). For rules that check installed versions. */
  packages?: Record<string, string>;
  /** Extra files to write next to the example. */
  files: Record<string, string>;
};

/**
 * Parses the examples on a page. Each code block needs a marker comment on the line before it:
 *
 * - `{/* bad *\/}`: the rule must report this code.
 * - `{/* good *\/}`: the rule must not report this code.
 * - `{/* file "name" *\/}`: an extra file for the next example.
 * - `{/* skip *\/}`: don't run this block.
 *
 * `bad` and `good` can be followed by JSON with `options`, `count`, `filename`, `compilerOptions`, `root`, `config`,
 * `settings` or `packages`. A page with `{/* never reports *\/}` on its own line doesn't need a `bad` example.
 */
export function examplesOf(page: string, body: string, firstLine: number): { examples: Example[]; problems: string[] } {
  const [examples, problems]: [Example[], string[]] = [[], []];
  const lines = body.split("\n");
  let pending: { word: string; meta: any; line: number } | null = null;
  let files: Record<string, string> = {};
  for (let i = 0; i < lines.length; i++) {
    const marker = /^\{\/\*\s*(bad|good|file|skip)\s*(.*?)\s*\*\/\}$/.exec(lines[i]);
    if (marker) {
      let meta: any = {};
      try {
        if (marker[2]) meta = JSON.parse(marker[2]);
      } catch {
        problems.push(`line ${firstLine + i}: invalid JSON after "${marker[1]}"`);
      }
      pending = { word: marker[1], meta, line: firstLine + i };
      continue;
    }
    const fence = /^```(\w*)/.exec(lines[i]);
    if (!fence) {
      if (pending && lines[i].trim()) problems.push(`line ${pending.line}: marker must be directly above a code block`);
      if (lines[i].trim()) pending = null;
      continue;
    }
    let end = i + 1;
    while (end < lines.length && !lines[end].startsWith("```")) end++;
    const code = lines.slice(i + 1, end).join("\n") + "\n";
    if (!pending) {
      if (/^([cm]?[jt]s|[jt]sx)$/.test(fence[1]))
        problems.push(`line ${firstLine + i}: ${fence[1]} block has no marker (bad, good, file or skip)`);
    } else if (pending.word === "file") {
      files[String(pending.meta)] = code;
    } else if (pending.word !== "skip") {
      const {
        options = [],
        count,
        filename = `example.${fence[1] || "js"}`,
        compilerOptions,
        root = false,
        config,
        settings,
        packages,
      } = pending.meta;
      examples.push({
        page,
        line: firstLine + i,
        want: pending.word as "bad" | "good",
        language: fence[1],
        code,
        options,
        count,
        filename,
        compilerOptions,
        root,
        config,
        settings,
        packages,
        files,
      });
      files = {};
    }
    pending = null;
    i = end;
  }
  const neverReports = lines.includes("{/* never reports */}");
  if (!neverReports && !examples.some(it => it.want === "bad")) problems.push("missing a {/* bad */} example");
  if (!examples.some(it => it.want === "good")) problems.push("missing a {/* good */} example");
  return { examples, problems };
}

/** The examples on a page, given the whole text of the page. */
export function examplesIn(page: string, text: string) {
  const body = readPage(text)?.body;
  if (body === undefined) return null;
  return examplesOf(page, body, text.slice(0, text.length - body.length).split("\n").length);
}

/** `compilerOptions` for the examples of rules that need types. */
export const typed = {
  strict: true,
  noEmit: true,
  target: "esnext",
  module: "esnext",
  moduleResolution: "bundler",
  jsx: "preserve",
  lib: ["esnext", "dom"],
  skipLibCheck: true,
};

export type Lint = (
  cwd: string,
  args: string[],
) => Promise<{ stdout: string; stderr: string; exitCode: number | null }>;

/** Where a rule reports in an example and what it says. 1-based, columns in UTF-16 units, the end is exclusive. */
export type Report = [line: number, column: number, endLine: number, endColumn: number, message: string];

/** What the page's rule reports in an example, or why the example couldn't be linted. */
export type Outcome = { reports: Report[]; error?: string };

/** Pages of rules whose message has a path with `\` in it on Windows. In other messages a `\` is part of what they say. */
const joinsPaths = new Set(["import/named", "import/no-relative-packages"]);

/** Lints every example, each in a directory of its own in `dir`. */
export async function lintExamples(dir: string, examples: Example[], byPage: Map<string, Rule>, lint: Lint) {
  const outcomes = new Map<Example, Outcome>();
  const nameOf = (it: Example) => `${it.page.replaceAll("/", "__")}__${it.line}`;
  const directoryOf = (it: Example) => join(dir, nameOf(it));
  const put = (path: string, content: string) => (
    mkdirSync(dirname(path), { recursive: true }),
    writeFileSync(path, content)
  );
  // A few messages name a file by its whole path. Make that `/project/file.js` on every machine.
  const portable = (it: Example, message: string) => {
    const said = message.replace(new RegExp(`[^\\s'"\`]*${nameOf(it)}[\\\\/]`, "g"), "/project/");
    return joinsPaths.has(it.page) ? said.replaceAll("\\", "/") : said;
  };

  put(join(dir, "package.json"), JSON.stringify({ dependencies: { react: "^19.0.0" } }));
  for (const it of examples) {
    const rule = byPage.get(it.page)!;
    for (const [name, content] of Object.entries(it.files)) put(join(directoryOf(it), name), content);
    for (const [name, version] of Object.entries(it.packages ?? {}))
      put(join(directoryOf(it), "node_modules", name, "package.json"), JSON.stringify({ name, version }));
    // Escape `*/` in options like `**/*.js`, or it would close the comment.
    const setting = JSON.stringify(["error", ...it.options]).replaceAll("*/", "*\\/");
    put(join(directoryOf(it), it.filename), `${it.code}\n/* eslint ${rule.id}: ${setting} */\n`);
    if (!rule.type_aware) continue;
    const compilerOptions = { ...typed, ...it.compilerOptions };
    put(join(directoryOf(it), "tsconfig.json"), JSON.stringify({ compilerOptions, include: ["."] }));
  }

  // Two runs for most examples: one without types, one with. Each `root` example gets its own run.
  const native = examples.filter(it => it.config !== "oxlint");
  const together = native.filter(it => !it.root);
  const runs = [
    ...[false, true].map(typed => ({
      cwd: dir,
      typed,
      part: together.filter(it => byPage.get(it.page)!.type_aware === typed),
    })),
    ...native
      .filter(it => it.root)
      .map(it => ({ cwd: directoryOf(it), typed: byPage.get(it.page)!.type_aware, part: [it] })),
  ];
  for (const it of examples) if (it.root && !it.files["package.json"]) put(join(directoryOf(it), "package.json"), "{}");
  for (const { cwd, typed, part } of runs) {
    if (part.length === 0) continue;
    const paths = part.map(it => directoryOf(it).slice(cwd.length + 1) || ".");
    const { stdout, stderr } = await lint(cwd, ["-f", "json", ...(typed ? ["--type-aware"] : []), ...paths]);
    type Message = {
      ruleId: string | null;
      fatal?: boolean;
      message: string;
      line: number;
      column: number;
      endLine?: number;
      endColumn?: number;
    };
    let report: { filePath: string; messages: Message[] }[];
    try {
      report = JSON.parse(stdout);
    } catch {
      throw new Error(`bun lint printed no JSON: ${stderr.slice(0, 2000)}`);
    }
    const byFile = new Map(report.map(it => [it.filePath, it.messages]));
    for (const it of part) {
      const rule = byPage.get(it.page)!;
      const messages = byFile.get(join(directoryOf(it), it.filename));
      const ids = [rule.id, ...rule.aliases, rule.twin?.id];
      const own = messages?.filter(message => ids.includes(message.ruleId!)) ?? [];
      // Invalid options are reported under the rule's own ID, so don't count that as a real report.
      const fatal =
        messages?.find(message => message.fatal) ??
        own.find(message => message.message.startsWith("Inline configuration for rule"));
      outcomes.set(it, {
        error: messages ? fatal?.message : `${it.filename} was not linted`,
        reports: own.map(({ line, column, endLine = line, endColumn = column, message }) => [
          line,
          column,
          endLine,
          endColumn,
          portable(it, message),
        ]),
      });
    }
  }

  // Rules that only report with an oxlint config.
  for (const it of examples.filter(it => it.config === "oxlint")) {
    const rule = byPage.get(it.page)!;
    const name = `${rule.scope.replaceAll("_", "-")}/${rule.value}`;
    const plugins = [
      "typescript",
      "unicorn",
      "oxc",
      "react",
      "react-perf",
      "import",
      "jsx-a11y",
      "nextjs",
      "promise",
      "node",
      "jest",
      "vitest",
    ];
    put(join(directoryOf(it), "package.json"), "{}");
    put(join(directoryOf(it), it.filename), it.code);
    put(
      join(directoryOf(it), ".oxlintrc.json"),
      JSON.stringify({
        plugins,
        categories: { correctness: "off" },
        settings: it.settings ?? {},
        rules: { [name]: ["error", ...it.options] },
      }),
    );
    const { stdout, stderr, exitCode } = await lint(directoryOf(it), ["-f", "json", "."]);
    if (exitCode === 2) {
      outcomes.set(it, { reports: [], error: stderr.slice(0, 300) });
      continue;
    }
    // oxlint's JSON has byte offsets.
    const bytes = Buffer.from(it.code);
    const at = (offset: number) => {
      const before = bytes.subarray(0, offset).toString().split("\n");
      return [before.length, before.at(-1)!.length + 1] as const;
    };
    const found: { message: string; labels: { span: { offset: number; length: number } }[] }[] =
      JSON.parse(stdout).diagnostics;
    outcomes.set(it, {
      reports: found.map(({ message, labels }) => {
        const { offset, length } = labels[0]?.span ?? { offset: 0, length: 0 };
        return [...at(offset), ...at(offset + length), portable(it, message)];
      }),
    });
  }
  return outcomes;
}

/** By page, then by the example's place among the examples of its page. Examples without reports are left out. */
export type Reports = Record<string, Record<number, Report[]>>;

/** `examples` has all the examples of each of its pages, in order. */
export function reportsOf(examples: Example[], outcomes: Map<Example, Outcome>) {
  const reports: Reports = {};
  const seen = new Map<string, number>();
  for (const it of examples) {
    const place = seen.get(it.page) ?? 0;
    seen.set(it.page, place + 1);
    const found = outcomes.get(it)?.reports ?? [];
    if (found.length) (reports[it.page] ??= {})[place] = found;
  }
  return reports;
}

/** A line per page, so that a change to one rule is a change to one line. */
export const reportsText = (reports: Reports) =>
  `{\n${Object.keys(reports)
    .sort()
    .map(page => `${JSON.stringify(page)}: ${JSON.stringify(reports[page])}`)
    .join(",\n")}\n}\n`;

if (import.meta.main) {
  const flag = (name: string) => process.argv.find(it => it.startsWith(`--${name}=`))?.slice(name.length + 3);
  const lint: Lint = async (cwd, args) => {
    const { stdout, stderr, exitCode } = Bun.spawnSync({
      cmd: [flag("bun") ?? process.execPath, "lint", ...args],
      env: { ...process.env, npm_lifecycle_event: "lint" },
      cwd,
    });
    return { stdout: stdout.toString(), stderr: stderr.toString(), exitCode };
  };
  const list = async () => (await lint(pagesRoot, ["--rules", "-f", "json"])).stdout;
  const rules = readRules(flag("rules") ? readFileSync(flag("rules")!, "utf8") : await list());
  let changed = 0;
  const put = (path: string, text: string) => {
    if (existsSync(path) && readFileSync(path, "utf8") === text) return;
    changed++;
    if (process.argv.includes("--write")) {
      mkdirSync(dirname(path), { recursive: true });
      writeFileSync(path, text);
    } else console.log(`out of date: ${relative(process.cwd(), path)}`);
  };
  for (const rule of rules) {
    const path = join(pagesRoot, pageOf(rule) + ".mdx");
    if (!existsSync(path)) {
      console.error(`missing page: ${relative(process.cwd(), path)}`);
      continue;
    }
    const page = readPage(readFileSync(path, "utf8"));
    if (page) put(path, withGenerated(page, rule));
  }
  put(join(pagesRoot, "index.mdx"), indexFor(rules));
  if (!flag("rules")) {
    const byPage = new Map(rules.map(rule => [pageOf(rule), rule]));
    const examples = [...byPage.keys()].flatMap(
      page => examplesIn(page, readFileSync(join(pagesRoot, page + ".mdx"), "utf8"))?.examples ?? [],
    );
    const dir = mkdtempSync(join(tmpdir(), "bun-lint-rule-docs-"));
    try {
      put(
        join(pagesRoot, "reports.json"),
        reportsText(reportsOf(examples, await lintExamples(dir, examples, byPage, lint))),
      );
    } finally {
      rmSync(dir, { recursive: true, force: true });
    }
  }
  console.log(`${changed} files ${process.argv.includes("--write") ? "written" : "out of date"}`);
  if (changed && !process.argv.includes("--write")) process.exit(1);
}
