#[derive(Clone, Copy)]
pub(crate) enum Part {
    /// Length, how many different bytes, the first of them
    Even(usize, usize, usize),
    /// Length, how often a byte is as high as the one below it
    Skewed(usize, usize),
    /// Length, offset
    Again(usize, usize),
    /// Length, how many different literals, the most in a row, then the least and the span of lengths and of offsets
    Mixed(usize, usize, usize, [usize; 2], [usize; 2]),
    /// Length, literals in a row, length of matches, how often an offset is a slot farther, or with 1 nearer
    Rare(usize, usize, usize, usize, usize),
    /// Length, how many different words, all with nearly the same hash
    Colliding(usize, usize),
    /// Ever longer pieces of a text, then the text
    Stairs(usize, usize),
}

