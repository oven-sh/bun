/// <https://drafts.csswg.org/css-text-4/#text-spacing-classes>
#[derive(Clone, Copy, PartialEq)]
pub(crate) enum Punctuation {
    Other,
    Opening,
    Closing,
    Middle,
    NarrowOpening,
    NarrowClosing,
}

/// `None` if it depends on the font.
pub(crate) fn spacing_class(character: char) -> Option<Punctuation> {
    Some(match character {
        '、' | '。' | '，' | '．' | '：' | '；' | '‘' | '’' | '“' | '”' => {
            return None;
        }
        '\u{3008}'..='\u{3011}' | '\u{3014}'..='\u{301b}' | '（' | '）'
            if (character as u32).is_multiple_of(2) =>
        {
            Punctuation::Opening
        }
        '\u{3008}'..='\u{3011}'
        | '\u{3014}'..='\u{301b}'
        | '）'
        | '〞'
        | '〟'
        | '］'
        | '｝'
        | '｠'
        | '\u{232a}' => Punctuation::Closing,
        '〝' | '［' | '｛' | '｟' | '\u{2329}' => Punctuation::Opening,
        '\u{3000}' | '・' | '·' | '‧' => Punctuation::Middle,
        '(' | '[' | '{' | '｢' => Punctuation::NarrowOpening,
        ')' | ']' | '}' | '｣' => Punctuation::NarrowClosing,
        _ => Punctuation::Other,
    })
}

/// General category Zs, and tabs.
pub(crate) fn is_blank(character: char) -> bool {
    matches!(
        character,
        ' ' | '\t' | '\u{a0}' | '\u{1680}' | '\u{2000}'
            ..='\u{200a}' | '\u{202f}' | '\u{205f}' | '\u{3000}'
    )
}

