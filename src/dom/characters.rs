pub(crate) fn math_italic(character: char) -> char {
    let code = character as u32;
    let italic = match code {
        0x68 => 0x210e,
        0x41..=0x5a => 0x1d434 + code - 0x41,
        0x61..=0x7a => 0x1d44e + code - 0x61,
        0x131 => 0x1d6a4,
        0x237 => 0x1d6a5,
        0x391..=0x3a1 | 0x3a3..=0x3a9 => 0x1d6e2 + code - 0x391,
        0x3f4 => 0x1d6f3,
        0x2207 => 0x1d6fb,
        0x3b1..=0x3c9 => 0x1d6fc + code - 0x3b1,
        0x2202 => 0x1d715,
        0x3f5 => 0x1d716,
        0x3d1 => 0x1d717,
        0x3f0 => 0x1d718,
        0x3d5 => 0x1d719,
        0x3f1 => 0x1d71a,
        0x3d6 => 0x1d71b,
        _ => code,
    };
    char::from_u32(italic).unwrap_or(character)
}

/// Where it is not the upper case.
pub(crate) fn title_case(character: char) -> Option<char> {
    let code = character as u32;
    char::from_u32(match code {
        0x1c4..=0x1cc => 0x1c5 + (code - 0x1c4) / 3 * 3,
        0x1f1..=0x1f3 => 0x1f2,
        0x1f80..=0x1faf => code | 8,
        0x1fb3 | 0x1fc3 | 0x1ff3 => code + 9,
        0x10d0..=0x10ff => code,
        _ if character.to_uppercase().len() > 1 => code,
        _ => return None,
    })
}

