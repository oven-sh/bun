use bun_engine_date::{iso_string, parse_cookie_date, parse_date_as_utc};
use bun_engine_standalone as _;

fn iso(time: f64) -> Option<String> {
    iso_string(time).map(|text| text.to_string())
}

#[test]
fn date_time_string_format() {
    for (text, expected) in [
        ("2022", "2022-01-01T00:00:00.000Z"),
        ("2022-02", "2022-02-01T00:00:00.000Z"),
        ("0001-02-03", "0001-02-03T00:00:00.000Z"),
        ("2022-02-31", "2022-03-03T00:00:00.000Z"),
        ("2022T13:05Z", "2022-01-01T13:05:00.000Z"),
        ("2022-02-03t13:05:09z", "2022-02-03T13:05:09.000Z"),
        ("2022-02-03T13:05:09.1Z", "2022-02-03T13:05:09.100Z"),
        ("2022-02-03T13:05:09.01Z", "2022-02-03T13:05:09.010Z"),
        ("2022-02-03T13:05:09.012999999Z", "2022-02-03T13:05:09.012Z"),
        ("2022-02-03T24:00:00.000Z", "2022-02-04T00:00:00.000Z"),
        ("2022-02-03T13:05+01:30", "2022-02-03T11:35:00.000Z"),
        ("2022-02-03T13:05-0130", "2022-02-03T14:35:00.000Z"),
        ("+000000-01-01T00:00Z", "0000-01-01T00:00:00.000Z"),
        ("-271821-04-20T00:00Z", "-271821-04-20T00:00:00.000Z"),
        ("+275760-09-13T01:00+01:00", "+275760-09-13T00:00:00.000Z"),
    ] {
        assert_eq!(
            iso(parse_date_as_utc(text.as_bytes())).as_deref(),
            Some(expected)
        );
    }
    for text in [
        "",
        "2022-02-03T",
        "2022-02-03T13Z",
        "2022-02-03T1:05Z",
        "2022-02-03T13:60Z",
        "2022-02-03T13:05:60Z",
        "2022-02-03T13:05:09.Z",
        "2022-02-03T24:00:00.001Z",
        "2022-02-03T13:05+01",
        "2022-02-03T13:05+24:00",
        "2022-02-03T13:05+0160",
        "2022-02-03T13:05Z ",
        "2022-13-03",
        "2022-02-32",
        "2022-2-03T13:05Z",
        "-000000-03-31T00:45Z",
        "+275760-09-13T00:00:00.001Z",
        "-271821-04-19T23:59:59.999Z",
    ] {
        assert!(parse_date_as_utc(text.as_bytes()).is_nan(), "{text}");
    }
}

#[test]
fn free_form() {
    for (text, expected) in [
        (
            "Thu Feb 03 2022 13:05:09 GMT+0100 (Central (European) Time)",
            "2022-02-03T12:05:09.000Z",
        ),
        ("Thu, 03 Feb 2022 13:05:09 GMT", "2022-02-03T13:05:09.000Z"),
        ("Thursday, 3-Feb-22 1:05 pm EST", "2022-02-03T18:05:00.000Z"),
        ("February 3 13:05:09 2022 PDT", "2022-02-03T20:05:09.000Z"),
        ("2/3/2022, 12:05:09 AM", "2022-02-03T00:05:09.000Z"),
        ("2/3/50", "1950-02-03T00:00:00.000Z"),
        ("2022/2/3 13:05:09.5 UT-8", "2022-02-03T21:05:09.500Z"),
        ("2022-02-03 13:05:09+01:30", "2022-02-03T11:35:09.000Z"),
        ("2022-2-3", "2022-02-03T00:00:00.000Z"),
        ("2022 Feb", "2022-02-01T00:00:00.000Z"),
        ("Feb 3", "2001-02-03T00:00:00.000Z"),
        ("3.2.2022", "2022-03-02T00:00:00.000Z"),
        ("Feb 3 2022 13:: z", "2022-02-03T13:00:00.000Z"),
        ("any words) + 2", "2001-02-01T00:00:00.000Z"),
        ("Feb 3 2022 24:00 (", "2022-02-04T00:00:00.000Z"),
        ("Feb 3 2022\0 and more", "2022-02-03T00:00:00.000Z"),
    ] {
        assert_eq!(
            iso(parse_date_as_utc(text.as_bytes())).as_deref(),
            Some(expected)
        );
    }
    for text in [
        "Feb",
        "word3",
        "Feb 3 2022 word",
        "Feb 3 2022 )",
        "Feb 3 2022 +0100",
        "Feb 3 2022 PM",
        "Feb 3 2022 13:05 PM",
        "Feb 3 2022 13:05,",
        "Feb 3 2022 24:01",
        "Feb 3 2022 13:05 +12345",
        "Feb 3 2022 13:05:09.",
        "Feb 32 2022",
        "13/1/2022",
        "1 2 3 4",
        "1:2:3:4:5: Feb 3",
        "Feb 3 1000001",
        "Feb 3 99999999999999999999",
        "Feb 3 2022\u{a0}13:05",
    ] {
        assert!(parse_date_as_utc(text.as_bytes()).is_nan(), "{text}");
    }
}

#[test]
fn cookie_dates() {
    for (text, expected) in [
        ("Thu, 03 Feb 2022 13:05:09 GMT", "2022-02-03T13:05:09.000Z"),
        (
            "Thursday, 03-Feb-22 13:05:09 gmt",
            "2022-02-03T13:05:09.000Z",
        ),
        ("Thu Feb  3 13:05:09 2022 UTC", "2022-02-03T13:05:09.000Z"),
        ("Thu Feb 3 13:05:09 GMT 2022", "2022-02-03T13:05:09.000Z"),
        ("3 Feb 99 13:05 +0130", "1999-02-03T11:35:00.000Z"),
        ("3 February 2022 EST", "2022-02-03T05:00:00.000Z"),
        ("Feb3, 2022 at 1:05 PM GMT-8", "2022-02-03T21:05:00.000Z"),
        ("(a (b)) 2/3/2022 12:05 am UT", "2022-02-03T00:05:00.000Z"),
        ("2022/2/3 13:05 GMT+01:30", "2022-02-03T11:35:00.000Z"),
        ("Feb 29 0:00 PDT", "2000-02-29T07:00:00.000Z"),
        ("Thu, 01 Jan 1970 00:00:00 GMT", "1970-01-01T00:00:00.000Z"),
    ] {
        let time = parse_cookie_date(text.as_bytes()).unwrap();
        assert_eq!(iso(time as f64).as_deref(), Some(expected));
    }
    for text in [
        "",
        "tomorrow",
        "2022-02-03T13:05:09Z",
        "3 Feb",
        "Feb word 3 2022",
        "0 Feb 2022 GMT",
        "32 Feb 2022 GMT",
        "3 Feb 2022 24:00 GMT",
        "3 Feb 2022 13:05:60 GMT",
        "3 Feb 2022 13 GMT",
        "3 Feb 2022 13:05 CET",
        "3 Feb 2022 13:05 +9960",
        "3 Feb 275761 GMT",
        "3 Feb 2147483647 GMT",
        "3 Feb 2022 GMT+0:2147483647",
        "3 Feb 99999999999999999999 GMT",
    ] {
        assert_eq!(parse_cookie_date(text.as_bytes()), None, "{text}");
    }
}
