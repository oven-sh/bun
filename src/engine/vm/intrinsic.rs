impl Intrinsic {
    /// Whether all that it does with numbers is to give an integer or a double. A compiler wants to know which, and
    /// nobody can tell whether such a call is a tail call.
    pub fn picks_kind_of_number(self) -> bool {
        use Intrinsic::*;
        matches!(self, Abs | Ceil | Floor | Max | Min | Pow | Round | Trunc)
    }

    pub(crate) const COUNT: usize = core::mem::variant_count::<Intrinsic>();
}

