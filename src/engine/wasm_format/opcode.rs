//! The first byte of an instruction.

macro_rules! opcodes {
    ($($value:literal $constant:ident $name:ident,)*) => {
        $(pub const $constant: u8 = $value;)*

        /// As error messages have it.
        pub(crate) fn name(opcode: u8) -> &'static str {
            match opcode {
                $($value => stringify!($name),)*
                _ => "",
            }
        }
    };
}

