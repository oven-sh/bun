// Regenerates mime_type_list_sorted.rs from mime_type_list.txt:
//   bun src/http_types/mime_type_list.generate.ts
// (test/internal/mime-type-list.test.ts fails if the checked-in file is stale.)
//
// The output is the set of full MIME strings `MimeType::by_name_static` interns,
// laid out for `bun_core::comptime_string_map::sorted_key_slice`: names sorted
// by (length, bytes) and concatenated, plus a per-length (offset, position)
// bucket table with one sentinel entry past the longest name.
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const dir = import.meta.dir;

export function generate(list: string): string {
  const names = [...new Set(list.split("\n").filter(Boolean))].map(s => Buffer.from(s, "latin1"));
  names.sort((a, b) => a.length - b.length || Buffer.compare(a, b));
  const maxLen = names.at(-1)!.length;

  let blob = "";
  const buckets: string[] = [];
  let offset = 0;
  let position = 0;
  let i = 0;
  for (let len = 0; len <= maxLen + 1; len++) {
    buckets.push(`(${offset}, ${position})`);
    while (i < names.length && names[i].length === len) {
      blob += names[i].toString("latin1");
      offset += len;
      position++;
      i++;
    }
  }

  // `\x20` rather than a literal space: a Rust `\`-newline continuation skips
  // leading whitespace on the next line, so a chunk boundary before a space
  // would otherwise drop a byte.
  const escaped = JSON.stringify(blob).slice(1, -1).replaceAll(" ", "\\x20");
  const lines: string[] = [];
  for (let at = 0; at < escaped.length; ) {
    let end = Math.min(at + 100, escaped.length);
    // don't split an escape sequence
    const lastBackslash = escaped.lastIndexOf("\\", end - 1);
    if (lastBackslash >= at && lastBackslash > end - 4 && end < escaped.length) end = lastBackslash;
    lines.push(escaped.slice(at, end));
    at = end;
  }

  let bucketRows = "";
  buckets.forEach((b, i) => {
    bucketRows += (i === 0 ? "    " : i % 8 === 0 ? ",\n    " : ", ") + b;
  });

  return `// Generated by mime_type_list.generate.ts from mime_type_list.txt; do not edit.

/// ${names.length} MIME strings sorted by (length, bytes), concatenated.
#[rustfmt::skip]
pub(crate) static NAMES: &[u8] = b"\\
${lines.join("\\\n")}";

/// \`(NAMES offset, sorted position)\` of the first name of each length, plus a sentinel.
#[rustfmt::skip]
pub(crate) static BUCKETS: [(u32, u32); ${buckets.length}] = [
${bucketRows},
];
`;
}

if (import.meta.main) {
  const output = generate(readFileSync(join(dir, "mime_type_list.txt"), "utf8"));
  writeFileSync(join(dir, "mime_type_list_sorted.rs"), output);
  console.log(`wrote mime_type_list_sorted.rs (${output.length} bytes)`);
}
