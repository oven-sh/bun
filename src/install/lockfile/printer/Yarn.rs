use crate::lockfile::package::PackageColumns as _;

use bun_collections::index_sort;
use bun_core::strings;
use bun_semver::String as SemverString;

use crate::lockfile_real::package::Alphabetizer;
use bun_install::Dependency;
use bun_install::DependencyID;
use bun_install::PackageID;
use bun_install::Resolution;
use bun_install::dependency::{self, TagExt as _};
use bun_install::lockfile::package;
// `lockfile.packages.slice()` returns
// `bun_collections::multi_array_list::Slice<Package<_>>`; the `items_<field>()`
// column accessors are an extension trait (hand-expanded per Package.rs).
use crate::integrity;
use crate::lockfile_real::Lockfile;

pub(crate) fn print(
    lockfile: &Lockfile,
    writer: &mut impl bun_io::Write,
) -> Result<(), crate::Error> {
    writer.write_all(
        b"# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.\n\
          # yarn lockfile v1\n\
          # bun ./bun.lockb --hash:",
    )?;
    write!(writer, " {}\n\n", lockfile.fmt_meta_hash())?;

    packages(lockfile, writer)
}

fn packages(lockfile: &Lockfile, writer: &mut impl bun_io::Write) -> Result<(), crate::Error> {
    let slice = lockfile.packages.slice();
    let names: &[SemverString] = slice.items_name();
    let resolved: &[Resolution] = slice.items_resolution();
    let metas: &[package::Meta] = slice.items_meta();
    if names.is_empty() {
        return Ok(());
    }
    let dependency_lists = slice.items_dependencies();
    let resolutions_buffer: &[PackageID] = lockfile.buffers.resolutions.as_slice();
    let dependencies_buffer: &[Dependency] = lockfile.buffers.dependencies.as_slice();

    let package_count = names.len();
    let mut alphabetized_names: Vec<PackageID> = (1..package_count as PackageID).collect();

    let string_buf: &[u8] = lockfile.buffers.string_bytes.as_slice();

    // The dependencies that resolved to package `i` are `requested[starts[i]..starts[i + 1]]`.
    let mut starts: Vec<usize> = vec![0; package_count + 1];
    for &package_id in resolutions_buffer {
        if (package_id as usize) < package_count {
            starts[package_id as usize + 1] += 1;
        }
    }
    for i in 1..=package_count {
        starts[i] += starts[i - 1];
    }
    let mut requested: Vec<DependencyID> = vec![0; starts[package_count]];
    let mut cursors = starts.clone();
    for (dependency_id, &package_id) in resolutions_buffer.iter().enumerate() {
        if (package_id as usize) < package_count {
            requested[cursors[package_id as usize]] = dependency_id as DependencyID;
            cursors[package_id as usize] += 1;
        }
    }

    let requested_as = |dependency_id: DependencyID| -> &[u8] {
        let version = &dependencies_buffer[dependency_id as usize].version;
        // Only the package.json parser gives the root's dependency on a workspace a literal, which
        // is the workspace's path.
        if version.literal.is_empty() && version.tag == dependency::Tag::Workspace {
            return version.workspace().slice(string_buf);
        }
        version.literal.slice(string_buf)
    };
    // Yarn looks up an `npm:` alias by its name in package.json, not by the package's real name.
    let requested_name = |dependency_id: DependencyID| -> &[u8] {
        let name = if requested_as(dependency_id).starts_with(b"npm:") {
            &dependencies_buffer[dependency_id as usize].name
        } else {
            &names[resolutions_buffer[dependency_id as usize] as usize]
        };
        name.slice(string_buf)
    };
    for i in 1..package_count {
        index_sort::sort_indices(&mut requested[starts[i]..starts[i + 1]], &mut |a, b| {
            let tag_of = |id: DependencyID| dependencies_buffer[id as usize].version.tag;
            strings::order(requested_name(a), requested_name(b))
                .then_with(|| tag_of(a).cmp(tag_of(b)))
                .then_with(|| strings::order(requested_as(a), requested_as(b)))
        });
    }

    {
        let alphabetizer = Alphabetizer::<u64> {
            names: names.into(),
            buf: string_buf.into(),
            resolutions: resolved.into(),
        };
        index_sort::sort_indices_unstable(&mut alphabetized_names, &mut |a, b| {
            alphabetizer.order(a, b)
        });
    }

    let mut dependencies: Vec<DependencyID> = Vec::new();

    // When printing, we start at 1
    for &i in alphabetized_names.iter() {
        let resolution = &resolved[i as usize];
        let meta = &metas[i as usize];
        // The manifest's order in a fresh install, this order once loaded from bun.lock.
        let dependency_list = dependency_lists[i as usize];
        dependencies.clear();
        dependencies.extend(dependency_list.begin()..dependency_list.end());
        index_sort::sort_indices(&mut dependencies, &mut |a, b| {
            Dependency::cmp(
                string_buf,
                &dependencies_buffer[a as usize],
                &dependencies_buffer[b as usize],
            )
        });
        let version_formatter = resolution.fmt(string_buf, bun_core::fmt::PathSep::Posix);

        // This prints:
        // "@babel/core@7.9.0":
        {
            writer.write_all(b"\n")?;
            let requests = &requested[starts[i as usize]..starts[i as usize + 1]];

            let mut needs_comma = false;
            for (nth, &request) in requests.iter().enumerate() {
                let name: &[u8] = requested_name(request);
                let version_name: &[u8] = requested_as(request);
                // one key per requested spec as written
                if requests[..nth].iter().any(|&earlier| {
                    requested_name(earlier) == name && requested_as(earlier) == version_name
                }) {
                    continue;
                }
                if needs_comma {
                    writer.write_all(b", ")?;
                }
                // https://github.com/yarnpkg/yarn/blob/158d96dce95313d9a00218302631cd263877d164/src/lockfile/stringify.js#L9
                let needs_quote = strings::must_escape_yaml_string(name)
                    || strings::index_of_any(version_name, b" |\t-/!:\"\\,\n\r").is_some()
                    || version_name.starts_with(b"npm:");

                if needs_quote {
                    writer.write_all(b"\"")?;
                    write!(
                        writer,
                        "{}",
                        bun_core::fmt::format_json_string_utf8(
                            name,
                            bun_core::fmt::JSONFormatterUTF8Options { quote: false }
                        ),
                    )?;
                } else {
                    writer.write_all(name)?;
                }
                writer.write_all(b"@")?;
                if version_name.is_empty() {
                    writer.write_all(b"^")?;
                    version_formatter.write_to(writer)?;
                } else if needs_quote {
                    write!(
                        writer,
                        "{}",
                        bun_core::fmt::format_json_string_utf8(
                            version_name,
                            bun_core::fmt::JSONFormatterUTF8Options { quote: false }
                        ),
                    )?;
                } else {
                    writer.write_all(version_name)?;
                }

                if needs_quote {
                    writer.write_all(b"\"")?;
                }
                needs_comma = true;
            }

            writer.write_all(b":\n")?;
        }

        {
            let mut quoted_buf: Vec<u8> = Vec::new();

            writer.write_all(b"  version ")?;

            // Version is always quoted
            version_formatter.write_to(&mut quoted_buf)?;
            writeln!(
                writer,
                "{}",
                bun_core::fmt::format_json_string_utf8(&quoted_buf, Default::default()),
            )?;

            writer.write_all(b"  resolved ")?;

            let url_formatter = resolution.fmt_url(string_buf);

            // Resolved URL is always quoted
            quoted_buf.clear();
            url_formatter.write_to(&mut quoted_buf)?;
            writeln!(
                writer,
                "{}",
                bun_core::fmt::format_json_string_utf8(&quoted_buf, Default::default()),
            )?;

            if meta.integrity.tag != integrity::Tag::UNKNOWN {
                // Integrity is...never quoted?
                writeln!(writer, "  integrity {}", meta.integrity)?;
            }

            {
                let mut group: &[u8] = b"";
                for &dependency_id in &dependencies {
                    let dep = &dependencies_buffer[dependency_id as usize];
                    let group_of_dep: &[u8] = if dep.behavior.is_optional() {
                        b"  optionalDependencies:\n"
                    } else if dep.behavior.is_prod() {
                        b"  dependencies:\n"
                    } else if dep.behavior.is_dev() {
                        b"  devDependencies:\n"
                    } else {
                        continue;
                    };
                    if group_of_dep != group {
                        writer.write_all(group_of_dep)?;
                        group = group_of_dep;
                    }

                    writer.write_all(b"    ")?;
                    let dependency_name: &[u8] = dep.name.slice(string_buf);

                    let needs_quote = strings::must_escape_yaml_string(dependency_name);

                    if needs_quote {
                        write!(
                            writer,
                            "{}",
                            bun_core::fmt::format_json_string_utf8(
                                dependency_name,
                                Default::default()
                            ),
                        )?;
                    } else {
                        writer.write_all(dependency_name)?;
                    }
                    writeln!(
                        writer,
                        " {}",
                        bun_core::fmt::format_json_string_utf8(
                            dep.version.literal.slice(string_buf),
                            Default::default()
                        ),
                    )?;
                }
            }
        }
    }

    Ok(())
}
