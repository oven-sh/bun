JSC::JSValue toJSNewlyCreated(JSC::JSGlobalObject* lexicalGlobalObject, JSDOMGlobalObject* globalObject, Ref<Document>&& impl)
{
    reportMemoryForDocumentIfFrameless(*lexicalGlobalObject, impl.get());
    if (is<HTMLDocument>(impl))
        return toJSNewlyCreated(lexicalGlobalObject, globalObject, uncheckedDowncast<HTMLDocument>(WTF::move(impl)));
    if (is<XMLDocument>(impl))
        return toJSNewlyCreated(lexicalGlobalObject, globalObject, uncheckedDowncast<XMLDocument>(WTF::move(impl)));
    return createWrapper<Document>(globalObject, WTF::move(impl));
}

JSC::JSValue toJS(JSC::JSGlobalObject* lexicalGlobalObject, JSDOMGlobalObject* globalObject, Document& impl)
{
    if (auto* wrapper = cachedDocumentWrapper(*lexicalGlobalObject, *globalObject, impl))
        return wrapper;
    return wrap(lexicalGlobalObject, globalObject, impl);
}

Document* JSDocument::toWrapped(JSC::VM&, JSC::JSValue value)
{
    if (auto* wrapper = dynamicDowncast<JSDocument>(value))
        return &wrapper->wrapped();
    return nullptr;
}

