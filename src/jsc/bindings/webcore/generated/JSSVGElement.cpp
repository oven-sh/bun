JSC::JSValue toJSNewlyCreated(JSC::JSGlobalObject* lexicalGlobalObject, JSDOMGlobalObject* globalObject, Ref<SVGElement>&& impl)
{
    UNUSED_PARAM(lexicalGlobalObject);
    if (is<SVGDescElement>(impl))
        return toJSNewlyCreated(lexicalGlobalObject, globalObject, uncheckedDowncast<SVGDescElement>(WTF::move(impl)));
    if (is<SVGGraphicsElement>(impl))
        return toJSNewlyCreated(lexicalGlobalObject, globalObject, uncheckedDowncast<SVGGraphicsElement>(WTF::move(impl)));
    if (is<SVGMetadataElement>(impl))
        return toJSNewlyCreated(lexicalGlobalObject, globalObject, uncheckedDowncast<SVGMetadataElement>(WTF::move(impl)));
    if (is<SVGTitleElement>(impl))
        return toJSNewlyCreated(lexicalGlobalObject, globalObject, uncheckedDowncast<SVGTitleElement>(WTF::move(impl)));
    return createWrapper<SVGElement>(globalObject, WTF::move(impl));
}

