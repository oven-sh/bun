/// A file to format.
pub(crate) struct Target {
    pub(crate) path: Vec<u8>,
    /// Size in bytes when it was found.
    pub(crate) size: u64,
    pub(crate) scope: Arc<Scope>,
    /// True if it was found in a directory passed as an argument, so it's silently skipped if it has no parser.
    pub(crate) ignores_unknown: bool,
    /// True if it was passed as an argument itself, so its parent directories haven't been checked against the ignore
    /// rules yet.
    pub(crate) is_named: bool,
    /// `Some` if the file has hard links. The other links can be targets too.
    pub(crate) linked: Option<fs::Identity>,
}

/// The expansion of the arguments, in the order Prettier processes them.
pub(crate) enum Expanded {
    File(Target),
    /// An error message for the user. The exit code is 2.
    Error(Vec<u8>),
}

/// How well a file's language is supported, judging by its name.
#[derive(Copy, Clone, PartialEq, Eq, Debug)]
pub(crate) enum Language {
    /// The formatter supports it. See [`Kind`].
    Supported,
    /// Prettier formats it, but this formatter doesn't.
    Other,
    /// Prettier has no parser for it either.
    Unknown,
}

/// oxfmt's `EXCLUDE_FILENAMES`: files that a tool generated, which are never formatted.
fn is_excluded_by_oxfmt(path: &[u8]) -> bool {
    matches!(
        paths::basename(path),
        b"package-lock.json"
            | b"pnpm-lock.yaml"
            | b"yarn.lock"
            | b"MODULE.bazel.lock"
            | b"bun.lock"
            | b"deno.lock"
            | b"composer.lock"
            | b"Package.resolved"
            | b"Pipfile.lock"
            | b"flake.lock"
            | b"mcmod.info"
            | b"Cargo.lock"
            | b"Gopkg.lock"
            | b"pdm.lock"
            | b"poetry.lock"
            | b"uv.lock"
    )
}

/// Returns true for minified code and for lock files, which are generated by tools and shouldn't be reformatted.
pub(crate) fn is_generated(path: &[u8]) -> bool {
    let name = paths::basename(path);
    let is_minified = || {
        [&b".min.js"[..], b".min.mjs", b".min.cjs", b".min.css"]
            .iter()
            .any(|ending| name.ends_with(ending))
    };
    is_excluded_by_oxfmt(path)
        || matches!(name, b"npm-shrinkwrap.json" | b"glide.lock" | b"pixi.lock")
        || is_minified()
}

/// A language the formatter supports.
#[derive(Copy, Clone, PartialEq, Eq, Debug)]
pub(crate) enum Kind {
    /// JavaScript or TypeScript.
    Script,
    Json(bun_format::json::Parser),
    Css(bun_format::css::Parser),
    Yaml,
    Markdown,
    Mdx,
    GraphQl,
    Handlebars,
    /// Only with an oxfmt config or in native mode. Prettier doesn't format TOML.
    Toml,
    /// HTML, Vue, Angular templates, Lightning Web Components, MJML.
    Html(bun_format::html::Parser),
    /// See [`Configs::formats_svelte`].
    Svelte,
}

impl Kind {
    /// The language that Prettier's parser of that name handles. `None` if Prettier has no such parser, so it's a
    /// plugin's or a mistake.
    pub(crate) fn from_parser(parser: &[u8]) -> Option<Kind> {
        let json = || bun_format::json::Parser::from_name(parser).map(Kind::Json);
        let css = || bun_format::css::Parser::from_name(parser).map(Kind::Css);
        let html = || bun_format::html::Parser::from_name(parser).map(Kind::Html);
        let other = || match parser {
            b"yaml" => Some(Kind::Yaml),
            b"markdown" | b"remark" => Some(Kind::Markdown),
            b"mdx" => Some(Kind::Mdx),
            b"graphql" => Some(Kind::GraphQl),
            b"glimmer" => Some(Kind::Handlebars),
            // From `prettier-plugin-svelte`. `Configs::formats_svelte` decides whether this formatter handles the file.
            b"svelte" => Some(Kind::Svelte),
            b"babel" | b"babel-flow" | b"babel-ts" | b"flow" | b"typescript" | b"acorn"
            | b"espree" | b"meriyah" | b"oxc" | b"oxc-ts" => Some(Kind::Script),
            _ => None,
        };
        json().or_else(css).or_else(html).or_else(other)
    }

    /// The kind of the file at `path`, given its `options`.
    pub(crate) fn with_options(path: &[u8], options: &bun_format::FormatOptions) -> Option<Kind> {
        // An oxfmt configuration file can't set `parser`, but oxfmt's tests do.
        if !options.flavor.is_oxfmt() || options.parser.is_some() {
            let is_toml = || options.toml && options.parser.is_none() && is_toml(path);
            let is_svelte =
                || options.svelte.is_on && options.parser.is_none() && path.ends_with(b".svelte");
            return Kind::of(path, options.parser.as_deref())
                .or_else(|| is_toml().then_some(Kind::Toml))
                .or_else(|| is_svelte().then_some(Kind::Svelte));
        }
        let is_svelte = || options.svelte.is_on && is_svelte_for_oxfmt(path);
        classify_for_oxfmt(path).or_else(|| is_svelte().then_some(Kind::Svelte))
    }

    /// The kind of the file at `path`. `parser` is Prettier's option of that name, which decides if it's set.
    fn of(path: &[u8], parser: Option<&[u8]>) -> Option<Kind> {
        if let Some(parser) = parser {
            return Kind::from_parser(parser);
        }
        // Prettier's `getLanguageByFileName` compares the lowercased name.
        let lowered;
        let name = match paths::basename(path) {
            name if name.iter().any(u8::is_ascii_uppercase) => {
                lowered = name.to_ascii_lowercase();
                &lowered[..]
            }
            name => name,
        };
        let extension =
            strings::last_index_of_char(name, b'.').map_or(&b""[..], |dot| &name[dot + 1..]);
        if matches!(
            extension,
            b"js" | b"mjs" | b"cjs" | b"jsx" | b"ts" | b"mts" | b"cts" | b"tsx"
        ) || name.ends_with(b".js.flow")
            || extension == b"wxs"
            || is_other_javascript_name(name, extension)
            || name == b"jakefile"
        {
            return Some(Kind::Script);
        }
        // None of them looks at the directory part.
        let json = || bun_format::json::parser_for_path(name).map(Kind::Json);
        let css = || bun_format::css::parser_for_path(name).map(Kind::Css);
        let yaml = || bun_format::yaml::is_yaml_path(name).then_some(Kind::Yaml);
        let markdown = || bun_format::markdown::is_markdown_path(name).then_some(Kind::Markdown);
        let mdx = || bun_format::markdown::is_mdx_path(name).then_some(Kind::Mdx);
        let graphql = || bun_format::graphql::is_graphql_path(name).then_some(Kind::GraphQl);
        let handlebars =
            || bun_format::handlebars::is_handlebars_path(name).then_some(Kind::Handlebars);
        let html = || bun_format::html::parser_for_path(name).map(Kind::Html);
        json()
            .or_else(css)
            .or_else(yaml)
            .or_else(markdown)
            .or_else(mdx)
            .or_else(graphql)
            .or_else(handlebars)
            .or_else(html)
    }
}

/// Other names that Prettier and oxfmt treat as JavaScript, which they take from GitHub's linguist.
fn is_other_javascript_name(name: &[u8], extension: &[u8]) -> bool {
    matches!(
        extension,
        b"_js"
            | b"bones"
            | b"es"
            | b"es6"
            | b"gs"
            | b"jake"
            | b"javascript"
            | b"jsb"
            | b"jscad"
            | b"jsfl"
            | b"jslib"
            | b"jsm"
            | b"jspre"
            | b"jss"
            | b"njs"
            | b"pac"
            | b"sjs"
            | b"ssjs"
            | b"xsjs"
            | b"xsjslib"
    ) || matches!(name, b"Jakefile" | b"start.frag" | b"end.frag")
        || name.ends_with(b".start.frag")
        || name.ends_with(b".end.frag")
}

/// Returns true for the file names oxfmt treats as TOML.
pub(crate) fn is_toml(path: &[u8]) -> bool {
    let name = paths::basename(path);
    name.strip_suffix(b".toml").is_some_and(|it| !it.is_empty())
        || matches!(name, b"Pipfile" | b"Cargo.toml.orig")
        || name.ends_with(b".toml.example")
}

/// oxfmt's `classify_file_kind`. Unlike Prettier, it's case-sensitive.
fn classify_for_oxfmt(path: &[u8]) -> Option<Kind> {
    use bun_format::{css, html, json};
    let name = paths::basename(path);
    // `Path::extension`: a name whose only dot is at the start has no extension.
    let extension = match strings::last_index_of_char(name, b'.') {
        None | Some(0) => &b""[..],
        Some(dot) => &name[dot + 1..],
    };
    let is_script = matches!(
        extension,
        b"js" | b"mjs" | b"cjs" | b"jsx" | b"ts" | b"mts" | b"cts" | b"tsx"
    );
    if !is_script && is_excluded_by_oxfmt(path) {
        return None;
    }
    if is_script || is_other_javascript_name(name, extension) {
        return Some(Kind::Script);
    }
    if is_toml(path) {
        return Some(Kind::Toml);
    }
    let by_name = match name {
        b"package.json" | b"composer.json" => Some(Kind::Json(json::Parser::JsonStringify)),
        b".all-contributorsrc"
        | b".arcconfig"
        | b".auto-changelog"
        | b".c8rc"
        | b".htmlhintrc"
        | b".imgbotconfig"
        | b".nycrc"
        | b".tern-config"
        | b".tern-project"
        | b".watchmanconfig"
        | b".babelrc"
        | b".jscsrc"
        | b".jshintrc"
        | b".jslintrc"
        | b".swcrc" => Some(Kind::Json(json::Parser::Json)),
        b".prettierrc" | b".stylelintrc" | b".lintstagedrc" | b".clang-format" | b".clang-tidy"
        | b".clangd" | b".gemrc" | b"CITATION.cff" | b"glide.lock" | b"pixi.lock" => {
            Some(Kind::Yaml)
        }
        b"contents.lr" | b"README" => Some(Kind::Markdown),
        _ => None,
    };
    let by_ending = || {
        [
            (&b".json.example"[..], Kind::Json(json::Parser::Json)),
            (b".tfstate.backup", Kind::Json(json::Parser::Json)),
            (b".component.html", Kind::Html(html::Parser::Angular)),
        ]
        .into_iter()
        .find(|it| name.ends_with(it.0))
        .map(|it| it.1)
    };
    let by_extension = || {
        Some(match extension {
            b"importmap" => Kind::Json(json::Parser::JsonStringify),
            b"json" | b"4DForm" | b"4DProject" | b"avsc" | b"geojson" | b"gltf" | b"har"
            | b"ice" | b"JSON-tmLanguage" | b"mcmeta" | b"sarif" | b"tact" | b"tfstate"
            | b"topojson" | b"webapp" | b"webmanifest" | b"yy" | b"yyp" => {
                Kind::Json(json::Parser::Json)
            }
            b"jsonc"
            | b"code-snippets"
            | b"code-workspace"
            | b"sublime-build"
            | b"sublime-color-scheme"
            | b"sublime-commands"
            | b"sublime-completions"
            | b"sublime-keymap"
            | b"sublime-macro"
            | b"sublime-menu"
            | b"sublime-mousemap"
            | b"sublime-project"
            | b"sublime-settings"
            | b"sublime-theme"
            | b"sublime-workspace"
            | b"sublime_metrics"
            | b"sublime_session" => Kind::Json(json::Parser::Jsonc),
            b"json5" => Kind::Json(json::Parser::Json5),
            b"graphql" | b"gql" | b"graphqls" => Kind::GraphQl,
            b"css" | b"wxss" | b"pcss" | b"postcss" => Kind::Css(css::Parser::Css),
            b"scss" => Kind::Css(css::Parser::Scss),
            b"less" => Kind::Css(css::Parser::Less),
            b"yml" | b"mir" | b"reek" | b"rviz" | b"sublime-syntax" | b"syntax" | b"yaml"
            | b"yaml-tmlanguage" => Kind::Yaml,
            b"md" | b"livemd" | b"markdown" | b"mdown" | b"mdwn" | b"mkd" | b"mkdn" | b"mkdown"
            | b"ronn" | b"scd" | b"workbook" => Kind::Markdown,
            b"html" | b"hta" | b"htm" | b"inc" | b"xht" | b"xhtml" => {
                Kind::Html(html::Parser::Html)
            }
            b"vue" => Kind::Html(html::Parser::Vue),
            b"mjml" => Kind::Html(html::Parser::Mjml),
            b"handlebars" | b"hbs" => Kind::Handlebars,
            _ => return None,
        })
    };
    match extension {
        // oxfmt passes MDX to its bundled Prettier.
        b"mdx" => Some(Kind::Mdx),
        _ => by_name.or_else(by_ending).or_else(by_extension),
    }
}

/// Prettier's `getLanguageByInterpreter`: picks the parser from the first line, like `#!/usr/bin/env node`, for a file
/// whose name has no `.` and isn't otherwise recognized.
pub(crate) fn parser_by_interpreter(path: &[u8]) -> Option<&'static [u8]> {
    if strings::contains_char(paths::basename(path), b'.') || Kind::of(path, None).is_some() {
        return None;
    }
    let mut start = [0; 256];
    let start = fs::read_start(path, &mut start);
    let line = strings::split(start, b"\n").next()?;
    let in_bin = (line.strip_prefix(b"#!/usr/local/bin/"))
        .or_else(|| line.strip_prefix(b"#!/usr/bin/"))
        .or_else(|| line.strip_prefix(b"#!/bin/"))?;
    let word = |text: &'_ [u8]| -> usize {
        text.iter()
            .take_while(|it| !it.is_ascii_whitespace())
            .count()
    };
    let after_env = (in_bin.strip_prefix(b"env"))
        .filter(|rest| !line.starts_with(b"#!/usr/local/") && word(rest) == 0)
        .map(<[u8]>::trim_ascii_start)
        .filter(|rest| !rest.is_empty());
    let rest = after_env.unwrap_or(in_bin);
    match &rest[..word(rest)] {
        b"bun" | b"chakra" | b"d8" | b"deno" | b"gjs" | b"js" | b"node" | b"nodejs" | b"qjs"
        | b"rhino" | b"v8" | b"v8-shell" | b"zx" => Some(b"babel"),
        b"ts-node" | b"tsx" => Some(b"typescript"),
        _ => None,
    }
}

pub(crate) fn language_of(path: &[u8]) -> Language {
    if Kind::of(path, None).is_some() {
        return Language::Supported;
    }
    match paths::basename(path) {
        b".prettierrc" | b".lintstagedrc" | b".stylelintrc" | b".clang-format" => Language::Other,
        _ => Language::Unknown,
    }
}

/// True if oxfmt treats the file at `path` as a Svelte component.
pub(crate) fn is_svelte_for_oxfmt(path: &[u8]) -> bool {
    (paths::basename(path).strip_suffix(b".svelte")).is_some_and(|stem| !stem.is_empty())
}

/// [`language_of`] for oxfmt, which also supports TOML and, if `formats_svelte`, Svelte.
pub(crate) fn language_for_oxfmt(path: &[u8], formats_svelte: bool) -> Language {
    match classify_for_oxfmt(path) {
        Some(_) => Language::Supported,
        None if formats_svelte && is_svelte_for_oxfmt(path) => Language::Supported,
        None => Language::Unknown,
    }
}

/// Each ASCII byte's weight in `a.localeCompare(b)`: punctuation, then digits, then letters regardless of case. Always
/// above zero.
const WEIGHTS: [u16; 256] = {
    const ORDER: &[u8] = b"\t\n\r _-,;:!?.'\"()[]{}@*/\\&#%`^+<=>|~$0123456789";
    let mut weights = [0; 256];
    let mut byte = 0;
    while byte < 256 {
        weights[byte] = match byte as u8 {
            letter @ (b'a'..=b'z' | b'A'..=b'Z') => 100 + letter.to_ascii_lowercase() as u16,
            _ => 300 + byte as u16,
        };
        byte += 1;
    }
    let mut at = 0;
    while at < ORDER.len() {
        weights[ORDER[at] as usize] = 1 + at as u16;
        at += 1;
    }
    weights
};

/// A key whose byte order matches how `a.localeCompare(b)` sorts the paths: the weights, then the inverted bytes, so
/// that `a` sorts before `A` if nothing else differs.
fn collation_key(path: &[u8]) -> Vec<u8> {
    let mut key = Vec::with_capacity(path.len() * 3 + 2);
    key.extend(
        path.iter()
            .flat_map(|byte| WEIGHTS[usize::from(*byte)].to_be_bytes()),
    );
    key.extend_from_slice(&[0, 0]);
    key.extend(path.iter().map(|byte| !byte));
    key
}

/// The arguments that start with `!`, read the way Prettier reads them: files they match are excluded from the files
/// the other arguments select. `bun lint` reads them the same way.
#[derive(Default)]
pub(crate) struct Exclusions(Vec<bun_glob::Pattern>);

impl Exclusions {
    /// `pattern` is an argument without its `!`.
    pub(crate) fn push(&mut self, pattern: &[u8]) {
        let pattern = pattern.strip_prefix(b"./").unwrap_or(pattern);
        self.0.push(prettier_glob(pattern, Picomatch::FastGlob));
    }

    /// `path` is a file or a directory. Patterns are relative to `cwd`.
    pub(crate) fn matches(&self, cwd: &[u8], path: &[u8]) -> bool {
        !self.0.is_empty() && {
            let relative = paths::relative(cwd, path);
            self.0.iter().any(|it| it.matches(&relative))
        }
    }
}

/// Decides which files are skipped.
pub(crate) struct Ignored {
    /// `.git`, `node_modules`, ..
    directories: Vec<&'static [u8]>,
    exclusions: Exclusions,
    /// `.gitignore`, `.prettierignore`: a file is ignored if any of them ignores it.
    files: Vec<Chain>,
    /// `Some` if every `.gitignore` applies, as in Git. Then none of them is in `files`. Caches the ones already read,
    /// keyed by directory.
    git_ignores: Option<Guarded<FxHashMap<Vec<u8>, GitIgnores>>>,
    cwd: Vec<u8>,
    /// Set when a search skips a matching file, or a directory it would enter, because of an ignore file.
    skipped_a_match: AtomicBool,
}

impl Ignored {
    /// `is_native` is [`Configs::is_native`].
    pub(crate) fn new(
        options: &Options,
        cwd: &[u8],
        flavor: Flavor,
        is_native: bool,
    ) -> Result<Ignored, Fatal> {
        let mut directories: Vec<&[u8]> = vec![b".git", b".sl", b".svn", b".hg", b".jj"];
        if !options.with_node_modules {
            directories.push(b"node_modules");
        }
        // Prettier only reads the working directory's `.gitignore`, so a project with a Prettier config gets only that
        // one.
        let follows_git = is_native && options.ignore_path.is_none();
        // oxfmt reads every `.gitignore` along the way, as Git does.
        let default: &[Vec<u8>] = match flavor {
            Flavor::Prettier if !follows_git => {
                &[b".gitignore".to_vec(), b".prettierignore".to_vec()]
            }
            _ => &[b".prettierignore".to_vec()],
        };
        let is_oxfmt = flavor == Flavor::Oxfmt;
        // Prettier doesn't read `info/exclude`. It's chained to `.gitignore`, the first of `default`, which Git checks
        // before it.
        let cannot_read = |file: &[u8], error: &bun_sys::Error| {
            let file = paths::relative(cwd, file);
            Fatal([b"Unable to read '", &file[..], b"': ", &fs::describe(error)].concat())
        };
        let mut excludes = match is_oxfmt || options.ignore_path.is_some() {
            true => None,
            false => gitignore::excludes_above(cwd)
                .map_err(|(file, error)| cannot_read(&file, &error))?,
        };
        if follows_git {
            // `GitIgnores` reads both files. It skips a file it can't read, but that's an error here.
            excludes = None;
            let file = paths::join(cwd, b".gitignore");
            if let Err(error) = fs::read(&file)
                && error.get_errno() != bun_sys::E::ENOENT
            {
                return Err(cannot_read(&file, &error));
            }
        }
        let mut files = Vec::new();
        for file in options.ignore_path.as_deref().unwrap_or(default) {
            let file = paths::resolve(cwd, &paths::from_native(file));
            if is_oxfmt && options.ignore_path.is_some() && !fs::is_file(&file) {
                return Err(Fatal([&file[..], b": File not found"].concat()));
            }
            let excludes = excludes.take();
            match options.pipes.read(&file) {
                Ok(text) => files.extend(
                    match gitignore::root_of_exclude_file(&file, cwd) {
                        Some(root) => gitignore::with_excludes(None, &root, &text, is_oxfmt),
                        None => {
                            gitignore::with_text(excludes, paths::dirname(&file), &text, is_oxfmt)
                        }
                    }
                    .map(Some),
                ),
                Err(error) if error.get_errno() == bun_sys::E::ENOENT => {
                    files.extend(excludes.map(Some))
                }
                Err(error) => return Err(cannot_read(&file, &error)),
            }
        }
        let all = &options.ignore_pattern;
        let (bunfig_lines, flag_lines) =
            all.split_at(options.bunfig_ignore_pattern_count.min(all.len()));
        for (start, lines) in [
            (&options.bunfig_base_directory(cwd)[..], bunfig_lines),
            (cwd, flag_lines),
        ] {
            if !lines.is_empty() {
                let lines = lines.join(&b"\n"[..]);
                files.extend(gitignore::with_text(None, start, &lines, is_oxfmt).map(Some));
            }
        }
        Ok(Ignored {
            directories,
            exclusions: Exclusions::default(),
            files,
            git_ignores: follows_git.then(Guarded::default),
            cwd: cwd.to_vec(),
            skipped_a_match: AtomicBool::new(false),
        })
    }

    /// `DirectoryIgnorer.shouldIgnore`
    fn is_in_ignored_directory(&self, path: &[u8]) -> bool {
        strings::split(&paths::relative(&self.cwd, path), b"/")
            .any(|name| self.directories.contains(&name))
    }

    /// Prettier appends the line `node_modules` to every ignore file, unless it's run with `--with-node-modules`.
    pub(crate) fn is_in_node_modules(&self, path: &[u8]) -> bool {
        const NAME: &[u8] = b"node_modules";
        self.directories.contains(&NAME)
            && strings::split(&paths::relative(&self.cwd, path), b"/").any(|name| name == NAME)
    }

    fn is_negated(&self, path: &[u8]) -> bool {
        self.exclusions.matches(&self.cwd, path)
    }

    /// True for entries that `fast-glob` never visits.
    fn is_never_visited(&self, path: &[u8], name: &[u8], is_directory: bool) -> bool {
        (is_directory && self.directories.contains(&name)) || self.is_negated(path)
    }

    /// True if an ignore file matches an entry reached by walking its parent directories, none of which is ignored.
    fn ignores_entry(&self, path: &[u8], is_directory: bool) -> bool {
        self.files
            .iter()
            .any(|chain| gitignore::is_ignored_in_search(chain, path, is_directory))
    }

    /// Returns Git's ignore files that apply in `directory`, or `None` if they aren't read.
    fn git_ignores_in(&self, directory: &[u8]) -> Option<GitIgnores> {
        let known = self.git_ignores.as_ref()?;
        if let Some(found) = known.lock().get(directory) {
            return Some(found.clone());
        }
        let read = GitIgnores::above_and_in_for_fmt(directory, &self.cwd);
        known.lock().insert(directory.to_vec(), read.clone());
        Some(read)
    }

    /// True if an ignore file matches the directory at `path` or one of its parents, which means everything in it is
    /// ignored.
    fn ignores_directory(&self, path: &[u8]) -> bool {
        self.files
            .iter()
            .any(|chain| gitignore::is_directory_ignored_anywhere(chain, path))
            || (self.git_ignores_in(path))
                .is_some_and(|git| git.is_directory_ignored_anywhere(path))
    }

    /// Prettier's `isIgnored`, for any file.
    pub(crate) fn ignores_file(&self, path: &[u8], config: &Chain) -> bool {
        self.files
            .iter()
            .chain([config])
            .any(|chain| gitignore::is_file_ignored_anywhere(chain, path))
            || (self.git_ignores_in(paths::dirname(path)))
                .is_some_and(|git| git.is_file_ignored_anywhere(path))
    }
}

struct Directory {
    path: Vec<u8>,
    /// Its parent directory's scope or, for the directory being searched, its own.
    above: Arc<Scope>,
    is_first: bool,
    /// Git's ignore files in its parent directories and, for the directory being searched, also its own.
    git: GitIgnores,
    /// True if the `ignorePatterns` of the configuration above it match it. It's still listed, because a configuration
    /// file in it starts over.
    is_ignored_by_configuration: bool,
}

/// The files in `base` for which `matches` returns true, given their path relative to the working directory.
fn search(
    configs: &Configs,
    pool: &Pool,
    ignored: &Ignored,
    base: &[u8],
    matches: &(dyn Fn(&[u8]) -> bool + Sync),
    enters: &(dyn Fn(&[u8]) -> bool + Sync),
    // Git's ignore files that apply in `base`, or `None` if they aren't read.
    git: Option<GitIgnores>,
) -> Result<Vec<Target>, Fatal> {
    let (mut found, mut failure) = (Guarded::new(Vec::new()), Guarded::new(None::<Fatal>));
    let reads_gitignore = git.is_some();
    let git = git.unwrap_or_default();
    let above = configs.for_directory(base)?;
    let mut level = vec![Directory {
        path: base.to_vec(),
        is_first: true,
        git,
        is_ignored_by_configuration: gitignore::is_directory_ignored_anywhere(
            configs.config_ignores(&above),
            base,
        ),
        above,
    }];
    while !level.is_empty() && failure.lock().is_none() {
        let mut next = Guarded::new(Vec::new());
        pool.for_each(level.len(), 1, &|index| {
            let directory = &level[index];
            let Some(mut listing) = fs::list(&directory.path) else {
                return;
            };
            let entries = std::mem::take(&mut listing.entries);
            let scope = match directory.is_first {
                true => Ok(Arc::clone(&directory.above)),
                false => configs.for_listed_directory(
                    &directory.path,
                    entries.iter().map(|it| (&it.name[..], it.is_directory)),
                    &directory.above,
                ),
            };
            let scope = match scope {
                Ok(scope) => scope,
                Err(error) => {
                    failure.lock().get_or_insert(error);
                    return;
                }
            };
            let ignore_patterns = configs.config_ignores(&scope);
            let starts_over = !directory.is_first
                && !std::ptr::eq(configs.config_ignores(&directory.above), ignore_patterns);
            let is_ignored_by_configuration = directory.is_ignored_by_configuration && !starts_over;
            let mut git = directory.git.clone();
            if reads_gitignore && !directory.is_first {
                git = git.and_in(&directory.path, |name| {
                    entries.iter().any(|it| it.name == name)
                });
            }
            let (mut files, mut directories) = (Vec::new(), Vec::new());
            // Links are neither followed nor formatted.
            for entry in entries.iter().filter(|it| !it.is_link) {
                let path = paths::join(&directory.path, &entry.name);
                if ignored.is_never_visited(&path, &entry.name, entry.is_directory) {
                    continue;
                }
                let relative = paths::relative(&ignored.cwd, &path);
                if ignored.ignores_entry(&path, entry.is_directory)
                    || git.is_ignored(&path, entry.is_directory)
                {
                    if match entry.is_directory {
                        true => enters(&relative),
                        false => matches(&relative),
                    } {
                        ignored.skipped_a_match.store(true, Ordering::Relaxed);
                    }
                    continue;
                }
                let is_ignored_by_configuration = is_ignored_by_configuration
                    || gitignore::is_ignored(ignore_patterns, &path, entry.is_directory);
                if entry.is_directory {
                    if enters(&relative) {
                        directories.push(Directory {
                            path,
                            above: Arc::clone(&scope),
                            is_first: false,
                            git: git.clone(),
                            is_ignored_by_configuration,
                        });
                    }
                } else if !is_ignored_by_configuration
                    && matches(&relative)
                    && let Some((size, linked)) = listing.size_and_identity_of(&entry.name)
                {
                    files.push(Target {
                        path,
                        size,
                        scope: Arc::clone(&scope),
                        ignores_unknown: false,
                        is_named: false,
                        linked,
                    });
                }
            }
            if !files.is_empty() {
                found.lock().append(&mut files);
            }
            if !directories.is_empty() {
                next.lock().append(&mut directories);
            }
        });
        level = std::mem::take(next.get_mut());
    }
    match failure.get_mut().take() {
        Some(error) => Err(error),
        None => Ok(std::mem::take(found.get_mut())),
    }
}

enum Entry {
    File(Vec<u8>, u64, Option<fs::Identity>),
    Directory(Vec<u8>),
    Pattern,
}

/// Prettier's `expandPatterns`. `patterns` is the list of arguments.
pub(crate) fn expand(
    configs: &Configs,
    pool: &Pool,
    ignored: &mut Ignored,
    patterns: &[Vec<u8>],
    error_on_unmatched_pattern: bool,
) -> Result<Vec<Expanded>, Fatal> {
    let cwd = ignored.cwd.clone();
    let mut expanded = Vec::new();
    // Each entry keeps the argument as written, which is how Prettier echoes it.
    let mut entries: Vec<(Entry, Vec<u8>, &[u8])> = Vec::new();
    for raw_argument in patterns {
        let pattern = paths::from_native(raw_argument);
        let path = paths::resolve(&cwd, &pattern);
        if ignored.is_in_ignored_directory(&path) {
            continue;
        }
        match fs::lstat(&path) {
            Some((fs::LinkKind::Link, ..)) => {
                if error_on_unmatched_pattern {
                    expanded.push(Expanded::Error(
                        [
                            b"Explicitly specified pattern \"",
                            &raw_argument[..],
                            b"\" is a symbolic link.",
                        ]
                        .concat(),
                    ));
                }
            }
            Some((fs::LinkKind::File, size, linked)) => {
                configs.name(paths::dirname(&path));
                entries.push((Entry::File(path, size, linked), pattern, &raw_argument[..]))
            }
            Some((fs::LinkKind::Directory, ..)) => {
                configs.name(&path);
                entries.push((Entry::Directory(path), pattern, &raw_argument[..]))
            }
            None => match pattern.strip_prefix(b"!") {
                Some(excluded_pattern) => ignored.exclusions.push(excluded_pattern),
                None => entries.push((Entry::Pattern, pattern, &raw_argument[..])),
            },
        }
    }
    let ignored = &*ignored;
    let mut seen: FxHashSet<Vec<u8>> = FxHashSet::default();
    let mut is_anything_ignored = false;
    for (entry, input, raw_argument) in entries {
        // The prefix of the paths that `fast-glob` returns, which they're sorted by.
        let mut pattern_base: (Vec<u8>, Vec<u8>) = (Vec::new(), cwd.clone());
        let (mut found, empty_message): (Vec<Target>, &[u8]) = match entry {
            Entry::File(path, size, linked) => {
                // An ignored file's configuration isn't even read.
                if ignored.ignores_file(&path, &None) {
                    is_anything_ignored = true;
                    continue;
                }
                let found = match ignored.is_negated(&path) {
                    true => Vec::new(),
                    false => vec![Target {
                        scope: configs.for_directory(paths::dirname(&path))?,
                        path,
                        size,
                        ignores_unknown: false,
                        is_named: true,
                        linked,
                    }],
                };
                (
                    found,
                    b"Explicitly specified file was ignored due to negative glob patterns",
                )
            }
            Entry::Directory(path) => {
                // Prettier finds the files and then skips each one, so this isn't an error.
                if ignored.ignores_directory(&path) {
                    is_anything_ignored = true;
                    continue;
                }
                let git = ignored.git_ignores_in(&path);
                let mut found = search(configs, pool, ignored, &path, &|_| true, &|_| true, git)?;
                found.iter_mut().for_each(|it| it.ignores_unknown = true);
                pattern_base = (paths::relative(&cwd, &path), path);
                (found, b"No supported files were found in the directory")
            }
            Entry::Pattern => {
                // `fast-glob`'s `removeLeadingDotSegment`
                let pattern = input.strip_prefix(b"./").unwrap_or(&input);
                let glob = prettier_glob(pattern, Picomatch::FastGlob);
                let parent = bun_glob::scan::glob_parent(pattern);
                let base = paths::resolve(&cwd, &parent);
                if parent != b"." {
                    pattern_base = (parent, base.clone());
                }
                // `fast-glob` matches paths spelled with the pattern's own base: an absolute pattern's results are
                // absolute, and what `../**` finds in the working directory starts with `../` plus that directory's
                // name.
                let is_absolute =
                    paths::is_absolute(pattern) || paths::is_external(&pattern_base.0);
                let absolute = |relative: &[u8]| {
                    let from_base = paths::relative(&base, &paths::resolve(&cwd, relative));
                    paths::join(&pattern_base.0, &from_base)
                };
                let found = match fs::kind(&base) {
                    Some(fs::Kind::Directory) if ignored.ignores_directory(&base) => {
                        is_anything_ignored = true;
                        continue;
                    }
                    Some(fs::Kind::Directory) => search(
                        configs,
                        pool,
                        ignored,
                        &base,
                        &|relative| match is_absolute {
                            true => glob.matches(&absolute(relative)),
                            false => glob.matches(relative),
                        },
                        &|relative| match is_absolute {
                            true => glob.may_match_inside(&absolute(relative)),
                            false => glob.may_match_inside(relative),
                        },
                        ignored.git_ignores_in(&base),
                    )?,
                    _ => Vec::new(),
                };
                (found, b"No files matching the pattern were found")
            }
        };
        let skipped_a_match = ignored.skipped_a_match.swap(false, Ordering::Relaxed);
        if found.is_empty() {
            // Prettier finds the files and then skips each one, so this isn't an error.
            if skipped_a_match {
                is_anything_ignored = true;
            } else if error_on_unmatched_pattern {
                expanded.push(Expanded::Error(
                    [empty_message, b": \"", raw_argument, b"\"."].concat(),
                ));
            }
            continue;
        }
        let key = |target: &Target| match &pattern_base.0[..] {
            b"" => paths::relative(&pattern_base.1, &target.path),
            base_prefix => {
                paths::join(base_prefix, &paths::relative(&pattern_base.1, &target.path))
            }
        };
        index_sort::sort_slice_by_cached_key(&mut found[..], |target| collation_key(&key(target)));
        for target in found {
            if seen.insert(target.path.clone()) {
                expanded.push(Expanded::File(target));
            }
        }
    }
    if expanded.is_empty() && !is_anything_ignored && error_on_unmatched_pattern {
        let patterns = patterns.join(&b' ');
        expanded.push(Expanded::Error(
            [b"No matching files. Patterns: ", &patterns[..]].concat(),
        ));
    }
    Ok(expanded)
}

/// oxfmt's `ScopedWalker`. `patterns` is the list of arguments.
pub(crate) fn expand_as_oxfmt(
    configs: &Configs,
    pool: &Pool,
    ignored: &mut Ignored,
    patterns: &[Vec<u8>],
    error_on_unmatched_pattern: bool,
) -> Result<Vec<Expanded>, Fatal> {
    let cwd = ignored.cwd.clone();
    let (mut targets, mut globs, mut excluded) = (Vec::new(), Vec::new(), Vec::new());
    for pattern in patterns {
        let pattern = paths::from_native(pattern);
        if let Some(rest) = pattern.strip_prefix(b"!") {
            excluded.push(rest.to_vec());
            continue;
        }
        let mut normalized = &pattern[..];
        if let Some(rest) = normalized.strip_prefix(b"./") {
            normalized = rest;
            while let Some(rest) = normalized.strip_prefix(b"/") {
                normalized = rest;
            }
        }
        let path = paths::resolve(&cwd, normalized);
        // Something that exists isn't a pattern, whatever it looks like.
        match strings::index_of_any(normalized, b"*?[{").is_some() && !bun_sys::exists(&path) {
            true => match glob_error(normalized) {
                Some(pattern_error) => return Err(Fatal(pattern_error)),
                None => globs.push(oxc_glob(normalized)),
            },
            false => targets.push(path),
        }
    }
    // These use `.gitignore` syntax, unlike Prettier's.
    let excluded = excluded.iter().map(|it: &Vec<u8>| &it[..]);
    ignored
        .files
        .extend(gitignore::with_lines(None, &cwd, excluded).map(Some));
    let ignored = &*ignored;
    if !globs.is_empty() || targets.is_empty() {
        targets.push(cwd);
    }
    index_sort::sort_slice(&mut targets[..]);
    targets.dedup();

    let is_ignored = |chain: &Chain, path: &[u8], kind: fs::Kind| match kind {
        fs::Kind::Directory => gitignore::is_directory_ignored_anywhere(chain, path),
        fs::Kind::File => gitignore::is_file_ignored_anywhere(chain, path),
    };
    let targets: Vec<(Vec<u8>, fs::Kind, u64, Option<fs::Identity>)> = targets
        .into_iter()
        .filter_map(|path| fs::stat(&path).map(|(kind, size, linked)| (path, kind, size, linked)))
        .filter(|(path, kind, ..)| !ignored.files.iter().any(|it| is_ignored(it, path, *kind)))
        .collect();
    let are_all_in_repositories = LazyCell::new(|| {
        let directories = || targets.iter().filter(|it| it.1 == fs::Kind::Directory);
        let searched = directories().map(|it| &it.0[..]);
        directories().count() == 1
            || gitignore::are_all_in_repositories(searched, std::iter::empty())
    });
    for (path, kind, ..) in &targets {
        configs.name(match kind {
            fs::Kind::Directory => path,
            fs::Kind::File => paths::dirname(path),
        });
    }
    let mut found: Vec<Target> = Vec::new();
    for (path, kind, size, linked) in &targets {
        if *kind == fs::Kind::Directory {
            let matches =
                |relative: &[u8]| globs.is_empty() || globs.iter().any(|it| it.matches(relative));
            let Some(git) = GitIgnores::for_search(path, true, || *are_all_in_repositories) else {
                continue;
            };
            found.append(&mut search(
                configs,
                pool,
                ignored,
                path,
                &matches,
                &|_| true,
                Some(git),
            )?);
            continue;
        }
        let scope = configs.for_directory(paths::dirname(path))?;
        if !is_ignored(configs.config_ignores(&scope), path, *kind) {
            found.push(Target {
                path: path.clone(),
                size: *size,
                linked: *linked,
                scope,
                ignores_unknown: true,
                is_named: false,
            });
        }
    }
    // A file without a parser is silently skipped and isn't counted.
    found.retain(|it| {
        language_for_oxfmt(&it.path, configs.formats_svelte(&it.scope, Some(&it.path)))
            != Language::Unknown
    });
    index_sort::sort_slice_by(&mut found[..], |a, b| a.path.cmp(&b.path));
    found.dedup_by(|a, b| a.path == b.path);
    if found.is_empty() && error_on_unmatched_pattern {
        let error = b"Expected at least one target file. All matched files may have been excluded by ignore rules.";
        return Ok(vec![Expanded::Error(error.to_vec())]);
    }
    Ok(found.into_iter().map(Expanded::File).collect())
}
