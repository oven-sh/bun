// Generates `oxlint_categories.rs`: what `.oxlintrc.json` means depends on what oxlint knows about its rules.
//
//   OXLINT=<the oxlint executable> OXC_DIR=<checkout of oxc> node generate-oxlint-categories.mjs
//
// The executable is the judge: the rules, their plugins and their categories are what `oxlint --rules` prints. Only on which kinds
// of files a rule runs (`should_run`) is not printed by anything. That is read from the source, which can be of another version:
// see `corrections`.

import { execFileSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";

const oxlint = resolve(process.env.OXLINT);
const oxc = resolve(process.env.OXC_DIR);
const version = /[\d.]+/.exec(execFileSync(oxlint, ["--version"]).toString())[0];
const rules = JSON.parse(execFileSync(oxlint, ["--rules", "--format", "json"], { maxBuffer: 1 << 26 }).toString());
const categories = ["correctness", "suspicious", "pedantic", "perf", "style", "restriction", "nursery"];
// The plugins of which something is implemented here.
const plugins = [
  "eslint",
  "typescript",
  "react",
  "import",
  "node",
  "oxc",
  "unicorn",
  "react_perf",
  "jsx_a11y",
  "nextjs",
  "promise",
  "jest",
  "vitest",
  "jsdoc",
  "vue",
];
// Where the executable does something else than the source says. Each was tried: a file of each kind that the rule reports.
const corrections = {
  // 1.80 reports `require()` in JavaScript files too.
  "typescript/no-var-requires": undefined,
};
const table = {};
const runsOn = {};
for (const { scope: plugin, value: name, category, fix, type_aware: needsTypes } of rules) {
  if (!plugins.includes(plugin)) continue;
  if (!categories.includes(category)) throw new Error(`${plugin}/${name}: ${category}`);
  ((table[plugin] ??= {})[category] ??= []).push(name);
  // `should_run`, as far as it is about the kind of file.
  const file = join(oxc, "crates/oxc_linter/src/rules", plugin, name.replaceAll("-", "_"));
  const path = [`${file}.rs`, join(file, "mod.rs")].find(it => existsSync(it));
  const text = path ? readFileSync(path, "utf8") : "";
  const body = /fn should_run\(&self, ctx: &[\w:]*ContextHost\) -> bool \{\n([\s\S]*?)\n    \}/.exec(text)?.[1] ?? "";
  const code = body
    .split("\n")
    .map(line => line.trim())
    .filter(line => line && !line.startsWith("//"))
    .join(" ");
  const read =
    /^ctx\.source_type\(\)\.is_typescript\(\)|return false; \} ctx\.source_type\(\)\.is_typescript\(\)$/.test(code)
      ? "TYPESCRIPT_ONLY"
      : code.startsWith("!ctx.source_type().is_typescript()")
        ? "NOT_TYPESCRIPT"
        : code.startsWith("!ctx.source_type().is_typescript_definition()")
          ? "NOT_DECLARATIONS"
          : undefined;
  const kind = `${plugin}/${name}` in corrections ? corrections[`${plugin}/${name}`] : read;
  if (kind) ((runsOn[kind] ??= {})[plugin] ??= []).push(name);
  // What `--fix` can do. For a rule with fixes of several kinds the executable prints the most dangerous one, which says nothing
  // about a report: only these two classes are certain. Not for the rules that need types: those are tsgolint's, which fixes
  // what the executable says has no fix (dot-notation, prefer-readonly). Of the plugins whose rules are ports of the rules for
  // ESLint here.
  const fixes = /^(none|pending)$/.test(fix)
    ? "WITHOUT_FIX"
    : /^(fixable|conditional)_suggestion$/.test(fix)
      ? "ONLY_SUGGESTIONS"
      : undefined;
  if (fixes && !needsTypes && ["eslint", "typescript"].includes(plugin))
    ((runsOn[fixes] ??= {})[plugin] ??= []).push(name);
}
// The names of all rules, whatever the plugin.
const allNames = new Set(rules.map(it => it.value));
const commit = execFileSync("git", ["-C", oxc, "rev-parse", "--short", "HEAD"]).toString().trim();
const wrap = names => {
  const lines = [];
  let line = "";
  for (const name of names) {
    if (line.length + name.length > 100) {
      lines.push(line);
      line = "";
    }
    line += `${name} `;
  }
  lines.push(line.trimEnd());
  return lines;
};
/** The names as one string. `indent`: of the line that it starts in. */
const literal = (names, indent) => {
  const lines = wrap(names);
  if (lines.length === 1) return `"${lines[0]}"`;
  return `concat!(\n${lines.map(line => `        "${line}",`).join("\n")}\n${indent})`;
};
writeFileSync(
  join(import.meta.dirname, "oxlint_categories.rs"),
  `//! Generated by \`generate-oxlint-categories.mjs\` from oxlint ${version}, and from oxc ${commit} for the kinds of files. Not edited by hand.

/// For each category, the plugins as oxlint calls them, each with the names of its rules in the category, separated by spaces.
#[rustfmt::skip]
pub(super) static CATEGORIES: &[(&str, &[(&str, &str)])] = &[
${categories
  .map(
    category => `    (
        "${category}",
        &[
${plugins
  .filter(plugin => table[plugin][category])
  .map(plugin => `        ("${plugin}", ${literal(table[plugin][category], "        ")}),`)
  .join("\n")}
        ],
    ),`,
  )
  .join("\n")}
];

${[
  ["TYPESCRIPT_ONLY", "The rules that only run on TypeScript files"],
  ["NOT_TYPESCRIPT", "The rules that do not run on TypeScript files"],
  ["NOT_DECLARATIONS", "The rules that do not run on declaration files"],
  ["WITHOUT_FIX", "The rules that have neither a fix nor a suggestion"],
  ["ONLY_SUGGESTIONS", "The rules that have suggestions and no fix"],
]
  .map(
    ([
      kind,
      what,
    ]) => `/// ${what}: the plugins as oxlint calls them, each with the names of its rules, separated by spaces.
#[rustfmt::skip]
pub(super) static ${kind}: &[(&str, &str)] = &[
${Object.entries(runsOn[kind] ?? {})
  .map(([plugin, names]) => `    ("${plugin}", ${literal(names, "    ")}),`)
  .join("\n")}
];
`,
  )
  .join("\n")}
/// The names of all rules of oxlint, without their plugins, sorted and separated by spaces.
#[rustfmt::skip]
pub(super) static RULE_NAMES: &str = ${literal([...allNames].sort(), "")};
`,
);
console.log(
  Object.entries(table)
    .map(([plugin, by]) => `${plugin}: ${Object.values(by).flat().length}`)
    .join(", "),
);
