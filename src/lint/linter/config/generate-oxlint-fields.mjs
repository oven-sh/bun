// Generates `oxlint_fields.rs`: the names of the options of oxlint's rules, for the rules that refuse a name they do not know.
//
//   OXLINT=<the oxlint executable> SCHEMA=<configuration_schema.json of its package> node generate-oxlint-fields.mjs
//
// The executable is the judge: each rule is given an object with a property that no rule has, and says "unknown field `..`,
// expected one of `a`, `b`", or takes it. The schema only says which rules there are, and what can stand before an object that is
// the second option.

import { execFileSync, spawnSync } from "node:child_process";
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";

const oxlint = resolve(process.env.OXLINT);
const schema = JSON.parse(readFileSync(resolve(process.env.SCHEMA), "utf8"));
const version = /[\d.]+/.exec(execFileSync(oxlint, ["--version"]).toString())[0];
const rules = schema.definitions.DummyRuleMap.properties;
const plugins = [...new Set(Object.keys(rules).flatMap(it => (it.includes("/") ? [it.split("/")[0]] : [])))];
const deref = it => (it?.$ref ? deref(schema.definitions[it.$ref.split("/").at(-1)]) : it);
const unknown = "zzUnknown";

/** A value that `it` takes, if it is one of a few words. */
function word(it) {
  it = deref(it);
  if (it?.enum) return it.enum[0];
  for (const one of it?.oneOf ?? it?.anyOf ?? []) {
    const found = word(one);
    if (found !== undefined) return found;
  }
}

/** What oxlint says about each of `settings`, by the rule. All that it refuses are in one answer. */
function ask(settings) {
  const directory = mkdtempSync(join(tmpdir(), "oxlint-fields-"));
  try {
    writeFileSync(join(directory, "a.js"), "");
    writeFileSync(
      join(directory, "c.json"),
      JSON.stringify({ plugins, categories: { correctness: "off" }, rules: settings }),
    );
    const { stdout, stderr, status } = spawnSync(oxlint, ["-c", "c.json", "--disable-nested-config", "a.js"], {
      cwd: directory,
      encoding: "utf8",
      env: { ...process.env, NO_COLOR: "1" },
    });
    if (status !== 0 && status !== 1) throw new Error(`oxlint: ${status}: ${stdout}${stderr}`);
    const refusals = new Map();
    for (const [, rule, lines] of (stdout + stderr).matchAll(
      /Invalid configuration for rule `([^`]+)`:\n((?:\s+[│|].*\n?)*)/g,
    )) {
      refusals.set(rule, lines.replace(/\n\s+[│|]\s*/g, "\n").trim());
    }
    return refusals;
  } finally {
    rmSync(directory, { recursive: true });
  }
}

/** The names in "unknown field `zzUnknown`, expected one of `a`, `b`". */
function names(refusal) {
  const [first] = (refusal ?? "").split(/\n|,? received /);
  const [, said] = first.split(`unknown field \`${unknown}\``);
  // react/jsx-no-literals says no more than that: there the names are not known.
  if (!/^, (expected|there are no fields)/.test(said ?? "")) return;
  return [...said.matchAll(/`([^`]+)`/g)].map(it => it[1]);
}

const first = ask(Object.fromEntries(Object.keys(rules).map(it => [it, ["error", { [unknown]: 1 }]])));
const before = Object.entries(rules).flatMap(([rule, it]) => {
  const items = it.anyOf?.map(deref).find(it => Array.isArray(it.items))?.items ?? [];
  const found = items.length > 2 ? word(items[1]) : undefined;
  return found === undefined ? [] : [[rule, found]];
});
const second = ask(Object.fromEntries(before.map(([rule, it]) => [rule, ["error", it, { [unknown]: 1 }]])));

const rows = Object.keys(rules)
  .flatMap(rule =>
    [first, second].flatMap((all, at) => (names(all.get(rule)) ? [[rule, at, names(all.get(rule))]] : [])),
  )
  .sort(([a, i], [b, j]) => (a < b ? -1 : a > b ? 1 : i - j));
const text = `//! Generated by \`generate-oxlint-fields.mjs\` from oxlint ${version}. Not edited by hand.

/// The rules whose option at this place, if it is an object, can only have properties of these names, which are separated by spaces.
/// Sorted. A rule is written as \`oxlint_rule_key\` writes it.
#[rustfmt::skip]
pub(super) static FIELDS: &[(&str, u8, &str)] = &[
${rows.map(([rule, at, all]) => `    ("${rule}", ${at}, "${all.join(" ")}"),`).join("\n")}
];
`;
writeFileSync(join(import.meta.dirname, "oxlint_fields.rs"), text);
console.log(`${rows.length} rows`);
