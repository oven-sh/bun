// Generates `data.rs`: since which version of Node.js each built-in is there, from eslint-plugin-n.
//
//   ESLINT_PLUGIN_N_DIR=<checkout of eslint-plugin-n with node_modules> node generate-data.mjs

import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import { pathToFileURL } from "node:url";

const root = resolve(process.env.ESLINT_PLUGIN_N_DIR);
const require = createRequire(join(root, "package.json"));
const { Table, check, place } = createRequire(import.meta.url)("./generate-table.cjs");
const load = file => import(pathToFileURL(join(root, file)).href);
// The same module that the plugin imports: its symbols are the keys.
const { READ, CALL, CONSTRUCT } = await import(
  pathToFileURL(require.resolve("@eslint-community/eslint-utils").replace(/\.js$/, ".mjs")).href
);
const rsort = require("semver/functions/rsort.js");

const { NodeBuiltinGlobals, NodeBuiltinModules, NodeBuiltinImportMeta } = await load(
  "lib/unsupported-features/node-builtins.js",
);
// The trace map of `es-builtins` is not exported.
const source = readFileSync(join(root, "lib/rules/no-unsupported-features/es-builtins.js"), "utf8");
const literal = source.slice(
  source.indexOf("const traceMap = {") + "const traceMap = ".length,
  source.indexOf("/** @type {import('../rule-module.js').RuleModule} */"),
);
// As a module of its own.
const pieces = mkdtempSync(join(tmpdir(), "generate-data-"));
writeFileSync(join(pieces, "trace-map.mjs"), `export default READ => (${literal});\n`);
const esBuiltins = (await import(pathToFileURL(join(pieces, "trace-map.mjs")).href)).default(READ);
rmSync(pieces, { recursive: true });

/** `versionsToString` */
const text = ([latest, ...backported]) =>
  backported.length === 0 ? latest : `${latest} (backported: ${backported.map(it => `^${it}`).join(", ")})`;

const versionPool = []; // "[1, 2, 3]"
/**
 * The arguments of `Part::new`: where the versions are in the pool, the latest first. And what upstream says, if that
 * is not what `versions_to_string` makes of the numbers.
 */
function versions(list) {
  const sorted = rsort([...(list ?? [])]);
  if (sorted.length === 0) return ["0, 0"];
  const numbers = sorted.map(it =>
    it
      .replace(/^v/, "")
      .split(".")
      .map(part => check(Number(part), 0x100, it)),
  );
  const start = place(
    versionPool,
    numbers.map(it => `[${it.join(", ")}]`),
  );
  const isRegular = text(numbers.map(it => it.join("."))) === text(sorted);
  return [
    `${check(start, 0x10000, "versions")}, ${check(numbers.length, 0x100, "versions")}`,
    isRegular ? undefined : text(sorted),
  ];
}
const infoRows = [];
const infoKeys = [];
const otherwise = []; // an info, what upstream says of `supported`
function info(value) {
  if (value === undefined) return undefined;
  const [supported, supportedText] = versions(value.supported);
  const [experimental, experimentalText] = versions(value.experimental);
  if (experimentalText !== undefined)
    throw new Error(`${experimentalText}: WRITTEN_OTHERWISE is for \`supported\` only`);
  const key = `${supported}, ${experimental}, ${supportedText}`;
  if (!infoKeys.includes(key)) {
    if (supportedText !== undefined) otherwise.push([infoRows.length, supportedText]);
    infoKeys.push(key);
    infoRows.push(`i(${supported}, ${experimental})`);
  }
  return infoKeys.indexOf(key);
}

const table = new Table();
const arrays = new Map(); // object -> array
function members(object) {
  if (arrays.has(object)) return arrays.get(object);
  const array = table.reserve();
  arrays.set(object, array);
  const keys = Object.getOwnPropertyNames(object).filter(key => object[key] != null);
  return table.fill(
    array,
    keys.map(name => {
      const child = object[name];
      const hasMembers = Object.getOwnPropertyNames(child).some(it => child[it] != null);
      return {
        name,
        kinds: [info(child[READ]), info(child[CALL]), info(child[CONSTRUCT])],
        members: hasMembers ? members(child) : undefined,
      };
    }),
  );
}
const roots = {
  ES_GLOBALS: members(esBuiltins.globals),
  NODE_GLOBALS: members(NodeBuiltinGlobals),
  NODE_MODULES: members(NodeBuiltinModules),
  NODE_IMPORT_META: members(NodeBuiltinImportMeta),
};
table.layOut();

const { version } = require("./package.json");
writeFileSync(
  join(import.meta.dirname, "data.rs"),
  `//! Generated by \`generate-data.mjs\` from eslint-plugin-n ${version}. Not edited by hand.

use super::Info;
use super::table::{Member, NONE, Part, Table};

${Object.entries(roots)
  .map(([name, array]) => `pub(crate) const ${name}: Part = Part::new(${table.runOf(array)});`)
  .join("\n")}

const fn i(supported: u16, supported_len: u8, experimental: u16, experimental_len: u8) -> Info {
    Info {
        supported: Part::new(supported, supported_len),
        experimental: Part::new(experimental, experimental_len),
    }
}

/// The [\`INFOS\`] whose \`supported\` upstream writes otherwise than [\`versions_to_string\`](super::versions_to_string)
/// does.
#[rustfmt::skip]
pub(crate) static WRITTEN_OTHERWISE: [(u16, &str); ${otherwise.length}] = [
${otherwise.map(([info, text]) => `    (${info}, ${JSON.stringify(text)}),`).join("\n")}
];

/// The versions that the [\`INFOS\`] have, those of one after each other, the latest first.
#[rustfmt::skip]
pub(crate) static VERSIONS: [[u8; 3]; ${versionPool.length}] = [
${versionPool.map(it => `    ${it},`).join("\n")}
];

#[rustfmt::skip]
pub(crate) static INFOS: [Info; ${infoRows.length}] = [
${infoRows.map(it => `    ${it},`).join("\n")}
];

${table.statics("Builtin", "The global variables and the modules, with indices into [`INFOS`].")}
`,
);
console.log(
  `${infoRows.length} infos, ${versionPool.length} versions, ${table.arrays.length} arrays, ${table.rows.length} members, ${table.kinds.length} kinds, ${table.names.length} bytes of names`,
);
