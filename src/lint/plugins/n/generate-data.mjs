// Generates `data.rs`: since which version of Node.js each built-in is there, from eslint-plugin-n.
//
//   ESLINT_PLUGIN_N_DIR=<checkout of eslint-plugin-n with node_modules> node generate-data.mjs

import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { join, resolve } from "node:path";
import { pathToFileURL } from "node:url";

const root = resolve(process.env.ESLINT_PLUGIN_N_DIR);
const require = createRequire(join(root, "package.json"));
const load = file => import(pathToFileURL(join(root, file)).href);
// The same module that the plugin imports: its symbols are the keys.
const { READ, CALL, CONSTRUCT } = await import(pathToFileURL(require.resolve("@eslint-community/eslint-utils").replace(/\.js$/, ".mjs")).href);
const rsort = require("semver/functions/rsort.js");

const { NodeBuiltinGlobals, NodeBuiltinModules, NodeBuiltinImportMeta } = await load("lib/unsupported-features/node-builtins.js");
// The trace map of `es-builtins` is not exported.
const source = readFileSync(join(root, "lib/rules/no-unsupported-features/es-builtins.js"), "utf8");
const literal = source.slice(source.indexOf("const traceMap = {") + "const traceMap = ".length, source.indexOf("/** @type {import('../rule-module.js').RuleModule} */"));
const esBuiltins = new Function("READ", `return (${literal})`)(READ);

const infos = new Map(); // JSON -> index
const infoRows = [];
const versions = list => `&[${rsort([...(list ?? [])]).map(it => `[${it.replace(/^v/, "").split(".").map(Number).join(", ")}]`).join(", ")}]`;
/** `versionsToString` */
function text(list) {
  const [latest, ...backported] = rsort([...(list ?? [])]);
  return JSON.stringify(backported.length === 0 ? (latest ?? "") : `${latest} (backported: ${backported.map(it => `^${it}`).join(", ")})`);
}
function info(value) {
  if (value === undefined) return "None";
  const row = `Info { supported: ${versions(value.supported)}, supported_text: ${text(value.supported)}, experimental: ${versions(value.experimental)}, experimental_text: ${text(value.experimental)} }`;
  if (!infos.has(row)) (infos.set(row, infoRows.length), infoRows.push(row));
  return `Some(${infos.get(row)})`;
}

const maps = new Map(); // object -> index
const mapRows = [];
function members(object) {
  if (maps.has(object)) return maps.get(object);
  const index = mapRows.length;
  maps.set(object, index);
  mapRows.push(null);
  const rows = Object.getOwnPropertyNames(object)
    .filter(key => object[key] != null)
    .map(key => {
      const child = object[key];
      const inner = Object.getOwnPropertyNames(child).some(it => child[it] != null) ? `&M${members(child)}` : "&[]";
      return `    (${JSON.stringify(key)}, m(${info(child[READ])}, ${info(child[CALL])}, ${info(child[CONSTRUCT])}, ${inner})),`;
    });
  mapRows[index] = rows;
  return index;
}
const roots = {
  ES_GLOBALS: members(esBuiltins.globals),
  NODE_GLOBALS: members(NodeBuiltinGlobals),
  NODE_MODULES: members(NodeBuiltinModules),
  NODE_IMPORT_META: members(NodeBuiltinImportMeta),
};

const { version } = require("./package.json");
writeFileSync(join(import.meta.dirname, "data.rs"), `//! Generated by \`generate-data.mjs\` from eslint-plugin-n ${version}. Not edited by hand.

use super::{Info, Map};

const fn m(read: Option<u16>, call: Option<u16>, construct: Option<u16>, members: &'static [(&'static str, Map)]) -> Map {
    Map {
        read,
        call,
        construct,
        esm: false,
        members,
    }
}

${Object.entries(roots).map(([name, index]) => `pub(crate) static ${name}: &[(&str, Map)] = &M${index};`).join("\n")}

/// The versions are sorted, the latest first.
#[rustfmt::skip]
pub(crate) static INFOS: [Info; ${infoRows.length}] = [
${infoRows.map(it => `    ${it},`).join("\n")}
];

${mapRows.map((rows, index) => `#[rustfmt::skip]\nstatic M${index}: [(&str, Map); ${rows.length}] = [\n${rows.join("\n")}\n];`).join("\n")}
`);
console.log(`${infoRows.length} infos, ${mapRows.length} maps, ${mapRows.reduce((sum, it) => sum + it.length, 0)} members`);
