// Generates `es_syntax_data.rs`: the features that `n/no-unsupported-features/es-syntax` knows, since which version of Node.js each
// is supported, and for those that eslint-plugin-es-x finds by the name of a global or of a method, these names.
//
//   ESLINT_PLUGIN_N_DIR=<checkout of eslint-plugin-n with node_modules> node generate-es-syntax.cjs

const { writeFileSync } = require("node:fs");
const { join, resolve } = require("node:path");

const root = resolve(process.env.ESLINT_PLUGIN_N_DIR);
const esx = join(root, "node_modules/eslint-plugin-es-x");
const { READ, CALL, CONSTRUCT, ReferenceTracker } = require(
  require.resolve("@eslint-community/eslint-utils", { paths: [esx] }),
);
const features = require(join(root, "lib/rules/no-unsupported-features/es-syntax.json"));

// What a rule asks its helpers for is recorded.
let traceMaps = [];
let prototypes = [];
let usesRegExp = false;
ReferenceTracker.prototype.iterateGlobalReferences = map => (traceMaps.push(map), []);
const stub = (file, exports) => {
  const path = require.resolve(join(esx, file));
  require.cache[path] = { id: path, filename: path, loaded: true, exports };
};
stub("lib/util/define-prototype-method-handler", {
  definePrototypeMethodHandler: (_, map) => (prototypes.push(map), { "(prototype)"() {} }),
});
stub("lib/util/define-regexp-handler", { defineRegExpHandler: () => ((usesRegExp = true), { "(regexp)"() {} }) });

const sourceCode = { getScope: () => ({}), scopeManager: { globalScope: {} }, ast: {}, text: "" };
const context = {
  options: [],
  settings: {},
  sourceCode,
  getSourceCode: () => sourceCode,
  report() {},
  languageOptions: {},
  filename: "a.js",
};

/** Whether everything in the map is `[READ]: true`. */
const isOnlyRead = map => Object.values(map).every(it => !it[CALL] && !it[CONSTRUCT] && isOnlyRead(it));
const traceMap = map =>
  `TraceMap::new(&[${Object.entries(map)
    .map(([key, value]) => `(${JSON.stringify(key)}, ${traceMap(value)}${value[READ] ? ".read(())" : ""})`)
    .join(", ")}])`;
const strings = list => `&[${list.map(it => JSON.stringify(it)).join(", ")}]`;
const constant = id => id.replace(/^no-/, "").replaceAll("-", "_").toUpperCase();

const rows = [];
const byHand = [];
for (const [id, meta] of Object.entries(features)) {
  traceMaps = [];
  prototypes = [];
  usesRegExp = false;
  const visitor = require(join(esx, "lib/rules", `${id}.js`)).create(context);
  try {
    visitor["Program:exit"]?.({});
  } catch {}
  const isGeneric = traceMaps.length <= 1 && traceMaps.every(isOnlyRead) && id !== "no-subclassing-builtins";
  const others = Object.keys(visitor).filter(
    key => key !== "(prototype)" && !(key === "Program:exit" && isGeneric && traceMaps.length === 1),
  );
  if (others.length > 0) byHand.push([id, rows.length]);
  const name = id.replace(/^no-/, "");
  const camel = name.replace(/-(\w)/g, (_, first) => first.toUpperCase());
  rows.push(`    Feature {
        name: ${JSON.stringify(name)},
        ignore_names: ${strings([id, name, camel, ...(meta.aliases ?? [])])},
        supported: ${meta.supported ? `Some(${JSON.stringify(meta.supported)})` : "None"},
        strict_mode: ${meta.strictMode ? `Some(${JSON.stringify(meta.strictMode)})` : "None"},
        globals: ${isGeneric && traceMaps.length === 1 ? traceMap(traceMaps[0]) : "TraceMap::EMPTY"},
        prototype: &[${prototypes
          .flatMap(map => Object.entries(map))
          .map(([name, methods]) => `(${JSON.stringify(name)}, ${strings(methods)})`)
          .join(", ")}],
    },`);
}

const { scValueSets, binPropertySets } = require(join(esx, "lib/util/unicode-properties"));
const years = [2019, 2020, 2021, 2022, 2023];
const set = (sets, year) => strings([...sets[`es${year}`]].filter(Boolean).sort());

writeFileSync(
  join(__dirname, "es_syntax_data.rs"),
  `//! Generated by \`generate-es-syntax.cjs\` from eslint-plugin-n ${require(join(root, "package.json")).version} and eslint-plugin-es-x
//! ${require(join(esx, "package.json")).version}. Not edited by hand.

use super::es_syntax::Feature;
use bun_lint::utils::eslint_utils::TraceMap;

/// The positions in [\`FEATURES\`] of those that take more than a look at \`globals\` and \`prototype\`.
${byHand.map(([id, index]) => `pub(crate) const ${constant(id)}: usize = ${index};`).join("\n")}

#[rustfmt::skip]
pub(crate) static FEATURES: [Feature; ${rows.length}] = [
${rows.join("\n")}
];

/// For each year from ${years[0]}: the values of \`Script\` and the binary properties that \`\\p{..}\` has had since then. Sorted.
#[rustfmt::skip]
pub(crate) static UNICODE_PROPERTIES: [(&[&str], &[&str]); ${years.length}] = [
${years.map(year => `    (${set(scValueSets, year)}, ${set(binPropertySets, year)}),`).join("\n")}
];
`,
);
console.log(`${rows.length} features, ${byHand.length} by hand`);
