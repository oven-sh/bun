// Generates regex_classes.rs.
//
//   bun src/lint/react/rules/react_capitalized_calls/generate_regex_classes.ts <regex-syntax>/src/unicode_tables
//
// The classes of `regex-syntax` that JavaScript lacks, with the code points and the names that the crate has for
// them. Take the version of `regex-syntax` from the Cargo.lock of the oxlint release that the rule follows.

import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const tablesDirectory = process.argv[2];
if (!tablesDirectory) throw new Error("usage: generate_regex_classes.ts <regex-syntax>/src/unicode_tables");

type Range = [start: number, end: number];
/** [normalized name, canonical name] */
type Alias = [string, string];

const read = (file: string) => readFileSync(join(tablesDirectory, file), "utf8");

const ESCAPES: Record<string, number> = { "\\0": 0, "\\t": 9, "\\n": 10, "\\r": 13, "\\'": 39, "\\\\": 92 };

function codePoint(literal: string): number {
  if (literal.startsWith("\\u{")) return parseInt(literal.slice(3, -1), 16);
  if (!literal.startsWith("\\")) return literal.codePointAt(0)!;
  const escaped = ESCAPES[literal];
  if (escaped === undefined) throw new Error(`unknown escape ${literal}`);
  return escaped;
}

/** The tables of a file, by the name that its `BY_NAME` gives each. */
function tables(file: string): Map<string, Range[]> {
  const source = read(file);
  const byName = source.match(/pub const BY_NAME: [^=]*= &\[\n(.*?)\n\];\n/s);
  if (!byName) throw new Error(`no BY_NAME in ${file}`);
  const names = new Map([...byName[1].matchAll(/\("([^"]+)", ([A-Z0-9_]+)\)/g)].map(m => [m[2], m[1]]));
  const char = String.raw`'(\\u\{[0-9a-f]+\}|\\.|[^\\])'`;
  const range = new RegExp(String.raw`\(${char}, ${char}\)`, "gsu");
  const out = new Map<string, Range[]>();
  for (const table of source.matchAll(/pub const ([A-Z0-9_]+): &'static \[\(char, char\)\] =\s+&\[(.*?)\];\n/gs)) {
    const name = names.get(table[1]);
    if (!name) throw new Error(`${file}: ${table[1]} has no name`);
    const ranges = [...table[2].matchAll(range)].map((m): Range => [codePoint(m[1]), codePoint(m[2])]);
    const rest = table[2].replace(range, "").replace(/[\s,]/g, "");
    if (rest || ranges.length === 0) throw new Error(`${file}: ${table[1]} has ${rest || "nothing"}`);
    out.set(name, ranges);
  }
  if (out.size !== names.size) throw new Error(`${file}: ${out.size} tables for ${names.size} names`);
  return out;
}

function aliases(list: string): Alias[] {
  return [...list.matchAll(/\("([^"]+)", "([^"]+)"\)/g)].map((m): Alias => [m[1], m[2]]);
}

const propertyNames = aliases(read("property_names.rs"));

/** The names of the values of a property. */
function propertyValues(property: string): Alias[] {
  const values = read("property_values.rs").match(
    new RegExp(String.raw`\(\n\s+"${property}",\n\s+&\[(.*?)\],\n\s+\),`, "s"),
  );
  if (!values) throw new Error(`no values of ${property}`);
  return aliases(values[1]);
}

/** How far each range starts past the end of the one before it, then how many code points follow its start. */
function encode(ranges: Range[]): number[] {
  const out: number[] = [];
  let next = 0;
  for (const [start, end] of ranges) {
    if (start < next || end < start) throw new Error("the ranges aren't sorted");
    out.push(start - next, end - start);
    next = end + 1;
  }
  return out;
}

const unicode = read("age.rs").match(/Unicode version: ([0-9.]+)\./)?.[1];
const crate = readFileSync(join(tablesDirectory, "../../Cargo.toml"), "utf8").match(/^version = "([^"]+)"/m)?.[1];
if (!unicode || !crate) throw new Error("no version");

const out: string[] = [
  "//! Generated by generate_regex_classes.ts. Do not edit.",
  "//!",
  `//! The classes that \`regex-syntax\` ${crate} has and JavaScript lacks, with the code points of Unicode ${unicode}.`,
  "//! - https://github.com/rust-lang/regex (Copyright The Rust Project Developers, MIT License)",
  `//! - https://www.unicode.org/Public/${unicode}/ucd (Copyright Unicode, Inc., Unicode License v3)`,
  "",
  "/// The classes of a property. Each has its names as the crate normalizes them, separated by spaces, and its",
  "/// ranges: how far each starts past the end of the one before it, then how many code points follow its start.",
  "pub(super) type Classes = &'static [(&'static str, &'static [u32])];",
  "",
];

function emit(doc: string, name: string, classes: { canonical: string; names: string[]; ranges: Range[] }[]) {
  out.push(...doc.split("\n").map(line => `/// ${line}`), "#[rustfmt::skip]");
  out.push(`pub(super) static ${name}: Classes = &[`);
  for (const { canonical, names, ranges } of classes) {
    if (names.length === 0) throw new Error(`${canonical} has no name`);
    out.push(`    ("${names.sort().join(" ")}", &[`);
    let line = "       ";
    for (const value of encode(ranges)) {
      const text = ` ${value},`;
      if (line.length + text.length > 110) {
        out.push(line);
        line = "       ";
      }
      line += text;
    }
    out.push(line, "    ]),");
  }
  out.push("];", "");
}

/** The classes of `file`, each with the names that `names` has for it. */
function classes(file: string, names: Alias[], only?: string[]) {
  const all = tables(file);
  for (const canonical of only ?? []) {
    if (!all.has(canonical)) throw new Error(`${file} has no ${canonical}`);
  }
  return [...all]
    .filter(([canonical]) => !only || only.includes(canonical))
    .map(([canonical, ranges]) => ({
      canonical,
      names: names.filter(alias => alias[1] === canonical).map(alias => alias[0]),
      ranges,
    }));
}

const version = (canonical: string) => canonical.slice(1).split("_").map(Number);

emit(
  "The binary properties that JavaScript lacks.",
  "BINARY_PROPERTIES",
  classes("property_bool.rs", propertyNames, [
    "Grapheme_Link",
    "Hyphen",
    "IDS_Unary_Operator",
    "ID_Compat_Math_Continue",
    "ID_Compat_Math_Start",
    "Modifier_Combining_Mark",
    "Other_Alphabetic",
    "Other_Default_Ignorable_Code_Point",
    "Other_Grapheme_Extend",
    "Other_ID_Continue",
    "Other_ID_Start",
    "Other_Lowercase",
    "Other_Math",
    "Other_Uppercase",
    "Prepended_Concatenation_Mark",
  ]),
);
emit(
  "What each version of Unicode added, oldest first. `Age` of a version is that and all before it.",
  "AGE",
  classes("age.rs", propertyValues("Age")).sort((a, b) => {
    const [majorA, minorA] = version(a.canonical);
    const [majorB, minorB] = version(b.canonical);
    return majorA - majorB || minorA - minorB;
  }),
);
emit(
  "The values of `Grapheme_Cluster_Break`. The crate has no class for the others.",
  "GRAPHEME_CLUSTER_BREAK",
  classes("grapheme_cluster_break.rs", propertyValues("Grapheme_Cluster_Break")),
);
emit(
  "The values of `Sentence_Break`. The crate has no class for the others.",
  "SENTENCE_BREAK",
  classes("sentence_break.rs", propertyValues("Sentence_Break")),
);
emit(
  "The values of `Word_Break`. The crate has no class for the others.",
  "WORD_BREAK",
  classes("word_break.rs", propertyValues("Word_Break")),
);

writeFileSync(join(import.meta.dir, "regex_classes.rs"), out.join("\n"));
