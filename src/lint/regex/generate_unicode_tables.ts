// Generates unicode_tables.rs.
//
//   bun src/lint/regex/generate_unicode_tables.ts <regexpp>/src/unicode/properties.ts <ucd>/emoji-zwj-sequences.txt
//
// The names of the properties, and the ECMAScript version that added each, come from regexpp. The
// data comes from the `RegExp` of the Bun that runs this script, so the tables have the version of
// Unicode that it has. It cannot list the sequences of emoji joined by U+200D: those of the file are
// kept if `RegExp` knows them. WebKit has the file in Source/JavaScriptCore/ucd.

import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

type Ranges = [number, number][];

const MAX = 0x10ffff;

// All code points but the surrogates, in order.
const universe = (() => {
  const parts: string[] = [];
  for (let start = 0; start <= MAX; start += 0x800) {
    if (start >= 0xd800 && start < 0xe000) continue;
    const chunk: number[] = [];
    for (let cp = start; cp < start + 0x800; cp++) chunk.push(cp);
    parts.push(String.fromCodePoint(...chunk));
  }
  return parts.join("");
})();

function codePointAtIndex(index: number): number {
  if (index < 0xd800) return index;
  if (index < 0xf800) return index + 0x800;
  return 0x10000 + (index - 0xf800) / 2;
}

function normalize(ranges: Ranges): Ranges {
  ranges.sort((a, b) => a[0] - b[0]);
  const out: Ranges = [];
  for (const [lo, hi] of ranges) {
    const last = out[out.length - 1];
    if (last && lo <= last[1] + 1) last[1] = Math.max(last[1], hi);
    else out.push([lo, hi]);
  }
  return out;
}

/** The code points that `\p{expression}` matches, or null if this engine does not know it. */
function property(expression: string): Ranges | null {
  let many: RegExp, one: RegExp;
  try {
    many = new RegExp(`\\p{${expression}}+`, "gu");
    one = new RegExp(`^\\p{${expression}}$`, "u");
  } catch {
    return null;
  }
  const ranges: Ranges = [];
  for (const match of universe.matchAll(many)) {
    const lo = codePointAtIndex(match.index);
    const hi = codePointAtIndex(match.index + match[0].length) - 1;
    if (lo < 0xd800 && hi >= 0xe000) ranges.push([lo, 0xd7ff], [0xe000, hi]);
    else if (hi === 0xdfff) ranges.push([lo, 0xd7ff]);
    else ranges.push([lo, hi]);
  }
  for (let cp = 0xd800; cp < 0xe000; cp++) {
    if (one.test(String.fromCharCode(cp))) ranges.push([cp, cp]);
  }
  return normalize(ranges);
}

const toggles = (ranges: Ranges) => ranges.flatMap(([lo, hi]) => [lo, hi + 1]);

function fromToggles(list: number[]): Ranges {
  const out: Ranges = [];
  for (let i = 0; i < list.length; i += 2) out.push([list[i], (list[i + 1] ?? MAX + 1) - 1]);
  return out;
}

function xor(a: number[], b: number[]): number[] {
  const out: number[] = [];
  let i = 0;
  let j = 0;
  while (i < a.length || j < b.length) {
    if (j >= b.length || a[i] < b[j]) out.push(a[i++]);
    else if (i >= a.length || b[j] < a[i]) out.push(b[j++]);
    else (i++, j++);
  }
  return out;
}

function contains(ranges: Ranges, cp: number): boolean {
  let lo = 0;
  let hi = ranges.length;
  while (lo < hi) {
    const mid = (lo + hi) >> 1;
    if (cp < ranges[mid][0]) hi = mid;
    else if (cp > ranges[mid][1]) lo = mid + 1;
    else return true;
  }
  return false;
}

function intersect(a: Ranges, b: Ranges): Ranges {
  const out: Ranges = [];
  let i = 0;
  let j = 0;
  while (i < a.length && j < b.length) {
    const lo = Math.max(a[i][0], b[j][0]);
    const hi = Math.min(a[i][1], b[j][1]);
    if (lo <= hi) out.push([lo, hi]);
    if (a[i][1] < b[j][1]) i++;
    else j++;
  }
  return out;
}

const complement = (a: Ranges) => fromToggles(xor(toggles(a), [0, MAX + 1]));
const subtract = (a: Ranges, b: Ranges) => intersect(a, complement(b));
const key = (ranges: Ranges) => ranges.map(r => r.join("-")).join(",");

// == names ==

const source = readFileSync(process.argv[2], "utf8");

/** The strings given to `new DataSet(..)` for `name`: one per version, from ES2018. */
function dataSet(name: string): string[][] {
  const start = source.indexOf(`const ${name} = new DataSet(`);
  if (start < 0) throw new Error(`no ${name}`);
  const end = source.indexOf("\n)", start);
  return [...source.slice(start, end).matchAll(/"([^"]*)"/g)].map(m => m[1].split(" ").filter(Boolean));
}

function named(name: string): { name: string; version: number }[] {
  return dataSet(name)
    .flatMap((names, i) => names.map(name => ({ name, version: i })))
    .sort((a, b) => (a.name < b.name ? -1 : 1));
}

const out: string[] = [
  `//! Generated by generate_unicode_tables.ts, with the data of Unicode ${process.versions.unicode ?? "?"}. Do not edit.`,
  "",
];

function emit(doc: string, name: string, type: string, values: (number | string)[]) {
  out.push(...doc.split("\n").map(line => `/// ${line}`), "#[rustfmt::skip]");
  out.push(`pub(super) static ${name}: &[${type}] = &[`);
  let line = "   ";
  for (const value of values) {
    const text = ` ${value},`;
    if (line.length + text.length > 110) {
      out.push(line);
      line = "   ";
    }
    line += text;
  }
  if (line.trim()) out.push(line);
  out.push("];", "");
}

function emitNames(doc: string, name: string, names: string[]) {
  out.push(...doc.split("\n").map(line => `/// ${line}`));
  out.push(`pub(super) static ${name}: &[u8] = b"\\`);
  let line = "";
  names.forEach((text, i) => {
    text += i + 1 < names.length ? " " : "";
    if (line.length + text.length > 100) {
      out.push(`${line}\\`);
      line = "";
    }
    line += text;
  });
  out.push(`${line}";`, "");
}

// == General_Category ==

const GC = "Lu Ll Lt Lm Lo Mn Mc Me Nd Nl No Pc Pd Ps Pe Pi Pf Po Sm Sc Sk So Zs Zl Zp Cc Cf Cs Co Cn".split(" ");
const gcRanges = GC.map(name => property(`gc=${name}`)!);

function partition(parts: Ranges[], bits: number): number[] {
  const all = parts.flatMap((ranges, i) => ranges.map(([lo, hi]) => [lo, hi, i]));
  all.sort((a, b) => a[0] - b[0]);
  let next = 0;
  const packed: number[] = [];
  for (const [lo, hi, i] of all) {
    if (lo !== next) throw new Error(`not a partition at ${lo.toString(16)}`);
    packed.push(lo * 2 ** bits + i);
    next = hi + 1;
  }
  if (next !== MAX + 1) throw new Error("not a partition at the end");
  return packed;
}

emit(
  `The General_Category of all code points: \`start << 5 | category\`, sorted. A category is an index in\n\`${GC.join(" ")}\`.`,
  "GENERAL_CATEGORY",
  "u32",
  partition(gcRanges, 5),
);

const gcNames = named("gcValueSets");
emitNames(
  "The values of General_Category, sorted.",
  "GENERAL_CATEGORY_NAMES",
  gcNames.map(n => n.name),
);
emit(
  "For each name in `GENERAL_CATEGORY_NAMES`, the categories it stands for as a set of bits.",
  "GENERAL_CATEGORY_MASKS",
  "u32",
  gcNames.map(({ name }) => {
    const ranges = property(`gc=${name}`)!;
    let mask = 0;
    GC.forEach((_, i) => {
      if (contains(ranges, gcRanges[i][0][0])) mask |= 1 << i;
    });
    const union = normalize(
      GC.flatMap((_, i) => (mask & (1 << i) ? gcRanges[i].map(r => [...r] as [number, number]) : [])),
    );
    if (key(union) !== key(ranges)) throw new Error(`gc=${name} is not a union of categories`);
    return `0x${(mask >>> 0).toString(16)}`;
  }),
);

// == Script, Script_Extensions ==

const UNSUPPORTED = 255;
const scNames = named("scValueSets");
const scripts: { sc: Ranges; scx: Ranges }[] = [];
const scriptIndex = new Map<string, number>();
const scValues = scNames.map(({ name, version }) => {
  const sc = property(`sc=${name}`);
  if (!sc) return (version << 8) | UNSUPPORTED;
  let index = scriptIndex.get(key(sc));
  if (index === undefined) {
    index = scripts.length;
    scriptIndex.set(key(sc), index);
    scripts.push({ sc, scx: property(`scx=${name}`)! });
  }
  return (version << 8) | index;
});
if (scripts.length >= UNSUPPORTED) throw new Error("too many scripts");

emit(
  "The Script of all code points: `start << 8 | script`, sorted.",
  "SCRIPT",
  "u32",
  partition(
    scripts.map(s => s.sc),
    8,
  ),
);
emitNames(
  "The values of Script and Script_Extensions, sorted.",
  "SCRIPT_NAMES",
  scNames.map(n => n.name),
);
emit(
  "For each name in `SCRIPT_NAMES`: `version << 8 | script`. The version counts from ES2018. The script is 255\nif the tables do not have it.",
  "SCRIPT_VALUES",
  "u16",
  scValues,
);

{
  const bounds = new Set<number>();
  for (const { sc, scx } of scripts) for (const b of xor(toggles(sc), toggles(scx))) bounds.add(b);
  const sorted = [...bounds].sort((a, b) => a - b);
  const sets: string[] = [];
  const explicit: [number, number, number][] = [];
  for (let i = 0; i + 1 < sorted.length; i++) {
    const lo = sorted[i];
    const hi = sorted[i + 1] - 1;
    const sc = scripts.findIndex(s => contains(s.sc, lo));
    const set = scripts.flatMap((s, index) => (contains(s.scx, lo) ? [index] : []));
    if (set.length === 1 && set[0] === sc) continue;
    let index = sets.indexOf(set.join(" "));
    if (index < 0) index = sets.push(set.join(" ")) - 1;
    const last = explicit[explicit.length - 1];
    if (last && last[1] + 1 === lo && last[2] === index) last[1] = hi;
    else explicit.push([lo, hi, index]);
  }
  if (sets.length >= 1 << 11) throw new Error("too many sets of scripts");
  const listed = normalize(explicit.map(([lo, hi]) => [lo, hi]));
  scripts.forEach(({ sc, scx }, index) => {
    const added = explicit
      .filter(e => sets[e[2]].split(" ").includes(String(index)))
      .map(([lo, hi]) => [lo, hi] as [number, number]);
    if (key(normalize([...subtract(sc, listed), ...added])) !== key(scx)) throw new Error(`scx of script ${index}`);
  });
  emit(
    "The code points whose Script_Extensions is not just their Script: pairs of `start << 11 | set` and the last\ncode point, sorted.",
    "SCRIPT_EXTENSIONS",
    "u32",
    explicit.flatMap(([lo, hi, set]) => [lo * 2 ** 11 + set, hi]),
  );
  const offsets = [0];
  const flat: number[] = [];
  for (const set of sets) {
    flat.push(...set.split(" ").filter(Boolean).map(Number));
    offsets.push(flat.length);
  }
  emit(
    "Set `i` of `SCRIPT_EXTENSIONS` is `SCRIPT_SETS[SCRIPT_SET_OFFSETS[i]..SCRIPT_SET_OFFSETS[i + 1]]`.",
    "SCRIPT_SET_OFFSETS",
    "u16",
    offsets,
  );
  emit("Scripts.", "SCRIPT_SETS", "u8", flat);
}

// == binary properties ==

{
  const names = named("binPropertySets");
  const index = new Map<string, number>();
  const masks: string[] = [];
  const offsets = [0];
  const data: number[] = [];
  const values = names.map(({ name, version }) => {
    const ranges = property(name);
    if (!ranges) return (version << 8) | UNSUPPORTED;
    let i = index.get(key(ranges));
    if (i === undefined) {
      i = masks.length;
      index.set(key(ranges), i);
      let mask = 0;
      GC.forEach((_, g) => {
        if (subtract(gcRanges[g], ranges).length < intersect(gcRanges[g], ranges).length) mask |= 1 << g;
      });
      let base: number[] = [];
      GC.forEach((_, g) => {
        if (mask & (1 << g)) base = xor(base, toggles(gcRanges[g]));
      });
      masks.push(`0x${(mask >>> 0).toString(16)}`);
      data.push(...xor(base, toggles(ranges)));
      offsets.push(data.length);
    }
    return (version << 8) | i;
  });
  emitNames(
    "The binary properties, sorted.",
    "BINARY_NAMES",
    names.map(n => n.name),
  );
  emit(
    "For each name in `BINARY_NAMES`: `version << 8 | property`, as in `SCRIPT_VALUES`.",
    "BINARY_VALUES",
    "u16",
    values,
  );
  emit(
    "A binary property is the code points of the categories in `BINARY_MASKS[property]`, except that those in\n`BINARY_TOGGLES[BINARY_OFFSETS[property]..BINARY_OFFSETS[property + 1]]` are the other way around. That is\na sorted list of code points at each of which membership flips.",
    "BINARY_MASKS",
    "u32",
    masks,
  );
  emit("See `BINARY_MASKS`.", "BINARY_OFFSETS", "u16", offsets);
  emit("See `BINARY_MASKS`.", "BINARY_TOGGLES", "u32", data);
}

// == case folding ==

function runs(map: Map<number, number>): number[] {
  const entries = [...map].filter(([cp, to]) => cp !== to).sort((a, b) => a[0] - b[0]);
  const packed: number[] = [];
  for (let i = 0; i < entries.length; ) {
    const [start, to] = entries[i];
    const delta = to - start;
    let stride = 1;
    let end = start;
    const next = entries[i + 1];
    if (next && next[1] - next[0] === delta && next[0] - start <= 2) stride = next[0] - start;
    let j = i + 1;
    while (j < entries.length && entries[j][0] === end + stride && entries[j][1] - entries[j][0] === delta)
      end = entries[j++][0];
    if (end === start) stride = 1;
    packed.push(start, end * 2 + (stride - 1), delta);
    i = j;
  }
  return packed;
}

function representatives(classes: Iterable<number[]>): Map<number, number> {
  const map = new Map<number, number>();
  for (const members of classes) {
    const least = Math.min(...members);
    for (const cp of members) map.set(cp, least);
  }
  return map;
}

const FOLD_DOC =
  "Triples of the first code point, `last << 1 | (stride - 1)` and a difference. Adding the difference to a code\npoint of the run gives the least of the code points that it is equal to when case is ignored.";

/** The sets of code points that `RegExp` holds equal with the flags `flags`, which include `i`. */
function foldClasses(flags: string): number[][] {
  const cased = property("Cased")!;
  for (const name of ["CWCF", "CWCM", "CWL", "CWU", "CWT", "CWKCF"]) cased.push(...property(name)!);
  const candidates: number[] = [];
  for (const [lo, hi] of normalize(cased)) for (let cp = lo; cp <= hi; cp++) candidates.push(cp);
  const text = String.fromCodePoint(...candidates);
  const parent = new Map<number, number>();
  const find = (cp: number): number => {
    const up = parent.get(cp);
    if (up === undefined || up === cp) return cp;
    const root = find(up);
    parent.set(cp, root);
    return root;
  };
  for (const cp of candidates) {
    const escape = cp > 0xffff ? `\\u{${cp.toString(16)}}` : `\\u${cp.toString(16).padStart(4, "0")}`;
    for (const match of text.matchAll(new RegExp(escape, flags))) {
      const a = find(cp);
      const b = find(match[0].codePointAt(0)!);
      if (a !== b) parent.set(Math.max(a, b), Math.min(a, b));
    }
  }
  const classes = new Map<number, number[]>();
  for (const cp of candidates) {
    const root = find(cp);
    if (!classes.has(root)) classes.set(root, []);
    classes.get(root)!.push(cp);
  }
  return [...classes.values()];
}

/**
 * The specification's `Canonicalize` without the `u` and `v` flags, from `toUpperCase`. JavaScriptCore has a table of its own for
 * this, which is behind the rest of its Unicode data.
 */
function legacyFoldClasses(): number[][] {
  const classes = new Map<number, number[]>();
  for (let unit = 0; unit <= 0xffff; unit++) {
    const upper = String.fromCharCode(unit).toUpperCase();
    let canonical = upper.length === 1 ? upper.charCodeAt(0) : unit;
    if (unit >= 128 && canonical < 128) canonical = unit;
    if (!classes.has(canonical)) classes.set(canonical, []);
    classes.get(canonical)!.push(unit);
  }
  return [...classes.values()].filter(members => members.length > 1);
}

emit(
  `Case folding with the \`u\` or \`v\` flag.\n${FOLD_DOC}`,
  "FOLD_UNICODE",
  "i32",
  runs(representatives(foldClasses("giu"))),
);
emit(
  `Case folding without the \`u\` and \`v\` flags.\n${FOLD_DOC}`,
  "FOLD_LEGACY",
  "i32",
  runs(representatives(legacyFoldClasses())),
);

// == properties of strings ==

{
  const names = named("binPropertyOfStringsSets").map(n => n.name);
  emitNames("The binary properties of strings, sorted.", "STRING_PROPERTY_NAMES", names);
  const has = (name: string) => {
    const re = new RegExp(`^\\p{${name}}$`, "v");
    return (...cps: number[]) => re.test(String.fromCodePoint(...cps));
  };
  const parts = names.filter(name => name !== "RGI_Emoji").map(has);
  const rgi = has("RGI_Emoji");
  /** RGI_Emoji is the union of the others. */
  const checked = (test: (...cps: number[]) => boolean, ...cps: number[]) => {
    if (rgi(...cps) !== parts.some(part => part(...cps))) throw new Error(`RGI_Emoji: ${cps}`);
    return test(...cps);
  };
  const emoji: number[] = [];
  for (const [lo, hi] of property("Emoji")!) for (let cp = lo; cp <= hi; cp++) emoji.push(cp);
  const where = (test: (cp: number) => boolean) => toggles(normalize(emoji.filter(test).map(cp => [cp, cp])));
  const TONES = [0x1f3fb, 0x1f3fc, 0x1f3fd, 0x1f3fe, 0x1f3ff];

  const basic = has("Basic_Emoji");
  emit(
    "The code points that are a Basic_Emoji: a list as in `BINARY_TOGGLES`.",
    "EMOJI_BASIC",
    "u32",
    where(cp => checked(basic, cp)),
  );
  emit(
    "The code points that are a Basic_Emoji when U+FE0F follows.",
    "EMOJI_BASIC_WITH_VARIATION_SELECTOR",
    "u32",
    where(cp => checked(basic, cp, 0xfe0f)),
  );

  const keycap = has("Emoji_Keycap_Sequence");
  const keys = emoji.filter(cp => checked(keycap, cp, 0xfe0f, 0x20e3));
  if (String.fromCodePoint(...keys) !== "#*0123456789") throw new Error("Emoji_Keycap_Sequence");

  const modified = has("RGI_Emoji_Modifier_Sequence");
  emit(
    "The code points that are an RGI_Emoji_Modifier_Sequence when one of U+1F3FB to U+1F3FF follows.",
    "EMOJI_MODIFIER_BASES",
    "u32",
    where(cp => {
      const count = TONES.filter(tone => checked(modified, cp, tone)).length;
      if (count % 5) throw new Error(`RGI_Emoji_Modifier_Sequence: ${cp}`);
      return count > 0;
    }),
  );

  const flagged = has("RGI_Emoji_Flag_Sequence");
  const letters = Array.from({ length: 26 }, (_, i) => 0x1f1e6 + i);
  emit(
    "Bit `j` of entry `i` is set if the regional indicators `i` and `j` are an RGI_Emoji_Flag_Sequence.",
    "EMOJI_FLAGS",
    "u32",
    letters.map(
      a => `0x${letters.reduce((mask, b, j) => (checked(flagged, a, b) ? mask | (1 << j) : mask), 0).toString(16)}`,
    ),
  );

  const tagged = has("RGI_Emoji_Tag_Sequence");
  const tags = ["gbeng", "gbsct", "gbwls"];
  for (const tag of tags) {
    if (!checked(tagged, 0x1f3f4, ...[...tag].map(c => 0xe0000 + c.charCodeAt(0)), 0xe007f)) throw new Error(tag);
  }
  emitNames(
    "An RGI_Emoji_Tag_Sequence is U+1F3F4, the tag characters for one of these, and U+E007F.",
    "EMOJI_TAGS",
    tags,
  );

  const joined = has("RGI_Emoji_ZWJ_Sequence");
  const ANY_TONE = 255;
  const groups = new Map<string, number[][]>();
  for (const line of readFileSync(process.argv[3], "utf8").split("\n")) {
    const field = line.split(/[;#]/)[0].trim();
    if (!field) continue;
    const cps = field.split(/\s+/).map(hex => parseInt(hex, 16));
    if (!checked(joined, ...cps)) continue;
    const shape = cps.map(cp => (TONES.includes(cp) ? "*" : cp)).join(" ");
    if (!groups.has(shape)) groups.set(shape, []);
    groups.get(shape)!.push(cps);
  }
  const alphabet: number[] = [];
  const letter = (cp: number) => {
    if (!alphabet.includes(cp)) alphabet.push(cp);
    return alphabet.indexOf(cp);
  };
  const data: number[] = [];
  for (const [shape, all] of groups) {
    const tones = shape.split(" ").filter(part => part === "*").length;
    const sequences =
      all.length === 5 ** tones ? [shape.split(" ").map(part => (part === "*" ? -1 : Number(part)))] : all;
    for (const cps of sequences) data.push(cps.length, ...cps.map(cp => (cp < 0 ? ANY_TONE : letter(cp))));
  }
  if (alphabet.length >= ANY_TONE) throw new Error("too many code points in RGI_Emoji_ZWJ_Sequence");
  emit("The code points of `EMOJI_ZWJ_SEQUENCES`.", "EMOJI_ZWJ_ALPHABET", "u32", alphabet);
  emit(
    "RGI_Emoji_ZWJ_Sequence. Each is its length, and then for each code point its index in `EMOJI_ZWJ_ALPHABET`, or\n255 for any of U+1F3FB to U+1F3FF.",
    "EMOJI_ZWJ_SEQUENCES",
    "u8",
    data,
  );
}

writeFileSync(process.argv[4] ?? join(import.meta.dir, "unicode_tables.rs"), out.join("\n"));
