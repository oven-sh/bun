/// ESLint's `keywords.includes(name)`.
#[inline]
pub fn is_keyword(name: &[u8]) -> bool {
    KEYWORDS
        .binary_search_by(|keyword| keyword.as_bytes().cmp(name))
        .is_ok()
}
