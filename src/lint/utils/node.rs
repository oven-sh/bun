/// Whether `specifier` is a module of Node.js, with or without `node:`.
pub fn is_builtin_module(specifier: &[u8]) -> bool {
    is_builtin_module_in(specifier, CURRENT)
}

/// `isCoreModule(specifier, version)`
pub fn is_builtin_module_in(specifier: &[u8], version: [u32; 3]) -> bool {
    let found = MODULES.binary_search_by_key(&specifier, |it| it.0).ok();
    let Some((_, ranges)) = found.and_then(|at| MODULES.get(at)) else {
        return false;
    };
    let mut ranges = ranges.iter();
    ranges.any(|(first, end)| first.map(u32::from) <= version && version < end.map(u32::from))
}
