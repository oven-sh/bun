/// `/^\p{L}$/u.test(c)`, in Unicode 17.
#[inline]
pub fn is_letter(c: u32) -> bool {
    match c {
        0..0x80 => (c as u8).is_ascii_alphabetic(),
        _ => is_in_runs(&LETTERS, c),
    }
}

/// ESLint's `LETTER_PATTERN`. Where `text.match(LETTER_PATTERN)` is: the range in bytes of the first
/// letter of `text`.
pub fn find_letter(text: &[u8]) -> Option<Range<usize>> {
    let (at, _) = code_points(text).find(|&(_, c)| is_letter(c))?;
    Some(at..at + code_point_at(text, at).1)
}

/// ESLint's `containsLetter`.
#[inline]
pub fn contains_letter(text: &[u8]) -> bool {
    code_points(text).any(|(_, c)| is_letter(c))
}

/// ESLint's `getGraphemeCount`. The length of text that is ASCII, where `\r\n` counts as two, and
/// otherwise the number of [`graphemes`]. typescript-eslint's `getStringLength`, which differs for
/// control characters, is `ts_utils::get_string_length`.
pub fn get_grapheme_count(text: &[u8]) -> usize {
    match strings::first_non_ascii(text) {
        None => text.len(),
        Some(_) => graphemes(text).count(),
    }
}

/// `new Intl.Segmenter().segment(text)`: the extended grapheme clusters of UAX #29, in Unicode 17.
#[inline]
pub fn graphemes(text: &[u8]) -> Graphemes<'_> {
    Graphemes { text }
}

#[derive(Copy, Clone)]
pub struct Graphemes<'t> {
    /// What is left.
    text: &'t [u8],
}

impl<'t> Iterator for Graphemes<'t> {
    type Item = &'t [u8];

    fn next(&mut self) -> Option<&'t [u8]> {
        use Class::*;
        let (first, mut at) = code_point_at(self.text, 0);
        if at == 0 {
            return None;
        }
        let mut previous = Class::of(first);
        // `previous` ends `\p{Extended_Pictographic} Extend*`, or that and a `ZWJ`.
        let mut is_after_pictographic = previous == Pictographic;
        // `previous` ends `\p{InCB=Consonant} [\p{InCB=Extend}\p{InCB=Linker}]*`, and whether there
        // is a linker in that.
        let (mut is_after_consonant, mut has_linker) = (previous == Consonant, false);
        // A cluster starts with an even number of regional indicators before it.
        let mut is_second_regional_indicator = false;
        loop {
            let (c, size) = code_point_at(self.text, at);
            if size == 0 {
                break;
            }
            let next = Class::of(c);
            let is_joined = match (previous, next) {
                (Cr, Lf) => true,
                (Cr | Lf | Control, _) | (_, Cr | Lf | Control) => false,
                (L, L | V | Lv | Lvt) | (Lv | V, V | T) | (Lvt | T, T) => true,
                (_, Extend | ExtendConjunct | Linker | Zwj | SpacingMark) | (Prepend, _) => true,
                (_, Consonant) if is_after_consonant && has_linker => true,
                (Zwj, Pictographic) if is_after_pictographic => true,
                (RegionalIndicator, RegionalIndicator) => !is_second_regional_indicator,
                _ => false,
            };
            if !is_joined {
                break;
            }
            is_after_pictographic = match next {
                Pictographic => true,
                Extend | ExtendConjunct | Linker | Zwj => is_after_pictographic && previous != Zwj,
                _ => false,
            };
            match next {
                Consonant => (is_after_consonant, has_linker) = (true, false),
                Linker => has_linker = true,
                ExtendConjunct | Zwj => {}
                _ => is_after_consonant = false,
            }
            is_second_regional_indicator =
                previous == RegionalIndicator && next == RegionalIndicator;
            previous = next;
            at += size;
        }
        let (cluster, rest) = self.text.split_at(at);
        self.text = rest;
        Some(cluster)
    }
}

/// What grapheme segmentation tells code points apart by: `Grapheme_Cluster_Break`, where `Other`
/// and `Extend` are divided by `Extended_Pictographic` and `Indic_Conjunct_Break`.
#[derive(Copy, Clone, PartialEq, Eq)]
enum Class {
    Other,
    Cr,
    Lf,
    Control,
    /// `Extend` with `InCB=None`
    Extend,
    /// `Extend` with `InCB=Extend`
    ExtendConjunct,
    /// `Extend` with `InCB=Linker`
    Linker,
    /// It has `InCB=Extend`.
    Zwj,
    RegionalIndicator,
    Prepend,
    SpacingMark,
    L,
    V,
    T,
    Lv,
    Lvt,
    Pictographic,
    /// `InCB=Consonant`
    Consonant,
}

impl Class {
    /// In the order of the numbers in [`GRAPHEME_CLASSES`].
    const ALL: [Class; 18] = [
        Class::Other,
        Class::Cr,
        Class::Lf,
        Class::Control,
        Class::Extend,
        Class::ExtendConjunct,
        Class::Linker,
        Class::Zwj,
        Class::RegionalIndicator,
        Class::Prepend,
        Class::SpacingMark,
        Class::L,
        Class::V,
        Class::T,
        Class::Lv,
        Class::Lvt,
        Class::Pictographic,
        Class::Consonant,
    ];

    fn of(c: u32) -> Class {
        match c {
            0x0D => Class::Cr,
            0x0A => Class::Lf,
            0..0x20 | 0x7F => Class::Control,
            0x20..0x7F => Class::Other,
            0xAC00..=0xD7A3 if (c - 0xAC00).is_multiple_of(28) => Class::Lv,
            0xAC00..=0xD7A3 => Class::Lvt,
            0xD800..=0xDFFF => Class::Control,
            _ => {
                let after = GRAPHEME_CLASSES.partition_point(|&run| run >> 5 <= c);
                let run = after.checked_sub(1).and_then(|at| GRAPHEME_CLASSES.get(at));
                let class = run.and_then(|&run| Class::ALL.get((run & 31) as usize));
                class.copied().unwrap_or(Class::Other)
            }
        }
    }
}

