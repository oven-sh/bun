const PUBLIC_IDS: &[&str] = &[
    "-//w3o//dtd w3 html strict 3.0//en//",
    "-/w3c/dtd html 4.0 transitional/en",
    "html",
];
const HTML_4_01: &[&str] = &[
    "-//w3c//dtd html 4.01 frameset//",
    "-//w3c//dtd html 4.01 transitional//",
];
const XHTML_1_0: &[&str] = &[
    "-//w3c//dtd xhtml 1.0 frameset//",
    "-//w3c//dtd xhtml 1.0 transitional//",
];

/// <https://html.spec.whatwg.org/multipage/parsing.html#the-initial-insertion-mode>
pub(super) fn of_doctype(name: Chars<'_>, public_id: Chars<'_>, system_id: Chars<'_>) -> Quirks {
    let has_prefix = |list: &[&str]| {
        list.iter()
            .any(|it| public_id.starts_with_ignoring_case(it.as_bytes()))
    };
    if !name.is(b"html")
        || PUBLIC_IDS
            .iter()
            .any(|it| public_id.is_ignoring_case(it.as_bytes()))
        || system_id.is_ignoring_case(b"http://www.ibm.com/data/dtd/v11/ibmxhtml1-transitional.dtd")
        || has_prefix(PUBLIC_ID_PREFIXES)
        || (system_id.is_empty() && has_prefix(HTML_4_01))
    {
        Quirks::Full
    } else if has_prefix(XHTML_1_0) || has_prefix(HTML_4_01) {
        Quirks::Limited
    } else {
        Quirks::None
    }
}
