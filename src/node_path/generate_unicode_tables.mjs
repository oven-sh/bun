// Generates unicode_tables.rs from what the Node.js that runs it does. Run it with the version that lib.rs names.

import assert from "node:assert";
import { writeFileSync } from "node:fs";

assert(!process.versions.bun, "run this with Node.js");

const END = 0x110000;
const text = String.fromCodePoint;
const hex = value => "0x" + value.toString(16).toUpperCase();

// The order of `Category` in unicode.rs.
const categories = ["Lu", "Ll", "L", "Nl", "Nd", "Zs", "Z", "Cc", "C", "Pc", "P"].map(
  name => new RegExp(`^\\p{${name}}$`, "u"),
);
const categoryOf = c => {
  const index = categories.findIndex(category => category.test(text(c)));
  return index < 0 ? categories.length : index;
};

// What a character in front of a sigma does to its lower case: 0 nothing, 1 it is cased, 2 it is skipped.
const endsInFinalSigma = string => string.toLowerCase().endsWith("ς");
const besideSigma = c => (endsInFinalSigma(text(c) + "Σ") ? 1 : endsInFinalSigma("a" + text(c) + "Σ") ? 2 : 0);

const UPPER = 0 | (1 << 4);
const LOWER = 1 | (1 << 4);
const ALTERNATING = (categories.length + 1) | (1 << 4);
const values = new Uint8Array(END);
for (let c = 0; c < END; c++) {
  const beside = besideSigma(c);
  const sigmaAfter = suffix => ("aΣ" + suffix).toLowerCase()[1];
  assert.equal(sigmaAfter(text(c)) === "σ", beside === 1);
  assert.equal(sigmaAfter(text(c) + "a") === "σ", beside !== 0);
  values[c] = categoryOf(c) | (beside << 4);
}
const properties = [];
for (let c = 0; c < END;) {
  let end = c;
  while (values[end] === ((end - c) % 2 ? LOWER : UPPER)) end++;
  const alternates = end - c > 2 && !(c > 0 && values[c - 1] === UPPER);
  if (!alternates) for (end = c; values[end] === values[c];) end++;
  properties.push(c * 256 + (alternates ? ALTERNATING : values[c]));
  c = end;
}

/** `[first, count, stride, distance]` for the characters that `map` moves. With the stride 0, neighbors trade places. */
function runs(map) {
  const out = [];
  for (const [from, to] of [...map].sort((a, b) => a[0] - b[0])) {
    const run = out.at(-1);
    const opensPair = to === from + 1 && map.get(to) === from;
    const closesPair = to === from - 1 && map.get(to) === from;
    if (run && run[2] === 0 && from === run[0] + run[1] && (closesPair || (opensPair && run[1] < 254))) {
      run[1]++;
      continue;
    }
    if (opensPair) {
      out.push([from, 1, 0, 1]);
      continue;
    }
    if (run && run[2] !== 0 && run[3] === to - from && run[1] < 255) {
      const gap = from - (run[0] + (run[1] - 1) * run[2]);
      if (run[1] === 1 && gap <= 2) run[2] = gap;
      if (gap === run[2]) {
        run[1]++;
        continue;
      }
    }
    out.push([from, 1, 1, to - from]);
  }
  return out;
}

const lower = new Map();
for (let c = 0; c < END; c++) {
  const to = text(c).toLowerCase();
  if (c === 0x130) assert.equal(to, "i̇");
  else if (to !== text(c)) {
    assert.equal(to.length, text(c).length);
    assert.equal([...to].length, 1);
    lower.set(c, to.codePointAt(0));
  }
}

/** Each character that a regular expression with `flags` takes for another, and the next of those, in a circle. */
function circles(flags, end) {
  const escape = c => (flags.includes("u") ? `\\u{${c.toString(16)}}` : "\\u" + c.toString(16).padStart(4, "0"));
  const isSurrogate = c => c >= 0xd800 && c <= 0xdfff;
  const cased = new Set();
  for (let c = 0; c < end; c++) {
    for (const other of [text(c).toLowerCase(), text(c).toUpperCase()]) {
      if (other === text(c)) continue;
      cased.add(c);
      if ([...other].length === 1) cased.add(other.codePointAt(0));
    }
  }
  const all = [...cased].map(c => text(c)).join("");
  const next = new Map();
  for (const c of cased) {
    const same = all
      .match(new RegExp(`[${escape(c)}]`, "g" + flags))
      .map(it => it.codePointAt(0))
      .sort((a, b) => a - b);
    assert.deepEqual(all.match(new RegExp(escape(c), "g" + flags)).length, same.length);
    if (same.length > 1) next.set(c, same[(same.indexOf(c) + 1) % same.length]);
  }
  // No other character is taken for another: any two differ in a bit, or in whether they are in `cased`.
  const split = isInside => {
    let source = "";
    let outside = "";
    for (let c = 0, start = -1; c <= end; c++) {
      const side = c < end && !isSurrogate(c) ? isInside(c) : undefined;
      if (side === true && start < 0) start = c;
      if (side !== true && start >= 0) {
        source += escape(start) + "-" + escape(c - 1);
        start = -1;
      }
      if (side === false) outside += text(c);
    }
    assert(!new RegExp(`[${source}]`, flags).test(outside));
  };
  split(c => cased.has(c));
  split(c => !cased.has(c));
  for (let bit = 1; bit < end; bit *= 2) split(c => (cased.has(c) ? undefined : (c & bit) !== 0));
  return next;
}

const out = [
  `//! Generated by generate_unicode_tables.mjs with Node.js ${process.version}, which has Unicode ${process.versions.unicode}. Do not edit.`,
  "",
];

function emit(doc, name, type, values) {
  out.push(`/// ${doc}`, "#[rustfmt::skip]", `pub(crate) static ${name}: &[${type}] = &[`);
  let line = "   ";
  for (const value of values) {
    if (line.length + value.length + 2 > 120) {
      out.push(line);
      line = "   ";
    }
    line += ` ${value},`;
  }
  out.push(line, "];", "");
}

const emitRuns = (doc, name, map) =>
  emit(
    doc + " See `moved` in unicode.rs.",
    name,
    "(u32, u8, u8, i32)",
    runs(map).map(([first, ...rest]) => `(${[hex(first), ...rest].join(", ")})`),
  );

emit(
  "Where a run of characters starts, above 8 bits of what they have in common.",
  "PROPERTIES",
  "u32",
  properties.map(hex),
);
emitRuns("`toLowerCase()` of one character, but for U+0130.", "LOWER_CASE", lower);
emitRuns("The next character that `/i` takes for the same.", "NEXT_CASE", circles("i", 0x10000));
emitRuns("The next character that `/iu` takes for the same.", "NEXT_CASE_UNICODE", circles("iu", END));

writeFileSync(new URL("unicode_tables.rs", import.meta.url), out.join("\n"));
