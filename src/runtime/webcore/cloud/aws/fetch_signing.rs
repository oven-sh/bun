//! Applies `AwsSignOptions` to an outgoing `fetch()` request.

use bun_http::Headers;
use bun_http::Method;
use bun_http_types::ETag::HeaderEntryColumns as _;
use bun_jsc::{JSGlobalObject, JSValue, StringJsc as _};
use bun_s3_signing::ProviderError;
use bun_s3_signing::sigv4;
use bun_url::URL;

use super::sign_options::AwsSignOptions;

#[derive(Clone, Copy)]
pub enum Body<'a> {
    Bytes(&'a [u8]),
    /// ReadableStream / sendfile: cannot be hashed up front.
    Streaming,
}

pub enum Signed {
    /// `Authorization` etc. were appended to the headers.
    Headers,
    /// `signQuery`: send to this URL instead.
    Url(Box<[u8]>),
}

/// Header names the caller must not set alongside `aws` (we generate them).
const RESERVED: &[&[u8]] = &[
    b"authorization",
    b"x-amz-date",
    b"x-amz-content-sha256",
    b"x-amz-security-token",
];

pub fn sign_fetch_request(
    opts: &AwsSignOptions,
    method: Method,
    url: &URL<'_>,
    headers: &mut Option<Headers>,
    body: Body<'_>,
) -> Result<Signed, String> {
    let creds = opts
        .resolve_credentials()
        .map_err(|m| format!("{}", bstr::BStr::new(&m)))?;

    // Sign the Host the HTTP client will send: the user's override, else the URL's.
    let user_host = headers
        .as_ref()
        .and_then(|h| h.get(b"host"))
        .map(<[u8]>::to_vec);
    let host: &[u8] = user_host.as_deref().unwrap_or(url.host);
    let (service, region) = opts.scope_for(host, &creds)?;
    let s3 = sigv4::is_s3_service(&service);

    let payload = match body {
        Body::Bytes(b) if opts.unsigned_payload && s3 => {
            let _ = b;
            sigv4::Payload::Unsigned
        }
        Body::Bytes(b) => sigv4::Payload::Bytes(b),
        Body::Streaming if s3 => sigv4::Payload::Unsigned,
        Body::Streaming => {
            return Err(
                "a streaming request body cannot be SigV4-signed for this service because its SHA-256 \
                 is not known up front (only S3-style services accept UNSIGNED-PAYLOAD); buffer the body first"
                    .into(),
            );
        }
    };

    let mut pairs: Vec<(&[u8], &[u8])> = Vec::new();
    if let Some(h) = headers.as_ref() {
        let entries = h.entries.slice();
        let names = entries.items_name();
        let values = entries.items_value();
        for (i, n) in names.iter().enumerate() {
            let name = h.as_str(*n);
            if RESERVED.iter().any(|r| name.eq_ignore_ascii_case(r)) {
                return Err(format!(
                    "the \"{}\" header is generated by aws request signing; remove it from headers",
                    bstr::BStr::new(name)
                ));
            }
            if name.eq_ignore_ascii_case(b"host") {
                continue;
            }
            pairs.push((name, h.as_str(values[i])));
        }
    }

    let query = url.search();
    let query = query.strip_prefix(b"?".as_slice()).unwrap_or(query);
    let req = sigv4::Request {
        method: method.as_str().as_bytes(),
        host,
        path: url.raw_pathname(),
        query,
        headers: &pairs,
        payload,
        scope: sigv4::Scope {
            service: &service,
            region: &region,
        },
        datetime: opts.datetime,
        s3_path_semantics: None,
    };
    let sig_creds = creds.sigv4();

    if opts.sign_query {
        let scheme = if url.is_https() {
            b"https".as_slice()
        } else {
            b"http".as_slice()
        };
        let signed = sigv4::presign(&sig_creds, &req, scheme, opts.expires_in)
            .map_err(|e| format!("could not presign request: {e:?}"))?;
        drop(pairs);
        return Ok(Signed::Url(signed.url));
    }

    let signed =
        sigv4::sign(&sig_creds, &req).map_err(|e| format!("could not sign request: {e:?}"))?;
    drop(pairs);
    let h = headers.get_or_insert_with(Headers::default);
    h.append(b"Authorization", &signed.authorization);
    h.append(b"x-amz-date", &signed.amz_date);
    if signed.send_content_sha256 {
        h.append(b"x-amz-content-sha256", &signed.content_sha256);
    }
    if let Some(t) = creds.session_token() {
        h.append(b"x-amz-security-token", t);
    }
    Ok(Signed::Headers)
}

/// A JS `Error` for a credential-provider failure, with `.code`.
pub fn provider_error_to_js(global: &JSGlobalObject, err: &ProviderError) -> JSValue {
    let value = global.create_error_instance(format_args!("{}", bstr::BStr::new(&err.message)));
    if let Ok(code) = bun_core::String::init(err.code.as_bytes()).to_js(global) {
        value.put(global, b"code".as_slice(), code);
    }
    value
}
