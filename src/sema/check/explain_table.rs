//! For which errors the arguments of the message can be read off the source: the name or the string the error is reported on, or a
//! text that is always the same.
//!
//! Generated from the error baselines of typescript-go 7.0.2: a code is listed if that holds for its every occurrence there. Not edited
//! by hand.

#[derive(Copy, Clone, PartialEq, Eq, Debug)]
pub(super) enum Source {
    /// The name, keyword or number at the start of the error.
    Name,
    /// What is between the quotes of the string at the start of the error.
    StringContents,
    Const(&'static str),
}

use Source::{Const, Name, StringContents};

/// Where each argument of the message of `code` comes from. Empty: not from the source.
pub(super) fn sources(code: u32) -> &'static [Source] {
    match TABLE.binary_search_by_key(&code, |row| row.0) {
        Ok(i) => TABLE[i].1,
        Err(_) => &[],
    }
}

