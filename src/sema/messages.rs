#[derive(Copy, Clone, PartialEq, Eq, Debug)]
pub enum Category {
    Warning,
    Error,
    Suggestion,
    Message,
}

impl Category {
    /// `Category.Name`
    pub fn name(self) -> &'static str {
        match self {
            Category::Warning => "warning",
            Category::Error => "error",
            Category::Suggestion => "suggestion",
            Category::Message => "message",
        }
    }
}

/// The category and the text of the message with `code`. `{0}`, `{1}`, ... stand for its arguments.
pub fn message(code: u32) -> Option<(Category, &'static str)> {
    MESSAGES
        .binary_search_by_key(&code, |m| m.0)
        .ok()
        .map(|i| (MESSAGES[i].1, MESSAGES[i].2))
}

/// `Message.Format`: `text` with `{n}` replaced by `args[n]`. What has no argument stays as it is written.
pub fn format(text: &str, args: &[String]) -> String {
    let mut out = String::with_capacity(text.len() + args.iter().map(String::len).sum::<usize>());
    let mut rest = text;
    while let Some(open) = rest.find('{') {
        let after = &rest[open + 1..];
        match after.find('}') {
            Some(close) if close > 0 && after[..close].bytes().all(|b| b.is_ascii_digit()) => {
                out.push_str(&rest[..open]);
                match after[..close]
                    .parse::<usize>()
                    .ok()
                    .and_then(|n| args.get(n))
                {
                    Some(arg) => out.push_str(arg),
                    None => out.push_str(&rest[open..open + close + 2]),
                }
                rest = &after[close + 1..];
            }
            _ => {
                out.push_str(&rest[..=open]);
                rest = after;
            }
        }
    }
    out.push_str(rest);
    out
}

