import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const dir = import.meta.dir;

type Raw = {
  category: string;
  code: number;
  reportsUnnecessary?: boolean;
  reportsDeprecated?: boolean;
  elidedInCompatabilityPyramid?: boolean;
};
export type Entry = { name: string; key: string; code: number; category: string; flags: number; text: string };

// The inputs beside this file are prettier-formatted copies of TypeScript's src/compiler/diagnosticMessages.json and typescript-go's internal/diagnostics/extraDiagnosticMessages.json.
export const pinned = {
  typescript: "5848bc515",
  typescriptGo: "89d5d5b2",
  messages: "56199b8ef3ebc47d7ad5b3b59b1cb64a107d9f44560318073f223d4b1adaf4ae",
  extra: "4d20e025e3f5766e18ef04f6005ba5fd26a5bb5c28cdf84ac791a13b4fbcf861",
  count: 2206,
};

const categories = ["Warning", "Error", "Suggestion", "Message"];

function readRawMessages(json: string, what: string, expectedHash: string): Map<number, Raw & { text: string }> {
  const raw = JSON.parse(json) as Record<string, Raw>;
  const hash = createHash("sha256").update(JSON.stringify(raw)).digest("hex");
  if (hash !== expectedHash) throw new Error(`${what}: content hash ${hash} is not the pinned ${expectedHash}`);
  const byCode = new Map<number, Raw & { text: string }>();
  for (const [text, m] of Object.entries(raw)) {
    if (byCode.has(m.code)) throw new Error(`${what}: code ${m.code} appears twice`);
    if (!Number.isInteger(m.code) || m.code <= 0 || m.code >= 2 ** 31) throw new Error(`${what}: bad code ${m.code}`);
    if (!categories.includes(m.category)) throw new Error(`${what}: bad category ${m.category} for ${m.code}`);
    if (!/^[\x20-\x7e]+$/.test(text)) throw new Error(`${what}: text of ${m.code} is not printable ASCII`);
    byCode.set(m.code, { ...m, text });
  }
  return byCode;
}

export function convertPropertyName(origName: string, code: number): { name: string; key: string } {
  let b = "";
  for (const ch of origName) {
    if (ch === "*") b += "_Asterisk";
    else if (ch === "/") b += "_Slash";
    else if (ch === ":") b += "_Colon";
    else if (!/[A-Za-z0-9]/.test(ch)) b += "_";
    else b += ch;
  }
  let name = b
    .replace(/_+/g, "_")
    .replace(/^_+([^0-9])/, "$1")
    .replace(/_$/, "");
  const key = name.slice(0, 100) + "_" + code;
  if (!/^[A-Z]/.test(name)) name = (name[0] === "_" ? "X" : "X_") + name;
  if (!/^[A-Z][A-Za-z0-9_]*$/.test(name))
    throw new Error(`cannot convert ${JSON.stringify(origName)} to an identifier`);
  return { name, key };
}

export function merge(messagesJson: string, extraJson: string): Entry[] {
  const merged = readRawMessages(messagesJson, "diagnosticMessages.json", pinned.messages);
  for (const [code, m] of readRawMessages(extraJson, "extraDiagnosticMessages.json", pinned.extra)) merged.set(code, m);
  const entries = [...merged.values()]
    .sort((a, b) => a.code - b.code)
    .map(m => {
      const { name, key } = convertPropertyName(m.text, m.code);
      return {
        // A constant is upstream's variable name in upper case.
        name: name.toUpperCase(),
        key,
        code: m.code,
        category: m.category,
        flags:
          (m.reportsUnnecessary ? 1 : 0) | (m.elidedInCompatabilityPyramid ? 2 : 0) | (m.reportsDeprecated ? 4 : 0),
        text: m.text,
      };
    });
  if (entries.length !== pinned.count) throw new Error(`expected ${pinned.count} messages, found ${entries.length}`);
  const names = new Set(entries.map(e => e.name));
  if (names.size !== entries.length) throw new Error("two messages convert to the same name");
  return entries;
}

export function generate(messagesJson: string, extraJson: string): string {
  const entries = merge(messagesJson, extraJson);
  const rows = entries.map(
    e =>
      `    (${e.name}, ${e.code}, ${e.category}, ${e.flags}, "${e.text.replaceAll("\\", "\\\\").replaceAll('"', '\\"')}"),`,
  );
  return `// Generated by src/typecheck/scripts/generate-diagnostics.ts from typescript-go ${pinned.typescriptGo} and TypeScript ${pinned.typescript}; do not edit.

pub(crate) const MESSAGE_COUNT: usize = ${entries.length};

#[rustfmt::skip]
messages! {
${rows.join("\n")}
}
`;
}

if (import.meta.main) {
  const output = generate(
    readFileSync(join(dir, "diagnosticMessages.json"), "utf8"),
    readFileSync(join(dir, "extraDiagnosticMessages.json"), "utf8"),
  );
  const out = join(dir, "..", "diagnostics", "diagnostics_generated.rs");
  writeFileSync(out, output);
  console.log(`wrote ${out} (${output.length} bytes)`);
}
