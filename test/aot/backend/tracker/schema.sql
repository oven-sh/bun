-- The tables of the issue tracker and what fills them. Run it as the owner of an empty database: psql -f schema.sql
--
-- 5,000 users, 60 projects, 30,000 issues and about 300,000 comments. Nothing is drawn at random: every value is computed
-- from the row's number by noise(), so two databases filled by this file hold the same rows (under one major version of Postgres).

SET client_min_messages = warning;

DROP TABLE IF EXISTS comments, issue_labels, issues, labels, projects, sessions, users CASCADE;
DROP FUNCTION IF EXISTS noise, word, decorated_word, sentence, title_text, snippet_text, active_user;

CREATE TABLE users (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  login text NOT NULL UNIQUE,
  name text NOT NULL,
  email text NOT NULL,
  bio text NOT NULL,
  role text NOT NULL CHECK (role IN ('member', 'admin')),
  password_salt text NOT NULL,
  password_hash text NOT NULL,
  created_at timestamptz NOT NULL
);

CREATE TABLE sessions (
  token text PRIMARY KEY,
  user_id integer NOT NULL REFERENCES users (id),
  csrf_token text NOT NULL,
  flash text,
  expires_at timestamptz NOT NULL
);

CREATE TABLE projects (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  slug text NOT NULL UNIQUE,
  name text NOT NULL,
  description text NOT NULL,
  next_number integer NOT NULL,
  open_issues integer NOT NULL,
  closed_issues integer NOT NULL,
  created_at timestamptz NOT NULL
);

CREATE TABLE labels (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_id integer NOT NULL REFERENCES projects (id),
  name text NOT NULL,
  color text NOT NULL,
  open_issues integer NOT NULL,
  UNIQUE (project_id, name)
);

CREATE TABLE issues (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_id integer NOT NULL REFERENCES projects (id),
  number integer NOT NULL,
  author_id integer NOT NULL REFERENCES users (id),
  assignee_id integer REFERENCES users (id),
  title text NOT NULL,
  body text NOT NULL,
  state text NOT NULL CHECK (state IN ('open', 'closed')),
  priority integer NOT NULL CHECK (priority BETWEEN 0 AND 3),
  comment_count integer NOT NULL,
  created_at timestamptz NOT NULL,
  updated_at timestamptz NOT NULL,
  closed_at timestamptz,
  search tsvector GENERATED ALWAYS AS (to_tsvector('english', title || ' ' || body)) STORED,
  UNIQUE (project_id, number)
);

CREATE TABLE issue_labels (
  issue_id integer NOT NULL REFERENCES issues (id),
  label_id integer NOT NULL REFERENCES labels (id),
  PRIMARY KEY (issue_id, label_id)
);

CREATE TABLE comments (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  issue_id integer NOT NULL REFERENCES issues (id),
  parent_id integer REFERENCES comments (id),
  author_id integer NOT NULL REFERENCES users (id),
  body text NOT NULL,
  created_at timestamptz NOT NULL,
  edited_at timestamptz
);

-- 0 to 8,388,607, the same for the same seed and salt.
CREATE FUNCTION noise(seed bigint, salt integer) RETURNS integer LANGUAGE sql IMMUTABLE PARALLEL SAFE
RETURN (hashint8extended(seed, salt) & 8388607)::integer;

