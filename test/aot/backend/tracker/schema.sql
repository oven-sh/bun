CREATE FUNCTION decorated_word(seed bigint) RETURNS text LANGUAGE sql IMMUTABLE PARALLEL SAFE
RETURN CASE
  WHEN noise(seed, 2) % 100 < 3 THEN '**' || word(noise(seed, 3)) || ' ' || word(noise(seed, 4)) || '**'
  WHEN noise(seed, 2) % 100 < 6 THEN '*' || word(noise(seed, 3)) || '*'
  WHEN noise(seed, 2) % 100 < 10 THEN '`' || word(noise(seed, 3)) || '.' || word(noise(seed, 4)) || '()`'
  WHEN noise(seed, 2) % 100 < 12 THEN '[' || word(noise(seed, 3)) || ' ' || word(noise(seed, 4)) || '](https://docs.example.com/' || word(noise(seed, 5)) || '?page=' || noise(seed, 6) % 40 || '&lang=en)'
  WHEN noise(seed, 2) % 100 < 13 THEN 'Map<' || word(noise(seed, 3)) || ', ' || word(noise(seed, 4)) || '>'
  WHEN noise(seed, 2) % 100 < 14 THEN '"' || word(noise(seed, 3)) || '"'
  WHEN noise(seed, 2) % 100 < 15 THEN word(noise(seed, 3)) || ' && ' || word(noise(seed, 4))
  WHEN noise(seed, 2) % 100 < 16 THEN word(noise(seed, 3)) || '''s'
  ELSE word(noise(seed, 3))
END;

CREATE FUNCTION sentence(seed bigint) RETURNS text LANGUAGE sql IMMUTABLE PARALLEL SAFE
RETURN (
  SELECT upper(left(words, 1)) || substr(words, 2) || '.'
  FROM (SELECT string_agg(decorated_word(seed * 37 + k), ' ' ORDER BY k) AS words FROM generate_series(1, 5 + noise(seed, 1) % 10) AS k) AS joined
);

CREATE FUNCTION title_text(seed bigint) RETURNS text LANGUAGE sql IMMUTABLE PARALLEL SAFE
RETURN (
  SELECT upper(left(words, 1)) || substr(words, 2)
  FROM (
    SELECT string_agg(CASE
      WHEN noise(seed * 37 + k, 2) % 100 < 3 THEN 'Map<' || word(noise(seed * 37 + k, 3)) || '>'
      WHEN noise(seed * 37 + k, 2) % 100 < 6 THEN '"' || word(noise(seed * 37 + k, 3)) || '"'
      WHEN noise(seed * 37 + k, 2) % 100 < 8 THEN word(noise(seed * 37 + k, 3)) || ' & ' || word(noise(seed * 37 + k, 4))
      ELSE word(noise(seed * 37 + k, 3))
    END, ' ' ORDER BY k) AS words
    FROM generate_series(1, 4 + noise(seed, 1) % 7) AS k
  ) AS joined
);

-- One block of Markdown: a paragraph, a list, a piece of code, a quotation, a heading, or a paragraph that is not Latin-1.
CREATE FUNCTION snippet_text(seed bigint) RETURNS text LANGUAGE sql IMMUTABLE PARALLEL SAFE
RETURN CASE
  WHEN noise(seed, 7) % 100 < 55 THEN
    (SELECT string_agg(sentence(seed * 11 + k), ' ' ORDER BY k) FROM generate_series(1, 1 + noise(seed, 8) % 4) AS k)
  WHEN noise(seed, 7) % 100 < 65 THEN
    (SELECT string_agg('- ' || sentence(seed * 11 + k), E'\n' ORDER BY k) FROM generate_series(1, 2 + noise(seed, 8) % 4) AS k)
  WHEN noise(seed, 7) % 100 < 70 THEN
    (SELECT string_agg(k || '. ' || sentence(seed * 11 + k), E'\n' ORDER BY k) FROM generate_series(1, 2 + noise(seed, 8) % 4) AS k)
  WHEN noise(seed, 7) % 100 < 80 THEN
    E'```\n' || (SELECT string_agg((ARRAY[
      'const server = Bun.serve({ port: 3000, fetch: handle });',
      'if (request.headers.get("accept") !== "text/html") return;',
      'for (let i = 0; i < rows.length && i < limit; i++) total += rows[i].count;',
      'const cache = new Map<string, Promise<Response>>();',
      'await sql`SELECT id, title FROM issues WHERE state = ${state}`;',
      'throw new TypeError(`expected a string, got ${typeof value}`);',
      '  at processTicksAndRejections (node:internal/process/task_queues:95:5)',
      '  at async handle (/srv/app/src/server.ts:142:18)',
      'error: connection closed before the response was read',
      '$ curl -s -H ''Accept: application/json'' "http://localhost:3000/api?a=1&b=2"',
      'export function clamp(n: number, low: number, high: number) { return n < low ? low : n > high ? high : n; }',
      '<div class="toolbar"><button disabled>Save</button></div>',
      'return items.filter(item => item.open).map(item => item.id);',
      'SELECT count(*) FROM comments WHERE created_at > now() - interval ''7 days'';',
      '',
      '}'])[noise(seed * 11 + k, 9) % 16 + 1], E'\n' ORDER BY k) FROM generate_series(1, 2 + noise(seed, 8) % 7) AS k) || E'\n```'
  WHEN noise(seed, 7) % 100 < 87 THEN
    (SELECT string_agg('> ' || sentence(seed * 11 + k), E'\n' ORDER BY k) FROM generate_series(1, 1 + noise(seed, 8) % 2) AS k)
  WHEN noise(seed, 7) % 100 < 91 THEN
    (ARRAY['## Steps to reproduce', '## Expected behavior', '## What happens instead', '### Environment', '# Summary', '### Workaround'])[noise(seed, 8) % 6 + 1]
      || E'\n\n' || sentence(seed * 11 + 1)
  ELSE
    sentence(seed * 11 + 1) || ' ' || (ARRAY[
      'It works on my machine — but only after a restart.',
      'The docs say “this cannot happen”, and yet here we are.',
      'Thanks, that fixed it 🎉',
      'これは日本語のロケールでだけ起きます。',
      'Voilà: le résumé s’affiche enfin correctement.',
      'Проверил на последней версии, ошибка осталась.',
      'The arrow → in the breadcrumb renders as a box.',
      '+1 👍 we see the same thing in production…'])[noise(seed, 8) % 8 + 1]
END;

-- A few users write most of what is written.
CREATE FUNCTION active_user(seed bigint, salt integer) RETURNS integer LANGUAGE sql IMMUTABLE PARALLEL SAFE
RETURN 1 + ((noise(seed, salt) % 5000)::bigint * (noise(seed, salt + 1) % 5000) / 5000)::integer;

