-- Low project numbers get most of the issues: from about 2,000 down to some dozens.
CREATE TEMPORARY TABLE drafts AS
SELECT n AS id,
       1 + ((noise(n, 15) % 60)::bigint * (noise(n, 16) % 60) / 60)::integer AS project_id,
       CASE
         WHEN noise(n, 17) % 100 < 30 THEN noise(n, 18) % 3
         WHEN noise(n, 17) % 100 < 70 THEN 3 + noise(n, 18) % 6
         WHEN noise(n, 17) % 100 < 93 THEN 9 + noise(n, 18) % 17
         WHEN noise(n, 17) % 100 < 99 THEN 26 + noise(n, 18) % 55
         ELSE 81 + noise(n, 18) % 220
       END AS comment_count,
       timestamptz '2023-07-01 00:00:00+00' + n * interval '50 minutes' + noise(n, 19) % 3000 * interval '1 second' AS created_at
FROM generate_series(1, 30000) AS n;

CREATE TEMPORARY TABLE placed AS
SELECT id, project_id, comment_count, created_at,
       row_number() OVER (PARTITION BY project_id ORDER BY id)::integer AS number,
       (sum(comment_count) OVER (ORDER BY id) - comment_count)::integer AS comments_before
FROM drafts;

INSERT INTO issues (id, project_id, number, author_id, assignee_id, title, body, state, priority, comment_count, created_at, updated_at, closed_at)
SELECT id, project_id, number,
       active_user(id, 20),
       CASE WHEN noise(id, 22) % 100 < 45 THEN active_user(id, 23) END,
       title_text(id),
       (SELECT string_agg(snippets.text, E'\n\n' ORDER BY k) FROM generate_series(1, 2 + noise(id, 25) % 4) AS k JOIN snippets ON snippets.id = noise(id::bigint * 7 + k, 26) % 4000)
         || E'\n\nSeen with build b' || noise(id, 43) % 4000 || ' on host h' || noise(id, 44) % 700 || '.',
       CASE WHEN noise(id, 27) % 100 < 62 THEN 'closed' ELSE 'open' END,
       CASE WHEN noise(id, 28) % 100 < 50 THEN 0 WHEN noise(id, 28) % 100 < 80 THEN 1 WHEN noise(id, 28) % 100 < 95 THEN 2 ELSE 3 END,
       comment_count,
       created_at,
       created_at + (comment_count * 7 + 1) * interval '1 hour',
       CASE WHEN noise(id, 27) % 100 < 62 THEN created_at + (comment_count * 7 + 1) * interval '1 hour' END
FROM placed;

INSERT INTO issue_labels (issue_id, label_id)
SELECT DISTINCT placed.id, (placed.project_id - 1) * 12 + 1 + noise(placed.id::bigint * 5 + k, 29) % (8 + placed.project_id % 5)
FROM placed, generate_series(1, 3) AS k
WHERE k <= noise(placed.id, 30) % 4;

-- The comments of an issue have numbers in a row, so a reply can name an earlier comment of its issue.
INSERT INTO comments (id, issue_id, parent_id, author_id, body, created_at, edited_at)
SELECT placed.comments_before + k,
       placed.id,
       CASE WHEN k > 1 AND noise(placed.comments_before + k, 31) % 100 < 55 THEN placed.comments_before + 1 + noise(placed.comments_before + k, 32) % (k - 1) END,
       active_user(placed.comments_before + k, 33),
       (SELECT string_agg(snippets.text, E'\n\n' ORDER BY j) FROM generate_series(1, 1 + noise(placed.comments_before + k, 35) % 3) AS j JOIN snippets ON snippets.id = noise((placed.comments_before + k)::bigint * 7 + j, 36) % 4000)
         || CASE
              WHEN noise(placed.comments_before + k, 37) % 100 < 12 THEN E'\n\nSee #' || 1 + noise(placed.comments_before + k, 38) % placed.number || ' for the same thing.'
              WHEN noise(placed.comments_before + k, 37) % 100 < 22 THEN E'\n\ncc @' || (SELECT login FROM users WHERE users.id = active_user(placed.comments_before + k, 39))
              ELSE ''
            END,
       placed.created_at + k * interval '7 hours' - noise(placed.comments_before + k, 41) % 20000 * interval '1 second',
       CASE WHEN noise(placed.comments_before + k, 42) % 100 < 8 THEN placed.created_at + k * interval '7 hours' END
FROM placed, generate_series(1, placed.comment_count) AS k;

UPDATE projects SET
  next_number = 1 + (SELECT count(*) FROM issues WHERE issues.project_id = projects.id),
  open_issues = (SELECT count(*) FROM issues WHERE issues.project_id = projects.id AND state = 'open'),
  closed_issues = (SELECT count(*) FROM issues WHERE issues.project_id = projects.id AND state = 'closed');

UPDATE labels SET open_issues = (
  SELECT count(*) FROM issue_labels JOIN issues ON issues.id = issue_labels.issue_id
  WHERE issue_labels.label_id = labels.id AND issues.state = 'open');

SELECT setval(pg_get_serial_sequence('users', 'id'), (SELECT max(id) FROM users));
SELECT setval(pg_get_serial_sequence('projects', 'id'), (SELECT max(id) FROM projects));
SELECT setval(pg_get_serial_sequence('labels', 'id'), (SELECT max(id) FROM labels));
SELECT setval(pg_get_serial_sequence('issues', 'id'), (SELECT max(id) FROM issues));
SELECT setval(pg_get_serial_sequence('comments', 'id'), (SELECT max(id) FROM comments));

