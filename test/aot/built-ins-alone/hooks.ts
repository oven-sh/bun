function trapPrograms(): Program[] {
  const programs: Program[] = [];
  for (const { trap, head, body, triggers, target } of traps) {
    for (const [words, rows, text] of triggers) {
      programs.push({
        name: `the-${trap}-trap-of-a-proxy-is-run-by-${words}`,
        rows: ["Proxy", ...rows],
        text: lines(
          target ?? "const inner = { value: 1.5 };",
          "const proxy = new Proxy(inner, {",
          `  ${head} {`,
          body.map(line => `    ${line}`),
          "  },",
          "});",
          text,
        ),
      });
    }
  }
  return programs;
}

