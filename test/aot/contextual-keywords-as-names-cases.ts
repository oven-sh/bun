// TypeScript or the language reads something else than a name there.
const notNames: Record<string, string[]> = {
  "$ as any;": ["accessor", "module", "namespace", "readonly", "type", "using"],
  "$ satisfies any;": ["accessor", "module", "namespace", "readonly", "type", "using"],
  "a = $ < a > $;": ["as", "satisfies"],
  "for ($ as any of a);": ["using"],
  "for ($ of a);": ["async"],
  "for ($ of a) $;": ["async"],
  "namespace N { var $: any, a: any = []; for ($ of a); }": ["async"],
};

export type Case = { name: string; text: string; isRejected: boolean };

const shown = (text: string) =>
  text.replaceAll("\r", "␍").replaceAll("\n", "⏎").replaceAll("\u2028", "\\u2028").replaceAll("\u2029", "\\u2029");

/** The first case is the file that the others import from. */
export function casesOf(word: string): Case[] {
  const escaped = `\\u{${word.charCodeAt(0).toString(16)}}${word.slice(1)}`;
  const cases: Case[] = [
    {
      name: "0.ts",
      text: `const value = 1;\nexport default value;\nexport const b = 1;\nexport { value as ${word} };\n`,
      isRejected: false,
    },
  ];
  const add = (places: string[], before: string, after: string, isProgram = true) => {
    for (const place of places) {
      const written = place.replaceAll("$", word).replaceAll("%", escaped);
      const isRejected = isProgram === (notNames[place]?.includes(word) ?? false);
      cases.push({ name: shown(written), text: `${before}${written}${after}`, isRejected });
    }
  };
  const takesTheWord = `export function f(this: any, ${word}: any, a: any): any {\n`;
  add(placesInAFunction, takesTheWord, "\n}\n");
  if (word !== "constructor") add(placesOfAClassMember, takesTheWord, "\n}\n");
  add(placesWhereNothingEndsTheStatement, takesTheWord, "\n}\n", false);
  add(placesThatDeclare, "export function f(this: any, a: any): any {\n", "\n}\n");
  add(placesInAFile, `var ${word}: any = () => [], a: any = [];\n`, "\nexport {};\n");
  add(placesInAFileThatDeclare, "", "\nexport {};\n");
  return cases;
}
