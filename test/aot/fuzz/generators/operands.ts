/** The operation with the operand in the place of each X that stands alone. */
const withOperand = (operation: string, operand: string) => operation.replace(/(?<![A-Za-z0-9_$"'])X(?![A-Za-z0-9_$"'])/g, () => operand);

/** One source through every operation, or through those that are handed in. */
export function program(source: Source, done: [string, boolean][] = operations): { file: string; text: string; files?: Record<string, string> } {
  const lines: string[] = [];
  if (source.typescript && !source.loose) lines.push("// @ts-nocheck");
  lines.push(helpers(!!source.loose));
  if (source.typescript) lines.push("class Optional { x?: number; y = 1; }\nclass Nullable { x: number | null = null; y = 1; }");
  const result = source.loose ? "r: any" : "r";
  done.forEach(([operation, isWellTyped], i) => {
    if (source.loose && !isWellTyped) return;
    const label = JSON.stringify(operation);
    if ("expression" in source) lines.push(`say(${label}, () => { const ${result} = ${withOperand(operation, source.expression)}; return ${afterwards}; });`);
    else if ("moduleVariable" in source) lines.push(`${source.moduleVariable.replace("V", "v" + i)} say(${label}, () => { const r = ${withOperand(operation, "v" + i)}; return ${afterwards}; });`);
    else if ("localVariable" in source) lines.push(`say(${label}, () => { ${source.localVariable.replace("V", "x")} const r = ${withOperand(operation, "x")}; return ${afterwards}; });`);
    else lines.push(`function f${i}(${source.parameter}) { const ${result} = ${withOperand(operation, source.read ?? "x")}; return ${afterwards}; } say(${label}, () => [${source.calls.map(call => "f" + i + call).join(", ")}]);`);
  });
  return {
    file: source.typescript ? "main.ts" : "main.mjs",
    text: lines.join("\n") + "\n",
    files: source.loose ? { "tsconfig.json": '{ "compilerOptions": { "strict": false, "target": "esnext", "module": "esnext", "moduleResolution": "bundler", "lib": ["esnext"] } }\n' } : undefined,
  };
}
