#!/usr/bin/env python3
"""async-generator-job-order.py <seed>: THE ORDER OF JOBS IS LAW. Each scene: one to three PRODUCERS (async generators: yields of plain values, settled | pending | rejected promises, thenables; awaits between the yields; try | finally; return; throw; yield* of another async generator, of a sync iterable, of an array of promises; jobs queued from inside the body), one to three CONSUMERS (for await in an async function that is in its first run | has been resumed by the job loop; bodies that await nothing | a value | a promise; break | return | throw at the k-th step; next() by hand, several at once; return() and throw() by hand, while running and while suspended; a generator that consumes another; two consumers of one generator), and WITNESSES: chains of `.then` that count the ticks and jobs queued at every joint, so that a job that is skipped or added moves a line. Every line as plain Bun's."""
import random, sys
seed = int(sys.argv[1]) if len(sys.argv) > 1 else 1
R = random.Random(seed)
out = []; w = out.append
w('// generated by async-generator-job-order.py %d' % seed)
w('declare const console: { log(...values: unknown[]): void };')
w('const queueMicrotask = (f: () => void): void => { Promise.resolve().then(f); };')
w('const rejected = (): Promise<any> => { const p = Promise.reject(new Error("no")); p.catch(() => {}); return p; };')
w('let lines: string[] = [];')
w('const log = (s: string) => { lines.push(s); };')
w('const show = (v: any): string => { try { return v === undefined ? "u" : typeof v === "object" && v !== null ? JSON.stringify(v) : String(v); } catch (e) { return "?"; } };')
w('const ticks = (name: string, n: number) => { let p: Promise<void> = Promise.resolve(); for (let i = 0; i < n; i++) p = p.then(() => log(name + i)); return p; };')
w('const later = (v: any, n: number): Promise<any> => { let p: Promise<any> = Promise.resolve(v); for (let i = 0; i < n; i++) p = p.then(x => x); return p; };')
w('const thenable = (v: any, name: string) => ({ then(resolve: (x: any) => void) { log(name + " then"); resolve(v); } });')
w('const lateThenable = (v: any, name: string) => ({ then(resolve: (x: any) => void) { log(name + " then"); queueMicrotask(() => resolve(v)); } });')
w('const settle = async () => { for (let i = 0; i < 60; i++) await null; };')
def operand(tag):
    return R.choice(['%d' % R.randrange(9), '"s"', 'undefined', 'null', '{ v: 1 }', 'Promise.resolve(%d)' % R.randrange(9), 'later(%d, %d)' % (R.randrange(9), R.randrange(1, 4)), 'thenable(%d, "%s")' % (R.randrange(9), tag), 'lateThenable(%d, "%s")' % (R.randrange(9), tag), 'rejected()', '[1, 2]', '(async () => %d)()' % R.randrange(9)] + ['%d' % R.randrange(9)] * 6)
def witness(tag):
    return R.choice(['', '', '', 'queueMicrotask(() => log("%s job"));' % tag, 'Promise.resolve().then(() => log("%s then"));' % tag, 'ticks("%s.", 2);' % tag, 'log("%s");' % tag])
counter = [0]
def fresh(p): counter[0] += 1; return '%s%d' % (p, counter[0])
def producer(depth=0):
    name = fresh('gen'); body = []
    n = R.randrange(1, 5)
    for i in range(n):
        tag = '%s.%d' % (name, i)
        k = R.random()
        body.append(witness(tag + 'a'))
        if k < 0.5: body.append('yield %s;' % operand(tag))
        elif k < 0.62: body.append('await %s; yield %d;' % (operand(tag), i))
        elif k < 0.7: body.append('const got%d: any = yield %d; log("%s got " + show(got%d));' % (i, i, tag, i))
        elif k < 0.78 and depth < 2: body.append('yield* %s();' % producer(depth + 1))
        elif k < 0.84: body.append('yield* [%s, %s];' % (operand(tag), operand(tag)))
        elif k < 0.9: body.append('try { yield %s; %s } finally { log("%s finally"); %s }' % (operand(tag), witness(tag + 'b'), tag, R.choice(['', 'await null;', 'yield "from finally";'])))
        elif k < 0.94: body.append('for (let j = 0; j < 3; j++) yield j;')
        elif k < 0.97: body.append('if (%s) throw new Error("%s");' % (R.choice(['true', 'lines.length > 1e9']), tag))
        else: body.append('return %s;' % operand(tag).replace('undefined', 'null'))  # plain Bun prints `return undefined;` as `return;` and loses its await
    w('async function* %s(): AsyncGenerator<any, any, any> { log("%s starts"); %s log("%s ends"); }' % (name, name, ' '.join(b for b in body if b), name))
    return name
def consumer(gens, shared):
    name = fresh('use'); g = R.choice(gens)
    src = shared if shared and R.random() < 0.5 else '%s()' % g
    first = R.choice(['', '', 'await null;', 'await later(0, 2);'])
    k = R.random(); tag = name
    inner = R.choice(['', '', 'await null;', 'await %s;' % operand(tag), witness(tag + 'w'), 'await later(0, 1);'])
    stop = R.choice(['', '', '', 'if (n === %d) break;' % R.randrange(1, 4), 'if (n === %d) return "left";' % R.randrange(1, 4), 'if (n === %d) throw new Error("stop");' % R.randrange(1, 4), 'if (n === %d) continue;' % R.randrange(1, 3)])
    if k < 0.6:
        body = 'let n = 0; for await (const x of %s) { n++; log("%s " + show(x)); %s %s }' % (src, tag, stop, inner)
    elif k < 0.72:
        body = 'const it = %s; const all = [it.next(), it.next("b"), it.next("c")]; %s for (const p of all) log("%s " + show(await p));' % (src, witness(tag + 'q'), tag)
    elif k < 0.8:
        body = 'const it = %s; log("%s " + show(await it.next())); const r = it.return("early"); %s log("%s " + show(await r)); log("%s " + show(await it.next()));' % (src, tag, witness(tag + 'r'), tag, tag)
    elif k < 0.86:
        body = 'const it = %s; log("%s " + show(await it.next())); const t = it.throw(new Error("in")); %s log("%s " + show(await t));' % (src, tag, witness(tag + 't'), tag)
    elif k < 0.93:
        other = R.choice(gens)
        body = 'const a = %s, b = %s(); for (let i = 0; i < 3; i++) { const [x, y] = [await a.next(), await b.next()]; log("%s " + show(x) + show(y)); %s }' % (src, other, tag, inner)
    else:
        body = 'let n = 0; for await (const x of (async function* () { for await (const y of %s) { log("%s mid " + show(y)); yield y; } })()) { n++; log("%s " + show(x)); %s %s }' % (src, tag, tag, stop, inner)
    w('async function %s(%s): Promise<any> { %s try { %s } catch (e) { log("%s caught " + (e as Error).message); } log("%s done"); return "%s"; }' % (name, 'shared: AsyncGenerator<any, any, any>' if shared else '', first, body, tag, tag, tag))
    return name
scenes = []
for s in range(14):
    gens = [producer() for _ in range(R.randrange(1, 4))]
    shared = 'shared' if R.random() < 0.25 else None
    users = [consumer(gens, shared) for _ in range(R.randrange(1, 4))]
    name = 'scene%d' % s
    start = []
    if shared: start.append('const shared = %s();' % R.choice(gens))
    for u in users:
        start.append(R.choice(['', '', 'ticks("t%d.", %d);' % (s, R.randrange(2, 9)), 'queueMicrotask(() => log("between"));']))
        start.append('%s(%s).then(v => log("-> " + show(v)), e => log("-> rejected " + (e as Error).message));' % (u, 'shared' if shared else ''))
    start.append(R.choice(['', 'ticks("T%d.", %d);' % (s, R.randrange(2, 12))]))
    w('async function %s() { %s %s await settle(); }' % (name, R.choice(['', 'await null;']), ' '.join(x for x in start if x)))
    scenes.append(name)
w('async function main() { for (const [i, scene] of [%s].entries()) { lines = []; await scene(); await settle(); console.log("scene " + i + ": " + lines.join(" | ")); } }' % ', '.join(scenes))
w('main();')
print('\n'.join(out))
