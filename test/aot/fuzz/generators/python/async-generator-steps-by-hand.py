#!/usr/bin/env python3
"""async-generator-steps-by-hand.py <seed>: random strict TypeScript programs that step async generators by hand: `await generator.next(sent)` in async functions and async generators, with the result
destructured, kept in a local, read in place, handed on or logged whole. Generators have their items at hand, wait for jobs or for immediates, yield promises and thenables, throw, return and clean up.
Requests are left waiting, two consumers share a generator, return() and throw() come in between. Every step logs, and other jobs are queued at random places, so the log shows the order of jobs."""
import random, sys
seed = int(sys.argv[1]) if len(sys.argv) > 1 else 1
R = random.Random(seed)
out = []; w = out.append
w('// generated by async-generator-steps-by-hand.py %d' % seed)
w('let lines: string[] = [];')
w('const log = (s: string) => { lines.push(s); };')
w('const show = (v: any): string => { try { return v === undefined ? "u" : typeof v === "object" && v !== null ? JSON.stringify(v) : String(v); } catch (e) { return "?"; } };')
w('const ticks = (name: string, n: number) => { let p: Promise<void> = Promise.resolve(); for (let i = 0; i < n; i++) p = p.then(() => log(name + i)); return p; };')
w('const later = (v: any, n: number): Promise<any> => { let p: Promise<any> = Promise.resolve(v); for (let i = 0; i < n; i++) p = p.then(x => x); return p; };')
w('const immediate = (v?: any): Promise<any> => new Promise(resolve => { setImmediate(() => resolve(v)); });')
w('const thenable = (v: any, name: string) => ({ then(resolve: (x: any) => void) { log(name + " then"); resolve(v); } });')
w('const settle = async (running: Promise<any>[]) => { await Promise.allSettled(running); for (let i = 0; i < 8; i++) { await immediate(); for (let j = 0; j < 30; j++) await null; } };')
counter = [0]
def fresh(p): counter[0] += 1; return '%s%d' % (p, counter[0])
def wait(): return R.choice(['null', 'null', '0', 'later(0, %d)' % R.randrange(1, 4), 'Promise.resolve(1)', 'immediate()', 'immediate()'])
def operand(i): return R.choice(['%s' % i] * 4 + ['{ v: %s }' % i, '"s" + %s' % i, '[%s]' % i, 'undefined', 'null', 'Promise.resolve(%s)' % i, 'later(%s, %d)' % (i, R.randrange(1, 3)), 'thenable(%s, "th")' % i, '{ value: %s, done: true }' % i])
def witness(tag):
    return R.choice([''] * 5 + ['queueMicrotask(() => log("%s job"));' % tag, 'Promise.resolve().then(() => log("%s then"));' % tag, 'ticks("%s.", %d);' % (tag, R.randrange(1, 4)), 'log("%s");' % tag, 'void (async () => { await null; log("%s side"); })();' % tag])
def sent(): return R.choice(['', '', '', '"s"', 'n', '{ n }', 'undefined', 'Promise.resolve(7)'])
def generator():
    name = fresh('gen'); n = R.randrange(0, 6); k = R.random()
    end = R.choice(['', '', '', 'return "end";', 'return { value: 1, done: false };', 'return later("late end", 1);', 'throw new Error("%s failed");' % name, 'await %s;' % wait()])
    pause = R.choice(['', '', '', 'await %s;' % wait(), 'await %s;' % wait()])
    if k < 0.5: body = 'for (let i = 0; i < %d; i++) { %s %s const got: any = yield %s; if (got !== undefined) log("%s got " + show(got)); %s }' % (n, pause, witness(name + 'a'), operand('i'), name, witness(name + 'b'))
    elif k < 0.65: body = 'try { for (let i = 0; i < %d; i++) { %s yield %s; } } finally { log("%s cleans up"); %s }' % (n, pause, operand('i'), name, R.choice(['', 'await %s;' % wait(), 'yield "late";']))
    elif k < 0.8: body = 'for (let i = 0; i < %d; i++) { try { %s yield %s; } catch (e) { log("%s caught " + (e as Error).message); yield "recovered"; } }' % (n, pause, operand('i'), name)
    elif k < 0.9 and counter[0] > 2: body = '%s yield* %s(); %s' % (R.choice(['', 'const r: any =', 'return']), 'gen%d' % R.choice(known), R.choice(['', 'yield "after";']))
    else: body = 'yield 1; %s yield 2; if (%d) throw new Error("%s threw"); yield 3;' % (pause, R.randrange(0, 2), name)
    w('async function* %s(): AsyncGenerator<any, any, any> { log("%s starts"); %s %s }' % (name, name, body, end))
    known.append(int(name[3:]))
    return name
known = []
def reads(t, call):
    """One step and what is done with its result. Leaves `stop` true when the generator is done."""
    k = R.random()
    if k < 0.3: return 'const { value, done } = await %s; log("%s " + show(value) + " " + done); if (done) break;' % (call, t)
    if k < 0.4: return 'const { done, value } = await %s; if (done) { log("%s ended " + show(value)); break; } log("%s " + show(value));' % (call, t, t)
    if k < 0.55: return 'const r = await %s; if (r.done) { log("%s ended " + show(r.value)); break; } log("%s " + show(r.value));' % (call, t, t)
    if k < 0.62: return 'const { value } = await %s; log("%s " + show(value)); if (value === undefined || n > 7) break;' % (call, t)
    if k < 0.69: return 'if ((await %s).done) break; log("%s stepped");' % (call, t)
    if k < 0.75: return 'const value = (await %s).value; log("%s " + show(value)); if (value === undefined || n > 7) break;' % (call, t)
    if k < 0.81: return 'const { value = "default", done = "none" } = await %s; log("%s " + show(value) + " " + done); if (done) break;' % (call, t)
    if k < 0.87: return 'const r = await %s; log("%s " + show(r)); if (r.done) break;' % (call, t)
    if k < 0.91: return 'const r: any = await %s; log("%s " + show(r.value) + " " + show(r.other) + " " + Object.keys(r).join()); if (r.done) break;' % (call, t)
    if k < 0.95: return 'const p = %s; %s const { value, done } = await p; log("%s " + show(value)); if (done) break;' % (call, witness(t + 'p'), t)
    return 'let value: any, done: boolean | undefined; ({ value, done } = await %s); log("%s " + show(value)); if (done) break;' % (call, t)
def fresh_helper(t):
    name = fresh('fetch')
    w('async function %s(it: AsyncGenerator<any, any, any>, n: number): Promise<[any, boolean | undefined]> { %s %s %s }' % (name, witness(name + 'a'), R.choice([
        'const { value, done } = await it.next(%s); %s return [value, done];' % (sent(), witness(name + 'b')),
        'const r = await it.next(%s); return [r.value, r.done];' % sent(),
        'try { const { value, done } = await it.next(%s); return [value, done]; } finally { log("%s finally"); }' % (sent(), name),
        'const r = await it.next(%s); log("%s " + show(r)); return [r.value, r.done];' % (sent(), name)]), ''))
    return name
def stepper():
    name = fresh('use'); t = name; g = generator(); k = R.random()
    shared = R.random() < 0.15 and sharedNames
    make = R.choice(sharedNames) if shared else '%s()' % g
    between = R.choice([''] * 5 + ['await null;', 'await %s;' % wait(), witness(t + 'w'), 'if (n === %d) log("%s return " + show(await it.return("early")));' % (R.randrange(1, 4), t),
                                   'if (n === %d) { try { log("%s throw " + show(await it.throw(new Error("thrown in")))); } catch (e) { log("%s threw back " + (e as Error).message); } }' % (R.randrange(1, 4), t, t),
                                   'if (n === %d) { const waiting = it.next("ahead"); waiting.then(r => log("%s ahead " + show(r)), e => log("%s ahead failed")); }' % (R.randrange(1, 4), t, t)])
    loop = 'let n = 0; for (;;) { n++; %s %s %s }' % (witness(t + 'f'), reads(t, 'it.next(%s)' % sent()), between)
    how = R.random()
    if how < 0.2:
        # Each step is the first await of a new call of an async function.
        helper = fresh_helper(t)
        loop = 'let n = 0; for (;;) { n++; %s const [value, done] = await %s(it, n); log("%s " + show(value) + " " + done); if (done) break; %s }' % (witness(t + 'f'), helper, t, between)
    elif how < 0.3 and k < 0.75:
        # A plain function starts the async function and does not wait for it.
        loop = ('let n = 0; await new Promise<void>((resolve, reject) => { async function one(): Promise<void> { n++; %s const { value, done } = await it.next(%s); log("%s " + show(value) + " " + done); %s if (done || n > 9) return resolve(); read(); } '
                'function read() { one().catch(reject); %s } read(); });') % (witness(t + 'f'), sent(), t, witness(t + 'g'), witness(t + 'h'))
    guard = R.choice(['try { %s } catch (e) { log("%s caught " + (e as Error).message); }', 'try { %s } catch (e) { log("%s caught " + (e as Error).message); } finally { log("finally"); }', 'try { %s } catch (e) { log("%s caught " + (e as Error).message); }'])
    body = 'const it = %s; %s' % (make, guard % (loop, t))
    if k < 0.75:
        w('async function %s(): Promise<any> { %s %s log("%s done"); return "%s"; }' % (name, R.choice(['', '', 'await null;', 'await immediate();']), body, t, t))
        return '%s()' % name
    inner = body.replace('log("%s " + show(value)' % t, 'yield value; log("%s " + show(value)' % t, 1)
    w('async function* %s(): AsyncGenerator<any, any, any> { %s log("%s done"); return "%s"; }' % (name, inner, t, t))
    return '(async () => { const seen: string[] = []; for await (const x of %s()) seen.push(show(x)); return seen.join(); })()' % name
sharedNames = []
scenes = []
for s in range(10):
    sharedNames = []
    setup = ''
    if R.random() < 0.3:
        g = generator(); sharedNames = ['shared%d' % s]; w('let shared%d: AsyncGenerator<any, any, any> = %s();' % (s, g))
    users = [stepper() for _ in range(R.choice([1, 1, 1, 2, 3]))]
    start = []
    for u in users:
        start.append(R.choice(['', '', '', 'ticks("t%d.", %d);' % (s, R.randrange(2, 9)), 'queueMicrotask(() => log("between"));']))
        start.append('running.push(%s.then(v => log("-> " + show(v)), e => log("-> rejected " + (e as Error).message)));' % u)
    w('async function scene%d() { const running: Promise<any>[] = []; %s await settle(running); }' % (s, ' '.join(x for x in start if x)))
    scenes.append('scene%d' % s)
w('for (const [i, scene] of [%s].entries()) { lines = []; await scene(); console.log("scene " + i + ": " + lines.join(" | ")); }' % ', '.join(scenes))
print('\n'.join(out))
