w('class Box<T> { constructor(public held: T) {} }')
w('const first = <T,>(s: Set<T>): T => [...s][0]!;')
w('const untyped = (x: any): any => x;')
w('const both = <A extends object, B extends object>(a: A, b: B): A & B => ({ ...a, ...b });')
w('function parsed<T>(text: string): T { return JSON.parse(text); }')
w('const show = (v: any, d = 0): string => { if (v === null) return "null"; if (v === undefined) return "u"; const t = typeof v; if (t === "function") return "fn"; if (t !== "object") return String(v); if (d > 14) return ".."; if (Array.isArray(v)) return "[" + v.map(e => show(e, d + 1)).join() + "]"; if (v instanceof Map) return "Map" + show([...v], d + 1); if (v instanceof Set) return "Set" + show([...v], d + 1); return "{" + Object.keys(v).map(k => k + ":" + show(v[k], d + 1)).join() + "}"; };')
w('const attempt = (f: () => unknown): string => { try { return show(f()); } catch (e) { return "THROWS " + (e as Error).name; } };')
# a type is a tuple; growth: T -> what `more` is instantiated with
counter = [0]
def num(): counter[0] += 1; return counter[0]
GROW = {
 'itself': lambda F, T: ('F', F, T), 'array': lambda F, T: ('arr', T), 'tuple': lambda F, T: ('tup', T), 'object': lambda F, T: ('obj', T), 'and': lambda F, T: ('and', F, T),
 'map': lambda F, T: ('map', T), 'set': lambda F, T: ('set', T), 'result': lambda F, T: ('fn0', T), 'parameter': lambda F, T: ('fn1', T), 'partial': lambda F, T: ('partial', F, T), 'readonly': lambda F, T: ('readonly', F, T),
 'and extra': lambda F, T: ('andx', T), 'and itself': lambda F, T: ('andt', F, T),
 'dictionary': lambda F, T: ('dict', T), 'box': lambda F, T: ('box', T), 'or null': lambda F, T: ('ornull', T), 'array of itself': lambda F, T: ('arr', ('F', F, T)), 'box of itself': lambda F, T: ('box', ('F', F, T)),
}
JSONABLE = {'and extra', 'and itself', 'itself', 'array', 'tuple', 'object', 'and', 'partial', 'readonly', 'dictionary', 'or null', 'array of itself'}
def text(t):
    k = t[0]
    if k == 'key': return 'Key'
    if k == 'T': return 'T'
    if k == 'num': return 'number'
    if k == 'F': return '%s<%s>' % (t[1], text(t[2]))
    if k == 'arr': return '%s[]' % (text(t[1]) if t[1][0] not in ('fn0', 'fn1', 'ornull', 'and', 'andx', 'andt') else '(' + text(t[1]) + ')')
    if k == 'tup': return '[%s, %s]' % (text(t[1]), text(t[1]))
    if k == 'obj': return '{ inner: %s }' % text(t[1])
    if k == 'and': return '%s<%s> & Key' % (t[1], text(t[2]))
    if k == 'andx': return '%s & { extra: %s }' % (text(t[1]), text(t[1]))
    if k == 'andt': return '%s<%s> & { also: %s }' % (t[1], text(t[2]), text(t[2]))
    if k == 'map': return 'Map<string, %s>' % text(t[1])
    if k == 'set': return 'Set<%s>' % text(t[1])
    if k == 'fn0': return '() => %s' % text(t[1])
    if k == 'fn1': return '(x: %s) => number' % text(t[1])
    if k == 'partial': return 'Partial<%s<%s>>' % (t[1], text(t[2]))
    if k == 'readonly': return 'Readonly<%s<%s>>' % (t[1], text(t[2]))
    if k == 'dict': return '{ [name: string]: %s }' % text(t[1])
    if k == 'box': return 'Box<%s>' % text(t[1])
    if k == 'ornull': return '%s | null' % text(t[1])
FAMILY = {}
def value(t, more):
    """an expression of type t; `more`: how many levels of `more` the outermost family value gets"""
    k = t[0]
    if k == 'key': return '{ key: %d }' % num()
    if k == 'num': return str(num())
    if k in ('F', 'partial', 'readonly', 'and'):
        F, T = t[1], t[2]; f = FAMILY[F]
        parts = ['%s: %s' % (f['field'], value(T, 0))]
        if k == 'and': parts.append('key: %d' % num())
        if more > 0: parts.append('%s: %s' % (f['more'], value(f['next'](T), more - 1)))
        body = '{ ' + ', '.join(parts) + ' }'
        return f['make'](body, T) if k == 'F' else body if not f['isClass'] else f['make'](body, T)
    if k == 'andx': return 'both(%s, { extra: %s })' % (value(t[1], 0), value(t[1], more))
    if k == 'andt': return '{ %s: %s, also: %s }' % (FAMILY[t[1]]['field'], value(t[2], 0), value(t[2], 0))
    if k == 'arr': return '[%s]' % value(t[1], more)
    if k == 'tup': return '[%s, %s]' % (value(t[1], 0), value(t[1], more))
    if k == 'obj': return '{ inner: %s }' % value(t[1], more)
    if k == 'map': return 'new Map([["k", %s]])' % value(t[1], more)
    if k == 'set': return 'new Set([%s])' % value(t[1], more)
    if k == 'fn0': return '() => (%s)' % value(t[1], more)
    if k == 'fn1': return '(x: %s) => %d' % (text(t[1]), num())
    if k == 'dict': return '{ k: %s }' % value(t[1], more)
    if k == 'box': return 'new Box(%s)' % value(t[1], more)
    if k == 'ornull': return value(t[1], more)
def leaf(t, base):
    """the way from an expression of type t down to a number"""
    k = t[0]
    if k == 'key': return base + '.key'
    if k == 'num': return base
    if k in ('F', 'readonly', 'and'): return leaf(t[2], base + '.' + FAMILY[t[1]]['field'])
    if k == 'partial': return leaf(t[2], base + '.' + FAMILY[t[1]]['field'] + '!')
    if k == 'andx': return leaf(t[1], base + '.extra')
    if k == 'andt': return leaf(t[2], base + '.also')
    if k == 'arr': return leaf(t[1], base + '[0]!')
    if k == 'tup': return leaf(t[1], base + '[1]')
    if k == 'obj': return leaf(t[1], base + '.inner')
    if k == 'map': return leaf(t[1], base + '.get("k")!')
    if k == 'set': return leaf(t[1], 'first(%s)' % base)
    if k == 'fn0': return leaf(t[1], base + '()')
    if k == 'fn1': return '%s(%s)' % (base, value(t[1], 0))
    if k == 'dict': return leaf(t[1], base + '["k"]!')
    if k == 'box': return leaf(t[1], base + '.held')
    if k == 'ornull': return leaf(t[1], base + '!')
def through(t, base):
    """from a value of type f.next(T) to the family value in it that carries the next `more` (None: there is none to follow)"""
    k = t[0]
    if k in ('F', 'partial', 'readonly', 'and'): return base, t
    return None, None
names = list(GROW)
only = os.environ.get('ONLY')
picked = [names[int(only)]] if only else R.sample(names, 5)
n = 0
for g in picked:
    n += 1
    form = R.choice(['interface', 'alias', 'class', 'turns', 'swap', 'interface', 'conditional'])
    if form == 'class' and g in ('and', 'and itself', 'partial', 'readonly'): form = 'interface'  # a literal is no object of a class
    F = 'F%d' % n; grow = GROW[g]
    f = {'field': 'value', 'more': 'more', 'isClass': False, 'make': lambda body, T: body, 'next': (lambda F, grow: lambda T: ('F', F, grow(F, T)))(F, grow)}
    FAMILY[F] = f
    G = text(grow(F, ('T',))) if False else None
    def T_text(t):  # the growth written over the parameter T
        return text(t).replace('Key', 'T')
    grown = text(grow(F, ('T',)))
    if form == 'interface': w('interface %s<T> { value: T; more?: %s<%s> }' % (F, F, grown))
    elif form == 'alias': w('type %s<T> = { value: T; more?: %s<%s> };' % (F, F, grown))
    elif form == 'class':
        w('class %s<T> { value: T; more?: %s<%s>; constructor(from: { value: T; more?: %s<%s> }) { this.value = from.value; if (from.more) this.more = from.more; } depth(): number { return this.more ? 1 + this.more.depth() : 0; } }' % (F, F, grown, F, grown))
        f['isClass'] = True; f['make'] = (lambda F: lambda body, T: 'new %s<%s>(%s)' % (F, text(T), body))(F)
    elif form == 'turns':
        H = F + 'b'; w('interface %s<T> { value: T; more?: %s<%s> }' % (F, H, grown.replace(F + '<', H + '<') if False else grown)); w('interface %s<T> { value: T; more?: %s<%s> }' % (H, F, grown))
        FAMILY[H] = dict(f); FAMILY[H]['next'] = (lambda F, grow: lambda T: ('F', F, grow(F, T)))(F, grow); f['next'] = (lambda H, F, grow: lambda T: ('F', H, grow(F, T)))(H, F, grow)
    elif form == 'swap':
        w('interface %sw<A, B> { value: A; other?: B; more?: %sw<B, %s> }' % (F, F, grown.replace('T', 'A').replace(F + '<A>', F + 'w<A, B>')))
        w('type %s<T> = { value: T; more?: %s<%s> };' % (F, F, grown)); w('const sw%d: %sw<Key, number> = { value: { key: 1 }, other: 2, more: { value: 3 } }; console.log("%s swap: " + attempt(() => sw%d.more!.value + sw%d.value.key));' % (n, F, g, n, n))
    elif form == 'conditional':
        w('type %s<T> = { value: T; more?: T extends number ? never : %s<%s> };' % (F, F, grown))
    root = ('F', F, ('key',)); depth = R.choice([1, 2, 3, 4, 5, 7, 8, 9, 10, 11]) if g in ('array', 'tuple', 'object', 'map', 'set', 'result', 'dictionary', 'box', 'or null', 'parameter') else R.choice([1, 2, 3, 4, 5, 6])
    lit = value(root, depth); ty = text(root); jsonable = g in JSONABLE and not f['isClass']
    sources = ['const v%d: %s = %s;' % (n, ty, lit), 'function mk%d(): %s { return %s; }\nconst v%d = mk%d();' % (n, ty, lit, n, n), 'const v%d: %s = { ...%s };' % (n, ty, lit) if not f['isClass'] and g != 'tuple' else None, 'const v%d: %s = Object.assign({}, %s);' % (n, ty, lit) if not f['isClass'] and g != 'tuple' else None,
      'const v%d = (%s as any) as %s;' % (n, lit, ty), 'class Holder%d { held: %s = %s; }\nconst v%d = new Holder%d().held;' % (n, ty, lit, n, n), 'function take%d(p: %s): %s { return p; }\nconst v%d = take%d(%s);' % (n, ty, ty, n, n, lit), 'const v%d = untyped(%s) as %s;' % (n, lit, ty),
      'const v%d = JSON.parse(JSON.stringify(%s)) as %s;' % (n, lit, ty) if jsonable else None, 'const v%d = parsed<%s>(JSON.stringify(%s));' % (n, ty, lit) if jsonable else None]
    w(R.choice([s for s in sources if s]))
    v = 'v%d' % n; tag = '%s %s %d' % (g, form, depth)
    # the leaf at every level
    at, t = v, root
    for level in range(depth + 1):
        w('console.log("%s level %d: " + attempt(() => %s));' % (tag, level, leaf(t, at)))
        t = FAMILY[t[1]]['next'](t[2]); at = at + '.more!'
    w('console.log("%s beyond: " + attempt(() => %s));' % (tag, at.replace('.more!', '.more?', 99)[:-1] if False else '(' + at[:-1] + ')'))
    deeds = R.sample(range(9), 5)
    second = FAMILY[F]['next'](('key',))
    for d in deeds:
        if d == 0: w('console.log("%s shown: " + attempt(() => untyped(%s)));' % (tag, v))
        if d == 1 and form != 'conditional': w('{ const kept = %s.more; %s.more = %s; console.log("%s stored: " + attempt(() => %s)); %s.more = kept; console.log("%s stored back: " + attempt(() => %s.more === kept)); }' % (v, v, value(second, 1), tag, leaf(second, v + '.more!'), v, tag, v))
        if d == 2: w('{ const list: %s[] = [%s, %s]; const byName = new Map<string, %s>([["a", %s]]); console.log("%s kept: " + attempt(() => [%s, %s, list[0] === byName.get("a")]));  }' % (ty, v, v, ty, v, tag, leaf(root, 'list[1]!'), leaf(root, 'byName.get("a")!')))
        if d == 3 and form not in ('turns', 'conditional'): w('function depth%d<T>(g: %s<T>): number { return g.more ? 1 + depth%d(g.more) : 0; }\nconsole.log("%s depth: " + attempt(() => depth%d(%s)));' % (n, F, n, tag, n, v))
