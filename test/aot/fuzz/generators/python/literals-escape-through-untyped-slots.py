#!/usr/bin/env python3
"""literals-escape-through-untyped-slots.py <seed>: A LITERAL IS LET OUT THROUGH A PLACE THAT SAYS NOTHING (a parameter, field, element, result of type unknown | any | object | {} | T), KEPT THERE, AND COMES BACK THROUGH A CAST THAT IS TRUE: of the HOLDER, of the value, by a guard, by a generic getter. Every cast in these programs is true and every store fits: SO NOTHING MAY BE REFUSED: every line as plain Bun, no throw."""
import random, sys
seed = int(sys.argv[1]) if len(sys.argv) > 1 else 1
R = random.Random(seed)
out = []; w = out.append
w('// generated by literals-escape-through-untyped-slots.py %d' % seed)
w('declare const console: { log(...values: unknown[]): void };')
w('const lines: string[] = []; const show = (v: unknown): string => JSON.stringify(v, (k, x) => x === undefined ? "u" : x) ?? "u";')
w('const row = (name: string, f: () => unknown) => { let s: string; try { s = show(f()); } catch (e) { s = "THROWS " + (e as Error).name + ": " + (e as Error).message.slice(0, 80); } lines.push(name + ": " + s); };')
w('interface Leaf { id: number; tag?: string }')
w('const leaf = (id: number): Leaf => ({ id });')
PRIM = [('number', lambda: str(R.randint(-3, 99))), ('string', lambda: '"s%d"' % R.randint(0, 9)), ('boolean', lambda: R.choice(['true', 'false']))]
def field(depth):
    k = R.random()
    if k < 0.45 or depth > 1: t, v = R.choice(PRIM); return t, v
    if k < 0.55: return 'number[]', lambda: '[%s]' % ', '.join(str(R.randint(0, 9)) for _ in range(R.randint(0, 3)))
    if k < 0.65: return 'Leaf', lambda: R.choice(['leaf(%d)' % R.randint(0, 9), '{ id: %d }' % R.randint(0, 9), '{ id: %d, tag: "t" }' % R.randint(0, 9)])
    if k < 0.72: return 'Leaf[]', lambda: '[%s]' % ', '.join('leaf(%d)' % R.randint(0, 9) for _ in range(R.randint(0, 2)))
    if k < 0.80: return 'Leaf | undefined', lambda: R.choice(['undefined', 'leaf(1)'])
    if k < 0.86: return 'number | string', lambda: R.choice(['1', '"one"'])
    if k < 0.92: return 'unknown', lambda: R.choice(['1', '"u"', '{ deep: 1 }', 'null', '[1, { in: 2 }]'])
    fs = record(depth + 1); return type_of(fs), lambda: lit(fs)
def record(depth=0):
    names = R.sample(['target', 'list', 'value', 'more', 'kind', 'name', 'x', 'y', 'next', 'count', 'flag', 'data'], R.randint(1, 4))
    return [(n, R.random() < 0.25) + field(depth) for n in names]
def type_of(fs): return '{ ' + '; '.join('%s%s: %s' % (n, '?' if o else '', t) for n, o, t, v in fs) + ' }'
def lit(fs, shuffle=True):
    fs = [f for f in fs if not f[1] or R.random() < 0.6]
    if shuffle and R.random() < 0.3: fs = R.sample(fs, len(fs))
    return '{ ' + ', '.join('%s: %s' % (n, v()) for n, o, t, v in fs) + ' }'
K = R.randint(3, 6); kinds = [record() for _ in range(K)]
w('interface Base { flags: number; node: unknown; other?: unknown }')
w('class Box { constructor(public flags: number, public node: unknown) {} }')
for k, fs in enumerate(kinds):
    w('type N%d = %s;' % (k, type_of(fs)))
    w('interface H%d extends Base { node: N%d }' % (k, k)); w('interface X%d { flags: number; node: N%d }' % (k, k))
    w('function is%d(b: Base): b is H%d { return b.flags === %d; }' % (k, k, k)); w('function use%d(n: N%d): string { return show(n) + Object.keys(n).length; }' % (k, k))
w('function make(flags: number, node: unknown): Base { return { flags, node }; }')
w('function makeAny(flags: number, node: any): Base { return { flags, node }; }')
w('function makeObject(flags: number, node: object): Base { return { flags, node }; }')
w('function makeEmpty(flags: number, node: {}): Base { return { flags, node }; }')
w('function makeT<T>(flags: number, node: T): Base { return { flags, node }; }')
w('function makeRest(flags: number, ...nodes: unknown[]): Base { return { flags, node: nodes[0] }; }')
w('function makeLater(flags: number, node: unknown): Base { const b: Base = { flags, node: undefined }; b.node = node; return b; }')
w('function makeBox(flags: number, node: unknown): Base { return new Box(flags, node); }')
w('type Flow = ' + ' | '.join('H%d' % k for k in range(K)) + ';')
w('function makeFlow(flags: number, node: unknown): Flow { return { flags, node } as Flow; }')
w('function makeFlowX(flags: number, node: unknown): ' + ' | '.join('X%d' % k for k in range(K)) + ' { return { flags, node } as ' + ' | '.join('X%d' % k for k in range(K)) + '; }')
w('function through(x: unknown): unknown { return x; } function get<T>(b: Base): T { return b.node as T; }')
w('const kept: Base[] = []; const byName = new Map<string, unknown>(); const loose: unknown[] = [];')
MAKE = ['makeFlow', 'makeFlow', 'makeFlowX', 'make', 'makeAny', 'makeObject', 'makeEmpty', 'makeT', 'makeRest', 'makeLater', 'makeBox']
n = 0
for _ in range(70):
    k = R.randrange(K); fs = kinds[k]; n += 1; m = R.choice(MAKE); L = lit(fs)
    how = R.randrange(7)
    if how == 0: mk = '%s(%d, %s)' % (m, k, L)
    elif how == 1: mk = '%s(%d, through(%s))' % ('make', k, L)
    elif how == 2: mk = '(() => { kept.push(%s(%d, %s)); return kept[kept.length - 1]; })()' % (m, k, L)
    elif how == 3: mk = '(() => { byName.set("k%d", %s); return make(%d, byName.get("k%d")); })()' % (n, L, k, n)
    elif how == 4: mk = '(() => { loose.push(%s); return make(%d, loose[loose.length - 1]); })()' % (L, k)
    elif how == 5: mk = '(() => { const b: Base = { flags: %d, node: %s }; return b; })()' % (k, L)
    else: mk = '(() => { const n: N%d = %s; return %s(%d, n); })()' % (k, L, m, k)
    back = R.choice(['(b as H%d).node' % k, '(b as X%d).node' % k, '(b.node as N%d)' % k, 'get<N%d>(b)' % k, '(is%d(b) ? b.node : (undefined as never))' % k, '(b as unknown as { node: N%d }).node' % k])
    w('{ const b: Base = %s;' % mk)
    w('  row("%d whole", () => %s);' % (n, back))
    for fn, o, t, v in fs:
        w('  row("%d read %s", () => %s.%s);' % (n, fn, back, fn))
        if R.random() < 0.6: w('  row("%d store %s", () => { %s.%s = %s; return %s.%s; });' % (n, fn, back, fn, v(), back, fn))
    if R.random() < 0.6: w('  row("%d another node", () => { (b as H%d).node = %s; return [%s, show(b.node)]; });' % (n, k, lit(fs), back))
    if R.random() < 0.5: w('  row("%d stored as unknown", () => { b.node = %s; return %s; });' % (n, lit(fs), back))
    w('  row("%d used", () => [use%d(%s), Object.keys(b.node as object), { ...(b.node as object) }, show(b)]);' % (n, k, back))
    w('}')
w('for (const b of kept) row("kept " + b.flags, () => { switch (b.flags) { %s default: return "none"; } });' % ' '.join('case %d: return use%d((b as H%d).node);' % (k, k, k) for k in range(K)))
w('for (const line of lines) console.log(line);')
print('\n'.join(out))
