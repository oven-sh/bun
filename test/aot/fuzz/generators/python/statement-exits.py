def nid(): ids[0] += 1; return ids[0]
CONST = ['0', '1', '2', '3', '7', '-1', '31', '32', '255', '65535', '2147483647', '-2147483648', '4294967295', '0.5', '-0.5', '1e9', '1e21', '-0', 'NaN', 'Infinity']
def expr(vs, d=0):
    k = R.random()
    if d > 3 or k < 0.25: return R.choice(vs)
    if k < 0.35: return 'K%d' % R.randrange(len(CONST))
    a, b = expr(vs, d + 1), expr(vs, d + 1)
    if k < 0.62: return '(%s %s %s)' % (a, R.choice(['+', '-', '*', '|', '&', '^', '<<', '>>', '>>>', '%', '/']), b)
    if k < 0.70: return '((%s) %s (%s) ? %s : %s)' % (a, R.choice(['<', '<=', '===', '!=='] if TS else ['<', '<=', '>', '>=', '===', '!==']), b, expr(vs, d + 1), expr(vs, d + 1))
    if k < 0.75: return 'Math.%s(%s, %s)' % (R.choice(['imul', 'min', 'max']), a, b)
    if k < 0.80: return 'Math.%s(%s)' % (R.choice(['abs', 'floor', 'trunc', 'sign', 'clz32', 'fround', 'round', 'ceil']), a)
    if k < 0.85: return '(%s %s %s)' % (a, R.choice(['&&', '||'] if TS else ['&&', '||', '??']), b)
    if k < 0.90: return '(%s | 0)' % a
    if k < 0.94: return 'log(%d, %s)' % (nid(), a)
    if k < 0.97: return '(-%s)' % a
    return '(~%s)' % a
def cond(vs): return '(%s) %s (%s)' % (expr(vs, 2), R.choice(['<', '<=', '===', '!=='] if TS else ['<', '<=', '>', '>=', '===', '!==']), expr(vs, 2))
def block(vs, depth, labels, loops, infn, ingen, n=None):
    return ' '.join(stmt(vs, depth, labels, loops, infn, ingen) for _ in range(n if n is not None else R.randint(1, 3)))
def stmt(vs, depth, labels, loops, infn, ingen):
    k = R.random(); mut = [v for v in vs if not v.startswith('c')] or vs
    if depth > 3 or k < 0.26:
        v = R.choice(mut); j = R.random()
        if j < 0.5: return '%s %s %s;' % (v, R.choice(['=', '+=', '-=', '*=', '|=', '&=', '^=', '<<=', '>>=', '>>>=', '%=']), expr(vs))
        if j < 0.7: return '%s%s;' % (v, R.choice(['++', '--']))
        return 'log(%d, %s);' % (nid(), expr(vs))
    if k < 0.32: return 'if (%s) { %s }%s' % (cond(vs), block(vs, depth + 1, labels, loops, infn, ingen), ' else { %s }' % block(vs, depth + 1, labels, loops, infn, ingen) if R.random() < 0.5 else '')
    if k < 0.42:
        i = 'i%d' % nid(); lab = 'L%d' % nid(); use = R.random() < 0.4
        body = block(vs + [i], depth + 1, labels + ([lab] if use else []), loops + [lab if use else None], infn, ingen)
        if R.random() < 0.3: body += ' later.push(() => %s + %s);' % (i, R.choice(vs))
        return '%sfor (let %s = %s; %s < %d; %s%s) { if (--fuel < 0) break; %s }' % (lab + ': ' if use else '', i, R.choice(['0', '1', '-2']), i, R.randint(1, 6), i, R.choice(['++', ' += 2']), body)
    if k < 0.48:
        lab = 'L%d' % nid(); use = R.random() < 0.4; c = 'w%d' % nid()
        body = block(vs + [c], depth + 1, labels + ([lab] if use else []), loops + [lab if use else None], infn, ingen)
        if R.random() < 0.5: return '{ let %s = 0; %swhile (%s++ < %d) { if (--fuel < 0) break; %s } }' % (c, lab + ': ' if use else '', c, R.randint(1, 5), body)
        return '{ let %s = 0; %sdo { if (--fuel < 0) break; %s } while (++%s < %d); }' % (c, lab + ': ' if use else '', body, c, R.randint(1, 4))
    if k < 0.53:
        x = 'c%d' % nid(); body = block(vs + [x], depth + 1, labels, loops + [None], infn, ingen)
        return 'for (const %s of [%s]) { if (--fuel < 0) break; %s }' % (x, ', '.join(expr(vs, 2) for _ in range(R.randint(1, 4))), body)
    if k < 0.61:
        cases = []
        for c in R.sample(range(-1, 6), R.randint(1, 4)):
            cases.append('case %d: %s %s' % (c, block(vs, depth + 1, labels, loops, infn, ingen, R.randint(0, 2)), R.choice(['break;', '', 'break;'])))
        if R.random() < 0.6: cases.insert(R.randint(0, len(cases)), 'default: %s %s' % (block(vs, depth + 1, labels, loops, infn, ingen, 1), R.choice(['break;', ''])))
        return 'switch (%s) { %s }' % ('(%s) %% 6 | 0' % expr(vs, 2), ' '.join(cases))
    if k < 0.73:
        t = block(vs, depth + 1, labels, loops, infn, ingen); e = 'e%d' % nid()
        c = 'catch (%s) { log(%d, typeof %s === "number" ? %s : -9); %s }' % (e, nid(), e, e, block(vs, depth + 1, labels, loops, infn, ingen, R.randint(0, 2)))
        f = 'finally { %s }' % block(vs, depth + 1, labels, loops, infn, ingen, R.randint(1, 2))
        j = R.random(); return 'try { %s } %s' % (t, c if j < 0.35 else f if j < 0.6 else c + ' ' + f)
    if k < 0.78:
        lab = 'B%d' % nid(); return '%s: { %s }' % (lab, block(vs, depth + 1, labels + [lab], loops, infn, ingen))
    if k < 0.84 and (labels or loops):
        j = R.random()
        if labels and j < 0.4: return 'if (%s) break %s;' % (cond(vs), R.choice(labels))
        named = [l for l in loops if l and l in labels]
        if named and j < 0.6: return 'if (%s) continue %s;' % (cond(vs), R.choice(named))
        if loops: return 'if (%s) %s;' % (cond(vs), R.choice(['break', 'continue']))
        return 'log(%d, 0);' % nid()
    if k < 0.88 and infn: return 'if (%s) return %s;' % (cond(vs), expr(vs))
    if k < 0.92: return 'if (%s) throw %s;' % (cond(vs), expr(vs, 2))
    if k < 0.95 and ingen: return '%s = (yield %s) | 0;' % (R.choice(mut), expr(vs, 2)) if False else 'yield %s;' % expr(vs, 2)
    if k < 0.98 and FNS: 
        f, ar, g = R.choice(FNS)
        if g:
            x = 'c%d' % nid(); return 'for (const %s of %s(%s)) { if (--fuel < 0) break; log(%d, %s); %s }' % (x, f, ', '.join(expr(vs, 2) for _ in range(ar)), nid(), x, 'if (%s) break;' % cond(vs) if R.random() < 0.5 else '')
        return '%s = %s(%s);' % (R.choice(mut), f, ', '.join(expr(vs, 2) for _ in range(ar)))
    x = 't%d' % nid(); return '{ let %s%s = %s; %s }' % (x, N, expr(vs), block(vs + [x], depth + 1, labels, loops, infn, ingen))
FNS = []
