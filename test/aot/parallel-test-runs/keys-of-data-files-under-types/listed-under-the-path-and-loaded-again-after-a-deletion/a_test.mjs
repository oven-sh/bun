import { test } from "bun:test";
import { createRequire } from "node:module";
import path from "node:path";
const require = createRequire(import.meta.url);
const file = path.join(import.meta.dir, "d.json");
const show = value => console.log(typeof value, JSON.stringify(value));
const json = async () => show((await import("./d.json", { with: { type: "json" } })).default);
const text = async () => show((await import("./d.json", { with: { type: "text" } })).default);
const required = () => show(require("./d.json"));
const entry = () => show(require.cache[file]?.exports);
const keys = () => console.log(Object.keys(require.cache).map(key => path.basename(key)).filter(key => key.startsWith("d.")).join(" "));
test("listed under the path, and loaded again after a deletion", async () => {
  await json();
  await text();
  console.log(file in require.cache, Object.hasOwn(require.cache, file), Object.keys(require.cache).some(key => key.includes("?")));
  required();
  delete require.cache[file];
  keys();
  entry();
  required();
  await text();
  entry();
});
