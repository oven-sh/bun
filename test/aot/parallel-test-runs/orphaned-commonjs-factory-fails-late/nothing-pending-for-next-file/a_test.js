import { test, vi } from "bun:test";
const said = load => Promise.resolve(load).then(it => String(it.a), error => error.message.slice(0, 30));
test("1 jobs", async () => {
  const log = [];
  const called = Promise.withResolvers(), gate = Promise.withResolvers();
  let failing;
  vi.doMock("./x1.cjs", () => { called.resolve(); return failing = gate.promise.then(() => { throw new Error("late"); }); });
  const first = said(import("./x1.cjs"));
  await called.promise;
  vi.doUnmock("./x1.cjs");
  log.push("second " + await said(import("./x1.cjs")));
  gate.resolve();
  await failing.catch(() => {});
  await null;
  const other = said(import("./other1.mjs"));
  log.push("first " + await first);
  log.push("last " + await said(import("./x1.cjs")));
  log.push("other " + await other);
  console.log("SAID", 1, log.join());
});
test("the case", async () => {
  const log = [];
  const called = Promise.withResolvers(), gate = Promise.withResolvers(), gate2 = Promise.withResolvers();
  let failing;
  vi.doMock("./y.cjs", () => { called.resolve(); return gate.promise.then(() => { throw new Error("late one"); }); });
  const first = said(import("./y.cjs"));
  await called.promise;
  vi.doMock("./y.cjs", () => failing = gate2.promise.then(() => { throw new Error("late two"); }));
  const second = said(import("./y.cjs"));
  for (let turn = 0; turn < 20; turn++) await 0;
  log.push("the second factory " + (failing ? "ran" : "did not run"));
  vi.doUnmock("./y.cjs");
  log.push("third " + await said(import("./y.cjs")));
  gate.resolve();
  gate2.resolve();
  log.push("first " + await first);
  log.push("second " + await second);
  log.push("last " + await said(import("./y.cjs")));
  console.log("SAID the case", log.join());
});
