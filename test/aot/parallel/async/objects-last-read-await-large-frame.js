// Each coroutine waits for a timer, as its loop does later, makes an object and many short-lived values, hands each value to a call of its own, reads the object, and then collects in a loop that awaits.
const registry = new FinalizationRegistry(markCollected => markCollected());
const maxRounds = 300;

class Box {
  constructor(first, second) {
    this.first = first;
    this.second = second;
  }
}

const passers = [value => value, value => value];
let passes = 0;
function pass(value) {
  return passers[passes++ & 1](value);
}

function show(value) {
  if (typeof value === "string") return JSON.stringify(value);
  if (typeof value === "function") return "function";
  if (value !== null && typeof value === "object")
    return (
      "{" +
      Object.keys(value)
        .map(key => key + ":" + show(value[key]))
        .join(",") +
      "}"
    );
  return String(value);
}

function mix(...values) {
  let sum = 7;
  for (const value of values) for (const unit of show(value)) sum = (sum * 31 + unit.charCodeAt(0)) | 0;
  return sum;
}

function readName(value) {
  return value.name.length;
}

function report(label, isCollected, sum) {
  console.log(label + ":", isCollected ? "collected" : "still held", sum);
}

