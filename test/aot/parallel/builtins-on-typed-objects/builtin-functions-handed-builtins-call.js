function show(value) {
  if (typeof value === "bigint") return value + "n";
  if (typeof value === "symbol") return value.toString();
  if (typeof value === "function") return "function " + value.name;
  if (Array.isArray(value)) { const parts = []; for (let i = 0; i < value.length; i++) parts.push(i in value ? show(value[i]) : "<hole>"); return "[" + parts.join(", ") + "]"; }
  if (value instanceof Map || value instanceof Set) return Object.prototype.toString.call(value) + value.size;
  if (value instanceof Promise) return "a promise";
  if (value instanceof RegExp || value instanceof Error) return String(value);
  if (typeof value === "object" && value !== null) return Object.prototype.toString.call(value) + JSON.stringify(value);
  return Object.is(value, -0) ? "-0" : typeof value === "string" ? JSON.stringify(value) : String(value);
}
