// split and join on constant texts: separators that are empty, absent, longer than the text or outside the basic plane, limits, and lists that are changed behind the split.
const show = (label, value) => console.log(label, Array.isArray(value) ? `${JSON.stringify(value)} length ${value.length}` : String(value));
show("commas", "a,b,c".split(","));
show("no separator in the text", "abc".split(","));
show("an empty text", "".split(","));
show("an empty text, an empty separator", "".split(""));
show("an empty separator", "abc".split(""));
show("at both ends", ",a,".split(","));
show("only separators", ",,".split(","));
show("the text is the separator", "ab".split("ab"));
show("a long separator", "a--b--c".split("--"));
show("a separator that overlaps itself", "a:::b".split("::"));
show("a separator that overlaps itself, more", "aaaa".split("aa"));
show("a separator longer than the text", "a".split("abc"));
show("blanks", "GET POST  PUT".split(" "));
show("lines", "a\nb\r\nc".split("\n"));
show("not ASCII", "ä,ö,ü".split(","));
show("a separator that is not ASCII", "aäbäc".split("ä"));
show("outside the basic plane", "😀,😁".split(","));
show("half a pair", "😀".split("\ud83d"));
show("half a pair, by units", "😀".split("").length);
show("no operand", "a,b".split());
show("undefined", "a,b".split(undefined));
show("null", "anullb".split(null));
show("a number", "a1b".split(1));
show("a limit", "a,b,c".split(",", 2));
show("a limit of nothing", "a,b,c".split(",", 0));
show("a limit that is undefined", "a,b,c".split(",", undefined));
show("a pattern", "a1b2c".split(/\d/));
show("a pattern with a group", "a1b".split(/(\d)/));
show("an object with its own way", "a,b".split({ [Symbol.split]: (text, limit) => [`own ${text} ${limit}`] }));
show("an object that is converted", "a,b".split({ toString: () => "," }));
const text = "x,y";
show("a constant that has a name", text.split(","));
const mark = ",";
show("a separator that has a name", "x,y".split(mark));
show("a template", `a${mark}b`.split(mark));
show("a sum", ("a" + "," + "b").split(","));
function pieces() { return "a,b,c".split(","); }
const first = pieces(), second = pieces();
first.push("d");
first[0] = "changed";
show("each call makes its own", `${first} | ${second} | ${pieces()} | ${first !== second}`);
show("an ordinary list", [Array.isArray(first), first.constructor === Array, Object.isFrozen(second), Object.keys(second).join()]);
function of(value) { return value.split(","); }
show("a text nobody knows", [of("p,q"), of({ split: separator => `other ${separator}` })]);
function at(separator) { return "a,b;c".split(separator); }
show("a separator nobody knows", [at(","), at(";"), at(""), at(undefined), at(/[,;]/)]);
show("what follows", "a,b,c".split(",").map(piece => piece.toUpperCase()).join("+"));
show("the last piece", "a/b/c".split("/").pop());
show("the last piece, by at", "a/b/c".split("/").at(-1));
show("a piece by its index", "a/b/c".split("/")[1]);
show("the number of pieces", "a/b/c".split("/").length);
show("searched", "GET,HEAD".split(",").includes("HEAD"));
const [head, ...rest] = "a,b,c".split(",");
show("taken apart", `${head} ${rest}`);
show("a set of pieces", [...new Set("a,b,a".split(","))]);
let total = 0;
