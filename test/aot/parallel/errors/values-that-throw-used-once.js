function show(run) {
  try {
    run();
    console.log(run.name + " no error");
  } catch (error) {
    const frames = String(error && error.stack).split("\n").slice(1, 3);
    console.log(run.name + " " + (error && error.constructor.name) + " " + frames.map(line => line.replace(/.*:(\d+:\d+)\)?$/, "$1").replace(/^\s*at /, "")).join(" < "));
  }
}
