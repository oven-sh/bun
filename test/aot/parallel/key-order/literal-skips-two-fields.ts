// A literal lists a and d of { a, b?, c?, d? }, or d alone, and stores create what it skipped, in both orders.
type Row = { a?: number; b?: number; c?: number; d?: number };
const x = Math.floor(Math.random()) + 1;
const forwards: Row = { a: x, d: x };
forwards.b = x + 1;
forwards.c = x + 2;
console.log(Object.keys(forwards).join(), JSON.stringify(forwards));
const backwards: Row = { a: x, d: x };
backwards.c = x + 2;
backwards.b = x + 1;
console.log(Object.keys(backwards).join(), JSON.stringify(backwards));
const one: Row = { a: x, d: x };
one.c = x + 2;
console.log(Object.keys(one).join(), JSON.stringify(one));
const last: Row = { d: x };
last.a = x + 1;
console.log(Object.keys(last).join(), JSON.stringify(last));
const lastThenAll: Row = { d: x };
lastThenAll.c = x + 1;
lastThenAll.b = x + 2;
lastThenAll.a = x + 3;
console.log(Object.keys(lastThenAll).join(), JSON.stringify(lastThenAll));
const middle: Row = { c: x, b: x };
middle.d = x + 1;
middle.a = x + 2;
console.log(Object.keys(middle).join(), JSON.stringify(middle));
