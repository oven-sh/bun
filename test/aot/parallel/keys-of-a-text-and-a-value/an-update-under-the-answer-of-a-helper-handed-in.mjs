const groupBy = (list, name) => list.reduce((groups, row) => { (groups[name(row)] ??= []).push(row.place); return groups; }, {});
const orGroupBy = (list, name) => list.reduce((groups, row) => { (groups[name(row)] ||= []).push(row.place); return groups; }, {});
const countBy = (list, name) => { const counts = {}; list.forEach(row => { counts[name(row)] ??= 0; counts[name(row)]++; }); return counts; };
const sumBy = (list, name) => { const sums = Object.create(null); list.forEach(row => { sums[name(row)] = 0; }); list.forEach(row => { sums[name(row)] += row.amount; }); return sums; };
