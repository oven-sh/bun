function show(value) {
  if (Array.isArray(value)) return "[" + value.map(show).join(", ") + "]";
  return typeof value === "function" ? "function" : String(value);
}
function say(label, run) {
  let text;
  try {
    text = show(run());
  } catch (error) {
    text = error.name;
  }
  console.log(label + ": " + text);
}
