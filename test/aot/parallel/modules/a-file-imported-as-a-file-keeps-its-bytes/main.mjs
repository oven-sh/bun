// A file imported with { type: "file" } is carried byte for byte, whatever it begins with and whatever its name ends in.
import fs from "node:fs";
import f1 from "./bytes.bin" with { type: "file" };
import f2 from "./bytes.js" with { type: "file" };
import f3 from "./bytes.json" with { type: "file" };
import f4 from "./bytes.ts" with { type: "file" };
import f5 from "./bytes.txt" with { type: "file" };
import f6 from "./utf16.bin" with { type: "file" };
import f7 from "./utf16.js" with { type: "file" };
import f8 from "./utf16.json" with { type: "file" };
import f9 from "./utf16.ts" with { type: "file" };
import f10 from "./utf16.txt" with { type: "file" };
import f11 from "./utf8.bin" with { type: "file" };
import f12 from "./utf8.js" with { type: "file" };
import f13 from "./utf8.json" with { type: "file" };
import f14 from "./utf8.ts" with { type: "file" };
import f15 from "./utf8.txt" with { type: "file" };
const hex = path => fs.readFileSync(path).toString("hex");
console.log("bytes.bin", hex(f1));
console.log("bytes.js", hex(f2));
console.log("bytes.json", hex(f3));
console.log("bytes.ts", hex(f4));
console.log("bytes.txt", hex(f5));
console.log("utf16.bin", hex(f6));
console.log("utf16.js", hex(f7));
console.log("utf16.json", hex(f8));
console.log("utf16.ts", hex(f9));
console.log("utf16.txt", hex(f10));
console.log("utf8.bin", hex(f11));
console.log("utf8.js", hex(f12));
console.log("utf8.json", hex(f13));
console.log("utf8.ts", hex(f14));
console.log("utf8.txt", hex(f15));
