"use strict";
// `Uint8Array.from(list, mapper)` and `Uint8Array.from(text, mapper)`: all the values are listed first, then the view is made by whatever `this` is, then each value is handed to the mapper with its index.
const lines = [];
function say(name, make) { try { const made = make(); lines.push(name + ": " + (made && made.constructor ? made.constructor.name : typeof made) + " [" + Array.prototype.join.call(made) + "]"); } catch (error) { lines.push(name + ": " + error.name + ": " + error.message); } }
const list = [1, 2, 3, 250, 300, -1, 2.5], holes = [1, , 3], texts = ["7", "x", null, undefined, true];
say("bytes", () => Uint8Array.from(list, x => x ^ 5));
say("clamped", () => Uint8ClampedArray.from(list, x => x * 2));
say("floats", () => Float32Array.from(list, x => x / 3));
say("doubles with the index", () => Float64Array.from(list, (x, k) => x * 10 + k));
say("big", () => BigInt64Array.from(list, x => BigInt(Math.trunc(x))));
say("big handed a number", () => BigInt64Array.from(list, x => x));
say("holes", () => Float64Array.from(holes, x => x));
say("what is no number", () => Int16Array.from(texts, x => x));
say("this of the mapper", () => Int8Array.from(list, function (x) { return x + this.by; }, { by: 1 }));
say("this of a sloppy mapper", () => Int8Array.from([1], new Function("x", "return this === globalThis ? 1 : 2")));
say("a text", () => Uint16Array.from("a\u{1F600}b", c => c.codePointAt(0) & 65535));
say("a text by its units", () => Uint8Array.from("abc", (c, k) => c.charCodeAt(0) + k));
say("nothing", () => Uint8Array.from([], x => x));
say("an empty text", () => Uint8Array.from("", x => x));
say("the mapper lengthens the list", () => { const grown = [1, 2, 3]; return Uint8Array.from(grown, x => { grown.push(9); return x; }); });
say("the mapper writes ahead", () => { const written = [1, 2, 3]; return Uint8Array.from(written, (x, k) => { written[k + 1] = 77; return x; }); });
say("the mapper shortens the list", () => { const cut = [1, 2, 3, 4]; return Uint8Array.from(cut, x => { cut.length = 1; return x; }); });
say("the mapper throws", () => Uint8Array.from(list, x => { if (x === 3) throw new RangeError("at three"); return x; }));
say("the order", () => { const order = []; class Seen extends Uint8Array { constructor(n) { order.push("made " + n); super(n); } } const made = Seen.from([5, 6], x => { order.push("mapped " + x); return x; }); lines.push(order.join()); return made; });
say("no constructor", () => Uint8Array.from.call(() => 0, list, x => x));
say("no function at all", () => Uint8Array.from.call({}, list, x => x));
say("too short", () => Uint8Array.from.call(function (n) { return new Uint8Array(n - 1); }, list, x => x));
say("longer", () => Uint8Array.from.call(function (n) { return new Uint8Array(n + 2); }, [1, 2], x => x));
say("no view", () => Uint8Array.from.call(function (n) { return new Array(n); }, list, x => x));
say("another kind", () => Uint8Array.from.call(Float64Array, [1.5, 2.5], x => x));
say("a list with steps of its own", () => { const own = [1, 2, 3]; own[Symbol.iterator] = function* () { yield 8; yield 9; }; return Uint8Array.from(own, x => x); });
say("an heir of Array", () => { class Row extends Array {} return Uint8Array.from(Row.of(4, 5), x => x + 1); });
say("no mapper", () => Uint8Array.from(list));
say("a mapper that is none", () => Uint8Array.from(list, 5));
say("a set", () => Uint8Array.from(new Set([3, 3, 4]), x => x * 2));
say("what only has a length", () => Uint8Array.from({ length: 2, 0: 6, 1: 7 }, x => x + 1));
const unseen = x => [x][JSON.parse("0")];
say("nobody knows the mapper", () => Uint8Array.from(list, unseen(x => x + 1)));
say("nobody knows the items: a list", () => Uint8Array.from(unseen([1, 2]), x => x + 1));
say("nobody knows the items: what only has a length", () => Uint8Array.from(unseen({ length: 2, 0: 6, 1: 7 }), x => x + 1));
say("nobody knows either", () => Uint8Array.from(unseen({ length: 2, 0: 6, 1: 7 }), unseen(x => x + 2)));
say("nobody knows the mapper, which is none", () => Uint8Array.from(list, unseen(5)));
say("nobody knows the mapper, which is undefined", () => Uint8Array.from(list, unseen(undefined)));
say("nobody knows the receiver", () => unseen(Int16Array).from(list, x => x * 300));
console.log(lines.join("\n"));
