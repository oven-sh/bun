// Stores that reach native setters, many times over so that the setter is noted: on the right object, on heirs and strangers (which the setter refuses), behind an own property, behind a setter put in front, after the native one is replaced or deleted, in strict and in sloppy code, with a value the setter refuses.
const log = [];
function attempt(what, body) { try { log.push(what + " " + String(body())); } catch (error) { log.push(what + " !" + error.constructor.name); } }
function storeOnabort(target, value) { "use strict"; target.onabort = value; return typeof target.onabort; }
const storeSloppily = new Function("target", "value", "target.onabort = value; return typeof target.onabort;");
function storeTimeout(target, value) { "use strict"; target._onTimeout = value; return typeof target._onTimeout; }
const handlers = [() => 1, () => 2];
const signal = new AbortController().signal;
const timer = setTimeout(() => {}, 1_000_000);
let kinds = "";
for (let round = 0; round < 300; round++) kinds = storeOnabort(signal, handlers[round & 1]) + storeTimeout(timer, handlers[round & 1]);
log.push("noted " + kinds + " " + (signal.onabort === handlers[1]) + " " + (timer._onTimeout === handlers[1]));
attempt("a number", () => storeOnabort(signal, 5));
attempt("null", () => storeOnabort(signal, null));
attempt("an object", () => storeOnabort(signal, {}));
attempt("the timer gets a number", () => storeTimeout(timer, 5));
attempt("the timer gets undefined", () => storeTimeout(timer, undefined));
attempt("an heir", () => storeOnabort(Object.create(signal), handlers[0]));
attempt("a stranger with the prototype", () => storeOnabort(Object.create(AbortSignal.prototype), handlers[0]));
attempt("a plain object", () => storeOnabort({}, handlers[0]));
attempt("a primitive", () => storeOnabort(5, handlers[0]));
attempt("undefined", () => storeOnabort(undefined, handlers[0]));
const second = new AbortController().signal;
for (let round = 0; round < 50; round++) storeOnabort(second, handlers[round & 1]);
log.push("a second signal " + (second.onabort === handlers[1]) + " " + (signal.onabort === handlers[1]));
Object.defineProperty(second, "onabort", { value: "own", writable: true, configurable: true });
attempt("behind an own property", () => storeOnabort(second, "stored") + " " + second.onabort);
const third = new AbortController().signal;
for (let round = 0; round < 50; round++) storeOnabort(third, handlers[round & 1]);
const native = Object.getOwnPropertyDescriptor(AbortSignal.prototype, "onabort");
let calls = 0;
Object.defineProperty(AbortSignal.prototype, "onabort", { get() { return "replaced"; }, set(value) { calls++; }, configurable: true });
attempt("the native one replaced", () => storeOnabort(third, handlers[0]) + " " + calls);
for (let round = 0; round < 50; round++) storeOnabort(third, handlers[round & 1]);
log.push("calls " + calls);
Object.defineProperty(AbortSignal.prototype, "onabort", native);
attempt("the native one again", () => storeOnabort(third, handlers[0]) + " " + (third.onabort === handlers[0]) + " " + calls);
for (let round = 0; round < 50; round++) storeOnabort(third, handlers[round & 1]);
delete AbortSignal.prototype.onabort;
attempt("deleted", () => storeOnabort(third, handlers[0]) + " " + Object.keys(third).join());
Object.defineProperty(AbortSignal.prototype, "onabort", native);
const fourth = new AbortController().signal;
for (let round = 0; round < 300; round++) kinds = storeSloppily(fourth, handlers[round & 1]);
log.push("sloppily " + kinds + " " + (fourth.onabort === handlers[1]));
attempt("sloppily an heir", () => storeSloppily(Object.create(fourth), handlers[0]));
attempt("sloppily a primitive", () => storeSloppily(5, handlers[0]));
const between = Object.create(AbortSignal.prototype, { onabort: { set(value) { calls += 100; }, get() { return "between"; }, configurable: true } });
const fifth = new AbortController().signal;
for (let round = 0; round < 50; round++) storeOnabort(fifth, handlers[round & 1]);
Object.setPrototypeOf(fifth, between);
attempt("a setter in front", () => storeOnabort(fifth, handlers[0]) + " " + calls);
clearTimeout(timer);
console.log(log.join("\n"));
