// The functions of a module are called by name with one callback, and then through the namespace object: by dynamic import, by a key, as any, by Object.keys and Object.values.
import { apply, applyUntyped, useHolder, useCurrent } from "./lib.ts";
import * as star from "./lib.ts";
import fallback from "./lib.ts";
const one = (n: number) => n + 1;
const two = (n: number) => n * 2;
const three = (n: number) => n * 3;
const four = (n: number) => n * 4;
const rows: string[] = [];
rows.push("direct " + apply(one, 5) + " " + applyUntyped(one, 5));
const ns = await import("./lib.ts");
rows.push("dynamic import " + ns.apply(two, 5) + " " + ns.applyUntyped(two, 5));
const key = Date.now() > 0 ? "apply" : "applyUntyped";
rows.push("by key " + (ns as any)[key](three, 5) + " " + (star as any)[key + "Untyped"](three, 5));
const anyStar: any = star;
rows.push("the namespace as any " + anyStar.apply(four, 5) + " " + anyStar.applyUntyped(four, 5));
anyStar.holder.step = two;
rows.push("stored through the namespace " + useHolder(5));
for (const name of Object.keys(star)) if (name === "setCurrent") (star as any)[name](three);
rows.push("a setter found by its name " + useCurrent(5));
rows.push("values " + (Object.values(star).filter(v => typeof v === "function" && v.name === "apply")[0] as any)(four, 6));
rows.push("default " + fallback.run(one, 5) + " " + (ns.default as any).run(two, 5) + " " + (Object.values(ns.default)[0] as any)(three, 5));
console.log(rows.join("\n"));
