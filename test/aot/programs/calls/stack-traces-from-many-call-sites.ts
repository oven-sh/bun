function fail(site: number): number { throw new Error("site " + site); }
function probe(site: () => number): unknown { try { const result = site(); return result; } catch (error) { return error; } }

function topFrames(error: unknown): string[] {
  const list: string[] = [];
  for (const line of String((error as Error).stack).split("\n")) {
    const frame = /^\s*at (.*?) \(.*:(\d+):\d+\)$/.exec(line);
    if (frame) list.push(frame[1] + ":" + frame[2]);
    if (list.length === 3) break;
  }
  return list;
}

function report(label: string, traces: string[][]): void {
  const [inFail, inFirstSite, inProbe] = traces[0];
  const firstLine = Number(inFirstSite.split(":")[1]);
  const wrong: string[] = [];
  traces.forEach((trace, site) => {
    const expected = [inFail, "s" + site + ":" + (firstLine + site), inProbe].join(" < ");
    if (trace.join(" < ") !== expected) wrong.push(site + ": " + trace.join(" < "));
  });
  console.log(label + ": " + (traces.length - wrong.length) + " of " + traces.length + " as expected; the first is " + traces[0].join(" < "));
  for (const line of wrong.slice(0, 5)) console.log("  " + line);
}

