// A class below BigInt64Array is first touched by nothing at all: only the class below it in the text is used.
function tell(what, run) {
  try {
    console.log(what, String(run()));
  } catch (error) {
    console.log(what, "threw " + error.constructor.name);
  }
}
class Late extends BigInt64Array {
  method() {
    return "method of " + this.constructor.name;
  }
  static fixed() {
    return "static of " + this.name;
  }
}
class Used extends BigInt64Array {}
tell("the other class", () => [new Used(1) instanceof BigInt64Array, Used.name].join(" "));
