// A loop calls what a list holds. At first the list holds a host function alone, and the loop runs above the declaration of the text that the program's own callee puts into a template in every turn.
let index = 0;
let total = 0;
function callEach(callees, end) { for (;;) { if (index >= end) break; callees[index & 1](index++); } }
callEach([structuredClone, structuredClone], 20);
console.log(total);
let text = "ab";
function addLength(step) { total += `${text}!`.length; }
index = 0; callEach([addLength, addLength], 2000);
console.log(total);
text = 12;
index = 0; callEach([addLength, structuredClone], 10);
console.log(total);
