const holders = {
  object: () => ({ 0: "zero", 1: "one", 1.5: "one and a half", "-0": "minus zero text", NaN: "not a number", abc: "letters", true: "yes", null: "nothing", undefined: "missing" }),
};

function readAndDouble(holder, key) {
  return [holder[key], key * 2];
}

function readAndCompare(holder, key) {
  return [holder[key], key < 2];
}

function readAndIncrement(holder, key) {
  const found = holder[key];
  key++;
  return [found, holder[key], key];
}

function readAndNegate(holder, key) {
  return [holder[key], holder[-key]];
}

const texts = impostors.concat(["1", "'1'", "1.5", "'1.5'", "-1", "1n", "[1]", "new Number(1)"]);
for (const name of Object.keys(holders)) {
  const inArray = value => readAndDouble(holders[name](), value);
  const compared = value => readAndCompare(holders[name](), value);
  const incremented = value => readAndIncrement(holders[name](), value);
  const negated = value => readAndNegate(holders[name](), value);
  for (const [label, use] of [["double", inArray], ["compare", compared], ["increment", incremented], ["negate", negated]]) {
    if (name !== "array" && name !== "object" && label !== "double") continue;
    for (const text of texts) {
      log.length = 0;
      const result = outcome(() => use(make(text)));
      console.log(name, label, text, "->", result + (log.length ? " after " + log.join(", ") : ""));
    }
  }
}
