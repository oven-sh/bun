const lines = [];
function say(path, read) {
  let text;
  try { const first = read(); text = typeof first; if (first !== null && (text === "object" || text === "function")) text += read() === first ? " same" : " ANOTHER"; } catch (error) { text = "throws " + (error && error.constructor && error.constructor.name); }
  lines.push(path + ": " + text);
}
function names(path, read) {
  let text;
  try { text = Object.getOwnPropertyNames(read()).sort().join(); } catch (error) { text = "throws"; }
  lines.push("names of " + path + ": " + text);
}
