  ordinaryOwn.push(JSON.parse('{"a' + i + '":1,"y":2}'));
  ordinaryAbsent.push(JSON.parse('{"a' + i + '":1}'));
  compiledAbsent.push(compiled[i]());
  const extra = compiled[i](); extra["z" + i] = 1; compiledExtra.push(extra);
