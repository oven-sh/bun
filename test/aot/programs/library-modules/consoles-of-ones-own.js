// node:console: a Console over two streams of the program's own, with groups, tables, counters, assertions, dir with options, formats, and errors that go to the second stream. Then the global console on the real stdout.
import { Console } from "node:console";
import { Writable } from "node:stream";

const out = [], err = [];
const sink = into => new Writable({ write(chunk, encoding, done) { into.push(chunk.toString()); done(); } });
const own = new Console({ stdout: sink(out), stderr: sink(err), colorMode: false });
own.log("plain", 1, { a: 1 });
own.log("%s is %d years and %i, %j %o", "Ada", 36.5, 36.5, { j: 1 }, [1]);
own.info("info");
own.debug("debug");
own.error("error");
own.warn("warn %s", "formatted");
own.group("outer");
own.log("indented");
own.group();
own.log("twice\nlines");
own.groupEnd();
own.groupEnd();
own.log("back");
own.count();
own.count();
own.count("label");
own.countReset();
own.count();
own.assert(true, "not printed");
own.assert(false, "printed %s", "so");
own.assert(false);
own.dir({ a: { b: { c: { d: 1 } } } }, { depth: 0 });
own.table([{ a: 1, b: "x" }, { a: 2, c: true }]);
own.table([[1, 2], [3, 4]]);
own.table([{ a: 1, b: 2 }], ["b"]);
own.table("no table");
own.trace === undefined || own.log(typeof own.trace, typeof own.time, typeof own.timeEnd, typeof own.timeLog, typeof own.profile);
console.log(out.join(""));
console.log("--- the second stream");
console.log(err.join(""));
console.log(own instanceof Console, console instanceof Console, typeof console.Console, Object.keys(new Console(process.stdout)).includes("log"));
console.group("global");
console.table([{ n: 1 }]);
console.groupEnd();
console.log("%c styled", "color: red", "%s left alone");
