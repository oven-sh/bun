// node:fs/promises in a temporary folder: write, append, read, copy, rename, stat, list, a file handle, a link, access to a file that is not there, and removal.
import { mkdtemp, writeFile, appendFile, readFile, copyFile, rename, stat, readdir, open, symlink, readlink, realpath, access, rm, mkdir, truncate, utimes, chmod, lstat } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join, basename } from "node:path";

const folder = await mkdtemp(join(tmpdir(), "library-modules-"));
const at = name => join(folder, name);
await writeFile(at("a.txt"), "first\n");
await appendFile(at("a.txt"), "second\n");
console.log(JSON.stringify(await readFile(at("a.txt"), "utf8")), (await readFile(at("a.txt"))).length);
await copyFile(at("a.txt"), at("b.txt"));
await rename(at("b.txt"), at("c.txt"));
await mkdir(at("deep/er"), { recursive: true });
await writeFile(at("deep/er/d.txt"), new Uint8Array([104, 105]));
const info = await stat(at("c.txt"));
console.log(info.size, info.isFile(), info.isDirectory(), (await stat(at("deep"))).isDirectory());
console.log((await readdir(folder)).sort().join(), (await readdir(folder, { recursive: true })).sort().join());
console.log((await readdir(folder, { withFileTypes: true })).map(entry => entry.name + ":" + entry.isDirectory()).sort().join());
const handle = await open(at("c.txt"), "r+");
const buffer = Buffer.alloc(5);
console.log((await handle.read(buffer, 0, 5, 6)).bytesRead, buffer.toString());
await handle.write("FIRST", 0);
await handle.close();
console.log((await readFile(at("c.txt"), "utf8")).split("\n")[0]);
await symlink(at("c.txt"), at("link"));
console.log(basename(await readlink(at("link"))), basename(await realpath(at("link"))), (await lstat(at("link"))).isSymbolicLink());
await truncate(at("c.txt"), 3);
await utimes(at("c.txt"), 1, 2);
await chmod(at("c.txt"), 0o600);
const changed = await stat(at("c.txt"));
console.log(changed.size, changed.mtimeMs, (changed.mode & 0o777).toString(8));
console.log(await access(at("missing")).catch(error => [error.code, error.syscall, error.errno < 0].join()));
console.log(await readFile(at("deep")).catch(error => error.code));
await rm(folder, { recursive: true });
console.log(await stat(folder).catch(error => error.code));
