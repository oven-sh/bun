// new Intl.NumberFormat(..) reads minimumFractionDigits of what it is given; here it is the object's own.
class Item {
  constructor(size) {
    this.size = size;
  }
  double() {
    return this.size * 2;
  }
}
const log = [];
const kept = [];
const item = new Item(1.5);
const holder = {
  minimumFractionDigits: item.double(),
};
try {
  const result = new Intl.NumberFormat("en", holder).format(1.5);
  console.log(result);
} catch (error) {
  console.log("threw " + error.constructor.name + ": " + error.message);
}
console.log(log.join("\n"));
