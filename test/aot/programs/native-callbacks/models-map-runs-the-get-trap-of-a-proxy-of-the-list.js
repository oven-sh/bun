// new Map(..) runs the get trap of a proxy around the list. Nothing else in the program reaches that code.
class Item {
  constructor(size) {
    this.size = size;
  }
  double() {
    return this.size * 2;
  }
}
const item = new Item(1.5);
const log = [];
const values = [["a", 1.5], ["b", item], [item, "two"]];
const source = new Proxy(values, {
  get(target, key, receiver) {
    log.push("get " + String(key) + " " + (receiver === source) + " " + arguments.length);
    return Reflect.get(target, key, receiver);
  },
});
try {
  const result = new Map(source);
  console.log(result.size, [...result.keys()].map(key => typeof key).join(), result.get("b").double(), result.get("a") + 1);
} catch (error) {
  console.log("threw " + error.constructor.name + ": " + error.message);
}
console.log(log.join("\n"));
