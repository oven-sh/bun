const map = new Map();
map.set(-0, "zero");
for (const key of map.keys()) console.log("map key", Object.is(key, -0), 1 / key);
for (const [key] of map) console.log("map entry", Object.is(key, -0), 1 / key);
map.forEach((value, key) => console.log("map forEach", Object.is(key, -0), 1 / key));
const set = new Set();
set.add(-0);
for (const key of set) console.log("set", Object.is(key, -0), 1 / key);
set.forEach(key => console.log("set forEach", Object.is(key, -0), 1 / key));
console.log("spread", 1 / [...set][0], 1 / [...map.keys()][0]);
const born = new Set([-0]);
for (const key of born) console.log("set at birth", Object.is(key, -0), 1 / key);
const bornMap = new Map([[-0, 1]]);
for (const key of bornMap.keys()) console.log("map at birth", Object.is(key, -0), 1 / key);
const values = new Map([["a", -0]]);
values.set("b", -0);
for (const value of values.values()) console.log("map value", Object.is(value, -0), 1 / value);
values.forEach(value => console.log("map value forEach", Object.is(value, -0), 1 / value));
