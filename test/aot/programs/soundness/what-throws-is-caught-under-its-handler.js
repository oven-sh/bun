let caught = 0;
function guard(label, run) {
  let state = "before";
  try {
    state = "running";
    const value = run();
    state = "done " + typeof value;
  } catch (error) {
    caught++;
    state += ", caught " + (error instanceof Error ? error.constructor.name : typeof error);
  } finally {
    state += ", finally";
  }
  console.log(label + ": " + state);
}
