const subjects = ["", "a", "b", "ab", "ba", "aa", "aab", "xay", "xy", "xaay", "abab", "c", "aac", "bc", "z", "aaz", "ababz", "a\nb", "aXa", "aaa", "xby", "baab", "\u4e2d", "\u4e2daab", "x\u4e2dy", "aa\u4e2d"];
function sumOf(text: string, sum: number) {
  for (let i = 0; i < text.length; i++) sum = (Math.imul(sum, 31) + text.charCodeAt(i)) | 0;
  return sum;
}
