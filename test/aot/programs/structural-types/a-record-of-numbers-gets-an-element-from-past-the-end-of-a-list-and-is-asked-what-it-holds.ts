const record: Record<string, number> = { a: 1, b: 2 };
const list = [1, 2];
record.b = list[5];
console.log("keys " + Object.keys(record).join());
console.log("a " + typeof record.a + " " + (record.a + 1));
console.log("b " + typeof record.b + " " + (record.b + 1));
console.log("values " + Object.values(record).map(value => typeof value).join());
console.log("entries " + Object.entries(record).map(([key, value]) => key + " " + typeof value).join());
console.log("some " + Object.values(record).some(value => value === undefined));
console.log("filter " + Object.values(record).filter(value => typeof value !== "number").length);
let walked = "";
for (const key in record) walked += key + " " + typeof record[key] + " ";
console.log("for in " + walked);
let sum = 0;
for (const value of Object.values(record)) sum += value;
console.log("sum " + sum);
console.log("JSON " + JSON.stringify(record));
console.log("spread " + JSON.stringify({ ...record }));

