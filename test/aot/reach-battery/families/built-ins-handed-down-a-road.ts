const subjects: Record<string, [text: string, name: string | undefined, use: string]> = {
  list: ["Array", "Array", `A.from("hi").length`],
  map: ["Map", "Map", `A.groupBy([1], n => n).size`],
  "lists-prototype": ["Array.prototype", undefined, `A.flatMap.call([1], n => [n, n]).length`],
};

export default function write(folder: string) {
  for (const [subject, [text, name, use]] of Object.entries(subjects)) {
    const roads = Object.entries({ ...expressions, ...(name ? expressionsOfAClass : {}) })
      .map(([road, expression]) => [road, `SAY(${expression});`])
      .concat(Object.entries(statements));
    for (const [road, written] of roads) {
      const named = name
        ? written.replaceAll("HEAD", name.slice(0, 2)).replaceAll("TAIL", name.slice(2)).replaceAll("NAME", name)
        : written;
      const body = `function SAY(A) { console.log(${use}); }\n${named.replaceAll("X", text)}\n`;
      const head = body.includes("require(")
        ? `import { createRequire } from "node:module";\nconst require = createRequire(import.meta.url);\n`
        : "";
      writeFileSync(join(folder, `${subject}--${road}.mjs`), head + body);
    }
  }
}
