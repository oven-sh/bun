// Every way in which a function of a program gets to run, for ./what-flow-says-of-an-entered-function-holds.test.ts.
//
// A way is the statements that enter `T`. They may name `self` and `other` (two objects), `first` (a fraction), `second` (a text) and `Other` (a class).
// Where the function cannot be a plain declaration (a method, an accessor, a constructor of a class), `declare` writes it: `T` is its name and `SEEN` the
// statement that reports what it was entered with. `SEEN0` and `SEEN1` are the same for a function of no and of one parameter.
export type Way = { name: string; enter: string; declare?: string };

const callbacksWithReceiver = (list: string, methods: string[]): Way[] =>
  methods.flatMap(method => [
    { name: `${list}.${method}(T)`, enter: `${list}.${method}(T);` },
    { name: `${list}.${method}(T, self)`, enter: `${list}.${method}(T, self);` },
  ]);

