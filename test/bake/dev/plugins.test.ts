// Plugin tests concern plugins in development mode.
import { expect } from "bun:test";
import { devTest, minimalFramework } from "../bake-harness";

// Note: more in depth testing of plugins is done in test/bundler/bundler_plugin.test.ts
devTest("onResolve", {
  framework: minimalFramework,
  pluginFile: `
    import * as path from 'path';
    export default [
      {
        name: 'a',
        setup(build) {
          build.onResolve({ filter: /trigger/ }, (args) => {
            return { path: path.join(import.meta.dirname, '/file.ts') };
          });
        },
      }
    ];
  `,
  files: {
    "file.ts": `
      export const value = 1;
    `,
    "routes/index.ts": `
      import { value } from 'trigger';

      export default function (req, meta) {
        return new Response('value: ' + value);
      }
    `,
  },
  async test(dev) {
    await dev.fetch("/").equals("value: 1");
  },
});
devTest("onLoad", {
  framework: minimalFramework,
  pluginFile: `
    import * as path from 'path';
    export default [
      {
        name: 'a',
        setup(build) {
          build.onLoad({ filter: /trigger/ }, (args) => {
            return { contents: 'export const value = 1;', loader: 'ts' };
          });
        },
      }
    ];
  `,
  files: {
    "trigger.ts": `
      throw new Error('should not be loaded');
    `,
    "routes/index.ts": `
      import { value } from '../trigger.ts';

      export default function (req, meta) {
        return new Response('value: ' + value);
      }
    `,
  },
  async test(dev) {
    await dev.fetch("/").equals("value: 1");
    await dev.fetch("/").equals("value: 1");
    await dev.fetch("/").equals("value: 1");
  },
});
devTest("onResolve + onLoad virtual file", {
  framework: minimalFramework,
  pluginFile: `
    import * as path from 'path';
    export default [
      {
        name: 'a',
        setup(build) {
          build.onResolve({ filter: /^trigger$/ }, (args) => {
            return { path: "hello.ts", namespace: "virtual" };
          });
          build.onLoad({ filter: /.*/, namespace: "virtual" }, (args) => {
            return { contents: 'export default ' + JSON.stringify(args) + ';', loader: 'ts' };
          });
        },
      }
    ];
  `,
  files: {
    // this file must not collide with the virtual file
    "hello.ts": `
      export default "file-on-disk";
    `,
    "routes/index.ts": `
      import disk from '../hello';
      import virtual from 'trigger';

      export default function (req, meta) {
        return Response.json([virtual, disk]);
      }
    `,
  },
  async test(dev) {
    await dev.fetch("/").equals([
      {
        path: "hello.ts",
        namespace: "virtual",
        loader: "ts",
        side: "server",
      },
      "file-on-disk",
    ]);
  },
});
// The plugin reads the file itself, and this one saves the file right after its
// first read. The dev server has to watch the file before it calls the plugin.
// If it does not, the save raises no event and the first bundle stays.
devTest("onLoad bundles again when the file is saved while the plugin reads it", {
  framework: minimalFramework,
  pluginFile: `
    import * as fs from 'fs';
    export default [
      {
        name: 'a',
        setup(build) {
          build.onLoad({ filter: /data.value\\.ts$/ }, (args) => {
            const contents = fs.readFileSync(args.path, 'utf8');
            if (contents.includes('= 1;')) fs.writeFileSync(args.path, contents.replace('= 1;', '= 2;'));
            return { contents, loader: 'ts' };
          });
        },
      }
    ];
  `,
  files: {
    "data/value.ts": `
      export const value = 1;
    `,
    "routes/index.ts": `
      import { value } from '../data/value.ts';

      export default function (req, meta) {
        return new Response('value: ' + value);
      }
    `,
  },
  async test(dev) {
    // The first bundle has what the plugin read. A later one has the save.
    const deadline = Date.now() + 30_000;
    let text = await dev.fetch("/").text();
    while (text !== "value: 2" && Date.now() < deadline) {
      await Bun.sleep(10);
      text = await dev.fetch("/").text();
    }
    expect(text).toBe("value: 2");
  },
});
