// With `separateSSRGraph`, the server graph never sees a "use client" module
// itself. The bundler generates a "client reference proxy" for it instead
// (src/bundler/ServerComponentParseTask.rs): a module with the same export
// names, each bound to `registerClientReference(thrower, file, name)`.
import { expect, test } from "bun:test";
import { existsSync } from "node:fs";
import { join } from "node:path";
import { bunEnv, bunExe, isASAN, isWindows } from "harness";
import { devTest, minimalFramework, tempDirWithBakeDeps } from "../bake-harness";

const separateSsrGraphFramework = {
  ...minimalFramework,
  serverComponents: {
    ...minimalFramework.serverComponents!,
    separateSSRGraph: true,
  },
};

const cannotCallClientFunction =
  "It's not possible to invoke a client function from the server, it can only be rendered as a Component or passed to props of a Client Component.";

function clientReference(file: string, name: string) {
  return {
    file,
    uid: name,
    thrown:
      name === "default"
        ? `Attempted to call the default export of ${file} from the server, but it's on the client. ${cannotCallClientFunction}`
        : `Attempted to call ${name}() from the server but ${name} is on the client. ${cannotCallClientFunction}`,
  };
}

devTest('the server graph imports a client reference proxy for a "use client" module', {
  framework: separateSsrGraphFramework,
  files: {
    "components/Widget.ts": `
      "use client";
      export function Widget() { return "widget"; }
      export const helperValue = 1;
      export default function DefaultWidget() { return "default"; }
    `,
    // minimal.server.ts's registerClientReference returns { value, file, uid }.
    "routes/index.ts": `
      import * as widget from "../components/Widget";
      export default function () {
        const references = {};
        for (const name of Object.keys(widget).sort()) {
          const { value, file, uid } = widget[name];
          let thrown;
          try {
            value();
          } catch (error) {
            thrown = error.message;
          }
          references[name] = { file, uid, thrown };
        }
        return Response.json(references);
      }
    `,
  },
  async test(dev) {
    const file = "components/Widget.ts";
    expect(await dev.fetch("/").json()).toEqual({
      Widget: clientReference(file, "Widget"),
      default: clientReference(file, "default"),
      helperValue: clientReference(file, "helperValue"),
    });

    // Every rebuild generates a fresh proxy from the module's current exports.
    await dev.write(
      file,
      `
        "use client";
        export const renamedValue = 2;
      `,
    );
    expect(await dev.fetch("/").json()).toEqual({
      renamedValue: clientReference(file, "renamedValue"),
    });
  },
});

// The proxy for each boundary is generated by a heap-allocated task that the
// bundler used to schedule and never free. `bun build --app` tears its worker
// pool down before exiting, so LeakSanitizer reports those tasks at exit; the
// dev server keeps the process-wide pool alive, whose idle threads still hold
// stale pointers to the tasks, so this is only observable in a production
// build. Other exit-time leaks of the production build (its transpilers are
// never dropped) keep the exit code non-zero either way, so the assertion is
// scoped to the allocation site of the task.
test.skipIf(!isASAN || isWindows)(
  "client reference proxy tasks are freed once the boundary has been generated",
  async () => {
    const clientComponents = ["Alpha", "Beta", "Gamma", "Delta"];
    const dir = await tempDirWithBakeDeps("bake-server-components-task-leak", {
      "src/index.tsx": `export default { app: { framework: "react" } };`,
      "pages/index.tsx": [
        ...clientComponents.map(name => `import { ${name} } from "../components/${name}";`),
        `export default function IndexPage() {`,
        `  return <div>${clientComponents.map(name => `<${name} />`).join("")}</div>;`,
        `}`,
      ].join("\n"),
      ...Object.fromEntries(
        clientComponents.map(name => [
          `components/${name}.tsx`,
          `"use client";\nexport function ${name}() { return <b>${name}</b>; }`,
        ]),
      ),
    });

    await using proc = Bun.spawn({
      cmd: [bunExe(), "build", "--app", "./src/index.tsx"],
      cwd: dir,
      env: {
        ...bunEnv,
        // Set outright rather than appended to bunEnv.ASAN_OPTIONS so the
        // child's sanitizer behaviour does not depend on what the outer runner
        // configured (e.g. abort_on_error=1 for the unrelated leaks above).
        ASAN_OPTIONS: "allow_user_segv_handler=1:disable_coredump=0:detect_leaks=1",
        LSAN_OPTIONS: `print_suppressions=0:suppressions=${join(import.meta.dir, "../../leaksan.supp")}`,
      },
      stdout: "pipe",
      stderr: "pipe",
    });
    const [stderr] = await Promise.all([proc.stderr.text(), proc.stdout.text(), proc.exited]);

    // The build has to have gone through the client boundaries for the leak
    // assertion to mean anything: a page with client components loads a script.
    const htmlPath = join(dir, "dist", "index.html");
    expect(existsSync(htmlPath)).toBe(true);
    expect(await Bun.file(htmlPath).text()).toContain('<script type="module"');

    const taskLeakFrames = stderr
      .split("\n")
      .filter(
        line => line.includes("enqueue_server_component_generated_file") || line.includes("ServerComponentParseTask"),
      );
    expect(taskLeakFrames).toEqual([]);
  },
  // Symbolizing a LeakSanitizer report loads the binary's full DWARF, which
  // takes several seconds on top of the React build itself.
  60_000,
);
