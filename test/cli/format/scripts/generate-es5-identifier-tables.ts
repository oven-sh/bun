// Generates src/format/js/utils/es5_identifier_tables.rs from the package that Prettier asks whether the quotes of a key can go,
// and from Bun's own tables of identifiers: only where the two differ is written down.
//
//   cd <a directory with is-es5-identifier-name installed, in the version of Prettier's package.json>
//   bun <this file> > src/format/js/utils/es5_identifier_tables.rs
import { readFileSync } from "node:fs";
import { createRequire } from "node:module";
import { join } from "node:path";
import { pathToFileURL } from "node:url";

const require = createRequire(pathToFileURL(process.cwd() + "/"));
const isEs5IdentifierName = (await import(pathToFileURL(require.resolve("is-es5-identifier-name")).href)).default;

// `is_id_start_es_next` and `is_id_continue_es_next` of src/bun_core/string/identifier.rs.
const identifier = readFileSync(join(import.meta.dir, "../../../../src/bun_core/string/identifier.rs"), "utf8");
function tableOfBun(module: string): (unit: number) => boolean {
  const body = identifier.slice(identifier.indexOf(`mod ${module} {`));
  const numbers = (name: string) => {
    const start = body.indexOf("= &[", body.indexOf(`static ${name}:`));
    return body.slice(start + 4, body.indexOf("];", start)).match(/\d+/g)!;
  };
  const stage1 = numbers("STAGE1").map(Number);
  const stage2 = numbers("STAGE2").map(BigInt);
  return unit => {
    const bit = stage1[unit >> 8] + (unit & 0xff);
    return ((stage2[bit >> 6] >> BigInt(bit & 63)) & 1n) === 1n;
  };
}
const isStartForBun = tableOfBun("id_start_es_next");
const isContinueForBun = tableOfBun("id_continue_es_next");
// `bun_core::lexer::is_type_script_identifier_part`
const isPartForBun = (unit: number) => isContinueForBun(unit) || unit === 0x30fb || unit === 0xff65;

function ranges(test: (unit: number) => boolean): [number, number][] {
  const result: [number, number][] = [];
  for (let unit = 0x80; unit <= 0xffff; unit++) {
    if (!test(unit)) continue;
    const last = result.at(-1);
    if (last && last[1] === unit - 1) last[1] = unit;
    else result.push([unit, unit]);
  }
  return result;
}

const isStart = (unit: number) => isEs5IdentifierName(String.fromCharCode(unit));
const isPart = (unit: number) => isEs5IdentifierName("a" + String.fromCharCode(unit));
const tables: [string, string, [number, number][]][] = [
  ["START_LESS", "What a name can start with for Bun and not for the package.", ranges(it => isStartForBun(it) && !isStart(it))],
  ["START_MORE", "What a name can start with for the package and not for Bun.", ranges(it => !isStartForBun(it) && isStart(it))],
  ["PART_LESS", "What can be in a name after its first character for Bun and not for the package.", ranges(it => isPartForBun(it) && !isPart(it))],
  ["PART_MORE", "What can be in a name after its first character for the package and not for Bun.", ranges(it => !isPartForBun(it) && isPart(it))],
];

let out = `//! Generated by test/cli/format/scripts/generate-es5-identifier-tables.ts. Where the package \`is-es5-identifier-name\` and\n//! \`bun_core::lexer::is_identifier_start\` / \`is_type_script_identifier_part\` differ, from U+0080 to U+FFFF, as sorted,\n//! inclusive ranges. The package takes nothing outside of the BMP.\n`;
for (const [name, doc, table] of tables) {
  out += `\n/// ${doc}\npub(super) const ${name}: &[(u16, u16)] = &[\n`;
  for (const [start, end] of table) out += `    (0x${start.toString(16).toUpperCase()}, 0x${end.toString(16).toUpperCase()}),\n`;
  out += `];\n`;
}
process.stdout.write(out);
