// Generates src/format/js/utils/es5_identifier_tables.rs from the package that Prettier asks whether the quotes of a key can go.
//
//   cd <a directory with is-es5-identifier-name installed, in the version of Prettier's package.json>
//   bun <this file> > src/format/js/utils/es5_identifier_tables.rs
import { createRequire } from "node:module";
import { pathToFileURL } from "node:url";

const require = createRequire(pathToFileURL(process.cwd() + "/"));
const isEs5IdentifierName = (await import(pathToFileURL(require.resolve("is-es5-identifier-name")).href)).default;

function ranges(test: (character: string) => boolean): [number, number][] {
  const result: [number, number][] = [];
  for (let unit = 0x80; unit <= 0xffff; unit++) {
    if (!test(String.fromCharCode(unit))) continue;
    const last = result.at(-1);
    if (last && last[1] === unit - 1) last[1] = unit;
    else result.push([unit, unit]);
  }
  return result;
}

const tables: [string, string, [number, number][]][] = [
  ["START", "What a name can start with.", ranges(character => isEs5IdentifierName(character))],
  ["PART", "What can be in a name after its first character.", ranges(character => isEs5IdentifierName("a" + character))],
];

let out = `//! Generated by test/cli/format/scripts/generate-es5-identifier-tables.ts. Sorted, inclusive ranges of the characters above\n//! U+007F that the package \`is-es5-identifier-name\` takes. None is outside of the BMP.\n`;
for (const [name, doc, table] of tables) {
  out += `\n/// ${doc}\npub(super) const ${name}: &[(u16, u16)] = &[\n`;
  for (const [start, end] of table) out += `    (0x${start.toString(16).toUpperCase()}, 0x${end.toString(16).toUpperCase()}),\n`;
  out += `];\n`;
}
process.stdout.write(out);
