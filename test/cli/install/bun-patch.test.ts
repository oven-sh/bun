// A bundled dependency ships inside the tarball of the package that bundles it, and bun does not
// install it on its own:
// - bundled-1@1.0.0 bundles no-deps@1.0.0.
// - bundled-file@1.0.0 bundles "bundled-file-dep": "file:vendor/bundled-file-dep".
// - npm-1@10.9.2 bundles depend-on-debug-1@1.0.0, which depends on debug-1@4.4.0. Its tarball
//   ships both in its node_modules.
// The lockfile still resolves the dependency to the registry's package of that name, and
// `bun patch` used to delete the bundled copy and copy the registry's package in its place.
describe.concurrent("a bundled dependency as the target", () => {
  const refusal = (name: string) =>
    `error: refusing to patch bundled dependency "${name}"\n` +
    "note: patch the package that bundles it, and edit it in that package's node_modules\n";

  // A file that only the bundled copy has shows whether `bun patch` replaced the folder.
  async function markBundledCopy(dir: string, bundledCopy: string) {
    expect(existsSync(join(dir, bundledCopy, "package.json"))).toBe(true);
    const marker = Bun.file(join(dir, bundledCopy, "only-in-the-bundled-copy.txt"));
    await Bun.write(marker, "bundled");
    return marker;
  }

  test.each([
    ["bundled-1", "1.0.0", "no-deps", ["no-deps"]],
    ["bundled-1", "1.0.0", "no-deps", ["no-deps@1.0.0"]],
    ["bundled-1", "1.0.0", "no-deps", ["node_modules/bundled-1/node_modules/no-deps"]],
    ["bundled-1", "1.0.0", "no-deps", ["--commit", "no-deps"]],
    ["bundled-1", "1.0.0", "no-deps", ["--commit", "node_modules/bundled-1/node_modules/no-deps"]],
    // It's also a file: folder. Only one message is printed, and it's this one.
    ["bundled-file", "1.0.0", "bundled-file-dep", ["bundled-file-dep"]],
    ["bundled-file", "1.0.0", "bundled-file-dep", ["node_modules/bundled-file/node_modules/bundled-file-dep"]],
    // A dependency of a bundled dependency.
    ["npm-1", "10.9.2", "debug-1", ["debug-1"]],
    ["npm-1", "10.9.2", "debug-1", ["node_modules/npm-1/node_modules/debug-1"]],
  ])("%s@%s bundles %s: bun patch %j is refused", async (bundler, version, name, args) => {
    await using project = await installedProject({ dependencies: { [bundler]: version } });
    const { dir, env } = project;
    const marker = await markBundledCopy(dir, `node_modules/${bundler}/node_modules/${name}`);

    const arg = args.at(-1)!;
    await expectRefused(dir, env, refusal(arg.startsWith("node_modules") ? name : arg), ...args);
    expect(await marker.exists()).toBe(true);
  });

  // These pass without the fix. They fail if the refusal is too wide.
  test("bun patch no-deps patches the copy that bun installed when no-deps is bundled as well", async () => {
    await using project = await installedProject({ dependencies: { "bundled-1": "1.0.0", "no-deps": "1.0.0" } });
    const { dir, env } = project;
    const marker = await markBundledCopy(dir, "node_modules/bundled-1/node_modules/no-deps");
    await expectPrepared(dir, env, "no-deps", "no-deps", "node_modules/no-deps");
    expect(await marker.exists()).toBe(true);
  });

  test("bun patch still patches a regular dependency of a package that bundles", async () => {
    await using project = await installedProject(bundledAndNested);
    const { dir, env } = project;
    await expectPrepared(dir, env, "one-dep@1.0.0", "one-dep", "node_modules/bundled-transitive/node_modules/one-dep");
  });

  // The only dependency with the name is bundled, so the name selects the alias of the package.
  test("bun patch no-deps selects an alias of no-deps, not the bundled copy", async () => {
    await using project = await installedProject({
      dependencies: { "bundled-1": "1.0.0", "my-alias": "npm:no-deps@1.0.0" },
    });
    const { dir, env } = project;
    const marker = await markBundledCopy(dir, "node_modules/bundled-1/node_modules/no-deps");
    await expectPrepared(dir, env, "no-deps", "no-deps", "node_modules/my-alias");
    expect(await marker.exists()).toBe(true);
  });
});

// ships-no-deps@1.0.0 declares no dependencies, but its tarball ships a copy of no-deps@1.0.0
