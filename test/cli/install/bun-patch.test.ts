// With the isolated linker `node_modules/<pkg>` is a link into `node_modules/.bun`, and the
// dependencies of <pkg> are links next to its folder there. `bun patch <pkg>` used to swap the
// project's link for a copy in a real directory, which cannot reach them, and no install put the
// link back. The copy to edit is made in the store entry, so the link never changes.
describe.concurrent("isolated linker: a package that the project links", () => {
  const dependencies = { "has-bin-entries": "1.0.0", "a-dep": "1.0.1" };
  const folder = "node_modules/has-bin-entries";

  // index.js of has-bin-entries requires each dependency of the package, and "no-deps" is one.
  const addPatchedExport = async (dir: string) =>
    Bun.write(
      join(dir, folder, "index.js"),
      (await Bun.file(join(dir, folder, "index.js")).text()) + "\nmodule.exports.patched = true;\n",
    );
  const load = (cwd: string, env: Env) =>
    bunOk(
      cwd,
      env,
      "-e",
      `const pkg = require("has-bin-entries"); console.log(pkg.version, pkg.patched, pkg.dependencies["no-deps"].version);`,
    );

  test.each(["has-bin-entries", folder])("bun patch and --commit %s keep the link", async arg => {
    await using project = await installedProject({ dependencies }, { linker: "isolated" });
    const { dir, env } = project;
    const entries = await readdirSorted(join(dir, "node_modules"));
    expect(entries).toEqual([".bin", ".bun", "a-dep", "has-bin-entries"]);
    const links = () => [kind(dir, folder), kind(dir, "node_modules", "a-dep")];

    await expectPrepared(dir, env, arg, "has-bin-entries", folder);
    await expectPrepared(dir, env, "a-dep", "a-dep", "node_modules/a-dep");
    expect(links()).toEqual(["link", "link"]);
    expect(lstatSync(join(dir, folder, "index.js")).nlink).toBe(1);

    // The package loads its dependencies while it is being edited.
    await addPatchedExport(dir);
    await Bun.write(join(dir, "node_modules", "a-dep", "edit.js"), "module.exports = 'in progress';\n");
    expect(await load(dir, env)).toBe("1.0.0 true 1.0.0\n");

    // An install in between keeps the edits.
    await bunOk(dir, env, "install");
    expect(await load(dir, env)).toBe("1.0.0 true 1.0.0\n");

    await bunOk(dir, env, "patch", "--commit", arg);
    expect({
      links: links(),
      // The edits to a-dep are not committed, and the install of this commit leaves them.
      edit: await Bun.file(join(dir, "node_modules", "a-dep", "edit.js")).text(),
      entries: await readdirSorted(join(dir, "node_modules")),
    }).toEqual({ links: ["link", "link"], edit: "module.exports = 'in progress';\n", entries });
    expect(await load(dir, env)).toBe("1.0.0 true 1.0.0\n");
    // bin-with-require.js requires "no-deps" as well.
    expect(await bunOk(dir, env, "run", "has-bin-entries-with-require")).toBe("no-deps\n1.0.0\n");

    // Another commit finds the same changes.
    const patchFile = Bun.file(join(dir, "patches", "has-bin-entries@1.0.0.patch"));
    const patch = await patchFile.text();
    await bunOk(dir, env, "patch", "--commit", arg);
    expect(await patchFile.text()).toBe(patch);
    expect(links()).toEqual(["link", "link"]);
  });

  // git reads a link operand as a file, and the patch used to be `new file mode 120000`.
  test.each([
    ["without bun patch", false],
    ["after bun patch, without edits", true],
  ])("--commit %s finds no changes", async (_, prepare) => {
    await using project = await installedProject({ dependencies }, { linker: "isolated" });
    const { dir, env } = project;
    const packageJson = await Bun.file(join(dir, "package.json")).json();
    if (prepare) await expectPrepared(dir, env, "has-bin-entries", "has-bin-entries", folder);

    for (const arg of ["has-bin-entries", folder]) {
      expect(await bunOk(dir, env, "patch", "--commit", arg)).toContain("No changes detected");
    }
    expect({
      link: kind(dir, folder),
      patches: existsSync(join(dir, "patches")),
      packageJson: await Bun.file(join(dir, "package.json")).json(),
    }).toEqual({ link: "link", patches: false, packageJson });
    expect(await load(dir, env)).toBe("1.0.0 undefined 1.0.0\n");
  });

  // The postinstall script of a workspace package runs in every install, this one included.
  test("the scripts of a workspace package see the patched dependency", async () => {
    await using project = await installedProject(
      { workspaces: ["packages/*"], dependencies: { "has-bin-entries": "2.0.0", w: "workspace:*" } },
      {
        linker: "isolated",
        files: {
          "packages/w/package.json": JSON.stringify({
            name: "w",
            version: "1.0.0",
            dependencies: { "has-bin-entries": "1.0.0" },
            scripts: { postinstall: `${bunExe()} postinstall.js` },
          }),
          "packages/w/postinstall.js": `require("fs").writeFileSync("postinstall.txt", String(require("has-bin-entries").patched));`,
        },
      },
    );
    const { dir, env } = project;
    const postinstall = Bun.file(join(dir, "packages", "w", "postinstall.txt"));
    expect(await postinstall.text()).toBe("undefined");

    // `node_modules/w` is a link to packages/w, so this is packages/w/node_modules/has-bin-entries.
    const nested = "node_modules/w/node_modules/has-bin-entries";
    await expectPrepared(dir, env, "has-bin-entries@1.0.0", "has-bin-entries", nested);
    const index = join(dir, nested, "index.js");
    await Bun.write(index, (await Bun.file(index).text()) + "\nmodule.exports.patched = true;\n");
    await bunOk(dir, env, "patch", "--commit", nested);

    expect([kind(dir, "node_modules", "w"), kind(dir, "packages", "w", "node_modules", "has-bin-entries")]).toEqual([
      "link",
      "link",
    ]);
    expect(await postinstall.text()).toBe("true");
    expect(await load(join(dir, "packages", "w"), env)).toBe("1.0.0 true 1.0.0\n");
  });

  // A patch that adds a symlink does not apply (`bad_file_mode`). Windows is skipped: git records
  // a symlink as mode 120000 only with `core.symlinks`, which is off there by default.
  test.skipIf(isWindows)("the edits are kept when the patch doesn't apply", async () => {
    await using project = await installedProject({ dependencies }, { linker: "isolated" });
    const { dir, env } = project;
    await expectPrepared(dir, env, "has-bin-entries", "has-bin-entries", folder);
    symlinkSync("index.js", join(dir, folder, "link.js"));

    const commit = await runBun(dir, env, "patch", "--commit", "has-bin-entries");
    expect(commit.stderr).toContain("error: failed to parse patchfile: ");
    expect({ link: kind(dir, folder), edit: kind(dir, folder, "link.js") }).toEqual({ link: "link", edit: "link" });
    expect(commit.exitCode).toBe(1);
  });
});

// The isolated linker links a package only into the packages that depend on it. A package that
// the root does not depend on has nothing at its hoisted path (`node_modules/<name>`,
// `node_modules/<dependent>/node_modules/<name>`), so `bun patch <name>` names its store folder.
// It used to create the hoisted path as a real directory that no install removed.
describe.concurrent("isolated linker: a package with no folder at its hoisted path", () => {
  async function patch(dir: string, env: Env, arg: string, name: string, folder: string) {
    await expectPrepared(dir, env, arg, name, folder);
    expect(kind(dir, folder)).toBe("directory");
  }

  test("a transitive dependency", async () => {
    await using project = await installedProject(
      { dependencies: { "one-fixed-dep": "1.0.0" } },
      { linker: "isolated" },
    );
    const { dir, env } = project;

    const folder = storeFolder("no-deps@1.0.0", "no-deps");
    await patch(dir, env, "no-deps", "no-deps", folder);
    expect(kind(dir, "node_modules", "no-deps")).toBe("missing");

    await Bun.write(join(dir, folder, "index.js"), patched);
    // The dependent links to the store folder, so it loads the edit before the commit.
    const loadDependency = "console.log(require('one-fixed-dep').dependencies['no-deps'])";
    expect(await bunOk(dir, env, "-e", loadDependency)).toBe("patched\n");

    await bunOk(dir, env, "patch", "--commit", "no-deps");

    expect(await Bun.file(join(dir, "patches", "no-deps@1.0.0.patch")).text()).toContain(
      "+module.exports = 'patched';",
    );
    expect((await Bun.file(join(dir, "package.json")).json()).patchedDependencies).toEqual({
      "no-deps@1.0.0": "patches/no-deps@1.0.0.patch",
    });
    expect({
      hoistedPath: kind(dir, "node_modules", "no-deps"),
      dependentLink: kind(dir, storeFolder("one-fixed-dep@1.0.0", "no-deps")),
      store: await Bun.file(join(dir, folder, "index.js")).text(),
    }).toEqual({ hoistedPath: "missing", dependentLink: "link", store: patched });
    expect(await bunOk(dir, env, "-e", loadDependency)).toBe("patched\n");
  });

  test("a dependency of a workspace that the root does not depend on", async () => {
    await using project = await installedProject(
      { workspaces: ["packages/*"], dependencies: { "no-deps": "2.0.0" } },
      {
        linker: "isolated",
        files: {
          "packages/w/package.json": JSON.stringify({
            name: "w",
            version: "1.0.0",
            dependencies: { "no-deps": "1.0.0" },
          }),
          "packages/w/index.js": "module.exports = require('no-deps');\n",
        },
      },
    );
    const { dir, env } = project;

    // The hoisted tree puts this copy at `node_modules/w/node_modules/no-deps`.
    const folder = storeFolder("no-deps@1.0.0", "no-deps");
    await patch(dir, env, "no-deps@1.0.0", "no-deps", folder);
    await Bun.write(join(dir, folder, "index.js"), patched);
    await bunOk(dir, env, "patch", "--commit", folder);

    expect({
      hoistedPath: kind(dir, "node_modules", "w"),
      workspaceLink: kind(dir, "packages", "w", "node_modules", "no-deps"),
      workspaceCopy: await Bun.file(join(dir, "packages", "w", "node_modules", "no-deps", "index.js")).text(),
    }).toEqual({ hoistedPath: "missing", workspaceLink: "link", workspaceCopy: patched });

    // A directory left at `node_modules/w` kept the install from linking the workspace there.
    const root = await Bun.file(join(dir, "package.json")).json();
    root.dependencies.w = "workspace:*";
    await Bun.write(join(dir, "package.json"), JSON.stringify(root));
    await bunOk(dir, env, "install");
    expect(kind(dir, "node_modules", "w")).toBe("link");
    expect(await bunOk(dir, env, "-e", "console.log(require('w'))")).toBe("patched\n");
  });

  test("a dependency that the hoisted tree nests under its dependent", async () => {
    await using project = await installedProject(
      { dependencies: { "one-fixed-dep": "1.0.0", "no-deps": "2.0.0" } },
      { linker: "isolated" },
    );
    const { dir, env } = project;

    // The hoisted tree puts this copy at `node_modules/one-fixed-dep/node_modules/no-deps`.
    // `node_modules/one-fixed-dep` is a link, so that path is inside the store entry of the dependent.
    const folder = storeFolder("no-deps@1.0.0", "no-deps");
    const nestedInDependent = join(storeFolder("one-fixed-dep@1.0.0", "one-fixed-dep"), "node_modules");
    // The second run finds what the first one left behind.
    for (const run of [1, 2]) {
      await patch(dir, env, "no-deps@1.0.0", "no-deps", folder);
      expect({ run, nested: kind(dir, nestedInDependent), link: kind(dir, "node_modules", "one-fixed-dep") }).toEqual({
        run,
        nested: "missing",
        link: "link",
      });
    }

    await Bun.write(join(dir, folder, "index.js"), patched);
    await bunOk(dir, env, "patch", "--commit", "no-deps@1.0.0");

    expect(kind(dir, nestedInDependent)).toBe("missing");
    const load = "console.log(require('one-fixed-dep').dependencies['no-deps'], require('no-deps').version)";
    expect(await bunOk(dir, env, "-e", load)).toBe("patched 2.0.0\n");
  });

  // `peer-deps@1.0.0` has the peer dependency `no-deps`. Each workspace resolves it to another
  // version, so the package has one store entry for each workspace.
  const peerVersions = ["1.0.0", "2.0.0"];

  async function installPeerVariants() {
    const project = await installedProject(
      { workspaces: ["packages/*"] },
      {
        linker: "isolated",
        files: {
          ...Object.fromEntries(
            peerVersions.map(version => [
              `packages/pkg-${version}/package.json`,
              JSON.stringify({
                name: `pkg-${version}`,
                version: "1.0.0",
                dependencies: { "peer-deps": "1.0.0", "no-deps": version },
              }),
            ]),
          ),
          // This workspace reaches `peer-deps` only through the workspace `pkg-2.0.0`.
          "packages/consumer/package.json": JSON.stringify({
            name: "consumer",
            version: "1.0.0",
            dependencies: { "pkg-2.0.0": "workspace:*" },
          }),
        },
      },
    );
    const entries = readdirSync(join(project.dir, "node_modules", ".bun")).filter(entry =>
      entry.startsWith("peer-deps@1.0.0+"),
    );
    expect(entries).toHaveLength(peerVersions.length);
    return { project, entries };
  }

  const suggestedFolder = (stdout: string) => stdout.match(/bun patch --commit '([^']+)'/)![1];
  const storeEntry = (path: string) => path.split(/[\\/]/).at(path.split(/[\\/]/).lastIndexOf(".bun") + 1);
  const linkedEntry = (dir: string, version: string) =>
    storeEntry(readlinkSync(join(dir, "packages", `pkg-${version}`, "node_modules", "peer-deps")));

  test("a package with one store entry for each peer resolution", async () => {
    const { project, entries } = await installPeerVariants();
    await using _ = project;
    const { dir, env } = project;

    const folder = suggestedFolder(await bunOk(dir, env, "patch", "peer-deps"));
    expect(entries.map(entry => storeFolder(entry, "peer-deps"))).toContain(folder);

    await Bun.write(join(dir, folder, "index.js"), patched);
    await bunOk(dir, env, "patch", "--commit", "peer-deps");

    expect(kind(dir, "node_modules", "peer-deps")).toBe("missing");
    for (const entry of entries) {
      expect(await Bun.file(join(dir, storeFolder(entry, "peer-deps"), "index.js")).text()).toBe(patched);
    }
  });

  // In a workspace, `bun patch` prepares the entry that this workspace links. The edits are then
  // behind `node_modules/peer-deps` of the workspace, for its code and for `--commit` with that path.
  test.each(peerVersions)("the store entry that the workspace pkg-%s links", async version => {
    const { project } = await installPeerVariants();
    await using _ = project;
    const { dir, env } = project;
    const workspace = join(dir, "packages", `pkg-${version}`);

    const folder = suggestedFolder(await bunOk(workspace, env, "patch", "peer-deps"));
    expect(storeEntry(folder)).toBe(linkedEntry(dir, version));

    await Bun.write(join(workspace, "node_modules", "peer-deps", "index.js"), patched);
    await bunOk(workspace, env, "patch", "--commit", "node_modules/peer-deps");

    expect(await Bun.file(join(dir, "patches", "peer-deps@1.0.0.patch")).text()).toContain(
      "+module.exports = 'patched';",
    );
  });

  test("the store entry that a workspace loads through another workspace", async () => {
    const { project } = await installPeerVariants();
    await using _ = project;
    const consumer = join(project.dir, "packages", "consumer");

    const folder = suggestedFolder(await bunOk(consumer, project.env, "patch", "peer-deps"));
    expect(storeEntry(folder)).toBe(linkedEntry(project.dir, "2.0.0"));
  });

  // `--commit <name>` names the entry that the current directory loads. When `bun patch` ran in
  // another directory, that entry has no changes, and the output lists the other folders.
  test("--commit <name> in another directory lists the folder that bun patch prepared", async () => {
    const { project } = await installPeerVariants();
    await using _ = project;
    const { dir, env } = project;
    const fromRoot = suggestedFolder(await bunOk(dir, env, "patch", "peer-deps"));
    const version = peerVersions.find(version => linkedEntry(dir, version) !== storeEntry(fromRoot))!;
    const workspace = join(dir, "packages", `pkg-${version}`);

    const prepared = suggestedFolder(await bunOk(workspace, env, "patch", "peer-deps"));
    await Bun.write(join(prepared, "index.js"), patched);

    const stdout = await bunOk(dir, env, "patch", "--commit", "peer-deps");
    expect(stdout).toContain("No changes detected");
    expect(stdout).toContain(`bun patch --commit '${storeFolder(storeEntry(prepared)!, "peer-deps")}'`);

    await bunOk(dir, env, "patch", "--commit", prepared);
    expect(await Bun.file(join(dir, "patches", "peer-deps@1.0.0.patch")).text()).toContain(
      "+module.exports = 'patched';",
    );
  });
});

