type Env = Record<string, string | undefined>;

/**
 * The env for bun processes in a project: resolve from the local registry and install through
 * `cache` (by default a cache inside the project). CI exports one BUN_INSTALL_CACHE_DIR for the
 * whole file, so the env has to set it for concurrent projects to have separate caches.
 */
function projectEnv(dir: string, cache = join(dir, ".bun-cache")): Env {
  return { ...bunEnv, NPM_CONFIG_REGISTRY: registry.registryUrl(), BUN_INSTALL_CACHE_DIR: cache };
}

async function runBun(cwd: string, env: Env, ...args: string[]) {
  await using proc = Bun.spawn({ cmd: [bunExe(), ...args], cwd, env, stdout: "pipe", stderr: "pipe" });
  const [stdout, stderr, exitCode] = await Promise.all([proc.stdout.text(), proc.stderr.text(), proc.exited]);
  return { stdout, stderr, exitCode };
}

/** Runs bun, asserts that it succeeded, and returns its stdout. */
async function bunOk(cwd: string, env: Env, ...args: string[]) {
  const { stdout, stderr, exitCode } = await runBun(cwd, env, ...args);
  expect(stderr).not.toContain("error");
  expect(exitCode, stderr).toBe(0);
  return stdout;
}

/** What `bun patch` prints once it has prepared `folder` for editing. */
function patchMessage(name: string, folder: string) {
  return `To patch ${name}, edit the following folder:\n\n  ${folder}\n\nOnce you're done with your changes, run:\n\n  bun patch --commit '${folder}'`;
}

/** Inserts `line` before the `return` of a stand-in's index.js. */
async function addLineBeforeReturn(indexJs: string, line: string) {
  const source = await Bun.file(indexJs).text();
  expect(source).toContain("\n  return ");
  await Bun.write(indexJs, source.replace("\n  return ", `\n  ${line}\n  return `));
}

type Linker = "hoisted" | "isolated";

/** A project whose bunfig.toml names the linker, with its dependencies installed. */
async function installedProject(
  packageJson: Record<string, unknown>,
  {
    linker = "hoisted",
    globalStore = false,
    files = {},
  }: { linker?: Linker; globalStore?: boolean; files?: DirectoryTree } = {},
) {
  const tmp = tempDir("bun-patch", {
    "package.json": JSON.stringify({ name: "root", ...packageJson }),
    "bunfig.toml": `[install]\nlinker = "${linker}"\nglobalStore = ${globalStore}\n`,
    ...files,
  });
  const dir = String(tmp);
  const env = projectEnv(dir);
  await bunOk(dir, env, "install");
  return { dir, env, [Symbol.asyncDispose]: () => tmp[Symbol.asyncDispose]() };
}

/** Runs `bun patch <arg>` in `cwd` and expects it to prepare `folder` of the package `name`. */
async function expectPrepared(cwd: string, env: Env, arg: string, name: string, folder: string) {
  expect(await bunOk(cwd, env, "patch", arg)).toContain(patchMessage(name, folder));
}

/** Runs `bun patch <...args>` and expects it to end with `message` without preparing or committing anything. */
async function expectRefused(dir: string, env: Env, message: string, ...args: string[]) {
  const packageJson = await Bun.file(join(dir, "package.json")).json();
  const { stdout, stderr, exitCode } = await runBun(dir, env, "patch", ...args);
  expect(stderr).toEndWith(message);
  expect(stdout).not.toContain("To patch");
  expect({
    packageJson: await Bun.file(join(dir, "package.json")).json(),
    patches: existsSync(join(dir, "patches")),
  }).toEqual({ packageJson, patches: false });
  expect(exitCode).toBe(1);
}

/** What `path` itself is: a link is not followed. */
function kind(...path: string[]) {
  const stat = lstatSync(join(...path), { throwIfNoEntry: false });
  if (!stat) return "missing";
  return stat.isSymbolicLink() ? "link" : stat.isDirectory() ? "directory" : "file";
}

/** Every path below `dir`. */
const tree = (dir: string) => (readdirSync(dir, { recursive: true }) as string[]).sort();

/** The folder of the package `name` in the isolated linker's store. */
const storeFolder = (entry: string, name: string) => `node_modules/.bun/${entry}/node_modules/${name}`;

const installedVersion = async (...path: string[]) => {
  const file = Bun.file(join(...path, "package.json"));
  return (await file.exists()) ? (await file.json()).version : undefined;
};

/** The .tgz of a package with `files`. */
async function packTarball(files: DirectoryTree) {
  const entries: Record<string, string | Buffer> = {};
  const add = (folder: string, tree: DirectoryTree) => {
    for (const [name, value] of Object.entries(tree)) {
      if (typeof value === "string" || Buffer.isBuffer(value)) entries[`${folder}/${name}`] = value;
      else add(`${folder}/${name}`, value as DirectoryTree);
    }
  };
  add("package", files);
  return Buffer.from(await new Bun.Archive(entries, { compress: "gzip" }).bytes());
}

/** `env` with `path` as the only PATH. */
function withPath(env: Env, path: string): Env {
  return { ...Object.fromEntries(Object.entries(env).filter(([key]) => key.toUpperCase() !== "PATH")), PATH: path };
}

