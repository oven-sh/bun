// Writes src/lint/linter/deprecated_data.rs: what ESLint's `usedDeprecatedRules` says about each deprecated rule.
//
//   bun generate-deprecated.mjs <eslint checkout> <typescript-eslint checkout> <eslint-plugin-react checkout> > src/lint/linter/deprecated_data.rs
import { createRequire } from "node:module";
import path from "node:path";

const [eslintRoot, typescriptRoot, reactRoot] = process.argv.slice(2).map(it => path.resolve(it));
const require = createRequire(import.meta.url);
const { getShorthandName } = require(path.join(eslintRoot, "lib/shared/naming.js"));
const core = require(path.join(eslintRoot, "lib/rules/index.js"));
const typescript = require(path.join(typescriptRoot, "packages/eslint-plugin/dist/index.js")).rules;
const react = require(path.join(reactRoot, "index.js")).rules;

// `getDeprecatedRuleReplacements` of lib/eslint/eslint.js
function replacements(meta) {
  if (typeof meta.deprecated !== "object") return meta.replacedBy || [];
  const { replacedBy } = meta.deprecated;
  if (!Array.isArray(replacedBy)) return [];
  return replacedBy.map(replacement => {
    if (typeof replacement !== "object" || replacement === null) return "";
    const pluginName = replacement.plugin?.name;
    const ruleName = replacement.rule?.name;
    return `${typeof pluginName === "string" ? `${getShorthandName(pluginName, "eslint-plugin")}/` : ""}${typeof ruleName === "string" ? ruleName : ""}`;
  });
}

// The rules about layout, which `bun lint` does not have: what @stylistic/eslint-plugin has taken over, and this one.
const isAboutLayout = (id, replacedBy) =>
  id === "react/jsx-space-before-closing" || (replacedBy.length > 0 && replacedBy.every(it => it.startsWith("@stylistic/")));

const entries = [];
for (const [prefix, rules] of [
  ["", [...core]],
  ["@typescript-eslint/", Object.entries(typescript)],
  ["react/", Object.entries(react)],
]) {
  for (const [name, rule] of rules) {
    const meta = rule.meta;
    if (!meta?.deprecated) continue;
    const info = typeof meta.deprecated === "object" ? meta.deprecated : undefined;
    const replacedBy = replacements(meta);
    if (prefix === "react/" && !isAboutLayout(prefix + name, replacedBy)) continue;
    const text = JSON.stringify({ replacedBy, info });
    entries.push([prefix + name, text.slice(1, -1), isAboutLayout(prefix + name, replacedBy)]);
  }
}
entries.sort((a, b) => (a[0] < b[0] ? -1 : 1));

let hashes = "#";
while (entries.some(it => it[1].includes(`"${hashes}`))) hashes += "#";
console.log("//! Generated by test/cli/lint/oracle/driver/generate-deprecated.mjs.\n");
console.log("/// The name of a rule that is deprecated, and what follows `ruleId` in ESLint's `DeprecatedRuleInfo` as JSON.");
console.log("pub type Deprecated = (&'static str, &'static str);");
for (const [name, comment, isMeant] of [
  ["DEPRECATED", "Those that are here, sorted by name.", it => !it[2]],
  [
    "FORMATTING",
    "Those about the layout of the code, sorted by name. They are not here: `bun format` does their work.",
    it => it[2],
  ],
]) {
  console.log(`\n/// ${comment}\npub(super) const ${name}: &[Deprecated] = &[`);
  for (const [id, text] of entries.filter(isMeant)) console.log(`    (${JSON.stringify(id)}, r${hashes}"${text}"${hashes}),`);
  console.log("];");
}
