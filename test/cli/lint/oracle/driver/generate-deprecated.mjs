// Writes src/lint/linter/deprecated_data.rs and deprecated.txt: what ESLint's `usedDeprecatedRules` says about each deprecated rule.
//
//   bun generate-deprecated.mjs <eslint checkout> <typescript-eslint checkout> <node_modules>
//
// `<node_modules>` has the packages whose rules are built in: eslint-plugin-react, -react-hooks, -import and -n.
import { writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import path from "node:path";

const [eslintRoot, typescriptRoot, packages] = process.argv.slice(2).map(it => path.resolve(it));
const require = createRequire(import.meta.url);
const { getShorthandName } = require(path.join(eslintRoot, "lib/shared/naming.js"));
const core = require(path.join(eslintRoot, "lib/rules/index.js"));
const typescript = require(path.join(typescriptRoot, "packages/eslint-plugin/dist/index.js")).rules;
const rulesOf = name => Object.entries(require(path.join(packages, `eslint-plugin-${name}`)).rules);

// `getDeprecatedRuleReplacements` of lib/eslint/eslint.js
function replacements(meta) {
  if (typeof meta.deprecated !== "object") return meta.replacedBy || [];
  const { replacedBy } = meta.deprecated;
  if (!Array.isArray(replacedBy)) return [];
  return replacedBy.map(replacement => {
    if (typeof replacement !== "object" || replacement === null) return "";
    const pluginName = replacement.plugin?.name;
    const ruleName = replacement.rule?.name;
    return `${typeof pluginName === "string" ? `${getShorthandName(pluginName, "eslint-plugin")}/` : ""}${typeof ruleName === "string" ? ruleName : ""}`;
  });
}

// The rules about layout, which `bun lint` does not have: what @stylistic/eslint-plugin has taken over, and this one.
const isAboutLayout = (id, replacedBy) =>
  id === "react/jsx-space-before-closing" || (replacedBy.length > 0 && replacedBy.every(it => it.startsWith("@stylistic/")));

const entries = [];
for (const [prefix, rules] of [
  ["", [...core]],
  ["@typescript-eslint/", Object.entries(typescript)],
  ...["react", "react-hooks", "import", "n"].map(name => [`${name}/`, rulesOf(name)]),
]) {
  for (const [name, rule] of rules) {
    const meta = rule.meta;
    if (!meta?.deprecated) continue;
    const info = typeof meta.deprecated === "object" ? meta.deprecated : undefined;
    const replacedBy = replacements(meta);
    const text = JSON.stringify({ replacedBy, info });
    entries.push([prefix + name, text.slice(1, -1), isAboutLayout(prefix + name, replacedBy)]);
  }
}
entries.sort((a, b) => (a[0] < b[0] ? -1 : 1));

const tables = [
  ["DEPRECATED", "ESLint's, and those of the plugins that are built in, in whole or in part. Sorted by name.", it => !it[2]],
  ["FORMATTING", "Rules about code layout, sorted by name. Bun doesn't have them: `bun fmt` does their work.", it => it[2]],
].map(([name, comment, isMeant]) => {
  const rows = entries.flatMap((it, line) => (isMeant(it) ? [`    (${JSON.stringify(it[0])}, ${line}),\n`] : []));
  return `\n/// ${comment}\npub(super) const ${name}: &[Deprecated] = &[\n${rows.join("")}];\n`;
});
const directory = path.join(import.meta.dirname, "../../../../../src/lint/linter");
writeFileSync(
  path.join(directory, "deprecated_data.rs"),
  `//! Generated by test/cli/lint/oracle/driver/generate-deprecated.mjs, together with \`deprecated.txt\`.

/// A deprecated rule's name, and the line of \`deprecated.txt\` (from 0) that is about it.
pub type Deprecated = (&'static str, u16);
${tables.join("")}`,
);
// One line per rule: what follows `ruleId` in ESLint's `DeprecatedRuleInfo`, as JSON.
writeFileSync(path.join(directory, "deprecated.txt"), entries.map(it => `${it[1]}\n`).join(""));
