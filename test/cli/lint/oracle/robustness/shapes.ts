// Inputs that are large in one dimension: `wide(n)` has n of something next to each other, `deep(n)` n of something in each
// other. The key is the file name. A linter has to take time and memory in proportion to n on each of them.

const seq = (n: number, f: (i: number) => string, sep = "") => Array.from({ length: n }, (_, i) => f(i)).join(sep);
const rep = (text: string, n: number) => text.repeat(n);

/** A shape is made when it is asked for: all of them at n = 1,000,000 take more memory than there is. */
function lazily(shapes: Record<string, () => string>): Record<string, string> {
  const made: Record<string, string> = {};
  for (const [name, make] of Object.entries(shapes)) Object.defineProperty(made, name, { get: make, enumerable: true });
  return made;
}

