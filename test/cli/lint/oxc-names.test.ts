  // of the places in the head of the table. A cell is what oxlint 1.87 prints about the file, a letter for each error:
  //   R  The keyword 'x' is reserved                        A  Cannot assign to 'x' in strict mode
  //   C  Cannot use `x` as an identifier in an async / a generator context
  //   L  `let` cannot be declared as a variable name inside of a `let` declaration
  //   F  'arguments' is not allowed in class field initializer    S  .. in static initialization block
  //   W  Cannot use await in class static initialization block
  //   E  A reserved word cannot be used as an exported binding without `from`
  //   I  Identifier expected. 'x' is a reserved word that cannot be used here.      U  Unexpected token
  // "-": it lints the file. "x": not compared, it has another error. ".": there is no such file.
  test("names that are keywords somewhere, eval and arguments: every use in many places", async () => {
    const letters: [RegExp, string][] = [
      [/^The keyword '.*' is reserved$/, "R"],
      [/^Cannot assign to '(eval|arguments)' in strict mode$/, "A"],
      [/^Cannot use `(await|yield)` as an identifier in an? (async|generator) context$/, "C"],
      [/^`let` cannot be declared as a variable name inside of a `.*` declaration$/, "L"],
      [/^'arguments' is not allowed in class field initializer$/, "F"],
      [/^'arguments' is not allowed in static initialization block$/, "S"],
      [/^Cannot use await in class static initialization block$/, "W"],
      [/^A reserved word cannot be used as an exported binding without `from`$/, "E"],
      [/^Identifier expected\. '(await|yield)' is a reserved word that cannot be used here\.$/, "I"],
      [/^Unexpected token$/, "U"],
    ];
    const names = ["eval", "arguments", "let", "static", "yield", "await"];
    const lines = tables.flatMap(([extension, places, groups]) =>
      groups.flatMap(([cells, all]) =>
        all.split(" ").map(use => ({
          extension,
          use,
          places: places.split(" "),
          cells: cells.split(" | ").map(group => group.split(" ")),
        })),
      ),
    );
    /** Calls `cell` with each cell of a line and the name of its file, and returns the line with what that returns. */
    const print = (line: (typeof lines)[number], cell: (expected: string, file: string, code: string) => string) =>
      `${line.extension} ${line.use}: ` +
      names
        .map((name, group) =>
          line.places
            .map((place, at) =>
              cell(
                line.cells[group][at],
                `${line.use}-${place}-${name}.${line.extension}`,
                around[place].replace("#", () => uses[line.use].replaceAll("$", () => name)),
              ),
            )
            .join(" "),
        )
        .join(" | ");
    const isCompared = (cell: string) => cell !== "." && cell !== "x";
    const files: Record<string, string> = {};
    for (const line of lines) {
      print(line, (expected, file, code) => {
        if (isCompared(expected)) files[file] = code + "\n";
        return expected;
      });
    }
    const result = await lint({ ".oxlintrc.json": quiet, ...files }, ["-f", "json"]);
    using _ = result.dir;
    const printed: Record<string, string> = {};
    for (const { filename, message } of JSON.parse(result.stdout).diagnostics as Diagnostic[]) {
      printed[filename] = (printed[filename] ?? "") + (letters.find(([pattern]) => pattern.test(message))?.[1] ?? "?");
    }
    expect(
      lines.map(line => print(line, (expected, file) => (isCompared(expected) ? (printed[file] ?? "-") : expected))),
    ).toEqual(lines.map(line => print(line, expected => expected)));
  });

