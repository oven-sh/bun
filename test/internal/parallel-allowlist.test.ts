import { expect, test } from "bun:test";
import { existsSync, readFileSync } from "node:fs";
import { dirname, join } from "node:path";

const testDir = join(import.meta.dir, "..");
const table = JSON.parse(readFileSync(join(testDir, "parallel-allowlist.json"), "utf8"));

test("test/parallel-allowlist.json has the shape the runner reads", () => {
  expect(table._meta).toBeObject();
  expect(table.dirs).toBeArray();
  expect(table.excludeFiles).toBeArray();
  expect(table.dirs.length).toBeGreaterThan(100);
  for (const p of [...table.dirs, ...table.excludeFiles]) {
    expect(p).not.toContain("\\");
    expect(p).not.toStartWith("test/");
    expect(p).not.toStartWith("/");
  }
});

test("excludeFiles are real files inside listed dirs", () => {
  const dirs = new Set(table.dirs);
  const bad = table.excludeFiles.filter((f: string) => !dirs.has(dirname(f)) || !existsSync(join(testDir, f)));
  expect(bad).toEqual([]);
});

const denylist = readFileSync(join(testDir, "parallel-denylist.txt"), "utf8")
  .split(/\r?\n/)
  .map(line => line.trim())
  .filter(line => line && !line.startsWith("#"));

test("parallel-denylist.txt entries are real files", () => {
  const bad = denylist.filter(f => f.includes("\\") || f.startsWith("test/") || !existsSync(join(testDir, f)));
  expect(bad).toEqual([]);
});

// The runner only consults parallel-allowlist.json, so a denylist entry keeps a
// file out of the batch only once a regen has copied it into excludeFiles. This
// catches a file added to the denylist by hand (or a table regenerated by an
// older script) that the committed table still runs in the batch.
test("denylisted files in listed dirs are in excludeFiles", () => {
  const dirs = new Set(table.dirs);
  const excluded = new Set(table.excludeFiles);
  const inBatch = denylist.filter(f => dirs.has(dirname(f)) && !excluded.has(f));
  expect(inBatch).toEqual([]);
});
