import { describe, expect, test } from "bun:test";
import { bunExe, tempDir } from "harness";
import { existsSync, readdirSync, readFileSync } from "node:fs";
import { join } from "node:path";
import { BuildError } from "../../../scripts/build/error.ts";
import {
  featureFiles,
  featureIndexLimit,
  firstEmbedderFeatureIndex,
  loadFeatures,
  parseFeatures,
  serializeFeatureModel,
} from "../../../scripts/build/trim/features.ts";
import { rustTableFormat } from "../../../scripts/build/trim/table-format.ts";
import { cppHeader, rustSource } from "../../../src/codegen/generate-removable-features.ts";
import {
  beginGuardedBody,
  endGuardedBody,
  guardedBindingCreation,
  guardedCall,
  hostFunctionDefinitionRecord,
  recordedPointer,
  removableFeatures,
  tableEntryRecord,
} from "../../../src/codegen/removable-entry-points.ts";
import { run } from "../../aot/harness/run";

type Files = Partial<Record<(typeof featureFiles)[number], string>>;

const generatorTimeout = 60_000;

const root = join(import.meta.dir, "..", "..", "..");
const script = join(root, "src", "codegen", "generate-removable-features.ts");
const realModel = loadFeatures(root);

const parse = (files: Files) => parseFeatures(featureFiles.map(name => ({ name, text: files[name] ?? "" })));

const sampleFiles = {
  "engine.def": `feature JIT "the just-in-time compilers"
  entered-from startup
feature URICoding "encodeURI and decodeURI"
`,
  "bun.def": String.raw`feature Sqlite "bun:sqlite"
feature Quoted "a \"quote\" and a \\"
  entered-from command-line
`,
  "trim-features.def": `trim-feature html-rewriter : Sqlite JIT
  about "Two features."
trim-feature jit : JIT
  about "One feature."
`,
} satisfies Files;
const sample = { ...parse(sampleFiles), hash: 0x0123456789abcdefn };

function buildErrorOf(action: () => unknown): BuildError {
  try {
    action();
  } catch (error) {
    expect(error).toBeInstanceOf(BuildError);
    return error as BuildError;
  }
  throw new Error("expected a BuildError");
}

const captures = (text: string, pattern: RegExp) => [...text.matchAll(pattern)].map(match => match.slice(1));

async function runGenerator(args: string[]) {
  const { stdout, stderr, exitCode } = await run([bunExe(), script, ...args]);
  return { stdout, stderr, exitCode };
}

describe("rustSource", () => {
  test("prints the nine items of removable_features.rs", () => {
    expect(rustSource(sample)).toBe(String.raw`// Generated by src/codegen/generate-removable-features.ts. Do not edit.
pub const FEATURES_HASH: u64 = 0x0123_4567_89ab_cdef;
#[repr(u16)]
#[derive(Copy, Clone, PartialEq, Eq, Hash, PartialOrd, Ord, Debug)]
pub enum Feature {
    Jit = 0,
    UriCoding = 1,
    Sqlite = 128,
    Quoted = 129,
}
#[repr(u8)]
#[derive(Copy, Clone, PartialEq, Eq, Hash, PartialOrd, Ord, Debug)]
pub enum TrimFeature {
    HtmlRewriter = 0,
    Jit = 1,
}
pub(crate) const ALL_FEATURES: &[Feature] = &[
    Feature::Jit,
    Feature::UriCoding,
    Feature::Sqlite,
    Feature::Quoted,
];
pub(crate) const ALL_TRIM_FEATURES: &[TrimFeature] = &[
    TrimFeature::HtmlRewriter,
    TrimFeature::Jit,
];
pub(crate) const FEATURE_RECORDS: &[FeatureRecord] = &[
    FeatureRecord { name: "JIT", text: "the just-in-time compilers", entered_from: EnteredFrom::Startup, narrowest_trim_feature: Some(TrimFeature::Jit) },
    FeatureRecord { name: "URICoding", text: "encodeURI and decodeURI", entered_from: EnteredFrom::Program, narrowest_trim_feature: None },
    FeatureRecord { name: "Sqlite", text: "bun:sqlite", entered_from: EnteredFrom::Program, narrowest_trim_feature: Some(TrimFeature::HtmlRewriter) },
    FeatureRecord { name: "Quoted", text: "a \"quote\" and a \\", entered_from: EnteredFrom::CommandLine, narrowest_trim_feature: None },
];
pub(crate) const TRIM_FEATURE_RECORDS: &[TrimFeatureRecord] = &[
    TrimFeatureRecord { name: "html-rewriter", features: &[Feature::Jit, Feature::Sqlite] },
    TrimFeatureRecord { name: "jit", features: &[Feature::Jit] },
];
#[unsafe(no_mangle)]
extern "C" fn Bun__removableFeatureName(index: u16) -> *const core::ffi::c_char {
    match index {
        0 => c"JIT".as_ptr(),
        1 => c"URICoding".as_ptr(),
        128 => c"Sqlite".as_ptr(),
        129 => c"Quoted".as_ptr(),
        _ => core::ptr::null(),
    }
}
pub(crate) const RUST_SOURCE_VERSION: u32 = 3;
`);
  });

  test("numbers the real features and trim features in ascending order", () => {
    const source = rustSource(realModel);
    expect(captures(source, /^pub(?:\(crate\))? (?:const|enum) (\w+)/gm).flat()).toEqual([
      "FEATURES_HASH",
      "Feature",
      "TrimFeature",
      "ALL_FEATURES",
      "ALL_TRIM_FEATURES",
      "FEATURE_RECORDS",
      "TRIM_FEATURE_RECORDS",
      "RUST_SOURCE_VERSION",
    ]);
    const [featureVariants, trimFeatureVariants] = captures(source, /^pub enum \w+ \{\n([^}]*)\}$/gm).map(([body]) =>
      captures(body!, /^ {4}(\w+) = (\d+),$/gm).map(([name, value]) => [name, Number(value)]),
    );
    expect(featureVariants).toEqual(realModel.features.map(({ rustName, index }) => [rustName, index]));
    expect(trimFeatureVariants).toEqual(realModel.trimFeatures.map(({ rustName }, position) => [rustName, position]));
    const indexes = realModel.features.map(feature => feature.index);
    expect(indexes).toEqual([...new Set(indexes)].sort((a, b) => a - b));
    expect(captures(source, /^ {8}(\d+) => c"(\w+)"\.as_ptr\(\),$/gm)).toEqual(
      realModel.features.map(({ name, index }) => [String(index), name]),
    );
  });

  test("rejects a model that would print an empty enum", () => {
    expect(buildErrorOf(() => rustSource(parse({}))).message).toBe("no feature is declared in src/trim/features/*.def");
    expect(buildErrorOf(() => rustSource(parse({ "bun.def": sampleFiles["bun.def"] }))).message).toBe(
      "no trim feature is declared in src/trim/features/trim-features.def",
    );
  });
});

describe("cppHeader", () => {
  test("prints BunRemovableFeatures.h", () => {
    expect(cppHeader(sample))
      .toBe(String.raw`// Generated by src/codegen/generate-removable-features.ts from src/trim/features/*.def. Do not edit.
#pragma once
#include <JavaScriptCore/AOTRemovableFeature.h>
#include <wtf/text/ASCIILiteral.h>
namespace Bun::Feature {
inline constexpr JSC::RemovableFeature JIT = JSC::RemovableFeature::JIT;
inline constexpr JSC::RemovableFeature URICoding = JSC::RemovableFeature::URICoding;
inline constexpr JSC::RemovableFeature Sqlite { 128 };
inline constexpr JSC::RemovableFeature Quoted { 129 };
}
static_assert(JSC::firstEmbedderRemovableFeature == 128 && JSC::removableFeatureIndexLimit == 512);
static_assert(static_cast<uint16_t>(JSC::RemovableFeature::JIT) == 0);
static_assert(static_cast<uint16_t>(JSC::RemovableFeature::URICoding) == 1);
namespace Bun {
inline constexpr unsigned numberOfEngineRemovableFeatures = 2;
inline constexpr uint64_t removableFeaturesHash = 0x0123456789abcdefULL;
struct RemovableFeatureText { uint16_t index; ASCIILiteral text; ASCIILiteral trimFeatureName; };
inline constexpr RemovableFeatureText removableFeatureTexts[] = {
    { 0, "the just-in-time compilers"_s, "jit"_s },
    { 1, "encodeURI and decodeURI"_s, ""_s },
    { 128, "bun:sqlite"_s, "html-rewriter"_s },
    { 129, "a \"quote\" and a \\"_s, ""_s },
};
}
static_assert(JSC::numberOfEngineRemovableFeatures == Bun::numberOfEngineRemovableFeatures, "src/trim/features/engine.def and JavaScriptCore's generated feature list differ");
`);
  });

  test("aliases and asserts every real engine feature and numbers every other one", () => {
    const header = cppHeader(realModel);
    const engineFeatures = realModel.features.filter(feature => feature.isEngine);
    const embedderFeatures = realModel.features.filter(feature => !feature.isEngine);
    const alias = /^inline constexpr JSC::RemovableFeature (\w+) = JSC::RemovableFeature::(\w+);$/gm;
    const assertion = /^static_assert\(static_cast<uint16_t>\(JSC::RemovableFeature::(\w+)\) == (\d+)\);$/gm;
    const numbered = /^inline constexpr JSC::RemovableFeature (\w+) \{ (\d+) \};$/gm;
    const text = /^ {4}\{ (\d+), "/gm;
    expect(captures(header, alias)).toEqual(engineFeatures.map(({ name }) => [name, name]));
    expect(captures(header, assertion)).toEqual(engineFeatures.map(({ name, index }) => [name, String(index)]));
    expect(captures(header, numbered)).toEqual(embedderFeatures.map(({ name, index }) => [name, String(index)]));
    expect(captures(header, text)).toEqual(realModel.features.map(({ index }) => [String(index)]));
    expect(header).toContain(`numberOfEngineRemovableFeatures = ${engineFeatures.length};`);
    expect(header).toContain(
      `static_assert(JSC::firstEmbedderRemovableFeature == ${firstEmbedderFeatureIndex} && JSC::removableFeatureIndexLimit == ${featureIndexLimit});`,
    );
  });

  test("rejects an empty model", () => {
    expect(() => cppHeader(parse({}))).toThrow(BuildError);
  });
});

describe.concurrent("command line", () => {
  test(
    "prints the usage unless there are two arguments",
    async () => {
      expect(await runGenerator([root])).toEqual({
        stdout: "",
        stderr: "usage: bun src/codegen/generate-removable-features.ts <repository root> <codegen dir>\n",
        exitCode: 1,
      });
    },
    generatorTimeout,
  );

  const featureFolder = (texts: Files) =>
    Object.fromEntries(featureFiles.map(name => [`src/trim/features/${name}`, texts[name] ?? ""]));

  test(
    "writes the Rust source, the C++ header and the model",
    async () => {
      using directory = tempDir("generated-features-written", featureFolder(sampleFiles));
      const codegenDir = join(String(directory), "codegen");
      expect(await runGenerator([String(directory), codegenDir])).toEqual({ stdout: "", stderr: "", exitCode: 0 });
      const model = parse(sampleFiles);
      expect(readdirSync(codegenDir).sort()).toEqual([
        "BunRemovableFeatures.h",
        "removable-features.json",
        "removable_features.rs",
      ]);
      expect(readFileSync(join(codegenDir, "removable_features.rs"), "utf8")).toBe(
        rustSource(model) + rustTableFormat().join("\n") + "\n",
      );
      expect(readFileSync(join(codegenDir, "BunRemovableFeatures.h"), "utf8")).toBe(cppHeader(model));
      expect(readFileSync(join(codegenDir, "removable-features.json"), "utf8")).toBe(serializeFeatureModel(model));
    },
    generatorTimeout,
  );

  test(
    "writes nothing when a feature file is rejected",
    async () => {
      using directory = tempDir(
        "generated-features-rejected",
        featureFolder({
          "bun.def": `feature Extra "extra"\n  class Missing\n`,
          "trim-features.def": `trim-feature extra : Extra\n  about "Extra."\n`,
        }),
      );
      const codegenDir = join(String(directory), "codegen");
      expect(await runGenerator([String(directory), codegenDir])).toEqual({
        stdout: "",
        stderr: "error: unknown feature attribute: class\n  at: src/trim/features/bun.def:2\n",
        exitCode: 1,
      });
      expect(existsSync(codegenDir)).toBe(false);
    },
    generatorTimeout,
  );
});

describe("removable-entry-points.ts", () => {
  test("loads the real model once", () => {
    expect(removableFeatures()).toBe(removableFeatures());
    expect(removableFeatures().hash).toBe(realModel.hash);
  });

  test("prints guards", () => {
    expect(recordedPointer(realModel, "Color", "Throw", "BunObject_callback_color")).toBe(
      "JSC::removableFunction<Bun::Feature::Color, JSC::RemovedFeatureStub::Throw, BunObject_callback_color>()",
    );
    expect(
      tableEntryRecord(realModel, "JSThingPrototypeTableValues", "Color", "Throw", "ThingPrototype__sizeGetterWrap"),
    ).toBe(
      "JSC::recordRemovableTableEntry<JSThingPrototypeTableValues, Bun::Feature::Color, JSC::RemovedFeatureStub::Throw, ThingPrototype__sizeGetterWrap>();",
    );
    expect(guardedCall(realModel, "Color", "Abort", "f", ["a", "b"])).toBe(
      "JSC::callRemovable<Bun::Feature::Color, JSC::RemovedFeatureStub::Abort, f>(a, b)",
    );
    expect(guardedCall(realModel, "Color", "ReturnDefault", "f", [])).toBe(
      "JSC::callRemovable<Bun::Feature::Color, JSC::RemovedFeatureStub::ReturnDefault, f>()",
    );
    expect(beginGuardedBody(realModel, "Color", "Abort", "void")).toBe(
      "BUN_BEGIN_REMOVABLE_ENTRY_POINT(Color, Abort, void)",
    );
    expect(hostFunctionDefinitionRecord(realModel, "Color", "jsColor")).toBe(
      "BUN_REMOVABLE_HOST_FUNCTION_DEFINITION(Color, jsColor);",
    );
    expect(endGuardedBody).toBe("BUN_END_REMOVABLE_ENTRY_POINT");
  });

  test("a guard that only JavaScript enters carries the id of its built-in", () => {
    expect(recordedPointer(realModel, "Color", "Throw", "BunObject_callback_color", 812)).toBe(
      "JSC::removableBuiltinFunction<Bun::Feature::Color, JSC::RemovedFeatureStub::Throw, BunObject_callback_color, 812>()",
    );
    expect(recordedPointer(realModel, "Color", "Throw", "f", 0)).toBe(
      "JSC::removableBuiltinFunction<Bun::Feature::Color, JSC::RemovedFeatureStub::Throw, f, 0>()",
    );
    expect(tableEntryRecord(realModel, "table", "Color", "Throw", "f", 812)).toBe(
      "JSC::recordRemovableTableEntry<table, Bun::Feature::Color, JSC::RemovedFeatureStub::Throw, f, JSC::GuardOrigin::Builtin, 812>();",
    );
    expect(guardedBindingCreation(realModel, "Color", "f", 812, ["global"])).toBe(
      "Bun::createRemovableBinding<Bun::Feature::Color, f, 812>(global)",
    );
    expect(hostFunctionDefinitionRecord(realModel, "Color", "jsColor", 812)).toBe(
      "BUN_REMOVABLE_BUILTIN_HOST_FUNCTION_DEFINITION(Color, 812, jsColor);",
    );
    expect(hostFunctionDefinitionRecord(realModel, "Color", "jsColor", 0)).toBe(
      "BUN_REMOVABLE_BUILTIN_HOST_FUNCTION_DEFINITION(Color, 0, jsColor);",
    );
  });

  test("rejects a feature that no file declares", () => {
    expect(() => recordedPointer(realModel, "color", "Throw", "f")).toThrow(BuildError);
    expect(() => tableEntryRecord(realModel, "table", "color", "Throw", "f")).toThrow(BuildError);
    expect(() => guardedCall(realModel, "Jit", "Abort", "f", [])).toThrow(BuildError);
    expect(() => guardedBindingCreation(realModel, "Jit", "f", 1, [])).toThrow(BuildError);
    expect(() => beginGuardedBody(realModel, "", "Abort", "void")).toThrow(BuildError);
    expect(() => hostFunctionDefinitionRecord(realModel, "Colour", "f")).toThrow(BuildError);
  });

  test("asks the model it is given", () => {
    expect(recordedPointer(sample, "Sqlite", "Throw", "f")).toBe(
      "JSC::removableFunction<Bun::Feature::Sqlite, JSC::RemovedFeatureStub::Throw, f>()",
    );
    expect(beginGuardedBody(sample, "Quoted", "Abort", "void")).toBe(
      "BUN_BEGIN_REMOVABLE_ENTRY_POINT(Quoted, Abort, void)",
    );
    expect(() => recordedPointer(sample, "Color", "Throw", "f")).toThrow(BuildError);
    expect(() => guardedCall(sample, "Color", "Abort", "f", [])).toThrow(BuildError);
    expect(() => beginGuardedBody(sample, "Color", "Abort", "void")).toThrow(BuildError);
    expect(() => hostFunctionDefinitionRecord(sample, "Color", "f")).toThrow(BuildError);
  });
});
