// A small exported function around a private helper that has one call site. The helper is inlined into its caller
// when the file is compiled, so it needs no code of its own then; the optimizing JIT later compiles the small caller
// a second time, into the JavaScript loop that calls it, and what that calls has to exist. The helpers are of the
// sizes around the one where a function's body stops being kept for that second compilation.
static unsigned helper_1(unsigned x) {
  x = x * 3u + 1u; x ^= x >> 7; x += x << 3;
  return x;
}
unsigned around_1(unsigned x) { return helper_1(x) + 1u; }

