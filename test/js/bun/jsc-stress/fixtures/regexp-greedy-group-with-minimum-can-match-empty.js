function shouldBe(actual, expected, what)
{
    actual = JSON.stringify(actual);
    expected = JSON.stringify(expected);
    if (actual !== expected)
        throw new Error(what + ": expected " + expected + " but got " + actual);
}

for (const [source, flags, input, exec, match, replace] of cases) {
    // A 16-bit copy of the input: the character before it is not matched by any of the patterns.
    for (const [prefix, string] of [[0, input], [1, "\u2603" + input]]) {
        if (prefix && /[\^\\]|\(\?[<!]/.test(source))
            continue;
        const what = "/" + source + "/" + flags + " on " + JSON.stringify(string);
        const once = new RegExp(source, flags);
        const global = new RegExp(source, flags + "g");
        for (let i = 0; i < 4; ++i) {
            const result = once.exec(string.slice(prefix));
            shouldBe(result && [result.index, ...result], exec, what + ", exec");
            shouldBe(once.test(string.slice(prefix)), !!exec, what + ", test");
            shouldBe(string.slice(prefix).match(global), match, what + ", match");
            shouldBe(string.slice(prefix).replace(global, "<$&>"), replace, what + ", replace");
        }
    }
}

