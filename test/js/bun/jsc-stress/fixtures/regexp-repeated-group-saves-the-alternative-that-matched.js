function shouldBe(actual, expected, what)
{
    actual = JSON.stringify(actual);
    expected = JSON.stringify(expected);
    if (actual !== expected)
        throw new Error(what + ": expected " + expected + " but got " + actual);
}

for (const [source, flags, input, exec, match, replace] of cases) {
    const what = "/" + source + "/" + flags + " on " + JSON.stringify(input);
    // The second string has 16-bit characters.
    for (const string of [input, (input + "\u2603").slice(0, -1)]) {
        const once = new RegExp(source, flags);
        const global = new RegExp(source, flags + "g");
        for (let i = 0; i < 3; ++i) {
            const result = once.exec(string);
            shouldBe(result && [result.index, ...result], exec, what + ", exec");
            shouldBe(once.test(string), !!exec, what + ", test");
            shouldBe(string.search(once), exec ? exec[0] : -1, what + ", search");
            shouldBe(string.match(global), match, what + ", match");
            shouldBe(string.replace(global, "<$&>"), replace, what + ", replace");
        }
    }
}
