// What JS can do to an object that few programs do: none of it may crash, and all of it should make some sense.
import m from "./004_classes.py";
import g from "./003_iteration.py";
import python from "bun:python";
const b = python.import("builtins");
const tryIt = (name, f) => { try { console.log(name, "->", String(f())); } catch (e) { console.log(name, "threw", e?.name, String(e?.message).slice(0, 100)); } };
const o = new m.Base(1);
tryIt("bind type", () => m.Base.bind(null, 7)().a);
tryIt("bind native", () => b.len.bind(null, [1, 2])());
tryIt("bind callable obj", () => Function.prototype.bind.call(o, null, 5)());
tryIt("new bound type", () => new (m.Base.bind(null, 8))().a);
tryIt("proxy call", () => new Proxy(m.func, {})(1, 2));
tryIt("proxy construct", () => new (new Proxy(m.Base, {}))(3).a);
tryIt("Reflect.construct func", () => Reflect.construct(m.func, [1, 2]));
tryIt("Reflect.construct newTarget", () => Reflect.construct(m.Base, [4], class Z { }).a);
tryIt("Reflect.construct as newTarget", () => typeof Reflect.construct(Object, [], m.Base));
tryIt("Reflect.construct Array newTarget", () => Array.isArray(Reflect.construct(Array, [], m.Base)));
tryIt("Reflect.construct Error newTarget pyfunc", () => typeof Reflect.construct(Error, ["x"], m.Base));
tryIt("caller", () => m.func.caller);
tryIt("arguments", () => m.func.arguments);
tryIt("prototype", () => m.func.prototype);
tryIt("extends func", () => { class X extends m.func { } });
tryIt("extends type", () => { class X extends m.Base { } return new X(1); });
tryIt("generator proto next", () => Object.getPrototypeOf(function* () { }).prototype.next.call(g.gen(1)));
tryIt("array iterator next", () => [][Symbol.iterator]().next.call(g.gen(1)));
tryIt("Map.prototype.get", () => Map.prototype.get.call(b.dict(), 1));
tryIt("Array.prototype.push on tuple", () => Array.prototype.push.call(b.tuple([1]), 2));
tryIt("Array.prototype.concat", () => [0].concat(b.tuple([1, 2])).length);
tryIt("captureStackTrace", () => { Error.captureStackTrace(o); return typeof o.stack; });
tryIt("Object.defineProperty accessor", () => Object.defineProperty(o, "acc", { get() { return 1; } }));
tryIt("Object.seal", () => Object.isSealed(Object.seal(new m.Other())));
tryIt("__proto__ get", () => o.__proto__ === Object.getPrototypeOf(o));
tryIt("__proto__ set", () => { o.__proto__ = null; return Object.getPrototypeOf(o) !== null; });
tryIt("__defineGetter__", () => o.__defineGetter__("zz", () => 1));
tryIt("__lookupGetter__", () => o.__lookupGetter__("a"));
tryIt("propertyIsEnumerable", () => [o.propertyIsEnumerable("a"), o.propertyIsEnumerable("describe")]);
tryIt("isPrototypeOf", () => Object.getPrototypeOf(o).isPrototypeOf(o));
tryIt("Symbol() key", () => { const s = Symbol(); m.Base[s] = 1; m.func[s] = 2; b.len[s] = 3; return [m.Base[s], m.func[s], b.len[s]]; });
tryIt("private field via return override", () => { class Stamp extends (function (x) { return x; }) { #p = 1; static has(x) { return #p in x; } } new Stamp(o); return Stamp.has(o); });
tryIt("with statement", () => new Function("o", "with (o) { return a; }")(o));
tryIt("for-in type", () => { const k = []; for (const x in m.Base) k.push(x); return k; });
tryIt("for-in func", () => { const k = []; for (const x in m.func) k.push(x); return k; });
tryIt("spread call", () => m.func(...b.tuple([1, 2])));
tryIt("apply tuple", () => m.func.apply(null, b.tuple([1, 2])));
tryIt("apply dict", () => m.func.apply(null, b.dict()));
tryIt("toString deep recursion", () => { const l = b.dict(); l.self = l; return String(l); });
tryIt("JSON cycle", () => { const l = b.dict(); l.self = l; return JSON.stringify(l); });
tryIt("huge index", () => b.tuple([1])[4294967295]);
tryIt("negative zero index", () => b.tuple([1])[-0]);
tryIt("float index", () => b.tuple([1])[0.5]);
tryIt("Object.entries type", () => Object.entries(m.Other).length);
