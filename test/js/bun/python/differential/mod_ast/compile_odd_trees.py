def ev(label, node, **ns):
    try:
        print(label, '->', repr(eval(compile(ast.Expression(node), '<e>', 'eval'), dict(ns))))
    except BaseException as e:
        print(label, '->', type(e).__name__ + ':', e)
def ex(label, *nodes, show=(), **ns):
    g = dict(ns)
    try:
        exec(compile(ast.Module(list(nodes), []), '<s>', 'exec'), g)
        print(label, '-> ok', [g.get(k) for k in show])
    except BaseException as e:
        print(label, '->', type(e).__name__ + ':', e)

