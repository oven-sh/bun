import asyncio, sys, signal
async def main():
    p = await asyncio.create_subprocess_exec('/bin/echo', 'hello', stdout=asyncio.subprocess.PIPE)
    out, err = await p.communicate(); print(out, err, p.returncode)
    p = await asyncio.create_subprocess_shell('echo out; echo err >&2; exit 3', stdout=asyncio.subprocess.PIPE, stderr=asyncio.subprocess.PIPE)
    print(await p.communicate(), p.returncode)
    p = await asyncio.create_subprocess_exec('/bin/cat', stdin=asyncio.subprocess.PIPE, stdout=asyncio.subprocess.PIPE)
    print(await p.communicate(b'through cat'), await p.wait())
    p = await asyncio.create_subprocess_exec('/bin/cat', stdin=asyncio.subprocess.PIPE, stdout=asyncio.subprocess.PIPE)
    p.stdin.write(b'line\n'); await p.stdin.drain(); print(await p.stdout.readline()); p.stdin.close(); print(await p.stdout.read(), await p.wait())
    p = await asyncio.create_subprocess_exec('/bin/sleep', '30'); p.terminate(); print(await p.wait())
    p = await asyncio.create_subprocess_exec('/bin/sleep', '30'); p.kill(); print(await p.wait())
    ps = [await asyncio.create_subprocess_shell('exit %d' % i) for i in range(5)]; print(await asyncio.gather(*(p.wait() for p in ps)))
    try: await asyncio.create_subprocess_exec('/nonexistent/program')
    except FileNotFoundError as e: print('FileNotFoundError', e.errno)
    p = await asyncio.create_subprocess_exec('/bin/sleep', '30')
    try: await asyncio.wait_for(p.wait(), 0.05)
    except TimeoutError: print('timeout'); p.kill(); print(await p.wait())
asyncio.run(main())
