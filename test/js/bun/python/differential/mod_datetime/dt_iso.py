print('--- round trips')
n = 0
for v in [datetime(1, 1, 1), datetime(9999, 12, 31, 23, 59, 59, 999999), datetime(2020, 2, 29, 12, 34, 56, 7), datetime(2020, 2, 29, 12, 34, 56, 700000)]:
    for z in [None, timezone.utc, timezone(timedelta(hours=5, minutes=30)), timezone(timedelta(seconds=-1)), timezone(timedelta(microseconds=1)), timezone(-timedelta(hours=23, minutes=59, seconds=59, microseconds=999999))]:
        w = v.replace(tzinfo=z)
        for sep in 'T x':
            for spec in ['auto', 'hours', 'minutes', 'seconds', 'milliseconds', 'microseconds']:
                s = w.isoformat(sep, spec)
                r = datetime.fromisoformat(s)
                n += 1
                print(s, r == w, r.isoformat(sep, spec) == s)
        s = w.timetz().isoformat()
        print(s, time.fromisoformat(s) == w.timetz())
print(n)

print('--- a deterministic fuzz')
state = 12345
def rnd(k):
    global state
    state = (state * 1103515245 + 12345) % 2**31
    return (state >> 8) % k
alphabet = '0123456789' * 3 + '--::..,,TTWWZZ++ ' + 'a'
for i in range(3000):
    base = ['2020-01-02T12:34:56.789012+01:30', '20200102T123456,789-0130', '2020-W01-4T12:34Z', '2020W014 1234', '12:34:56.789012+01:30:15.123456', '2020-01-02'][rnd(6)]
    chars = list(base)
    for _ in range(1 + rnd(3)):
        k = rnd(3)
        pos = rnd(len(chars)) if chars else 0
        if k == 0 and chars: chars[pos] = alphabet[rnd(len(alphabet))]
        elif k == 1 and chars: del chars[pos]
        else: chars.insert(pos, alphabet[rnd(len(alphabet))])
    s = ''.join(chars)
    for f in (datetime.fromisoformat, date.fromisoformat, time.fromisoformat):
        t(f, s)
