# fsum, sumprod, prod, hypot and dist: the results depend on how CPython adds.
import math

inf = float('inf')
nan = float('nan')
state = 99
def rnd():
    global state
    state = (state * 6364136223846793005 + 1442695040888963407) % 2**64
    return (state >> 11) / 2**53

def show(name, *args, **kw):
    try:
        r = repr(getattr(math, name)(*args, **kw))
    except Exception as e:
        r = '%s: %s' % (type(e).__name__, e)
    a = repr(args) if ' at 0x' not in repr(args) else '<iterators>'
    print(name, a if len(a) < 120 else a[:117] + '...', kw or '', r)

