# The module fcntl.
import fcntl, posix, struct, warnings

def show(function, *args, **kwargs):
    try:
        result = function(*args, **kwargs)
    except BaseException as e:
        print(type(e).__name__, e)
    else:
        print(repr(result))

BAD = 9999
base = '/tmp/pyposix_fcntl_%d' % posix.getpid()
posix.mkdir(base)
posix.chdir(base)
try:
    fd = posix.open('f', posix.O_RDWR | posix.O_CREAT, 0o600)
    class File:
        def fileno(self):
            return fd

    print('-- fcntl with ints')
    show(fcntl.fcntl, fd, fcntl.F_GETFD)
    show(fcntl.fcntl, fd, fcntl.F_SETFD, 0)
    show(fcntl.fcntl, fd, fcntl.F_GETFD)
    print(posix.get_inheritable(fd))
    show(fcntl.fcntl, fd, fcntl.F_SETFD, fcntl.FD_CLOEXEC)
    show(fcntl.fcntl, File(), fcntl.F_GETFD)
    flags = fcntl.fcntl(fd, fcntl.F_GETFL)
    print(flags & posix.O_ACCMODE == posix.O_RDWR, bool(flags & posix.O_NONBLOCK))
    show(fcntl.fcntl, fd, fcntl.F_SETFL, flags | posix.O_NONBLOCK)
    print(bool(fcntl.fcntl(fd, fcntl.F_GETFL) & posix.O_NONBLOCK), posix.get_blocking(fd))
    copy = fcntl.fcntl(fd, fcntl.F_DUPFD, 100)
    print(copy >= 100, posix.get_inheritable(copy))
    posix.close(copy)
    copy = fcntl.fcntl(fd, fcntl.F_DUPFD_CLOEXEC, 100)
    print(copy >= 100, posix.get_inheritable(copy))
    posix.close(copy)
    show(fcntl.fcntl, fd, fcntl.F_GETFD, True)
    show(fcntl.fcntl, fd, fcntl.F_GETFD, 2**32 + 1)
    show(fcntl.fcntl, fd, fcntl.F_GETFD, -1)
    show(fcntl.fcntl, fd, fcntl.F_GETFD, 2**70)
    show(fcntl.fcntl, BAD, fcntl.F_GETFD)
    show(fcntl.fcntl, -1, fcntl.F_GETFD)
    show(fcntl.fcntl, 'a', fcntl.F_GETFD)
    show(fcntl.fcntl, fd, 'a')
    show(fcntl.fcntl, fd, 9999)
    show(fcntl.fcntl, fd, 2**40)
    show(fcntl.fcntl, fd, fcntl.F_GETFD, 1.5)
    show(fcntl.fcntl, fd, fcntl.F_GETFD, None)
    show(fcntl.fcntl, fd, fcntl.F_GETFD, [])
    show(fcntl.fcntl, fd)
    show(fcntl.fcntl, fd, 1, 2, 3)
    show(fcntl.fcntl, fd=fd, cmd=1)

    print('-- fcntl with structures')
    # struct flock: short l_type, short l_whence, off_t l_start, off_t l_len, pid_t l_pid
    FORMAT = 'hhqqi4x'
    lock = struct.pack(FORMAT, fcntl.F_WRLCK, 0, 0, 0, 0)
    result = fcntl.fcntl(fd, fcntl.F_GETLK, lock)
    print(type(result).__name__, len(result) == len(lock), struct.unpack(FORMAT, result)[0] == fcntl.F_UNLCK)
    result = fcntl.fcntl(fd, fcntl.F_SETLK, lock)
    print(result == lock)
    print(fcntl.fcntl(fd, fcntl.F_SETLK, bytearray(struct.pack(FORMAT, fcntl.F_UNLCK, 0, 0, 0, 0)))[:2])
    print(fcntl.fcntl(fd, fcntl.F_GETLK, memoryview(lock))[:2] == struct.pack('h', fcntl.F_UNLCK))
    show(fcntl.fcntl, fd, fcntl.F_GETFD, b'ignored')
    show(fcntl.fcntl, fd, fcntl.F_GETFD, 'text \xe9')
    show(fcntl.fcntl, fd, fcntl.F_GETFD, b'')
    print(len(fcntl.fcntl(fd, fcntl.F_GETFD, b'x' * 1024)), len(fcntl.fcntl(fd, fcntl.F_GETFD, b'x' * 1025)), len(fcntl.fcntl(fd, fcntl.F_GETFD, b'x' * 100000)))
    show(fcntl.fcntl, fd, fcntl.F_GETFD, '\ud800')
    show(fcntl.fcntl, BAD, fcntl.F_GETLK, lock)
    show(fcntl.fcntl, fd, fcntl.F_GETLK, b'short')

    print('-- pipes')
    r, w = posix.pipe()
    size = fcntl.fcntl(w, fcntl.F_GETPIPE_SZ)
    print(size >= 4096)
    print(fcntl.fcntl(w, fcntl.F_SETPIPE_SZ, 8192) >= 8192, fcntl.fcntl(r, fcntl.F_GETPIPE_SZ) >= 8192)

    print('-- ioctl')
    FIONREAD, TIOCGWINSZ, TIOCSWINSZ, FIONBIO = 0x541B, 0x5413, 0x5414, 0x5421
    posix.write(w, b'12345')
    result = fcntl.ioctl(r, FIONREAD, b'\0\0\0\0')
    print(result, struct.unpack('i', result))
    buffer = bytearray(4)
    show(fcntl.ioctl, r, FIONREAD, buffer)
    print(buffer)
    buffer = bytearray(4)
    show(fcntl.ioctl, r, FIONREAD, buffer, True)
    print(buffer)
    buffer = bytearray(4)
    show(fcntl.ioctl, r, FIONREAD, buffer, False)
    print(buffer)
    buffer = bytearray(8)
    show(fcntl.ioctl, r, FIONREAD, memoryview(buffer)[2:6])
    print(buffer)
    show(fcntl.ioctl, r, FIONREAD, memoryview(b'\0\0\0\0'))
    show(fcntl.ioctl, r, FIONREAD, '\0\0\0\0')
    big = bytearray(2000)
    show(fcntl.ioctl, r, FIONREAD, big)
    print(big[:6], len(big))
    print(fcntl.ioctl(r, FIONREAD, bytes(2000))[:6])
    show(fcntl.ioctl, r, FIONBIO, struct.pack('i', 1))
    print(posix.get_blocking(r))
    show(fcntl.ioctl, r, TIOCGWINSZ, bytes(8))
    show(fcntl.ioctl, BAD, FIONREAD, bytes(4))
    show(fcntl.ioctl, r, FIONREAD, 0)
    show(fcntl.ioctl, r, 0xdeadbeef)
    show(fcntl.ioctl, r, -1)
    show(fcntl.ioctl, r, 'a')
    show(fcntl.ioctl, r, 1.5)
    show(fcntl.ioctl, r, None)
    show(fcntl.ioctl, r, FIONREAD, 1.5)
    show(fcntl.ioctl, r, FIONREAD, None)
    show(fcntl.ioctl, r, FIONREAD, 2**31)
    show(fcntl.ioctl, r, FIONREAD, -2**31 - 1)
    show(fcntl.ioctl, r, FIONREAD, 2**70)
    show(fcntl.ioctl, 'a', FIONREAD)
    show(fcntl.ioctl, r)
    show(fcntl.ioctl, r, 1, 2, 3, 4)
    with warnings.catch_warnings(record=True) as caught:
        warnings.simplefilter('always')
        show(fcntl.ioctl, r, 2**64 + FIONREAD, bytes(4))
        show(fcntl.ioctl, r, 2**64 - 1)
        print([(x.category.__name__, str(x.message)) for x in caught])
    posix.close(r); posix.close(w)
    master, slave = posix.openpty()
    show(fcntl.ioctl, slave, TIOCSWINSZ, struct.pack('HHHH', 30, 100, 0, 0))
    print(struct.unpack('HHHH', fcntl.ioctl(slave, TIOCGWINSZ, bytes(8))), posix.get_terminal_size(slave), posix.get_terminal_size(master))
    posix.close(master); posix.close(slave)

    print('-- flock')
    show(fcntl.flock, fd, fcntl.LOCK_EX)
    other = posix.open('f', posix.O_RDWR)
    show(fcntl.flock, other, fcntl.LOCK_EX | fcntl.LOCK_NB)
    show(fcntl.flock, other, fcntl.LOCK_SH | fcntl.LOCK_NB)
    show(fcntl.flock, fd, fcntl.LOCK_SH)
    show(fcntl.flock, other, fcntl.LOCK_SH | fcntl.LOCK_NB)
    show(fcntl.flock, fd, fcntl.LOCK_UN)
    show(fcntl.flock, other, fcntl.LOCK_UN)
    show(fcntl.flock, File(), fcntl.LOCK_EX)
    show(fcntl.flock, fd, fcntl.LOCK_UN)
    show(fcntl.flock, fd, 0)
    show(fcntl.flock, fd, 'a')
    show(fcntl.flock, BAD, fcntl.LOCK_EX)
    show(fcntl.flock, fd)
    posix.close(other)

    print('-- lockf')
    show(fcntl.lockf, fd, fcntl.LOCK_EX)
    show(fcntl.lockf, fd, fcntl.LOCK_UN)
    show(fcntl.lockf, fd, fcntl.LOCK_SH | fcntl.LOCK_NB, 10)
    show(fcntl.lockf, fd, fcntl.LOCK_EX | fcntl.LOCK_NB, 10, 5)
    show(fcntl.lockf, fd, fcntl.LOCK_EX | fcntl.LOCK_NB, 10, 5, 0)
    show(fcntl.lockf, fd, fcntl.LOCK_UN, 0, 0, 2)
    show(fcntl.lockf, fd, 0)
    show(fcntl.lockf, fd, fcntl.LOCK_NB)
    show(fcntl.lockf, fd, fcntl.LOCK_EX, 'a')
    show(fcntl.lockf, fd, fcntl.LOCK_EX, 0, 'a')
    show(fcntl.lockf, fd, fcntl.LOCK_EX, 0, 0, 'a')
    show(fcntl.lockf, fd, fcntl.LOCK_EX, 2**70)
    show(fcntl.lockf, fd, fcntl.LOCK_EX, 0, -1)
    show(fcntl.lockf, fd, fcntl.LOCK_EX, 0, 0, 99)
    show(fcntl.lockf, 0 if False else BAD, fcntl.LOCK_EX)
    ro = posix.open('f', posix.O_RDONLY)
    show(fcntl.lockf, ro, fcntl.LOCK_EX | fcntl.LOCK_NB)
    show(fcntl.lockf, ro, fcntl.LOCK_SH | fcntl.LOCK_NB)
    posix.close(ro)
    show(fcntl.lockf, fd)
    posix.close(fd)
finally:
    posix.chdir('/')
    for name in posix.listdir(base):
        posix.unlink(base + '/' + name)
    posix.rmdir(base)
