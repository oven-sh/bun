# Making, moving and removing files; their sizes, modes and times.
import posix, stat

def show(function, *args, **kwargs):
    try:
        result = function(*args, **kwargs)
    except BaseException as e:
        print(type(e).__name__, e, getattr(e, 'errno', None), repr(getattr(e, 'filename', None)), repr(getattr(e, 'filename2', None)))
    else:
        print(repr(result))

def remove_tree(path):
    for entry in posix.scandir(path):
        if entry.is_dir(follow_symlinks=False):
            remove_tree(entry.path)
        else:
            posix.unlink(entry.path)
    posix.rmdir(path)

def write(path, data, **kwargs):
    fd = posix.open(path, posix.O_WRONLY | posix.O_CREAT | posix.O_TRUNC, 0o644, **kwargs)
    posix.write(fd, data)
    posix.close(fd)

def read(path):
    fd = posix.open(path, posix.O_RDONLY)
    data = posix.read(fd, 10000)
    posix.close(fd)
    return data

