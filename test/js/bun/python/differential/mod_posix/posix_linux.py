print('-- statx')
base = '/tmp/pyposix_linux_%d' % posix.getpid()
posix.mkdir(base)
posix.chdir(base)
try:
    path = 'file'
    old_mask = posix.umask(0o022)
    fd = posix.open(path, posix.O_RDWR | posix.O_CREAT, 0o640)
    posix.umask(old_mask)
    posix.write(fd, b'12345')
    posix.utime(path, ns=(1234567890123456789, 987654321))
    posix.symlink('file', 'link')
    x = posix.statx(path, posix.STATX_BASIC_STATS | posix.STATX_BTIME)
    s = posix.stat(path)
    print(type(x), type(x).__name__, type(x).__module__)
    print(x.stx_size, oct(x.stx_mode), x.stx_nlink, x.stx_uid == s.st_uid, x.stx_gid == s.st_gid, x.stx_ino == s.st_ino, x.stx_blocks == s.st_blocks, x.stx_blksize == s.st_blksize)
    print(x.stx_atime, x.stx_atime_ns, x.stx_mtime, x.stx_mtime_ns, x.stx_ctime == s.st_ctime, x.stx_ctime_ns == s.st_ctime_ns)
    print(x.stx_dev == s.st_dev, x.stx_dev == posix.makedev(x.stx_dev_major, x.stx_dev_minor), x.stx_rdev, x.stx_rdev_major, x.stx_rdev_minor)
    print(x.stx_mask & posix.STATX_BASIC_STATS == posix.STATX_BASIC_STATS, type(x.stx_attributes).__name__, type(x.stx_attributes_mask).__name__)
    print(type(x.stx_btime).__name__ in ('float', 'NoneType'), (x.stx_btime is None) == (x.stx_btime_ns is None))
    text = repr(x)
    print(text.startswith('os.statx_result(stx_mask='), 'stx_size=5' in text, 'stx_mtime_ns=987654321' in text, text.endswith(')'))
    names = [part.split('=')[0] for part in text[len('os.statx_result('):-1].split(', ')]
    print(names[:17])
    x = posix.statx(path, posix.STATX_SIZE)
    print(x.stx_size)
    print(posix.statx(fd, posix.STATX_SIZE).stx_size, posix.statx(path.encode(), posix.STATX_SIZE).stx_size)
    print(posix.statx(path=path, mask=posix.STATX_SIZE, flags=posix.AT_STATX_SYNC_AS_STAT).stx_size)
    dfd = posix.open('.', posix.O_RDONLY)
    print(posix.statx('file', posix.STATX_SIZE, dir_fd=dfd).stx_size)
    posix.close(dfd)
    print(stat.S_ISLNK(posix.statx('link', posix.STATX_TYPE).stx_mode))
    show(posix.statx, 'nope', 0)
    show(posix.statx, BAD, 0)
    show(posix.statx, path, 'a')
    show(posix.statx, path, 0, flags='a')
    show(posix.statx, path, 0, flags=0x100)
    show(posix.statx, path, 0, flags=0x400)
    show(posix.statx, path, 0, flags=0x1000)
    show(posix.statx, path, 0, 0)
    show(posix.statx, path)
    show(posix.statx_result)
    show(setattr, x, 'stx_mask', 1)
    show(setattr, x, 'stx_size', 1)
    show(setattr, x, 'other', 1)
    show(delattr, x, 'stx_dev')
    posix.close(fd)

    print('-- extended attributes')
    show(posix.listxattr, path)
    show(posix.getxattr, path, 'user.nope')
    show(posix.setxattr, path, 'user.one', b'first')
    show(posix.setxattr, path, b'user.two', bytearray(b'second'))
    show(posix.setxattr, path.encode(), 'user.empty', b'')
    print(sorted(posix.listxattr(path)))
    show(posix.getxattr, path, 'user.one')
    show(posix.getxattr, path, b'user.two')
    show(posix.getxattr, path, 'user.empty')
    show(posix.setxattr, path, 'user.one', b'x', posix.XATTR_CREATE)
    show(posix.setxattr, path, 'user.three', b'x', posix.XATTR_REPLACE)
    show(posix.setxattr, path, 'user.one', b'replaced', posix.XATTR_REPLACE)
    show(posix.getxattr, path, 'user.one')
    show(posix.setxattr, path, 'user.big', b'b' * 1000)
    print(len(posix.getxattr(path, 'user.big')))
    show(posix.setxattr, path, 'nonsense', b'x')
    show(posix.setxattr, path, 'user.x', 'text')
    show(posix.setxattr, path, 'user.x', b'x', 'a')
    show(posix.removexattr, path, 'user.big')
    show(posix.removexattr, path, 'user.big')
    print(sorted(posix.listxattr(path)))
    fd = posix.open(path, posix.O_RDONLY)
    print(sorted(posix.listxattr(fd)))
    show(posix.getxattr, fd, 'user.one')
    show(posix.setxattr, fd, 'user.byfd', b'f')
    show(posix.removexattr, fd, 'user.byfd')
    posix.close(fd)
    print(sorted(posix.listxattr('link')), posix.listxattr('link', follow_symlinks=False))
    show(posix.getxattr, 'link', 'user.one')
    show(posix.getxattr, 'link', 'user.one', follow_symlinks=False)
    show(posix.setxattr, 'link', 'user.l', b'x', follow_symlinks=False)
    show(posix.removexattr, 'link', 'user.one', follow_symlinks=False)
    show(posix.listxattr, 'nope')
    show(posix.getxattr, 'nope', 'user.one')
    show(posix.listxattr, BAD)
    show(posix.listxattr)
    show(posix.listxattr, None)
finally:
    posix.chdir('/')
    for name in posix.listdir(base):
        posix.unlink(base + '/' + name)
    posix.rmdir(base)
