# What only Linux has: scheduling, eventfd, timerfd, memfd, pidfd, extended attributes, statx.
import posix, stat

def show(function, *args, **kwargs):
    try:
        result = function(*args, **kwargs)
    except BaseException as e:
        print(type(e).__name__, e)
    else:
        print(repr(result))

