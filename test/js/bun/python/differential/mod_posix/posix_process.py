def output_of(path, argv, env, function=posix.posix_spawn, **kwargs):
    r, w = posix.pipe()
    actions = [(posix.POSIX_SPAWN_DUP2, w, 1), (posix.POSIX_SPAWN_CLOSE, r)] + kwargs.pop('file_actions', [])
    pid = function(path, argv, env, file_actions=actions, **kwargs)
    posix.close(w)
    data = b''
    while True:
        chunk = posix.read(r, 1000)
        if not chunk:
            break
        data += chunk
    posix.close(r)
    return data, posix.waitstatus_to_exitcode(posix.waitpid(pid, 0)[1])

