import select, os, time
def t(f):
    try: print(repr(f()))
    except BaseException as x: print(type(x).__name__ + ':', x)
r, w = os.pipe()
p = select.poll()
print(p.poll(0))
print(p.register(r), p.register(w, select.POLLOUT))
print(p.poll(0) == [(w, select.POLLOUT)])
os.write(w, b'abc')
print(sorted(p.poll()) == sorted([(r, select.POLLIN), (w, select.POLLOUT)]))
print(p.modify(w, 0), p.poll(10) == [(r, select.POLLIN)])
print(p.modify(r, select.POLLOUT), p.poll(0))
p.modify(r, select.POLLIN | select.POLLPRI)
print(p.unregister(w), p.poll(None) == [(r, select.POLLIN)], p.poll(-1) == [(r, 1)], p.poll(-1000.5) == [(r, 1)])
os.read(r, 3)
t0 = time.monotonic(); print(p.poll(50)); d = time.monotonic() - t0; print(0.045 <= d < 2)
t0 = time.monotonic(); print(p.poll(20.5)); d = time.monotonic() - t0; print(0.02 <= d < 2)
os.close(w)
print(p.poll(1000) == [(r, select.POLLHUP)])
