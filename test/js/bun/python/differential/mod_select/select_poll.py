# The order of the results is that of registration.
a = [os.pipe() for _ in range(5)]
q = select.poll()
for x, y in reversed(a): q.register(y, select.POLLOUT)
print([fd for fd, ev in q.poll(0)] == [y for x, y in reversed(a)])
q.register(a[4][1], select.POLLOUT)
print([fd for fd, ev in q.poll(0)] == [y for x, y in reversed(a)])
q.unregister(a[4][1]); q.register(a[4][1], select.POLLOUT)
print([fd for fd, ev in q.poll(0)] == [y for x, y in reversed(a[:4])] + [a[4][1]])
