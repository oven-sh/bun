def hand_written():
    """*.py.in: tests written by hand, where C(pattern[, flags]) with literal arguments stands for re.compile(), and the
    list REPLS holds all the replacement templates that are used."""
    import ast, warnings
    for name in sorted(os.listdir(HERE)):
        if not name.endswith('.py.in'):
            continue
        with open(os.path.join(HERE, name)) as f:
            source = f.read()
        tree = ast.parse(source)
        codes, compiled, repls = {}, {}, []
        for node in ast.walk(tree):
            if isinstance(node, ast.Call) and isinstance(node.func, ast.Name) and node.func.id == 'C':
                args = [eval(compile(ast.Expression(a), name, 'eval'), dict(I=2, L=4, M=8, S=16, U=32, X=64, DEBUG=128, A=256)) for a in node.args]
                key = (args[0], args[1] if len(args) > 1 else 0)
                with warnings.catch_warnings():
                    warnings.simplefilter('ignore')
                    codes[key] = compile_args(*key)
                    compiled[key] = re.compile(*key)
            if isinstance(node, ast.Assign) and getattr(node.targets[0], 'id', None) == 'REPLS':
                repls = ast.literal_eval(node.value)
        templates = {}
        for key, p in compiled.items():
            for r in repls:
                try:
                    templates[key[0], r] = _parser.parse_template(r, p)
                except (re.error, IndexError, TypeError):
                    pass
        variants = re.match(r'# VARIANTS: (\d+)', source)
        if variants:
            for i in range(int(variants[1])):
                with open(os.path.join(OUT, 'g_%s_%d.py' % (name[:-6], i)), 'w') as f:
                    f.write(HAND_PRELUDE % (name, ascii(codes), ascii(templates)) + 'VARIANT = %d\n' % i + source)
            continue
        with open(os.path.join(OUT, 'g_' + name[:-3]), 'w') as f:
            f.write(HAND_PRELUDE % (name, ascii(codes), ascii(templates)) + source)


