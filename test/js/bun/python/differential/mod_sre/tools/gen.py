PRELUDE = r'''# Generated by gen.py.
import sys, _sre

class _FakeRe:
    templates = {}
    @staticmethod
    def _compile_template(pattern, repl):
        return _sre.template(pattern, list(_FakeRe.templates[repl]))
sys.modules['re'] = _FakeRe

def M(m):
    if m is None:
        return None
    return (m.span(), m.group(), m.groups(), m.groupdict(), m.lastindex, m.lastgroup, m.regs, m.pos, m.endpos)

def attempt(f, *args):
    try:
        return f(*args)
    except Exception as e:
        return '%s: %s' % (type(e).__name__, e)

def battery(n, p, templates, subjects):
    _FakeRe.templates = templates
    for s in subjects:
        empty = s[:0]
        x = 'X' if isinstance(s, str) else b'X'
        out = [
            attempt(lambda: M(p.match(s))),
            attempt(lambda: M(p.fullmatch(s))),
            attempt(lambda: M(p.search(s))),
            attempt(lambda: M(p.search(s, 1))),
            attempt(lambda: M(p.match(s, 1, len(s) - 1))),
            attempt(lambda: M(p.fullmatch(s, 0, len(s) - 1))),
            attempt(lambda: p.findall(s)),
            attempt(lambda: p.findall(s, 1, len(s) - 1)),
            attempt(lambda: p.split(s)),
            attempt(lambda: p.split(s, 1)),
            attempt(lambda: [M(m) for m in p.finditer(s)]),
            attempt(lambda: p.subn(x, s)),
            attempt(lambda: p.sub(x, s, 1)),
            attempt(lambda: p.sub(lambda m: x + m.group() + x, s)),
        ]
        for t in templates:
            out.append(attempt(lambda: p.subn(t, s)))
            out.append(attempt(lambda: [m.expand(t) for m in p.finditer(s)]))
        sc = p.scanner(s)
        out.append(attempt(lambda: [M(sc.match()), M(sc.search()), M(sc.match()), M(sc.search())]))
        print(n, ascii(out))
'''


def compile_args(p, flags=0):
    """What re.compile() passes to _sre.compile()."""
    pp = _parser.parse(p, flags)
    code = _compiler._code(pp, flags)
    groupindex = pp.state.groupdict
    indexgroup = [None] * pp.state.groups
    for k, i in groupindex.items():
        indexgroup[i] = k
    return (p, int(flags | pp.state.flags), [int(c) for c in code], pp.state.groups - 1, groupindex, tuple(indexgroup))


def emit(name, cases, per_file=60):
    """cases: (pattern, flags, subjects, templates)"""
    part = 0
    for first in range(0, len(cases), per_file):
        lines = [PRELUDE]
        for n, (pattern, flags, subjects, templates) in enumerate(cases[first:first + per_file], first):
            import warnings
            with warnings.catch_warnings():
                warnings.simplefilter('ignore')
                try:
                    args = compile_args(pattern, flags)
                    compiled = re.compile(pattern, flags)
                except (re.error, RecursionError, OverflowError) as e:
                    continue
            parsed = {}
            for t in templates:
                try:
                    parsed[t] = _parser.parse_template(t, compiled)
                except (re.error, IndexError):
                    pass
            lines.append('battery(%d, _sre.compile(%s), %s, %s)' % (n, ', '.join(ascii(a) for a in args), ascii(parsed), ascii(list(subjects))))
        with open(os.path.join(OUT, 'g_%s_%02d.py' % (name, part)), 'w') as f:
            f.write('\n'.join(lines) + '\n')
        part += 1


def templates_for(pattern, flags=0):
    b = isinstance(pattern, bytes)
    ts = [r'[\g<0>]', r'\1-\1', r'<\2|\1>', r'a\nb\\c']
    return [t.encode() for t in ts] if b else ts


def from_re_tests():
    scope = {}
    with open(LIB + '/test/re_tests.py') as f:
        exec(compile(f.read(), 're_tests.py', 'exec'), scope)
    cases = []
    for t in scope['tests']:
        pattern, s = t[0], t[1]
        cases.append((pattern, 0, [s], templates_for(pattern)))
    emit('retests', cases)
    # The same as bytes, ignoring case, and with a non-Latin-1 and an astral character before the subject.
    cases = []
    for t in scope['tests']:
        pattern, s = t[0], t[1]
        try:
            cases.append((pattern.encode('latin-1'), 0, [s.encode('latin-1')], templates_for(b'')))
        except UnicodeEncodeError:
            pass
    emit('retests_bytes', cases)
    emit('retests_icase', [(t[0], re.I, [t[1], t[1].upper()], []) for t in scope['tests']])
    emit('retests_wide', [(t[0], 0, ['\u20ac' + t[1], '\U0001f600' + t[1] + '\U0001f600'], templates_for(t[0])[:2]) for t in scope['tests']])


