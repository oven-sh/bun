# gmtime, localtime, mktime, asctime, ctime, strftime over many times. (The tests run in UTC.)
import time

def show(name, *args):
    try:
        r = getattr(time, name)(*args)
        if isinstance(r, time.struct_time):
            r = '%r zone=%r gmtoff=%r' % (r, r.tm_zone, r.tm_gmtoff)
        else:
            r = repr(r)
    except Exception as e:
        r = '%s: %s' % (type(e).__name__, e)
    print(name, args, r)

