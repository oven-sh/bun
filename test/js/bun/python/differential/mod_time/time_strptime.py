# strptime() is _strptime._strptime_time().
import time

def show(*args):
    try:
        r = time.strptime(*args)
        r = '%r zone=%r gmtoff=%r %s' % (r, r.tm_zone, r.tm_gmtoff, type(r).__name__)
    except Exception as e:
        r = '%s: %s' % (type(e).__name__, e)
    print(args, r)

show('2001-02-03 04:05:06', '%Y-%m-%d %H:%M:%S')
show('Sat Feb  3 04:05:06 2001')
show('Sat Feb  3 04:05:06 2001', '%a %b %d %H:%M:%S %Y')
show('3 February 2001', '%d %B %Y')
show('12/31/99', '%m/%d/%y')
show('12/31/68', '%m/%d/%y')
show('12/31/69', '%m/%d/%y')
show('11:59 PM', '%I:%M %p')
show('12:00 AM', '%I:%M %p')
show('2001 034', '%Y %j')
show('2001-02-03 +0530', '%Y-%m-%d %z')
show('2001-02-03 -05:30', '%Y-%m-%d %z')
show('2001-02-03 Z', '%Y-%m-%d %z')
show('2001-02-03 UTC', '%Y-%m-%d %Z')
show('2001-02-03 GMT', '%Y-%m-%d %Z')
show('2024 10 1', '%Y %W %w')
show('2024 10 1', '%Y %U %w')
show('2024 10 1', '%G %V %u')
show('100%', '%H0%%')
