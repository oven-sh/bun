import _tokenize
T = _tokenize.TokenizerIter

def run(lines, **kw):
    it = iter(lines)
    for extra in (True, False):
        print(lines, extra)
        try:
            for t in T(iter(lines).__next__, extra_tokens=extra, **kw):
                print('  ', t)
        except SyntaxError as e:
            print('  ', type(e).__name__, e.args, e.lineno, e.offset)

run(['a = 1\r\n', 'b = 2\r\n'])
run(['a = 1 # c\r\n', '# d\r\n', '\r\n', 'b\r\n'])
run(['a = 1 # c\n', '# d\n', '\n', 'b'])
run(['x = """a\r\n', 'b\r\n', '""" + 1\r\n'])
run(['x = (1,\r\n', '  2)\r\n'])
run(['if x:\r\n', '    y\r\n', 'z\r\n'])
run(['if x:\n', '    y\n', '    # c\n', '  # d\n', 'z'])
run(['if x:\n', '  if y:\n', '    z'])
run(['if x:\n', '  if y:\n', '    z\n', '\n'])
run(['a \\\r\n', 'b\r\n'])
run(['a', 'b'])
run(['a\n', ''])
run(['# only a comment'])
run(['# only a comment\n'])
run(['   '])
run(['\n'])
run(['\r\n'])
run(['\t\n', 'x'])
run(['(', ')'])
run(['f"""a\r\n', '{x}b\r\n', '"""\r\n'])
run(['f"{x!r:>{w}}" f\'{{}}\'\n'])
run(['f"{x = }" t"{y:%d}"\n'])
run(['f"a{\n', 'x\n', '}b"\n'])
run(['é = "ü" # ñ\n', '"""é\n', 'ü""" + é\n'])
run(['😀 = 1\n'])
run(['x = "😀" + y\n'])
run(['a\x0cb\n', '\x0c  c\n'])
run([b'a = 1\n', b'\xc3\xa9 = 2\n'], encoding='utf-8')
run([b'\xe9 = 1\n'], encoding='latin-1')
run([b'\xe9 = 1\n'], encoding='utf-8')
run(['1_000 0x_f 0b1 0o7 1e5 1.5j .5 1. 0_0 1__0\n'])
run(['01 0x 1e 1_ 0b2 1.e+ 0o8\n'])
run(['a.b ... -> := != <> ** //= >>= <<= @= ! ? $ `\n'])
run(['async def f(): await x\n', 'match x:\n', '  case _: pass\n', 'type X = int\n', 'lazy import y\n'])
run(['x = 1 # type: int\n', '# type: ignore\n'])
run(["'a' \"b\" b'c' rb'd' u'e' Rb\"f\" br'''g''' bu'x'\n"])
run(["'unterminated\n"])
