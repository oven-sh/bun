// add(a, b) and bump() (a counter in linear memory), driven hard right before the snapshot so that tier-up compilations
// are in flight on the compiler threads when it is taken: they must be quiesced, or the snapshot ends up holding
// pointers to code that was installed after its pages were walked.
const bytes = new Uint8Array([
  0x00, 0x61, 0x73, 0x6d, 0x01, 0x00, 0x00, 0x00, 0x01, 0x0b, 0x02, 0x60, 0x02, 0x7f, 0x7f, 0x01, 0x7f, 0x60, 0x00, 0x01,
  0x7f, 0x03, 0x03, 0x02, 0x00, 0x01, 0x05, 0x03, 0x01, 0x00, 0x01, 0x07, 0x17, 0x03, 0x03, 0x61, 0x64, 0x64, 0x00, 0x00,
  0x04, 0x62, 0x75, 0x6d, 0x70, 0x00, 0x01, 0x06, 0x6d, 0x65, 0x6d, 0x6f, 0x72, 0x79, 0x02, 0x00, 0x0a, 0x1e, 0x02, 0x07,
  0x00, 0x20, 0x00, 0x20, 0x01, 0x6a, 0x0b, 0x14, 0x00, 0x41, 0x00, 0x41, 0x00, 0x28, 0x02, 0x00, 0x41, 0x01, 0x6a, 0x36,
  0x02, 0x00, 0x41, 0x00, 0x28, 0x02, 0x00, 0x0b,
]);
const { instance } = await WebAssembly.instantiate(bytes);
const { add, bump } = instance.exports;
let acc = 0;
for (let i = 0; i < 300000; i++) acc = add(acc, 1);
for (let i = 0; i < 100000; i++) bump();
Bun.startupSnapshot.main(() => {
  let sum = 0;
  for (let i = 0; i < 1000; i++) sum = add(sum, 2);
  console.log(`[js] epoch=${Bun.startupSnapshot.epoch()} warmed=${acc} sum=${sum} bump=${bump()}`);
});
